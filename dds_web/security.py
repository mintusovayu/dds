"""
Модуль безопасности веб-интерфейса DDS.

Этот модуль содержит централизованные функции безопасности,
используемые в веб-слое (presentation layer) DDS. Модуль
объединяет ранее дублировавшиеся функции из ``lifespan.py``
и ``pages.py``.

Функции:

+-------------------------------+--------------------------------------+
| Функция                       | Назначение                         |
+===============================+======================================+
| ``is_safe_redirect_path()``   | Проверка безопасности пути для      |
|                               | редиректа. Предотвращает           |
|                               | open redirect-атаки.               |
+-------------------------------+--------------------------------------+
| ``should_use_secure_cookie()``| Определение необходимости флага     |
|                               | ``secure`` у cookie.              |
+-------------------------------+--------------------------------------+

Принципы:

- Модуль находится в presentation layer и не содержит бизнес-логики.
- Модуль не зависит от конкретных компонентов приложения
  (``SearchEngine``, ``ScanOrchestrator`` и т.д.).
- Функции модуля являются чистыми: не имеют побочных эффектов,
  не изменяют входные данные.
- Модуль использует только стандартные библиотеки.

Безопасность редиректов:

Функция ``is_safe_redirect_path`` предотвращает open redirect-атаки,
принимая только относительные пути, начинающиеся с ``/`` и не
содержащие схемы URL. Это единая точка проверки, используемая
всеми компонентами веб-слоя.

Использование:

.. code-block:: python

    from dds_web.security import (
        is_safe_redirect_path,
        should_use_secure_cookie,
    )

    # Проверка пути редиректа
    if is_safe_redirect_path(next_path):
        redirect(next_path)

    # Определение флага secure cookie
    secure = should_use_secure_cookie(request)
"""

from __future__ import annotations

from typing import Any

# ----------------------------------------------------------------------
# Безопасность редиректов
# ----------------------------------------------------------------------


def is_safe_redirect_path(path: str) -> bool:
    """Проверяет, что путь безопасен для редиректа.

    Предотвращает open redirect-атаки, принимая только относительные
    пути, начинающиеся с ``/`` и не содержащие схемы URL.

    Операции:

    +----+-----------------------------------------------------+
    | №  | Описание                                            |
    +====+=====================================================+
    | 1  | Проверка типа: ``path`` должен быть строкой.        |
    +----+-----------------------------------------------------+
    | 2  | Проверка непустоты: ``path`` не должен быть         |
    |    | пустой строкой.                                     |
    +----+-----------------------------------------------------+
    | 3  | Проверка начала с ``/``: путь должен начинаться     |
    |    | с символа ``/`` (относительный путь).               |
    +----+-----------------------------------------------------+
    | 4  | Проверка отсутствия ``//``: путь не должен          |
    |    | начинаться с ``//`` (protocol-relative URL).        |
    +----+-----------------------------------------------------+
    | 5  | Проверка отсутствия ``/\\``: путь не должен         |
    |    | начинаться с ``/\\`` (обход в Windows).             |
    +----+-----------------------------------------------------+
    | 6  | Проверка первого сегмента: первый сегмент пути      |
    |    | (между первым и вторым ``/``) не должен             |
    |    | содержать символ ``:`` (схема URL).                |
    +----+-----------------------------------------------------+
    | 7  | Возврат ``True``, если все проверки пройдены.       |
    +----+-----------------------------------------------------+

    Безопасные пути:

    +--------------------------------------+-------------------------+
    | Путь                                 | Результат               |
    +======================================+=========================+
    | ``/``                                | ``True`` (безопасный)   |
    +--------------------------------------+-------------------------+
    | ``/admin``                           | ``True`` (безопасный)   |
    +--------------------------------------+-------------------------+
    | ``/search?q=test``                   | ``True`` (безопасный)   |
    +--------------------------------------+-------------------------+
    | ``/document/abc123``                 | ``True`` (безопасный)   |
    +--------------------------------------+-------------------------+

    Небезопасные пути:

    +--------------------------------------+-------------------------+
    | Путь                                 | Результат               |
    +======================================+=========================+
    | ``https://evil.com``                 | ``False``               |
    +--------------------------------------+-------------------------+
    | ``//evil.com``                       | ``False``               |
    +--------------------------------------+-------------------------+
    | ``http://evil.com/path``             | ``False``               |
    +--------------------------------------+-------------------------+
    | ``/\\evil.com``                      | ``False``               |
    +--------------------------------------+-------------------------+
    | ``javascript:alert(1)``              | ``False``               |
    +--------------------------------------+-------------------------+
    | ``""`` (пустая строка)               | ``False``               |
    +--------------------------------------+-------------------------+
    | ``None``                             | ``False``               |
    +--------------------------------------+-------------------------+

    Примечание:
        Функция является централизованной точкой проверки путей
        редиректа. Все компоненты веб-слоя (``lifespan.py``,
        ``pages.py``, ``api.py``) должны использовать эту функцию
        вместо собственных реализаций.

        Функция заменяет приватные функции ``_is_safe_redirect_path``,
        которые ранее были определены в ``lifespan.py`` и ``pages.py``.

    Args:
        path: Путь для проверки. Может быть строкой или ``None``.

    Returns:
        ``True``, если путь безопасен для редиректа.
        ``False`` в противном случае.
    """
    # Проверка типа и непустоты
    if not path or not isinstance(path, str):
        return False

    # Путь должен начинаться с "/" (относительный путь)
    if not path.startswith("/"):
        return False

    # Путь не должен начинаться с "//" (protocol-relative URL)
    if path.startswith("//"):
        return False

    # Путь не должен начинаться с "/\" (обход в Windows)
    if path.startswith("/\\"):
        return False

    # Первый сегмент пути не должен содержать ":" (схема URL)
    first_segment = path.split("/", 2)[1] if len(path) > 1 else ""
    return ":" not in first_segment


# ----------------------------------------------------------------------
# Безопасность cookie
# ----------------------------------------------------------------------


def should_use_secure_cookie(request: Any) -> bool:
    """Определяет, нужно ли устанавливать флаг ``secure`` у cookie.

    Флаг ``secure`` гарантирует, что cookie передаётся только
    по защищённому соединению (HTTPS). Это предотвращает перехват
    сессионного токена при передаче по незашифрованному каналу.

    Операции:

    +----+-----------------------------------------------------+
    | №  | Описание                                            |
    +====+=====================================================+
    | 1  | Проверка заголовка ``X-Forwarded-Proto``. Если      |
    |    | значение равно ``"https"`` (без учёта регистра)     |
    |    | → возврат ``True``. Это покрывает случай,           |
    |    | когда приложение работает за обратным прокси         |
    |    | (nginx, Caddy, AWS ALB), и прокси передаёт          |
    |    | оригинальный протокол через заголовок.              |
    +----+-----------------------------------------------------+
    | 2  | Проверка схемы запроса: если ``request.url.scheme`` |
    |    | равно ``"https"`` → возврат ``True``.               |
    |    | Это покрывает случай, когда приложение работает     |
    |    | напрямую за HTTPS без прокси.                       |
    +----+-----------------------------------------------------+
    | 3  | Если ни одна проверка не сработала → возврат        |
    |    | ``False``. Приложение работает за HTTP,             |
    |    | и флаг ``secure`` не устанавливается.               |
    +----+-----------------------------------------------------+

    Примечание:
        Функция принимает объект запроса как ``Any``, чтобы не
        создавать жёсткую зависимость от конкретного фреймворка.
        Ожидается, что объект имеет:

        +-------------------------------+----------------------------------+
        | Атрибут                       | Описание                         |
        +===============================+==================================+
        | ``headers``                   | Словарь заголовков запроса.      |
        +-------------------------------+----------------------------------+
        | ``url.scheme``                | Схема запроса (``"http"``        |
        |                               | или ``"https"``).                |
        +-------------------------------+----------------------------------+

        В FastAPI этим требованиям удовлетворяет объект
        ``fastapi.Request``.

        Порядок проверок: сначала проверяется заголовок
        ``X-Forwarded-Proto``, так как он наиболее точно отражает
        оригинальный протокол клиента при работе за прокси.
        Если заголовок отсутствует или не равен ``"https"``,
        проверяется схема запроса напрямую.

    Пример использования:

    .. code-block:: python

        secure = should_use_secure_cookie(request)
        response.set_cookie(
            key=SESSION_COOKIE_NAME,
            value=token,
            httponly=True,
            samesite="lax",
            secure=secure,
            max_age=session_ttl,
            path="/",
        )

    Args:
        request: HTTP-запрос. Ожидается объект с атрибутами
            ``headers`` и ``url.scheme``. В FastAPI это
            ``fastapi.Request``.

    Returns:
        ``True``, если соединение защищено (HTTPS).
        ``False`` в противном случае.
    """
    # Проверка заголовка X-Forwarded-Proto (за обратным прокси)
    forwarded_proto = request.headers.get("X-Forwarded-Proto", "")
    if forwarded_proto.lower() == "https":
        return True

    # Проверка схемы запроса напрямую
    return request.url.scheme == "https"
