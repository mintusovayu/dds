/**
 * Логика просмотра документов веб-приложения DDS.
 *
 * Модуль реализует клиентскую сторону просмотра документов:
 * загрузку метаданных и текста страниц через REST API,
 * растровый рендер страницы PDF с подсветкой совпадений,
 * навигацию по страницам, переключение режимов просмотра
 * и масштабирование.
 *
 * Архитектура модуля:
 *
 * +----------------------------------+----------------------------------+
 * | Компонент                        | Ответственность                  |
 * +==================================+==================================+
 * | ``DocumentLoader``               | Загрузка метаданных и текста     |
 * |                                  | документа через REST API.        |
 * +----------------------------------+----------------------------------+
 * | ``DocumentRenderer``             | Рендеринг метаданных, текста     |
 * |                                  | страницы и навигации по          |
 * |                                  | страницам.                       |
 * +----------------------------------+----------------------------------+
 * | ``createPageRenderer(docId)``    | Фабрика per-tab объекта          |
 * |                                  | рендера страницы PDF. Хранит      |
 * |                                  | ``_blobUrl``, ``_zoom``,          |
 * |                                  | ``_transformByPage`` и методы     |
 * |                                  | управления ими. Публичный метод   |
 * |                                  | ``refreshHighlights`` —           |
 * |                                  | пересчёт подсветки из внешних     |
 * |                                  | модулей (``app.js``).             |
 * +----------------------------------+----------------------------------+
 * | ``_updateTransformCheckboxState``| Синхронизация визуального        |
 * |                                  | состояния чекбокса «Ротация      |
 * |                                  | координат» с per-page флагом     |
 * |                                  | перед запросом подсветки.        |
 * +----------------------------------+----------------------------------+
 * | ``_syncTransformCheckbox``       | Синхронизация чекбокса после     |
 * |                                  | ответа сервера на ``/highlights``.|
 * +----------------------------------+----------------------------------+
 * | ``ViewModeManager``              | Управление режимом просмотра     |
 * |                                  | («рендер» / «текст»),            |
 * |                                  | рендеринг переключателя.         |
 * |                                  | Публичный метод                  |
 * |                                  | ``applyTextFallbackState`` —     |
 * |                                  | применение fallback-состояния    |
 * |                                  | из ``PageRenderer``.              |
 * +----------------------------------+----------------------------------+
 * | ``DocumentUtils``                | Вспомогательные функции:         |
 * |                                  | форматирование размера файла,    |
 * |                                  | экранирование HTML,              |
 * |                                  | извлечение имени файла.          |
 * +----------------------------------+----------------------------------+
 *
 * Режимы просмотра:
 *
 * - **Рендер** — растровое изображение страницы PDF, полученное
 *   через ``GET /api/documents/{id}/pages/{n}/render?dpi=300``.
 *   Поверх изображения накладывается слой подсветки совпадений
 *   (результат ``POST .../highlights``).
 * - **Текст** — текстовый слой страницы, полученный через
 *   ``GET /api/documents/{id}/pages/{n}``.
 *
 * Состояние режима хранится per-tab в ``AppState.openDocuments[i].viewMode``.
 * Глобальный дефолт для новых вкладок — в ``localStorage`` под
 * ключом ``"dds-doc-view-mode"``. Fallback при недоступности рендера
 * (HTTP 500 / 504) переключает вкладку на текстовый режим **без**
 * сохранения этого выбора в ``localStorage``.
 *
 * Per-tab состояние и фасад ``window.DDSApp``:
 *
 * Модуль не имеет прямого доступа к ``AppState`` (он в IIFE-скоупе
 * ``app.js``). Все обращения к состоянию вкладки выполняются через
 * фасад ``window.DDSApp``:
 *
 * - ``getDocumentRecord(docId)`` — получить запись вкладки.
 * - ``updateDocumentRecord(docId, updates)`` — обновить поля записи.
 * - ``incrementLoadSeq(docId)`` / ``getLoadSeq(docId)`` — счётчик
 *   асинхронных операций вкладки для защиты от race condition.
 * - ``ensureRenderer(docId)`` — гарантировать наличие renderer.
 *
 * Счётчик ``_seq`` защищает от race condition: при быстрой смене
 * страниц или режимов устаревшие ответы API игнорируются, так как
 * их ``seq`` не совпадает с текущим. Это предотвращает:
 *
 * - утечку blob URL (устаревший ответ не создаёт объект);
 * - перезапись актуального содержимого устаревшим.
 *
 * Инкапсуляция публичного API:
 *
 * Ранее ``app.js`` вызывал приватные методы ``renderer._fetchAndApplyHighlights``
 * и ``ViewModeManager._setActive`` напрямую, что нарушало инкапсуляцию.
 * Введены публичные методы ``PageRenderer.refreshHighlights`` и
 * ``ViewModeManager.applyTextFallbackState``, инкапсулирующие
 * детали (инкремент ``_seq`` для подсветки, блокировка кнопки
 * «Рендер» для fallback). Внутренние методы остаются приватными.
 *
 * Подсветка совпадений:
 *
 * Термины для подсветки извлекаются из сниппетов FTS5 в ``search.js``
 * и передаются в ``openDocumentTab`` через параметр ``options``
 * (карта ``termsByPage``: номер страницы → список терминов). При
 * рендере страницы, для которой есть термины, выполняется запрос
 * ``POST .../highlights`` с телом ``{terms: [...]}``. Сервер
 * возвращает координаты прямоугольников в нормализованных единицах
 * ``[0..1]``; клиент умножает их на 100 и применяет как CSS-проценты
 * для элементов подсветки. Цвет прямоугольников — бирюзовый
 * (``--page-render-highlight-bg`` в ``base.css``).
 *
 * Диагностика и коррекция системы координат:
 *
 * Для страниц PDF с аномальной системой координат (bottom-left
 * с перепутанными осями) координаты слов из
 * ``page.get_text("words")`` не соответствуют их визуальному
 * положению. Поиск, индексация и рендер PNG работают корректно,
 * но подсветка совпадений отображается в неправильных местах.
 *
 * На вкладке документа предусмотрен чекбокс «Ротация координат»
 * (``#doc-transform-{docId}``), который управляет применением
 * трансформации координат к bbox-ам подсветки:
 *
 * - Чекбокс устанавливается автоматически по результату
 *   авто-диагностики на сервере при первом запросе подсветки
 *   страницы.
 * - Пользователь может переключить чекбокс вручную; при
 *   переключении подсветка пересчитывается **без перезагрузки**
 *   PNG-рендера.
 *
 * Состояние чекбокса хранится per-page в
 * ``PageRenderer._transformByPage``. Отсутствие ключа для страницы
 * означает, что сервер ещё не отвечал (авто-диагностика не
 * выполнена).
 *
 * При формировании запроса ``POST /highlights`` клиент передаёт
 * поле ``apply_transform`` только если для страницы уже установлено
 * явное значение (пользователь переключил или сервер ответил
 * ранее). При отсутствии поля сервер выполняет авто-диагностику
 * и возвращает фактически применённый флаг в поле
 * ``applied_transform`` ответа, а также уровень уверенности в
 * поле ``transform_confidence`` (``"high"`` / ``"medium"`` /
 * ``"none"`` / ``"manual"``).
 *
 * Масштабирование:
 *
 * - При первом рендере страницы zoom автоматически устанавливается
 *   так, чтобы изображение полностью помещалось по ширине контейнера
 *   (fit-width). Значение ограничено диапазоном ``[0.25, 1.0]``:
 *   страница не увеличивается выше натурального размера.
 * - ``Ctrl + колесо`` — изменение zoom в диапазоне ``[0.25, 4.0]``.
 *   После первого ручного изменения автоматический fit-width больше
 *   не применяется для текущей вкладки.
 * - ``Ctrl + 0`` — сброс zoom: если пользователь ещё не менял zoom,
 *   применяется fit-width; иначе — ``1.0``.
 *
 * Реализация fit-width:
 * Размеры изображения задаются через явные ``style.width`` и
 * ``style.height`` на ``<img>`` (не через ``transform: scale``).
 * Это синхронизирует layout контейнера с визуальным отображением
 * и обеспечивает корректную работу скроллбара и панорамирования.
 * До применения fit-width (до события ``load``) на ``<img>``
 * временно устанавливается ``style.maxWidth = "100%"`` — защита
 * от flash гигантского изображения при первой отрисовке.
 *
 * Навигация по рендеру:
 *
 * - Скроллбар и колесо — нативная вертикальная прокрутка.
 * - Перетаскивание правой кнопкой мыши (drag) — панорамирование
 *   контейнера. Системное контекстное меню на рендере подавляется.
 *   Курсор: ``grab`` → ``grabbing`` при перетаскивании.
 *
 * Управление ресурсами:
 *
 * Каждая вкладка владеет собственным ``PageRenderer`` с полем
 * ``_blobUrl``. При смене страницы, переходе в текстовый режим
 * или закрытии вкладки blob URL освобождается через
 * ``URL.revokeObjectURL``. Это предотвращает утечки памяти
 * при интенсивной навигации. Обработчики панорамирования на
 * ``document`` снимаются в ``cleanup()``. Карта
 * ``_transformByPage`` обнуляется в ``cleanup()``.
 *
 * Принципы:
 * - Модуль не содержит бизнес-логики — только отображение
 *   и координация запросов к API.
 * - Данные загружаются через REST API.
 * - Обработка ошибок на уровне пользовательского интерфейса.
 * - Рендеринг через DOM API без внешних библиотек.
 * - Per-tab состояние изолировано: несколько открытых документов
 *   не влияют друг на друга.
 *
 * Зависимости:
 * - ``app.js`` — фасад ``window.DDSApp`` для доступа к per-tab
 *   состоянию.
 * - ``main.html`` — DOM-структура с контейнерами для документов.
 * - ``base.css`` — стили ``.table``, ``.card``, ``.page-text``,
 *   ``.pagination``, ``.alert``, ``.page-render-*``,
 *   ``.page-view-switch``, ``.doc-nav-*``, ``.doc-checkbox-label``,
 *   ``.doc-render-controls``.
 */

(function () {
    "use strict";

    /* ==============================================================
       1. Вспомогательные функции
       ============================================================== */

    /**
     * Вспомогательные функции для работы с документами.
     *
     * Операции:
     * +----------------------------------+----------------------------------+
     * | Метод                            | Описание                         |
     * +==================================+==================================+
     * | ``formatFileSize(bytes)``        | Форматирует размер файла         |
     * |                                  | в человекочитаемый вид.          |
     * +----------------------------------+----------------------------------+
     * | ``escapeHtml(text)``             | Экранирует HTML-специальные      |
     * |                                  | символы для предотвращения XSS.  |
     * +----------------------------------+----------------------------------+
     * | ``getBaseName(filePath,          | Универсальная функция извлечения |
     * | withExtension)``                 | имени файла: с расширением или   |
     * |                                  | без него.                        |
     * +----------------------------------+----------------------------------+
     */
    var DocumentUtils = {

        /**
         * Форматирует размер файла в человекочитаемый вид.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Если ``bytes > 1048576`` → форматирование в МБ      |
         * |   | с одним знаком после запятой.                       |
         * +---+-----------------------------------------------------+
         * | 2 | Если ``bytes > 1024`` → форматирование в КБ         |
         * |   | с одним знаком после запятой.                       |
         * +---+-----------------------------------------------------+
         * | 3 | Иначе → форматирование в байтах.                    |
         * +---+-----------------------------------------------------+
         *
         * @param {number} bytes — Размер файла в байтах.
         * @returns {string} Форматированная строка.
         */
        formatFileSize: function (bytes) {
            if (bytes > 1048576) {
                return (bytes / 1048576).toFixed(1) + " МБ";
            }
            if (bytes > 1024) {
                return (bytes / 1024).toFixed(1) + " КБ";
            }
            return bytes + " Б";
        },

        /**
         * Экранирует HTML-специальные символы.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Создание временного ``div``-элемента.               |
         * +---+-----------------------------------------------------+
         * | 2 | Установка ``textContent`` — браузер автоматически   |
         * |   | экранирует специальные символы.                     |
         * +---+-----------------------------------------------------+
         * | 3 | Возврат ``innerHTML`` — экранированная строка.      |
         * +---+-----------------------------------------------------+
         *
         * @param {string} text — Текст для экранирования.
         * @returns {string} Экранированный текст.
         */
        escapeHtml: function (text) {
            var div = document.createElement("div");
            div.textContent = text;
            return div.innerHTML;
        },

        /**
         * Возвращает имя файла из полного пути.
         *
         * Универсальная функция для извлечения basename.
         * Поддерживает разделители ``/`` и ``\``.
         * При ``withExtension = false`` удаляет последнее расширение
         * (текст после последней точки, если точка не является первым
         * символом имени файла).
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Если ``filePath`` не строка или пустая — возврат    |
         * |   | пустой строки.                                      |
         * +---+-----------------------------------------------------+
         * | 2 | Поиск последнего разделителя (``/`` или ``\``).     |
         * |   | Если найден, обрезать путь до имени файла.          |
         * +---+-----------------------------------------------------+
         * | 3 | Если ``withExtension`` истинно — возврат имени      |
         * |   | файла с расширением.                                |
         * +---+-----------------------------------------------------+
         * | 4 | Если ``withExtension`` ложно:                       |
         * |   | a. Найти последнюю точку в имени файла.            |
         * |   | b. Если точка есть и она не первая в имени —       |
         * |   |    вернуть подстроку до точки.                     |
         * |   | c. Иначе вернуть имя файла без изменений.           |
         * +---+-----------------------------------------------------+
         *
         * @param {string} filePath — Полный путь к файлу.
         * @param {boolean} [withExtension=true] — Флаг, указывающий,
         *     нужно ли включать расширение в результат.
         * @returns {string} Имя файла (с расширением или без).
         */
        getBaseName: function (filePath, withExtension) {
            if (typeof filePath !== "string" || filePath.length === 0) {
                return "";
            }

            // Определяем разделитель: поддерживаем "/" и "\".
            var lastSlash = filePath.lastIndexOf("/");
            var lastBackslash = filePath.lastIndexOf("\\");
            var lastSep = Math.max(lastSlash, lastBackslash);

            var fileName = lastSep === -1
                ? filePath
                : filePath.substring(lastSep + 1);

            if (withExtension === undefined || withExtension === true) {
                return fileName;
            }

            // Удаляем расширение (текст после последней точки).
            var lastDot = fileName.lastIndexOf(".");
            if (lastDot > 0) { // точка не первая и не отсутствует
                return fileName.substring(0, lastDot);
            }
            return fileName;
        }
    };

    /* ==============================================================
       2. Рендеринг содержимого документа
       ============================================================== */

    /**
     * Рендерер содержимого документа.
     *
     * Отвечает за рендеринг метаданных, текста страницы
     * и навигации по страницам внутри вкладки документа.
     *
     * Операции:
     * +----------------------------------+----------------------------------+
     * | Метод                            | Описание                         |
     * +==================================+==================================+
     * | ``renderMetadata(container,      | Рендеринг таблицы метаданных     |
     * | doc)``                           | документа.                       |
     * +----------------------------------+----------------------------------+
     * | ``renderPageNavigation(          | Рендеринг навигации по           |
     * | container, docId, fileName,      | страницам документа.             |
     * | currentPage, totalPages)``       |                                  |
     * +----------------------------------+----------------------------------+
     * | ``renderPageText(container,      | Рендеринг текста страницы.       |
     * | text)``                          |                                  |
     * +----------------------------------+----------------------------------+
     */
    var DocumentRenderer = {

        /**
         * Рендерит таблицу метаданных документа.
         *
         * Операции:
         * +----+-----------------------------------------------------+
         * | №  | Описание                                            |
         * +====+=====================================================+
         * | 1  | Формирование HTML-таблицы с полями:                 |
         * |    | a. Идентификатор (``doc.doc_id``).                  |
         * |    | b. Путь файла (``doc.file_path``).                  |
         * |    | c. Хеш файла (первые 16 символов + ``...``).        |
         * |    | d. Размер файла (через ``formatFileSize``).         |
         * |    | e. Количество страниц (``doc.page_count``).         |
         * |    | f. Дата индексирования (``doc.indexed_at``).        |
         * |    | g. Дата изменения файла (``doc.last_modified``).    |
         * +----+-----------------------------------------------------+
         * | 2  | Экранирование текстовых значений через              |
         * |    | ``escapeHtml()`` для предотвращения XSS.            |
         * +----+-----------------------------------------------------+
         * | 3  | Установка ``innerHTML`` контейнера.                 |
         * +----+-----------------------------------------------------+
         *
         * @param {Element} container — DOM-контейнер для метаданных.
         * @param {Object} doc — Объект метаданных документа из API.
         */
        renderMetadata: function (container, doc) {
            if (!container) return;

            var fileSize = DocumentUtils.formatFileSize(doc.file_size || 0);
            var fileHash = doc.file_hash
                ? doc.file_hash.substring(0, 16) + "..."
                : "—";

            var html =
                '<table class="table">' +
                "<tr>" +
                '<th style="width: 200px;">Идентификатор</th>' +
                "<td>" + DocumentUtils.escapeHtml(doc.doc_id || "") + "</td>" +
                "</tr>" +
                "<tr>" +
                "<th>Путь файла</th>" +
                "<td>" + DocumentUtils.escapeHtml(doc.file_path || "") + "</td>" +
                "</tr>" +
                "<tr>" +
                "<th>Хеш файла</th>" +
                '<td class="text-muted">' + DocumentUtils.escapeHtml(fileHash) + "</td>" +
                "</tr>" +
                "<tr>" +
                "<th>Размер файла</th>" +
                "<td>" + fileSize + "</td>" +
                "</tr>" +
                "<tr>" +
                "<th>Количество страниц</th>" +
                "<td>" + (doc.page_count || 0) + "</td>" +
                "</tr>" +
                "<tr>" +
                "<th>Дата индексирования</th>" +
                "<td>" + DocumentUtils.escapeHtml(doc.indexed_at || "—") + "</td>" +
                "</tr>" +
                "<tr>" +
                "<th>Дата изменения файла</th>" +
                "<td>" + DocumentUtils.escapeHtml(doc.last_modified || "—") + "</td>" +
                "</tr>" +
                "</table>";

            container.innerHTML = html;
        },

        /**
         * Рендерит навигацию по страницам документа.
         *
         * Режимы навигации (определяются чекбоксом
         * «Навигация по всем страницам» в записи вкладки):
         *
         * - **Все страницы** — навигация по ``[0, totalPages)``.
         *   «Стр. X из Y» = ``currentPage + 1`` и ``totalPages``.
         * - **Только совпадения** — навигация по страницам,
         *   которые присутствуют в ``options.termsByPage``.
         *   «Стр. X из Y» — X = позиция текущей страницы среди
         *   совпадений (1-based), Y = количество совпадений.
         *   Если текущей страницы нет среди совпадений —
         *   отображается «Стр. — из Y», Prev скрыт, Next →
         *   первая совпавшая страница.
         *
         * Операции:
         * +----+-----------------------------------------------------+
         * | №  | Описание                                            |
         * +====+=====================================================+
         * | 1  | Получение записи вкладки через фасад ``window.DDSApp``.|
         * +----+-----------------------------------------------------+
         * | 2  | Определение режима навигации (``navAllPages``).     |
         * +----+-----------------------------------------------------+
         * | 3  | Формирование отсортированного списка ``matchedPages``|
         * |    | из ключей ``options.termsByPage`` (явный           |
         * |    | числовой компаратор).                               |
         * +----+-----------------------------------------------------+
         * | 4  | Ранние выходы: нет страниц вообще; одна страница    |
         * |    | в режиме «все страницы».                            |
         * +----+-----------------------------------------------------+
         * | 5  | Вычисление ``displayTotal``, ``displayCurrent``,    |
         * |    | ``prevPage``, ``nextPage``.                          |
         * +----+-----------------------------------------------------+
         * | 6  | Формирование HTML: Prev (если есть), индикатор      |
         * |    | «Стр. X из Y», Next (если есть).                    |
         * +----+-----------------------------------------------------+
         * | 7  | Установка ``innerHTML`` контейнера.                 |
         * +----+-----------------------------------------------------+
         * | 8  | Привязка обработчиков клика: получение записи       |
         * |    | вкладки через ``window.DDSApp.getDocumentRecord``,  |
         * |    | сохранение существующего ``renderer`` и ``options``,|
         * |    | вызов ``DocumentLoader.loadDocument`` с новым       |
         * |    | номером страницы.                                    |
         * +----+-----------------------------------------------------+
         *
         * Примечание:
         * Нумерация страниц в API — 0-based. В интерфейсе
         * отображается 1-based (``currentPage + 1``).
         *
         * @param {Element} container — DOM-контейнер для навигации.
         * @param {string} docId — Идентификатор документа.
         * @param {string} fileName — Имя файла для вкладки.
         * @param {number} currentPage — Текущая страница (0-based).
         * @param {number} totalPages — Общее количество страниц.
         */
        renderPageNavigation: function (
            container,
            docId,
            fileName,
            currentPage,
            totalPages
        ) {
            if (!container) return;

            // Получаем запись вкладки через фасад.
            var rec = window.DDSApp.getDocumentRecord(docId);
            var navAll = (!rec) || (rec.navAllPages !== false);

            // Собираем страницы с совпадениями.
            var termsByPage = (rec && rec.options && rec.options.termsByPage) || {};
            var matchedPages = Object.keys(termsByPage)
                .map(Number)
                .filter(function (n) { return !isNaN(n); })
                .sort(function (a, b) { return a - b; });

            // Фильтр применяется только если чекбокс снят и есть
            // хотя бы одно совпадение. При отсутствии совпадений
            // fallback на «все страницы» (защита от пустой навигации).
            var filtered = (!navAll) && (matchedPages.length > 0);

            // Ранние выходы.
            if (totalPages <= 0) {
                container.innerHTML = "";
                return;
            }
            if (!filtered && totalPages <= 1) {
                container.innerHTML = "";
                return;
            }

            // Вычисление параметров навигации.
            var displayTotal;
            var displayCurrent;
            var prevPage;
            var nextPage;

            if (filtered) {
                var idx = matchedPages.indexOf(currentPage);
                displayTotal = matchedPages.length;
                if (idx >= 0) {
                    displayCurrent = idx + 1;
                    prevPage = (idx > 0) ? matchedPages[idx - 1] : null;
                    nextPage = (idx < matchedPages.length - 1)
                        ? matchedPages[idx + 1]
                        : null;
                } else {
                    // Текущей страницы нет среди совпадений.
                    displayCurrent = null;
                    prevPage = null;
                    nextPage = matchedPages[0];
                }
            } else {
                displayTotal = totalPages;
                displayCurrent = currentPage + 1;
                prevPage = (currentPage > 0) ? currentPage - 1 : null;
                nextPage = (currentPage < totalPages - 1)
                    ? currentPage + 1
                    : null;
            }

            // Формирование HTML.
            var html = '<div class="pagination">';

            if (prevPage !== null) {
                html +=
                    '<a href="#" data-doc-page="' +
                    prevPage +
                    '">← Пред.</a>';
            }

            var currentText = (displayCurrent === null)
                ? "—"
                : String(displayCurrent);
            html +=
                '<span class="current">Стр. ' +
                currentText +
                " из " +
                displayTotal +
                "</span>";

            if (nextPage !== null) {
                html +=
                    '<a href="#" data-doc-page="' +
                    nextPage +
                    '">След. →</a>';
            }

            html += "</div>";
            container.innerHTML = html;

            // Привязка обработчиков навигации. Запись вкладки получается
            // через фасад window.DDSApp, чтобы гарантировать сохранение
            // существующего renderer и options.
            var links = container.querySelectorAll("[data-doc-page]");
            for (var i = 0; i < links.length; i++) {
                links[i].addEventListener("click", function (e) {
                    e.preventDefault();
                    var page = parseInt(this.dataset.docPage, 10);

                    var r = window.DDSApp.getDocumentRecord(docId);
                    if (r) {
                        var renderer = r.renderer ||
                            window.DDSApp.ensureRenderer(docId);
                        DocumentLoader.loadDocument(
                            r.docId, r.fileName, page,
                            r.options, renderer
                        );
                    } else {
                        DocumentLoader.loadDocument(docId, fileName, page);
                    }
                });
            }
        },

        /**
         * Рендерит текст страницы документа.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Если текст пуст или ``null`` — отображение          |
         * |   | сообщения «Текст на этой странице не найден».       |
         * +---+-----------------------------------------------------+
         * | 2 | Иначе — установка ``textContent`` контейнера.       |
         * |   | Использование ``textContent`` вместо ``innerHTML``  |
         * |   | для предотвращения XSS.                             |
         * +---+-----------------------------------------------------+
         *
         * @param {Element} container — DOM-контейнер для текста.
         * @param {string|null} text — Текст страницы из API.
         */
        renderPageText: function (container, text) {
            if (!container) return;

            if (!text || text.trim() === "") {
                container.innerHTML =
                    '<div class="alert alert--info">' +
                    "Текст на этой странице не найден. " +
                    "Страница может содержать только изображения." +
                    "</div>";
                return;
            }

            // Использование textContent для предотвращения XSS
            container.textContent = text;
        }
    };

    /* ==============================================================
       3. Фабрика PageRenderer (per-tab)
       ============================================================== */

    /**
     * Создаёт объект ``PageRenderer`` для одной вкладки документа.
     *
     * Объект инкапсулирует per-tab состояние:
     * - ``_blobUrl`` — текущий blob URL отрисованного PNG-рендера.
     * - ``_zoom`` — текущий zoom (``0.25..4.0``). Всегда число;
     *   инициализируется ``1.0``.
     * - ``_fitWidthPending`` — флаг «нужно применить fit-width
     *   после загрузки изображения». Устанавливается в ``renderPage``
     *   при ``!self._userZoomed``.
     * - ``_userZoomed`` — ``true`` после первого ручного изменения
     *   zoom (через ``setZoom`` или ``Ctrl+колесо``).
     * - ``_container`` — внешний DOM-контейнер вкладки
     *   (``doc-text-{docId}``).
     * - ``_wrapper`` — обёртка ``.page-render-wrapper`` для ``<img>``
     *   и overlay.
     * - ``_overlay`` — слой подсветки.
     * - ``_img`` — ссылка на текущий ``<img>``.
     * - ``_scroll`` — ссылка на ``.page-render-container`` (для
     *   пересчёта fit-width в ``resetZoom``).
     * - ``_panMoveHandler``, ``_panUpHandler`` — сохранённые ссылки
     *   на обработчики панорамирования для снятия в ``cleanup``.
     * - ``_transformByPage`` — карта «номер страницы → флаг
     *   трансформации координат». Ключ — номер страницы (0-based),
     *   значение — ``true`` (трансформация применена) или ``false``
     *   (не применена). Отсутствие ключа означает, что для страницы
     *   ещё не было ответа сервера: трансформация определяется
     *   авто-диагностикой.
     *
     * Изоляция состояния:
     * Каждая вкладка получает собственный экземпляр ``PageRenderer``
     * (см. ``app.js::openDocumentTab``). Это гарантирует, что
     * открытие/закрытие нескольких документов не влияет на blob URL,
     * zoom и флаги трансформации друг друга.
     *
     * Защита от race condition:
     * Все асинхронные операции (запрос PNG, подсветка) принимают
     * параметр ``seq`` — значение счётчика ``AppState.openDocuments[i]._seq``
     * на момент запуска. После каждого ``await`` (в терминах Promise)
     * проверяется ``seq === window.DDSApp.getLoadSeq(docId)``.
     * Устаревшие ответы игнорируются.
     *
     * Публичный API для внешних модулей:
     * Метод ``refreshHighlights(pageNumber, terms)`` — единственный
     * публичный способ пересчитать подсветку страницы извне
     * (``app.js`` вызывает его при переключении чекбокса
     * «Ротация координат»). Он инкапсулирует инкремент ``_seq``
     * и вызов приватного ``_fetchAndApplyHighlights``. Остальные
     * методы ``_fetchAndApplyHighlights``, ``_applyHighlights``
     * остаются приватными.
     *
     * @param {string} docId — идентификатор документа.
     * @returns {Object} Объект с методами ``renderPage``, ``setZoom``,
     *   ``resetZoom``, ``releaseBlob``, ``refreshHighlights``,
     *   ``cleanup``, ``getZoom``, ``getTransformForPage``,
     *   ``setTransformForPage``.
     */
    function createPageRenderer(docId) {
        var self = {
            _docId: docId,
            _blobUrl: null,
            _zoom: 1.0,
            _fitWidthPending: false,
            _userZoomed: false,
            _container: null,
            _wrapper: null,
            _overlay: null,
            _img: null,
            _scroll: null,
            _panMoveHandler: null,
            _panUpHandler: null,
            _transformByPage: {},
        };

        /**
         * Возвращает текущий zoom (для диагностики и внешних запросов).
         *
         * @returns {number}
         */
        self.getZoom = function () {
            return self._zoom;
        };

        /**
         * Возвращает сохранённый флаг трансформации для страницы.
         *
         * @param {number} pageNumber — номер страницы (0-based).
         * @returns {boolean|undefined} — ``true``/``false``, если для
         *   страницы установлено явное значение; ``undefined``, если
         *   сервер ещё не отвечал и авто-диагностика не выполнялась.
         */
        self.getTransformForPage = function (pageNumber) {
            return self._transformByPage[pageNumber];
        };

        /**
         * Устанавливает флаг трансформации для страницы.
         *
         * Вызывается из обработчика изменения чекбокса «Ротация
         * координат» (см. ``app.js``) при ручном переключении
         * пользователем.
         *
         * @param {number} pageNumber — номер страницы (0-based).
         * @param {boolean} value — новое значение флага.
         */
        self.setTransformForPage = function (pageNumber, value) {
            self._transformByPage[pageNumber] = value;
        };

        /**
         * Публичное освобождение текущего blob URL.
         *
         * Используется вызывающим кодом (в частности,
         * ``DocumentLoader.loadDocument`` при переходе в текстовый
         * режим), чтобы явно освободить ресурс без запуска нового
         * рендера.
         */
        self.releaseBlob = function () {
            self._releaseBlob();
        };

        /**
         * Пересчитывает подсветку страницы (публичный метод).
         *
         * Инкрементирует счётчик загрузок вкладки (``_seq``) через
         * фасад ``window.DDSApp``, затем вызывает приватный
         * ``_fetchAndApplyHighlights`` с полученным ``seq``. Это
         * защищает от race condition при быстрой смене страницы
         * или режима просмотра.
         *
         * Единственная публичная точка пересчёта подсветки извне
         * (``app.js`` использует её при переключении чекбокса
         * «Ротация координат»). Прямой вызов
         * ``_fetchAndApplyHighlights`` из внешних модулей не
         * допускается: инкапсуляция деталей (инкремент ``_seq``)
         * обеспечена этим методом.
         *
         * Если ``window.DDSApp`` недоступен (например, из-за
         * нарушения порядка загрузки скриптов), метод не выполняет
         * действий и выводит предупреждение в консоль.
         *
         * @param {number} pageNumber — номер страницы (0-based).
         * @param {Array<string>} terms — термины для подсветки.
         */
        self.refreshHighlights = function (pageNumber, terms) {
            if (!window.DDSApp ||
                typeof window.DDSApp.incrementLoadSeq !== "function") {
                console.warn(
                    "refreshHighlights: window.DDSApp.incrementLoadSeq " +
                    "недоступен, пересчёт подсветки пропущен."
                );
                return;
            }
            var seq = window.DDSApp.incrementLoadSeq(docId);
            self._fetchAndApplyHighlights(pageNumber, terms, seq);
        };

        /**
         * Вычисляет значение zoom для fit-width: изображение
         * полностью помещается по ширине видимой области
         * скролл-контейнера.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Если ``naturalW <= 0`` — возврат ``1.0``.           |
         * +---+-----------------------------------------------------+
         * | 2 | Получение padding контейнера.                       |
         * +---+-----------------------------------------------------+
         * | 3 | ``availableW = clientWidth - padding``.             |
         * +---+-----------------------------------------------------+
         * | 4 | Если ``availableW <= 0`` — возврат ``1.0``.         |
         * +---+-----------------------------------------------------+
         * | 5 | ``fit = availableW / naturalW``.                    |
         * +---+-----------------------------------------------------+
         * | 6 | Ограничение сверху ``1.0`` — не увеличивать выше    |
         * |   | натурального размера.                               |
         * +---+-----------------------------------------------------+
         * | 7 | Ограничение диапазоном ``[0.25, 4.0]``.             |
         * +---+-----------------------------------------------------+
         *
         * @param {HTMLElement} scroll — ``.page-render-container``.
         * @param {HTMLImageElement} img — элемент изображения.
         * @returns {number} Значение zoom в диапазоне ``[0.25, 1.0]``.
         * @private
         */
        self._computeFitWidthZoom = function (scroll, img) {
            var naturalW = img.naturalWidth;
            if (naturalW <= 0) return 1.0;

            var cs = window.getComputedStyle(scroll);
            var padLeft = parseFloat(cs.paddingLeft) || 0;
            var padRight = parseFloat(cs.paddingRight) || 0;
            var availableW = scroll.clientWidth - padLeft - padRight;
            if (availableW <= 0) return 1.0;

            var fit = availableW / naturalW;
            if (fit > 1.0) fit = 1.0;
            return Math.max(0.25, Math.min(4.0, fit));
        };

        /**
         * Отрисовывает страницу в режиме рендера.
         *
         * Последовательность:
         * 1. Сброс ``_zoom`` в ``1.0`` и установка ``_fitWidthPending``,
         *    если пользователь ещё не менял zoom вручную. Это
         *    гарантирует, что при переключении страницы без ручного
         *    zoom fit-width применяется заново, а при ручном zoom
         *    сохраняется пользовательское значение.
         * 2. Освобождение предыдущего blob URL.
         * 3. Показ скелетона в контейнере.
         * 4. Синхронизация состояния чекбокса «Ротация координат»
         *    с per-page флагом текущей страницы.
         * 5. Fetch PNG (с защитой от race через ``seq``).
         * 6. Создание DOM-структуры: wrapper, img, overlay,
         *    scroll-container.
         * 7. Установка ``img.style.maxWidth = "100%"`` и
         *    ``img.style.height = "auto"`` — защита от flash
         *    гигантского изображения до применения fit-width.
         * 8. Планирование fit-width (при ``img.complete`` — сразу;
         *    иначе — по событию ``load``).
         * 9. Навешивание обработчиков zoom и panning.
         * 10. Опциональный fetch подсветки.
         *
         * @param {number} pageNumber — номер страницы (0-based).
         * @param {Object} options — параметры вкладки
         *   (``{termsByPage: {pageNumber: [terms]}}``).
         * @param {number} seq — значение счётчика загрузок вкладки
         *   на момент запуска.
         */
        self.renderPage = function (pageNumber, options, seq) {
            // При смене страницы без ручного zoom — сбросить zoom
            // и запланировать пересчёт fit-width для новой страницы.
            if (!self._userZoomed) {
                self._zoom = 1.0;
                self._fitWidthPending = true;
            }

            self._releaseBlob();

            var container = document.getElementById("doc-text-" + docId);
            if (!container) return;
            self._container = container;
            container.innerHTML = '<div class="page-render-skeleton"></div>';

            // Синхронизация чекбокса «Ротация координат» с per-page
            // состоянием до запроса подсветки. Чекбокс создаётся
            // в app.js::openDocumentTab.
            _updateTransformCheckboxState(docId, pageNumber, options);

            var url = "/api/documents/" + encodeURIComponent(docId) +
                "/pages/" + pageNumber + "/render?dpi=300";

            fetch(url)
                .then(function (response) {
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return null;
                    if (!response.ok) {
                        var err = new Error("render_error");
                        err.status = response.status;
                        throw err;
                    }
                    return response.blob();
                })
                .then(function (blob) {
                    if (blob === null) return;
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return;

                    self._blobUrl = URL.createObjectURL(blob);

                    var rec = window.DDSApp.getDocumentRecord(docId);
                    var fname = rec ? rec.fileName : docId;

                    var wrapper = document.createElement("div");
                    wrapper.className = "page-render-wrapper";

                    var img = document.createElement("img");
                    img.className = "page-render-image";
                    img.src = self._blobUrl;
                    img.alt = "Страница " + (pageNumber + 1) +
                        " документа " + fname;
                    // Асинхронное декодирование: большие PNG (A0 @ 300 dpi)
                    // не блокируют главный поток браузера при декодировании.
                    img.decoding = "async";
                    // Защита от flash гигантского изображения до применения
                    // fit-width. Снимается в _applyZoom.
                    img.style.maxWidth = "100%";
                    img.style.height = "auto";

                    var overlay = document.createElement("div");
                    overlay.className = "page-render-overlay";

                    wrapper.appendChild(img);
                    wrapper.appendChild(overlay);

                    var scroll = document.createElement("div");
                    scroll.className = "page-render-container";
                    scroll.tabIndex = 0;
                    scroll.appendChild(wrapper);

                    container.innerHTML = "";
                    container.appendChild(scroll);

                    self._img = img;
                    self._wrapper = wrapper;
                    self._overlay = overlay;
                    self._scroll = scroll;

                    // Планирование fit-width.
                    var applyInitialZoomOnce = function () {
                        if (self._userZoomed) return;
                        if (!self._fitWidthPending) return;
                        if (img.naturalWidth <= 0) return;
                        self._zoom = self._computeFitWidthZoom(scroll, img);
                        self._fitWidthPending = false;
                        self._applyZoom();
                    };

                    if (img.complete && img.naturalWidth > 0) {
                        // Изображение уже декодировано (редкий случай для
                        // blob URL, но защищаемся).
                        applyInitialZoomOnce();
                    } else {
                        img.addEventListener(
                            "load", applyInitialZoomOnce, { once: true }
                        );
                    }

                    self._installWheelHandler(scroll);
                    self._installPanHandler(scroll);

                    var terms = (options && options.termsByPage &&
                        options.termsByPage[pageNumber]) || [];
                    if (terms.length > 0) {
                        self._fetchAndApplyHighlights(pageNumber, terms, seq);
                    }
                })
                .catch(function (error) {
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return;
                    if (error.status === 500 || error.status === 504) {
                        self._fallbackToText(pageNumber, seq);
                    } else {
                        container.innerHTML =
                            '<div class="alert alert--error">' +
                            "Не удалось отрисовать страницу." +
                            "</div>";
                    }
                });
        };

        /**
         * Загружает подсветку и применяет её к overlay.
         *
         * Формирует тело запроса, включая опциональное поле
         * ``apply_transform`` на основе per-page флага трансформации:
         *
         * - Если для страницы установлено явное значение
         *   (``self._transformByPage[pageNumber]`` — boolean),
         *   оно передаётся как ``apply_transform``.
         * - Если значение не установлено (сервер ещё не отвечал),
         *   поле не передаётся — сервер выполнит авто-диагностику.
         *
         * После получения ответа:
         * - Сохраняет фактическое значение ``data.applied_transform``
         *   в ``self._transformByPage[pageNumber]``.
         * - Синхронизирует чекбокс «Ротация координат» с фактическим
         *   состоянием и уровнем уверенности.
         * - Применяет прямоугольники подсветки к overlay.
         *
         * Примечание:
         *     Метод приватный. Для вызова из внешних модулей
         *     (например, ``app.js``) следует использовать публичный
         *     ``refreshHighlights(pageNumber, terms)``, который
         *     инкрементирует ``_seq`` и предотвращает race condition.
         *
         * @param {number} pageNumber — номер страницы.
         * @param {Array<string>} terms — термины для поиска.
         * @param {number} seq — текущий счётчик загрузок.
         * @private
         */
        self._fetchAndApplyHighlights = function (pageNumber, terms, seq) {
            var body = { terms: terms };
            var saved = self._transformByPage[pageNumber];
            if (typeof saved === "boolean") {
                body.apply_transform = saved;
            }

            fetch(
                "/api/documents/" + encodeURIComponent(docId) +
                "/pages/" + pageNumber + "/highlights",
                {
                    method: "POST",
                    headers: { "Content-Type": "application/json" },
                    body: JSON.stringify(body),
                }
            )
                .then(function (r) {
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return null;
                    if (!r.ok) return null;
                    return r.json();
                })
                .then(function (data) {
                    if (data === null) return;
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return;

                    // Сохраняем фактическое значение трансформации
                    // для страницы (для последующих запросов и
                    // переключения режима).
                    self._transformByPage[pageNumber] = data.applied_transform;

                    // Синхронизируем чекбокс с фактическим состоянием.
                    _syncTransformCheckbox(
                        docId,
                        pageNumber,
                        seq,
                        data.applied_transform,
                        data.transform_confidence
                    );

                    self._applyHighlights(data.highlights || []);
                })
                .catch(function (err) {
                    console.warn("Highlights fetch failed:", err);
                });
        };

        /**
         * Применяет список прямоугольников подсветки к overlay.
         *
         * @param {Array<Object>} highlights — массив
         *   ``{x, y, w, h, term}`` в нормализованных координатах.
         * @private
         */
        self._applyHighlights = function (highlights) {
            if (!self._overlay) return;
            self._overlay.innerHTML = "";
            for (var i = 0; i < highlights.length; i++) {
                var h = highlights[i];
                var div = document.createElement("div");
                div.className = "page-render-highlight";
                div.style.left = (h.x * 100).toFixed(4) + "%";
                div.style.top = (h.y * 100).toFixed(4) + "%";
                div.style.width = (h.w * 100).toFixed(4) + "%";
                div.style.height = (h.h * 100).toFixed(4) + "%";
                if (h.term) div.title = h.term;
                self._overlay.appendChild(div);
            }
        };

        /**
         * Устанавливает обработчик ``wheel`` для zoom через
         * ``Ctrl + колесо``.
         *
         * Опция ``{passive: false}`` обязательна: без неё
         * ``e.preventDefault()`` не остановит нативный browser zoom.
         *
         * @param {HTMLElement} scroll — контейнер прокрутки рендера.
         * @private
         */
        self._installWheelHandler = function (scroll) {
            scroll.addEventListener("wheel", function (e) {
                if (!e.ctrlKey) return;
                e.preventDefault();
                var delta = e.deltaY > 0 ? -0.1 : 0.1;
                self.setZoom(self._zoom + delta);
            }, { passive: false });
        };

        /**
         * Устанавливает обработчики панорамирования правой кнопкой
         * мыши.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | ``contextmenu`` на ``scroll`` — подавляет системное |
         * |   | контекстное меню на области рендера.                |
         * +---+-----------------------------------------------------+
         * | 2 | ``mousedown`` (button === 2) — старт drag;          |
         * |   | сохранение начальных координат и позиции скролла;   |
         * |   | добавление ``.is-panning``; подписка на             |
         * |   | ``mousemove``/``mouseup`` на ``document``.          |
         * +---+-----------------------------------------------------+
         * | 3 | ``mousemove`` — обновление ``scrollLeft``/          |
         * |   | ``scrollTop`` инкрементально относительно           |
         * |   | начальной позиции.                                  |
         * +---+-----------------------------------------------------+
         * | 4 | ``mouseup`` (button === 2) — завершение drag;       |
         * |   | снятие класса и слушателей.                         |
         * +---+-----------------------------------------------------+
         *
         * Слушатели ``mousemove``/``mouseup`` навешиваются на
         * ``document``, чтобы панорамирование продолжалось при
         * выходе курсора за пределы контейнера. Ссылки на функции
         * сохраняются в ``self._panMoveHandler`` и
         * ``self._panUpHandler`` для снятия в ``cleanup``.
         *
         * @param {HTMLElement} scroll — контейнер прокрутки рендера.
         * @private
         */
        self._installPanHandler = function (scroll) {
            var isPanning = false;
            var startX = 0;
            var startY = 0;
            var startScrollLeft = 0;
            var startScrollTop = 0;

            var onMouseMove = function (e) {
                if (!isPanning) return;
                var dx = e.clientX - startX;
                var dy = e.clientY - startY;
                scroll.scrollLeft = startScrollLeft - dx;
                scroll.scrollTop = startScrollTop - dy;
            };

            var onMouseUp = function (e) {
                if (e.button !== 2) return;
                if (!isPanning) return;
                isPanning = false;
                scroll.classList.remove("is-panning");
                document.removeEventListener("mousemove", onMouseMove);
                document.removeEventListener("mouseup", onMouseUp);
            };

            // Подавление системного контекстного меню на рендере.
            scroll.addEventListener("contextmenu", function (e) {
                e.preventDefault();
            });

            scroll.addEventListener("mousedown", function (e) {
                if (e.button !== 2) return;   // только правая кнопка
                e.preventDefault();
                isPanning = true;
                startX = e.clientX;
                startY = e.clientY;
                startScrollLeft = scroll.scrollLeft;
                startScrollTop = scroll.scrollTop;
                scroll.classList.add("is-panning");
                document.addEventListener("mousemove", onMouseMove);
                document.addEventListener("mouseup", onMouseUp);
            });

            // Сохраняем ссылки для снятия в cleanup.
            self._panMoveHandler = onMouseMove;
            self._panUpHandler = onMouseUp;
        };

        /**
         * Устанавливает zoom в допустимом диапазоне ``[0.25, 4.0]``
         * и применяет размеры к изображению.
         *
         * Флаг ``_userZoomed`` выставляется в ``true`` — после
         * первого ручного изменения автоматический fit-width
         * больше не применяется для текущей вкладки.
         *
         * @param {number} value — новое значение zoom.
         */
        self.setZoom = function (value) {
            self._userZoomed = true;
            self._fitWidthPending = false;
            self._zoom = Math.max(0.25, Math.min(4.0, value));
            self._applyZoom();
        };

        /**
         * Сбрасывает zoom.
         *
         * Если пользователь ещё не менял zoom вручную
         * (``_userZoomed === false``), применяется fit-width:
         * zoom пересчитывается для текущего изображения и
         * скролл-контейнера. Иначе — сброс к ``1.0`` через
         * ``setZoom``.
         *
         * Примечание:
         * В текстовом режиме (``viewMode === "text"``) вызов не
         * производит видимых изменений: сохранённая ссылка
         * ``_scroll`` может указывать на отсоединённый контейнер,
         * ``clientWidth`` которого равен ``0``. Функция в этом
         * случае сходится к ``_zoom = 1.0`` без визуального
         * эффекта. Это ожидаемое поведение — масштабирование
         * применяется только в режиме рендера.
         */
        self.resetZoom = function () {
            if (!self._userZoomed) {
                if (!self._img || !self._scroll) return;
                self._zoom = self._computeFitWidthZoom(
                    self._scroll, self._img
                );
                self._fitWidthPending = false;
                self._applyZoom();
                return;
            }
            self.setZoom(1.0);
        };

        /**
         * Применяет текущий zoom к изображению через явные
         * пиксельные размеры.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Guard: нет ``_img`` или ``_wrapper`` → выход.       |
         * +---+-----------------------------------------------------+
         * | 2 | Guard: ``_zoom`` не конечное число → выход.         |
         * +---+-----------------------------------------------------+
         * | 3 | Чтение ``naturalWidth``/``naturalHeight``.          |
         * |   | Если любое из них ``<= 0`` → выход.                 |
         * +---+-----------------------------------------------------+
         * | 4 | Сброс ``style.maxWidth`` в ``"none"`` — снимает     |
         * |   | защитное ограничение, установленное при создании    |
         * |   | ``<img>`` (использовалось для защиты от flash).     |
         * +---+-----------------------------------------------------+
         * | 5 | Установка ``style.width`` и ``style.height``        |
         * |   | в пикселях: ``natural * _zoom``.                    |
         * +---+-----------------------------------------------------+
         *
         * Примечание:
         * Размеры задаются явно на ``<img>``, а не через
         * ``transform: scale``. Это синхронизирует layout
         * контейнера с визуальным отображением: wrapper
         * (``display: inline-block``) принимает размеры img,
         * overlay (``position: absolute; inset: 0``) растягивается
         * по wrapper, скроллбар пересчитывается корректно.
         *
         * @private
         */
        self._applyZoom = function () {
            if (!self._img || !self._wrapper) return;
            if (!isFinite(self._zoom)) return;
            var naturalW = self._img.naturalWidth;
            var naturalH = self._img.naturalHeight;
            if (naturalW <= 0 || naturalH <= 0) return;

            self._img.style.maxWidth = "none";
            self._img.style.width = (naturalW * self._zoom) + "px";
            self._img.style.height = (naturalH * self._zoom) + "px";
        };

        /**
         * Освобождает текущий blob URL, если он существует.
         * @private
         */
        self._releaseBlob = function () {
            if (self._blobUrl) {
                URL.revokeObjectURL(self._blobUrl);
                self._blobUrl = null;
            }
        };

        /**
         * Переключает вкладку в текстовый режим.
         *
         * Вызывается из ``renderPage`` при получении HTTP 500 или
         * 504. Освобождает blob URL, загружает текстовый слой и
         * обновляет UI переключателя режимов. Значение режима
         * **не** сохраняется в ``localStorage``.
         *
         * Ранний выход при закрытой вкладке:
         * Если пользователь закрыл вкладку до того, как рендер
         * завершился (или упал), ``self._container`` будет ``null``.
         * В этом случае вызов ``_loadPageText`` бессмысленен и
         * приводит к тихому no-op. Явный ранний выход делает
         * это поведение очевидным.
         *
         * Обновление UI делегируется публичному методу
         * ``ViewModeManager.applyTextFallbackState(docId)``, который
         * инкапсулирует переключение активной кнопки и блокировку
         * кнопки «Рендер».
         *
         * @param {number} pageNumber — номер страницы.
         * @param {number} seq — текущий счётчик загрузок.
         * @private
         */
        self._fallbackToText = function (pageNumber, seq) {
            // Вкладка закрыта — нечего отрисовывать.
            if (!self._container) return;

            self._releaseBlob();
            DocumentLoader._loadPageText(
                docId, pageNumber, self._container, seq
            );
            ViewModeManager.setMode(docId, "text", { persist: false });
            ViewModeManager.applyTextFallbackState(docId);
        };

        /**
         * Освобождает все ресурсы renderer. Вызывается при
         * закрытии вкладки (``app.js::closeDocumentTab``).
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Освобождение blob URL.                              |
         * +---+-----------------------------------------------------+
         * | 2 | Снятие обработчиков ``mousemove``/``mouseup`` с     |
         * |   | ``document`` (если drag был активен в момент       |
         * |   | закрытия вкладки).                                  |
         * +---+-----------------------------------------------------+
         * | 3 | Обнуление ссылок на DOM-элементы.                   |
         * +---+-----------------------------------------------------+
         * | 4 | Обнуление карты ``_transformByPage``.               |
         * +---+-----------------------------------------------------+
         *
         * Примечание:
         * Сброс числовых полей (``_zoom``, ``_fitWidthPending``,
         * ``_userZoomed``) не производится: renderer удаляется из
         * ``AppState`` сразу после ``cleanup``, и объект становится
         * недостижимым. Обнуление ``_transformByPage`` — симметричная
         * операция: если renderer по какой-то причине переиспользуется,
         * карта трансформаций не должна сохранять устаревшие флаги.
         */
        self.cleanup = function () {
            self._releaseBlob();

            if (self._panMoveHandler) {
                document.removeEventListener("mousemove", self._panMoveHandler);
                self._panMoveHandler = null;
            }
            if (self._panUpHandler) {
                document.removeEventListener("mouseup", self._panUpHandler);
                self._panUpHandler = null;
            }

            self._container = null;
            self._wrapper = null;
            self._overlay = null;
            self._img = null;
            self._scroll = null;
            self._transformByPage = {};
        };

        return self;
    }

    /* ==============================================================
       4. Синхронизация чекбокса «Ротация координат»
       ============================================================== */

    /**
     * Синхронизирует визуальное состояние чекбокса «Ротация координат»
     * с per-page флагом трансформации.
     *
     * Вызывается в ``renderPage`` **до** запроса подсветки. Это
     * гарантирует, что при переходе на новую страницу чекбокс:
     *
     * - отражает сохранённое значение ``_transformByPage[page]``,
     *   если оно установлено (пользователь уже переключал или
     *   сервер отвечал ранее);
     * - сброшен в состояние «Определяется…» (``disabled``), если
     *   значение ещё не установлено;
     * - отключён (``disabled``), если у страницы нет терминов для
     *   подсветки — в этом случае запрос ``/highlights`` не будет
     *   отправлен.
     *
     * Операции:
     * +----+----------------------------------------------------+
     * | №  | Описание                                           |
     * +====+====================================================+
     * | 1  | Поиск чекбокса по id ``doc-transform-{docId}``.    |
     * |    | Если не найден — выход.                            |
     * +----+----------------------------------------------------+
     * | 2  | Получение списка терминов для страницы через       |
     * |    | ``options.termsByPage[pageNumber]``.               |
     * +----+----------------------------------------------------+
     * | 3  | Если терминов нет:                                 |
     * |    | a. ``disabled = true``, ``checked = false``;       |
     * |    | b. ``title`` — пояснение;                          |
     * |    | c. выход.                                          |
     * +----+----------------------------------------------------+
     * | 4  | Получение сохранённого значения через              |
     * |    | ``renderer.getTransformForPage(pageNumber)``.      |
     * +----+----------------------------------------------------+
     * | 5  | Если значение — boolean:                           |
     * |    | a. ``checked = saved``, ``disabled = false``;      |
     * |    | b. ``title`` — «Ручное управление».                |
     * +----+----------------------------------------------------+
     * | 6  | Иначе (сервер ещё не отвечал):                     |
     * |    | a. ``checked = false``, ``disabled = true``;       |
     * |    | b. ``title`` — «Определяется…».                    |
     * +----+----------------------------------------------------+
     *
     * @param {string} docId — идентификатор документа.
     * @param {number} pageNumber — номер страницы (0-based).
     * @param {Object} options — параметры вкладки
     *   (``{termsByPage: {pageNumber: [terms]}}``).
     * @private
     */
    function _updateTransformCheckboxState(docId, pageNumber, options) {
        var cb = document.getElementById("doc-transform-" + docId);
        if (!cb) return;

        var terms = (options && options.termsByPage &&
            options.termsByPage[pageNumber]) || [];
        if (terms.length === 0) {
            cb.disabled = true;
            cb.checked = false;
            cb.title = "Подсветка не запрашивалась для этой страницы — нет совпадений.";
            return;
        }

        var rec = window.DDSApp.getDocumentRecord(docId);
        var saved = rec && rec.renderer &&
            rec.renderer.getTransformForPage(pageNumber);

        if (typeof saved === "boolean") {
            cb.checked = saved;
            cb.disabled = false;
            cb.title = "Ручное управление коррекцией координат.";
        } else {
            cb.checked = false;
            cb.disabled = true;
            cb.title = "Определяется…";
        }
    }

    /**
     * Синхронизирует чекбокс «Ротация координат» с фактическим
     * состоянием, возвращённым сервером в ответе ``/highlights``.
     *
     * Вызывается из ``PageRenderer._fetchAndApplyHighlights`` после
     * получения ответа. Устанавливает флаг и уровень уверенности,
     * а также формирует всплывающую подсказку с пояснением.
     *
     * Операции:
     * +----+----------------------------------------------------+
     * | №  | Описание                                           |
     * +====+====================================================+
     * | 1  | Проверка актуальности ``seq``: если счётчик         |
     * |    | изменился — ответ устарел, выход.                   |
     * +----+----------------------------------------------------+
     * | 2  | Проверка, что ответ относится к текущей странице    |
     * |    | вкладки (``rec.page === pageNumber``). Если нет —   |
     * |    | выход.                                              |
     * +----+----------------------------------------------------+
     * | 3  | Поиск чекбокса по id. Если не найден — выход.       |
     * +----+----------------------------------------------------+
     * | 4  | Установка ``disabled = false`` и                    |
     * |    | ``checked = !!applied``.                            |
     * +----+----------------------------------------------------+
     * | 5  | Установка ``title`` в зависимости от ``confidence``:|
     * |    | a. ``"high"`` — высокая уверенность;                |
     * |    | b. ``"medium"`` — средняя уверенность;              |
     * |    | c. ``"manual"`` — ручное управление;                |
     * |    | d. иначе — аномалия не обнаружена.                  |
     * +----+----------------------------------------------------+
     *
     * @param {string} docId — идентификатор документа.
     * @param {number} pageNumber — номер страницы (0-based).
     * @param {number} seq — значение счётчика загрузок на момент
     *   отправки запроса.
     * @param {boolean} applied — фактически применённая трансформация.
     * @param {string} confidence — уровень уверенности диагностики
     *   (``"high"`` / ``"medium"`` / ``"none"`` / ``"manual"``).
     * @private
     */
    function _syncTransformCheckbox(docId, pageNumber, seq, applied, confidence) {
        // Проверка актуальности seq.
        if (seq !== window.DDSApp.getLoadSeq(docId)) return;

        // Проверка, что ответ относится к текущей странице.
        var rec = window.DDSApp.getDocumentRecord(docId);
        if (rec && rec.page !== pageNumber) return;

        var cb = document.getElementById("doc-transform-" + docId);
        if (!cb) return;

        cb.disabled = false;
        cb.checked = !!applied;

        if (confidence === "high") {
            cb.title = "Аномалия системы координат (высокая уверенность). " +
                "Коррекция включена автоматически.";
        } else if (confidence === "medium") {
            cb.title = "Возможна аномалия системы координат (средняя уверенность). " +
                "Коррекция включена; при необходимости снимите галочку.";
        } else if (confidence === "manual") {
            cb.title = "Ручное управление коррекцией координат.";
        } else {
            cb.title = "Аномалия системы координат не обнаружена.";
        }
    }

    /* ==============================================================
       5. Управление режимом просмотра (рендер ↔ текст)
       ============================================================== */

    /**
     * Менеджер режима просмотра документа.
     *
     * Режимы:
     * - ``"render"`` — растровый рендер страницы с подсветкой.
     * - ``"text"`` — текстовый слой страницы.
     *
     * Per-tab состояние режима хранится в
     * ``AppState.openDocuments[i].viewMode`` (доступ через
     * ``window.DDSApp``). Глобальный дефолт для новых вкладок — в
     * ``localStorage`` под ключом ``dds-doc-view-mode``.
     *
     * Переключатель UI:
     * Каждая вкладка документа содержит контейнер
     * ``#doc-view-switch-{docId}``, в который через
     * ``installSwitcher`` вставляются кнопки «Рендер» и «Текст».
     * Активная кнопка помечается классом ``active``, заблокированная
     * (после fallback) — атрибутом ``disabled`` и классом
     * ``page-render-switch-disabled``.
     *
     * Публичный API для внешних модулей:
     * ``applyTextFallbackState(docId)`` — применяет состояние
     * fallback: активна кнопка «Текст», кнопка «Рендер»
     * заблокирована. Инкапсулирует вызов приватного ``_setActive``
     * и установку ``disabled`` на кнопку «Рендер». Вызывается из
     * ``PageRenderer._fallbackToText``.
     *
     * Операции:
     * +----------------------------------+----------------------------------+
     * | Метод                            | Описание                         |
     * +==================================+==================================+
     * | ``getDefault()``                 | Дефолт из localStorage.          |
     * +----------------------------------+----------------------------------+
     * | ``getMode(docId)``               | Режим активной вкладки.          |
     * +----------------------------------+----------------------------------+
     * | ``setMode(docId, mode, opts)``   | Установка режима.                |
     * +----------------------------------+----------------------------------+
     * | ``installSwitcher(el, docId)``   | Рендеринг переключателя.         |
     * +----------------------------------+----------------------------------+
     * | ``applyTextFallbackState(docId)``| Fallback-состояние UI (публичный).|
     * +----------------------------------+----------------------------------+
     * | ``_setActive(el, mode)``         | Активная кнопка (приватный).     |
     * +----------------------------------+----------------------------------+
     */
    var ViewModeManager = {

        _KEY: "dds-doc-view-mode",

        /**
         * Возвращает дефолтный режим из ``localStorage``.
         *
         * Если значение отсутствует или невалидно — возвращает
         * ``"render"``.
         *
         * @returns {string} — ``"render"`` или ``"text"``.
         */
        getDefault: function () {
            try {
                var v = window.localStorage.getItem(this._KEY);
                return v === "text" ? "text" : "render";
            } catch (e) {
                return "render";
            }
        },

        /**
         * Возвращает режим для указанной вкладки.
         *
         * @param {string} docId — идентификатор документа.
         * @returns {string} — текущий режим.
         */
        getMode: function (docId) {
            var rec = window.DDSApp.getDocumentRecord(docId);
            return rec ? (rec.viewMode || "render") : this.getDefault();
        },

        /**
         * Устанавливает режим для указанной вкладки.
         *
         * @param {string} docId — идентификатор документа.
         * @param {string} mode — ``"render"`` или ``"text"``.
         * @param {Object} [opts] — параметры:
         *   - ``persist`` — если ``false``, значение не сохраняется
         *     в ``localStorage``. Используется при fallback на текст
         *     из-за недоступности рендера (не портит глобальный
         *     дефолт для будущих вкладок).
         */
        setMode: function (docId, mode, opts) {
            opts = opts || {};
            if (mode !== "render" && mode !== "text") return;
            window.DDSApp.updateDocumentRecord(docId, { viewMode: mode });
            if (opts.persist !== false) {
                try {
                    window.localStorage.setItem(this._KEY, mode);
                } catch (e) { /* ignore */ }
            }
        },

        /**
         * Создаёт и вставляет переключатель режимов в указанный
         * контейнер.
         *
         * Обработчик клика по кнопке:
         * 1. Проверяет, что кнопка не заблокирована и режим отличается
         *    от текущего.
         * 2. Устанавливает новый режим через ``setMode``.
         * 3. Обновляет активный класс.
         * 4. Перезагружает страницу в новом режиме через
         *    ``DocumentLoader.loadDocument`` с сохранением renderer
         *    и options.
         *
         * @param {HTMLElement} panelElement — контейнер для переключателя.
         * @param {string} docId — идентификатор документа.
         */
        installSwitcher: function (panelElement, docId) {
            var self = this;
            var switchEl = document.createElement("div");
            switchEl.className = "page-view-switch";
            switchEl.innerHTML =
                '<button type="button" data-view-mode="render">Рендер</button>' +
                '<button type="button" data-view-mode="text">Текст</button>';
            panelElement.insertBefore(switchEl, panelElement.firstChild);

            self._setActive(switchEl, self.getMode(docId));

            switchEl.addEventListener("click", function (e) {
                var btn = e.target.closest("[data-view-mode]");
                if (!btn || btn.disabled) return;
                var mode = btn.dataset.viewMode;
                if (mode === self.getMode(docId)) return;

                self.setMode(docId, mode);
                self._setActive(switchEl, mode);

                var rec = window.DDSApp.getDocumentRecord(docId);
                if (!rec) return;
                DocumentLoader.loadDocument(
                    rec.docId, rec.fileName, rec.page,
                    rec.options, rec.renderer
                );
            });
        },

        /**
         * Применяет fallback-состояние UI: активна кнопка «Текст»,
         * кнопка «Рендер» заблокирована.
         *
         * Публичный метод. Вызывается из
         * ``PageRenderer._fallbackToText`` при получении HTTP 500
         * или 504 от ``/render``. Инкапсулирует детали:
         *
         * 1. Поиск панели и переключателя.
         * 2. Установку активной кнопки «Текст» через ``_setActive``.
         * 3. Установку ``disabled`` и класса
         *    ``page-render-switch-disabled`` на кнопку «Рендер».
         *
         * Замена прямого вызова ``_setActive`` и ручной установки
         * ``disabled`` из ``document.js::_fallbackToText`` на этот
         * публичный метод устраняет нарушение инкапсуляции.
         *
         * Если панель или переключатель не найдены (например,
         * вкладка уже закрыта), метод не выполняет действий.
         *
         * @param {string} docId — идентификатор документа.
         */
        applyTextFallbackState: function (docId) {
            var panel = document.querySelector(
                '[data-panel-id="doc-' + docId + '"]'
            );
            if (!panel) return;
            var sw = panel.querySelector(".page-view-switch");
            if (!sw) return;
            this._setActive(sw, "text");
            var rb = sw.querySelector('[data-view-mode="render"]');
            if (rb) {
                rb.disabled = true;
                rb.classList.add("page-render-switch-disabled");
            }
        },

        /**
         * Обновляет активное состояние кнопок переключателя.
         *
         * @param {HTMLElement} switchEl — контейнер переключателя.
         * @param {string} mode — активный режим.
         * @private
         */
        _setActive: function (switchEl, mode) {
            var buttons = switchEl.querySelectorAll("[data-view-mode]");
            for (var i = 0; i < buttons.length; i++) {
                var b = buttons[i];
                b.classList.toggle("active", b.dataset.viewMode === mode);
            }
        },
    };

    /* ==============================================================
       6. Загрузка данных документа
       ============================================================== */

    /**
     * Загрузчик данных документа.
     *
     * Загружает метаданные и содержимое страницы документа через
     * REST API и рендерит содержимое во вкладке документа. Режим
     * рендеринга определяется ``ViewModeManager.getMode(docId)``.
     *
     * Координация асинхронных операций:
     * При каждом вызове ``loadDocument`` инкрементируется счётчик
     * ``AppState.openDocuments[i]._seq``. Все асинхронные операции
     * внутри загрузки проверяют актуальность счётчика после каждого
     * Promise — если счётчик изменился (запущена новая загрузка),
     * ответ игнорируется.
     *
     * Окно ``pageCount === undefined``:
     * Между первым и вторым вызовом ``updateDocumentRecord``
     * в ``loadDocument`` есть окно (~100–500 мс), когда
     * ``rec.pageCount`` ещё не установлен. Если в этом окне
     * пользователь кликнет по чекбоксу «Навигация по всем страницам»,
     * ``refreshNavigation`` тихо выйдет (нет ``pageCount``).
     * Навигация отрисуется автоматически по завершении
     * ``loadDocument`` с актуальным значением ``navAllPages``.
     *
     * Операции:
     * +----------------------------------+----------------------------------+
     * | Метод                            | Описание                         |
     * +==================================+==================================+
     * | ``loadDocument(docId, fileName,  | Загрузка метаданных и содержимого|
     * | pageNumber, options, renderer)`` | страницы, рендеринг.             |
     * +----------------------------------+----------------------------------+
     * | ``_loadPageText(docId, pageNumber,| Загрузка текста страницы и его  |
     * | textContainer, seq)``            | рендеринг.                       |
     * +----------------------------------+----------------------------------+
     * | ``refreshNavigation(docId)``     | Перерисовка пагинации без        |
     * |                                  | перезагрузки содержимого.        |
     * +----------------------------------+----------------------------------+
     */
    var DocumentLoader = {

        /**
         * Загружает данные документа через API.
         *
         * Последовательность:
         * 1. Инкремент счётчика загрузок вкладки.
         * 2. Обновление записи вкладки (page, options, renderer).
         * 3. Запрос метаданных.
         * 4. Установка ``pageCount`` в записи вкладки.
         * 5. Рендеринг метаданных.
         * 6. Рендеринг содержимого в зависимости от режима
         *    (``renderer.renderPage`` или ``_loadPageText``).
         * 7. Рендеринг навигации.
         *
         * @param {string} docId — Идентификатор документа.
         * @param {string} fileName — Отображаемое имя файла.
         * @param {number} pageNumber — Номер страницы (0-based).
         * @param {Object} [options] — параметры вкладки
         *   (``{termsByPage: {...}}``).
         * @param {Object} [renderer] — существующий ``PageRenderer``
         *   вкладки. Если не передан — создаётся через
         *   ``window.createPageRenderer(docId)``.
         */
        loadDocument: function (docId, fileName, pageNumber, options, renderer) {
            options = options || {};
            renderer = renderer ||
                window.DDSApp.ensureRenderer(docId) ||
                window.createPageRenderer(docId);

            var metaContainer = document.getElementById("doc-meta-" + docId);
            var navContainer = document.getElementById("doc-nav-" + docId);
            var textContainer = document.getElementById("doc-text-" + docId);

            // Инкремент счётчика загрузок для защиты от race.
            var seq = window.DDSApp.incrementLoadSeq(docId);

            window.DDSApp.updateDocumentRecord(docId, {
                page: pageNumber,
                options: options,
                renderer: renderer,
            });

            fetch("/api/documents/" + encodeURIComponent(docId))
                .then(function (r) {
                    if (!r.ok) throw new Error("Документ не найден");
                    return r.json();
                })
                .then(function (doc) {
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return;

                    // Сохраняем pageCount для refreshNavigation.
                    window.DDSApp.updateDocumentRecord(docId, {
                        pageCount: doc.page_count,
                    });

                    DocumentRenderer.renderMetadata(metaContainer, doc);

                    var viewMode = ViewModeManager.getMode(docId);
                    if (viewMode === "render") {
                        renderer.renderPage(pageNumber, options, seq);
                    } else {
                        // Освобождаем blob URL от предыдущего рендера,
                        // если он был: при переключении render → text
                        // blob остаётся в памяти до следующего рендера.
                        if (renderer && typeof renderer.releaseBlob === "function") {
                            renderer.releaseBlob();
                        }
                        DocumentLoader._loadPageText(
                            docId, pageNumber, textContainer, seq
                        );
                    }

                    DocumentRenderer.renderPageNavigation(
                        navContainer, docId, fileName, pageNumber, doc.page_count
                    );
                })
                .catch(function (error) {
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return;
                    if (textContainer) {
                        textContainer.innerHTML =
                            '<div class="alert alert--error">' +
                            "Ошибка загрузки: " +
                            DocumentUtils.escapeHtml(error.message) +
                            "</div>";
                    }
                });
        },

        /**
         * Перерисовывает пагинацию вкладки без перезагрузки
         * содержимого страницы.
         *
         * Вызывается из ``app.js`` при изменении чекбокса
         * «Навигация по всем страницам». Использует ``pageCount``
         * из записи вкладки; если ``pageCount`` ещё не установлен
         * (метаданные в полёте), метод выходит без ошибок —
         * навигация отрисуется автоматически по завершении
         * ``loadDocument``.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Получение записи вкладки. Если нет — выход.         |
         * +---+-----------------------------------------------------+
         * | 2 | Проверка ``rec.pageCount``. Если не задан или       |
         * |   | ``<= 0`` — выход.                                   |
         * +---+-----------------------------------------------------+
         * | 3 | Получение контейнера ``doc-nav-{docId}``. Если нет  |
         * |   | — выход.                                            |
         * +---+-----------------------------------------------------+
         * | 4 | Вызов ``DocumentRenderer.renderPageNavigation``.    |
         * +---+-----------------------------------------------------+
         *
         * Примечание:
         * Метод публичный — вызывается из ``app.js`` (обработчик
         * чекбокса). Не имеет префикса ``_``.
         *
         * @param {string} docId — Идентификатор документа.
         */
        refreshNavigation: function (docId) {
            var rec = window.DDSApp.getDocumentRecord(docId);
            if (!rec) return;
            if (!rec.pageCount || rec.pageCount <= 0) return;

            var navContainer = document.getElementById("doc-nav-" + docId);
            if (!navContainer) return;

            DocumentRenderer.renderPageNavigation(
                navContainer, docId, rec.fileName, rec.page, rec.pageCount
            );
        },

        /**
         * Загружает текстовый слой страницы и рендерит его.
         *
         * Последовательность:
         * 1. Показ скелетона.
         * 2. Fetch ``GET /api/documents/{id}/pages/{n}``.
         * 3. Проверка ``seq``.
         * 4. Рендеринг текста через ``DocumentRenderer.renderPageText``.
         *
         * @param {string} docId — Идентификатор документа.
         * @param {number} pageNumber — Номер страницы (0-based).
         * @param {HTMLElement} textContainer — Контейнер для текста.
         * @param {number} seq — Текущий счётчик загрузок вкладки.
         */
        _loadPageText: function (docId, pageNumber, textContainer, seq) {
            if (!textContainer) return;
            textContainer.innerHTML = '<div class="page-render-skeleton"></div>';

            fetch(
                "/api/documents/" + encodeURIComponent(docId) +
                "/pages/" + pageNumber
            )
                .then(function (r) {
                    if (!r.ok) throw new Error("Страница не найдена");
                    return r.json();
                })
                .then(function (pageData) {
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return;
                    DocumentRenderer.renderPageText(
                        textContainer, pageData.text
                    );
                })
                .catch(function (err) {
                    if (seq !== window.DDSApp.getLoadSeq(docId)) return;
                    textContainer.innerHTML =
                        '<div class="alert alert--error">' +
                        DocumentUtils.escapeHtml(err.message) +
                        "</div>";
                });
        },
    };

    /* ==============================================================
       7. Экспорт для внешних модулей
       ============================================================== */

    if (typeof window !== "undefined") {
        window.DocumentLoader = DocumentLoader;
        window.DocumentRenderer = DocumentRenderer;
        window.DocumentUtils = DocumentUtils;
        window.createPageRenderer = createPageRenderer;
        window.ViewModeManager = ViewModeManager;
    }
})();
