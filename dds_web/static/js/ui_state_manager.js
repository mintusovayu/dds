/**
 * UIStateManager — централизованное управление состояниями
 * элементов интерфейса.
 *
 * Единый объект хранит факторы состояния системы и правила
 * активности элементов. При изменении факторов все элементы
 * обновляются автоматически. Это обеспечивает декларативное
 * описание поведения интерфейса и предотвращает рассинхронизацию
 * между серверным состоянием и отображением.
 *
 * Архитектура модуля:
 *
 * +----------------------------------+----------------------------------+
 * | Компонент                        | Ответственность                  |
 * +==================================+==================================+
 * | ``factors``                      | Хранилище текущих факторов       |
 * |                                  | состояния системы.               |
 * +----------------------------------+----------------------------------+
 * | ``rules``                        | Хранилище правил активности      |
 * |                                  | элементов.                       |
 * +----------------------------------+----------------------------------+
 * | ``init()``                       | Инициализация менеджера с        |
 * |                                  | начальными факторами.            |
 * +----------------------------------+----------------------------------+
 * | ``addRule()``                    | Регистрация правила активности   |
 * |                                  | для элемента.                    |
 * +----------------------------------+----------------------------------+
 * | ``apply()``                      | Применение всех правил к DOM.    |
 * +----------------------------------+----------------------------------+
 * | ``update()``                     | Обновление факторов и            |
 * |                                  | переприменение правил.           |
 * +----------------------------------+----------------------------------+
 *
 * Факторы состояния:
 *
 * +---------------------+--------------------------------------------+
 * | Фактор              | Описание                                   |
 * +=====================+============================================+
 * | ``scan_status``     | Статус сканирования:                       |
 * |                     | ``"idle"``, ``"running"``,                 |
 * |                     | ``"completed"``, ``"interrupted"``,        |
 * |                     | ``"error"``.                               |
 * +---------------------+--------------------------------------------+
 * | ``index_refresh``   | Статус пересчёта состояния индексации:     |
 * |                     | ``"idle"``, ``"running"``.                 |
 * +---------------------+--------------------------------------------+
 * | ``user_role``       | Роль пользователя:                         |
 * |                     | ``"admin"``, ``"user"``.                   |
 * +---------------------+--------------------------------------------+
 *
 * Таблица правил активности (примеры):
 *
 * +-------------------------+------------------------------------------+
 * | Элемент                 | Условие активности                       |
 * +=========================+==========================================+
 * | ``btn-start-scan``      | ``scan_status !== "running"``             |
 * +-------------------------+------------------------------------------+
 * | ``btn-cancel-scan``     | ``scan_status === "running"``             |
 * +-------------------------+------------------------------------------+
 * | ``btn-refresh-index``   | ``scan_status !== "running"`` И           |
 * |                         | ``index_refresh === "idle"``              |
 * +-------------------------+------------------------------------------+
 * | ``btn-admin-start``     | ``scan_status !== "running"``             |
 * +-------------------------+------------------------------------------+
 * | ``btn-admin-cancel``    | ``scan_status === "running"``             |
 * +-------------------------+------------------------------------------+
 * | ``settings-form``       | ``scan_status !== "running"``             |
 * |                         | (с опцией ``target: "form"``)             |
 * +-------------------------+------------------------------------------+
 *
 * Поддерживаемые опции правил:
 *
 * +-------------------------+------------------------------------------+
 * | Опция                   | Описание                                 |
 * +=========================+==========================================+
 * | ``target: "self"``      | Блокируется только сам элемент           |
 * |                         | через ``disabled``. Значение             |
 * |                         | по умолчанию.                            |
 * +-------------------------+------------------------------------------+
 * | ``target: "form"``      | Блокируются все поля формы               |
 * |                         | (``input``, ``button``, ``select``,      |
 * |                         | ``textarea``) внутри элемента.           |
 * +-------------------------+------------------------------------------+
 *
 * Использование:
 *
 * .. code-block:: javascript
 *
 *    // Инициализация с начальными факторами
 *    UIStateManager.init({
 *        scan_status: "idle",
 *        index_refresh: "idle"
 *    });
 *
 *    // Добавление правил активности
 *    UIStateManager.addRule("btn-start-scan", function (f) {
 *        return f.scan_status !== "running";
 *    });
 *
 *    UIStateManager.addRule("settings-form", function (f) {
 *        return f.scan_status !== "running";
 *    }, { target: "form" });
 *
 *    // Применение правил к DOM
 *    UIStateManager.apply();
 *
 *    // Обновление факторов при изменении состояния
 *    UIStateManager.update({ scan_status: "running" });
 *
 * Принципы:
 * - Модуль не содержит бизнес-логики — только управление
 *   состояниями DOM-элементов.
 * - Правила задаются декларативно через функции, что
 *   обеспечивает гибкость и расширяемость.
 * - Модуль не зависит от конкретных компонентов приложения
 *   (``SearchEngine``, ``ScanOrchestrator`` и т.д.).
 * - Модуль инкапсулирован в IIFE для предотвращения
 *   загрязнения глобального пространства имён.
 * - Экспорт через ``window.UIStateManager`` для использования
 *   из других скриптов и шаблонов.
 *
 * Подключение в шаблонах:
 *
 * .. code-block:: html
 *
 *    <script src="/static/js/ui_state_manager.js"></script>
 *
 * Интеграция с серверным рендерингом:
 * Начальное состояние элементов задаётся через Jinja2
 * (атрибут ``disabled`` в шаблоне), что предотвращает
 * мигание интерфейса до загрузки JavaScript. При обновлении
 * состояния через SSE или действия пользователя вызывается
 * ``UIStateManager.update()``, который автоматически
 * переприменяет все правила.
 */

(function () {
    "use strict";

    /**
     * Менеджер состояний элементов интерфейса.
     *
     * Хранит факторы состояния системы и правила активности
     * элементов. При изменении факторов все правила
     * переприменяются автоматически.
     *
     * Атрибуты:
     *
     * +---------------------+------------------------------------------+
     * | Атрибут             | Описание                                 |
     * +=====================+==========================================+
     * | ``factors``         | Объект с текущими факторами состояния.   |
     * |                     | Ключ — имя фактора, значение —           |
     * |                     | текущее значение.                        |
     * +---------------------+------------------------------------------+
     * | ``rules``           | Объект с правилами активности.           |
     * |                     | Ключ — ``id`` DOM-элемента, значение —   |
     * |                     | объект с функцией ``enabled_when``       |
     * |                     | и опциями.                               |
     * +---------------------+------------------------------------------+
     */
    var UIStateManager = {

        /**
         * Текущие факторы состояния системы.
         * Обновляются через метод ``update()``.
         * @type {Object}
         */
        factors: {},

        /**
         * Правила активности элементов.
         * Ключ — ``id`` DOM-элемента.
         * Значение — объект с функцией ``enabled_when`` и опциями.
         * @type {Object}
         */
        rules: {},

        /**
         * Инициализирует менеджер с начальными факторами.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Присвоение ``initialFactors`` в ``this.factors``.   |
         * |   | Если ``initialFactors`` не задан, используется      |
         * |   | пустой объект.                                      |
         * +---+-----------------------------------------------------+
         * | 2 | Сброс ``this.rules`` в пустой объект.               |
         * +---+-----------------------------------------------------+
         *
         * Примечание:
         * Метод должен вызываться один раз при загрузке страницы,
         * перед добавлением правил и применением.
         *
         * @param {Object} initialFactors — начальные значения факторов.
         *   Например: ``{ scan_status: "idle", index_refresh: "idle" }``.
         */
        init: function (initialFactors) {
            this.factors = initialFactors || {};
            this.rules = {};
        },

        /**
         * Добавляет правило активности для элемента.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Создание записи правила в ``this.rules``            |
         * |   | с ключом ``elementId``.                             |
         * +---+-----------------------------------------------------+
         * | 2 | Сохранение функции ``enabledWhen`` в поле           |
         * |   | ``enabled_when``.                                   |
         * +---+-----------------------------------------------------+
         * | 3 | Сохранение опций в поле ``options``.                |
         * |   | Если опции не заданы, используется пустой объект.   |
         * +---+-----------------------------------------------------+
         *
         * Поддерживаемые опции:
         *
         * +-------------------------+----------------------------------+
         * | Опция                   | Описание                         |
         * +=========================+==================================+
         * | ``target: "self"``      | Блокируется только сам элемент   |
         * |                         | через ``disabled``. Значение     |
         * |                         | по умолчанию.                    |
         * +-------------------------+----------------------------------+
         * | ``target: "form"``      | Блокируются все поля формы       |
         * |                         | (``input``, ``button``,          |
         * |                         | ``select``, ``textarea``)        |
         * |                         | внутри элемента.                 |
         * +-------------------------+----------------------------------+
         *
         * @param {string} elementId — id DOM-элемента.
         *   Например: ``"btn-start-scan"``, ``"settings-form"``.
         * @param {Function} enabledWhen — функция, принимающая
         *   объект факторов и возвращающая ``true``, если элемент
         *   должен быть активен, ``false`` — если заблокирован.
         *   Сигнатура: ``function(factors) { return boolean; }``.
         * @param {Object} [options] — дополнительные опции.
         *   ``options.target`` — ``"self"`` (по умолчанию) или
         *   ``"form"`` для блокировки всех полей формы.
         */
        addRule: function (elementId, enabledWhen, options) {
            this.rules[elementId] = {
                enabled_when: enabledWhen,
                options: options || {}
            };
        },

        /**
         * Применяет все правила к DOM.
         *
         * Операции:
         * +----+-----------------------------------------------------+
         * | №  | Описание                                            |
         * +====+=====================================================+
         * | 1  | Для каждого правила в ``this.rules``:               |
         * +----+-----------------------------------------------------+
         * | 2  | Поиск DOM-элемента по ``id`` через                  |
         * |    | ``document.getElementById()``. Если элемент         |
         * |    | не найден — пропуск правила.                        |
         * +----+-----------------------------------------------------+
         * | 3  | Вычисление состояния активности: вызов              |
         * |    | ``rule.enabled_when(this.factors)``.                |
         * +----+-----------------------------------------------------+
         * | 4  | Если ``rule.options.target === "form"``:            |
         * |    | a. Поиск всех полей формы внутри элемента           |
         * |    |    (``input``, ``button``, ``select``,              |
         * |    |    ``textarea``) через ``querySelectorAll``.        |
         * |    | b. Для каждого поля: установка ``disabled``         |
         * |    |    в ``!enabled``.                                  |
         * +----+-----------------------------------------------------+
         * | 5  | Иначе (``target === "self"`` или не задан):         |
         * |    | Установка ``el.disabled = !enabled``.               |
         * +----+-----------------------------------------------------+
         *
         * Примечание:
         * Метод должен вызываться после ``init()`` и ``addRule()``,
         * а также после каждого вызова ``update()`` для
         * переприменения правил.
         *
         * Примечание:
         * Если DOM-элемент с указанным ``id`` не найден,
         * правило молча пропускается. Это позволяет использовать
         * один набор правил для страниц с разными наборами
         * элементов.
         */
        apply: function () {
            for (var id in this.rules) {
                if (!this.rules.hasOwnProperty(id)) continue;
                var el = document.getElementById(id);
                if (!el) continue;
                var rule = this.rules[id];
                var enabled = rule.enabled_when(this.factors);
                if (rule.options.target === "form") {
                    // Блокировка всех полей формы
                    var inputs = el.querySelectorAll(
                        "input, button, select, textarea"
                    );
                    for (var i = 0; i < inputs.length; i++) {
                        inputs[i].disabled = !enabled;
                    }
                } else {
                    // Блокировка самого элемента
                    el.disabled = !enabled;
                }
            }
        },

        /**
         * Обновляет факторы и переприменяет правила.
         *
         * Операции:
         * +---+-----------------------------------------------------+
         * | № | Описание                                            |
         * +===+=====================================================+
         * | 1 | Для каждого ключа в ``partial``:                    |
         * |   | присвоение значения в ``this.factors[key]``.        |
         * +---+-----------------------------------------------------+
         * | 2 | Вызов ``this.apply()`` для переприменения           |
         * |   | всех правил к DOM с обновлёнными факторами.         |
         * +---+-----------------------------------------------------+
         *
         * Примечание:
         * Обновление является частичным: передаются только
         * изменённые факторы. Остальные факторы сохраняют
         * прежние значения.
         *
         * Пример:
         *
         * .. code-block:: javascript
         *
         *    // При получении события прогресса сканирования:
         *    UIStateManager.update({ scan_status: data.status });
         *
         *    // При начале пересчёта состояния индексации:
         *    UIStateManager.update({ index_refresh: "running" });
         *
         *    // При завершении пересчёта:
         *    UIStateManager.update({ index_refresh: "idle" });
         *
         * @param {Object} partial — частичное обновление факторов.
         *   Например: ``{ scan_status: "running" }``.
         */
        update: function (partial) {
            for (var key in partial) {
                if (partial.hasOwnProperty(key)) {
                    this.factors[key] = partial[key];
                }
            }
            this.apply();
        }
    };

    /* ==============================================================
       Экспорт для внешних модулей
       ============================================================== */

    // Экспорт через глобальный объект для использования из
    // других скриптов и шаблонов.
    if (typeof window !== "undefined") {
        window.UIStateManager = UIStateManager;
    }
})();
