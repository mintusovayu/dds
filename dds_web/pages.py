"""
Маршруты страниц веб-интерфейса DDS.

Этот модуль содержит маршруты для серверного рендеринга HTML-страниц
веб-интерфейса. Используется Jinja2 для шаблонизации и минимальный
JavaScript для интерактивности.

Рефакторинг интерфейса:
Все ранее отдельные страницы (``/search``, ``/document/{doc_id}``,
``/scan``, ``/modules``, ``/admin``) объединены в единый интерфейс
``main.html``, реализованный в стиле Visual Studio Code.
Роут ``/`` рендерит ``main.html`` — единую страницу с вкладками,
фильтрами, панелью настроек и панелью статуса.

Асинхронная модель (Фаза 4):
Все обработчики являются асинхронными (``async def``). Блокирующие
операции (чтение из БД, чтение из файловой системы, хеширование
пароля) выполняются через ``run_in_executor`` с ``api_executor``
для предотвращения блокировки event loop и обеспечения
обработки нескольких запросов параллельно.

Разделение пулов потоков (скорректированный план):
Все блокирующие операции веб-запросов выполняются через
``ctx.api_executor`` вместо дефолтного пула потоков. Это
предотвращает конкуренцию между веб-запросами и фоновым
сканированием за потоки.

Таймауты блокирующих операций (скорректированный план):
Критичные блокирующие операции обёрнуты в ``run_with_timeout``
из ``dds_core.application.timeout_guard``. При срабатывании
таймаута публикуется событие ``OperationTimedOut`` на уровне
WARNING, а клиенту возвращается HTTP 504.

+-------------------------------+--------------------------------------+
| Операция                      | Дескриптор таймаута                |
+===============================+======================================+
| Хеширование пароля при входе  | ``auth.login``                     |
+-------------------------------+--------------------------------------+

Опциональная шина событий в ``APIContext``
(скорректированный план по типизации):

``APIContext.event_bus`` имеет тип ``IEventBus | None``: в тестах
и сценариях, где шина не требуется, допускается ``None``. В
production-пути ``lifespan.py`` всегда передаёт полноценную шину.
Обработчики, использующие ``run_with_timeout(event_bus=...)``,
обязаны проверить наличие шины явно и вернуть HTTP 503 при её
отсутствии — это устраняет неконтролируемый ``AttributeError``
и корректно сужает тип для статического анализа.

Аутентификация:
Все страницы, кроме /login, защищены зависимостью LoginRequiredDep.
При отсутствии валидной сессии пользователь перенаправляется на
/login с параметром next для возврата на исходную страницу.

Автологин по IP-адресу (расширение):
Для развёртывания в сети с доверенным доступом (MAC-whitelist на
роутере, статический DHCP binding) поддерживается автологин по
IP-адресу через middleware ``auto_login_middleware``
(см. ``dds_web/auto_login.py``). Модуль ``pages.py`` обеспечивает
opt-out механизм:

- ``logout_submit`` устанавливает cookie
  ``AUTO_LOGIN_OPT_OUT_COOKIE_NAME`` с TTL из
  ``core_config.AUTO_LOGIN_OPT_OUT_TTL_SECONDS`` (8 часов).
  Наличие этой cookie заставляет middleware пропускать автологин:
  пользователь, нажавший «Выйти», остаётся неавторизованным
  в течение указанного интервала.
- ``login_submit`` удаляет opt-out cookie после успешного
  ручного входа. Это возвращает автологин в активное состояние
  и позволяет пользователю работать под своим аккаунтом на
  общем устройстве, даже если оно привязано к другому IP.

Подробности см. в docstring ``dds_web/auth.py`` и
``dds_web/auto_login.py``.

Скрытие навигации:
Страница входа ``/login`` передаёт в контекст шаблона флаг
``hide_nav=True``. Это сигнализирует базовому шаблону ``base.html``
не рендерить элементы навигации (Activity Bar, Sidebar, Tab Bar).
Остальные страницы флаг не передают — базовый шаблон трактует
отсутствие переменной как falsy и рендерит навигацию.

Безопасность:
- Защита от open redirect: параметр next проверяется функцией
  ``is_safe_redirect_path`` из ``dds_web/security.py`` перед
  использованием в редиректе.
- Cookie устанавливаются с флагами ``httponly=True``,
  ``samesite=lax`` и ``secure`` (определяется через
  ``should_use_secure_cookie`` из ``dds_web/security.py``).

Принципы:
- Модуль находится в presentation layer и не содержит бизнес-логики.
- Модуль зависит от application layer через dependency injection.
- Серверный рендеринг: HTML генерируется на сервере через Jinja2.
- Минимальный JavaScript только для динамических элементов.
- Сессия передаётся в контекст всех шаблонов для отображения
  информации о пользователе в шапке.
- Проверка безопасности редиректов выполняется через единую
  функцию из ``dds_web/security.py``.
- Флаг ``secure`` у cookie определяется через
  ``should_use_secure_cookie`` из ``dds_web/security.py``.
- Критичные блокирующие операции обёрнуты в ``run_with_timeout``
  для предотвращения зависания.

Страницы:

/                  — единый интерфейс (``main.html``). Требует входа.
/login             — вход. Доступна без входа.
"""

from __future__ import annotations

import asyncio
import os
from typing import Annotated

try:
    from fastapi import APIRouter, Depends, Form, HTTPException, Query, Request
    from fastapi.responses import HTMLResponse, RedirectResponse
    from fastapi.templating import Jinja2Templates
except ImportError:
    raise ImportError(
        "Для запуска веб-интерфейса DDS необходимо установить "
        "fastapi и jinja2: pip install fastapi jinja2"
    )

from dds_core.application.timeout_guard import run_with_timeout
from dds_core.domain import config as core_config

from .api import APIContext, get_context
from .auth import (
    AUTO_LOGIN_OPT_OUT_COOKIE_NAME,
    SESSION_COOKIE_NAME,
    AuthService,
    LoginRequiredDep,
    extract_all_tokens,
    get_auth_service,
)
from .security import (
    is_safe_redirect_path,
    should_use_secure_cookie,
)

# ----------------------------------------------------------------------
# Шаблоны
# ----------------------------------------------------------------------

# Каталог шаблонов относительно данного файла
_TEMPLATES_DIR = os.path.join(os.path.dirname(__file__), "templates")

templates = Jinja2Templates(directory=_TEMPLATES_DIR)

# Типизированная зависимость для контекста API
CtxDep = Annotated[APIContext, Depends(get_context)]

# Типизированная зависимость для сервиса аутентификации
AuthDep = Annotated[AuthService, Depends(get_auth_service)]

# ----------------------------------------------------------------------
# Router страниц
# ----------------------------------------------------------------------

pages_router = APIRouter(tags=["Страницы"])

# ----------------------------------------------------------------------
# Единый интерфейс (главная страница)
# ----------------------------------------------------------------------


@pages_router.get("/", response_class=HTMLResponse)
async def index_page(
    request: Request,
    *,
    session: LoginRequiredDep,
    ctx: CtxDep,
) -> HTMLResponse:
    """Единый интерфейс с вкладками (референс — VS Code).

    Требует авторизации. При отсутствии сессии выполняется
    редирект на /login через LoginRequiredException.

    Рендерит шаблон ``main.html``, который содержит:

    +----------------------------------+----------------------------------+
    | Область                          | Содержимое                       |
    +==================================+==================================+
    | Вкладка «Поиск»                 | Форма поиска + таблица           |
    |                                  | результатов. Постоянная          |
    |                                  | вкладка, нельзя закрыть.         |
    +----------------------------------+----------------------------------+
    | Вкладки документов               | Метаданные + текст страницы.     |
    |                                  | Динамические вкладки,            |
    |                                  | открываются кликом по            |
    |                                  | результату поиска.               |
    +----------------------------------+----------------------------------+
    | Панель настроек                  | Профиль, сканирование,           |
    |                                  | модули, система (для             |
    |                                  | администратора).                 |
    +----------------------------------+----------------------------------+
    | Панель статуса                   | Статус индекса, сканирования,    |
    |                                  | пользователь.                    |
    +----------------------------------+----------------------------------+

    Блокирующая операция получения статуса сканирования
    выполняется через ``run_in_executor`` с ``api_executor``
    для предотвращения блокировки event loop (Фаза 4,
    скорректированный план).

    Флаг ``hide_nav`` **не передаётся** в контекст — базовый
    шаблон ``base.html`` рендерит Activity Bar и Sidebar (они
    необходимы для отображения фильтров и переключения вкладок).

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | ``run_in_executor(api_executor, get_scan_status)``  |
    |   | → получение статуса сканирования в пуле потоков.    |
    +---+-----------------------------------------------------+
    | 2 | Рендеринг шаблона ``main.html`` с контекстом.       |
    +---+-----------------------------------------------------+

    Контекст, передаваемый в шаблон:

    +---------------------+------------------------------------------+
    | Ключ                | Описание                                 |
    +=====================+==========================================+
    | ``title``           | Заголовок страницы.                      |
    +---------------------+------------------------------------------+
    | ``session``         | Сессия текущего пользователя.            |
    +---------------------+------------------------------------------+
    | ``scan_status``     | Статус сканирования (``ScanProgress``).  |
    +---------------------+------------------------------------------+
    | ``user_role``       | Роль пользователя (строка:               |
    |                     | ``"admin"`` или ``"user"``).             |
    +---------------------+------------------------------------------+

    Args:
        request: HTTP-запрос (для Jinja2).
        session: Сессия текущего пользователя.
        ctx: Контейнер зависимостей.

    Returns:
        HTML-страница единого интерфейса.
    """
    loop = asyncio.get_running_loop()
    scan_status = await loop.run_in_executor(
        ctx.api_executor,
        ctx.scan_orchestrator.get_scan_status,
    )
    return templates.TemplateResponse(
        request=request,
        name="main.html",
        context={
            "title": "Deep Doc Search",
            "session": session,
            "scan_status": scan_status,
            "user_role": session.role.value,
        },
    )


