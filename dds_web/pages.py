@pages_router.get("/login", response_class=HTMLResponse)
async def login_page(
    request: Request,
    error: str = Query(default="", description="Сообщение об ошибке"),
    next: str = Query(
        default="/",
        description="Страница для возврата после входа",
    ),
) -> HTMLResponse:
    """Страница входа.

    Доступна без авторизации. Принимает параметр ``next`` для
    возврата на исходную страницу после успешного входа.

    Параметр ``next`` проверяется на безопасность для предотвращения
    open redirect-атак через ``is_safe_redirect_path`` из
    ``dds_web/security.py``. Если путь небезопасен, используется
    главная страница.

    Скрытие навигации:
    В контекст передаётся флаг ``hide_nav=True``. Базовый шаблон
    ``base.html`` интерпретирует его как указание не рендерить
    Activity Bar и Sidebar — на странице входа они не нужны,
    и без этого флага форма входа была бы сдвинута вправо
    пустым ``<aside class="sidebar">`` шириной 280 px.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | ``is_safe_redirect_path(next)`` → проверка          |
    |   | безопасности пути редиректа.                        |
    +---+-----------------------------------------------------+
    | 2 | Рендеринг шаблона ``login.html`` с контекстом,      |
    |   | включающим ``hide_nav=True``.                       |
    +---+-----------------------------------------------------+

    Контекст, передаваемый в шаблон:

    +---------------------+------------------------------------------+
    | Ключ                | Описание                                 |
    +=====================+==========================================+
    | ``title``           | Заголовок страницы.                      |
    +---------------------+------------------------------------------+
    | ``error``           | Сообщение об ошибке (пустая строка,      |
    |                     | если ошибок нет).                        |
    +---------------------+------------------------------------------+
    | ``next``            | Путь для возврата после входа            |
    |                     | (проверен на безопасность).              |
    +---------------------+------------------------------------------+
    | ``hide_nav``        | ``True`` — базовый шаблон не рендерит    |
    |                     | Activity Bar и Sidebar.                  |
    +---------------------+------------------------------------------+

    Args:
        request: HTTP-запрос (для Jinja2).
        error: Сообщение об ошибке (при неудачном входе).
        next: Путь для возврата после входа.

    Returns:
        HTML-страница с формой входа.
    """
    # Проверка безопасности параметра next
    if not is_safe_redirect_path(next):
        next = "/"

    return templates.TemplateResponse(
        request=request,
        name="login.html",
        context={
            "title": "Вход",
            "error": error,
            "next": next,
            "hide_nav": True,
        },
    )


@pages_router.post("/login")
async def login_submit(
    request: Request,
    username: str = Form(...),
    password: str = Form(...),
    next: str = Form(default="/"),
    *,
    auth: AuthDep,
    ctx: CtxDep,
) -> RedirectResponse:
    """Обрабатывает форму входа.

    При успешном входе устанавливает cookie с сессионным токеном
    и переносит на страницу, указанную в параметре ``next``.

    Удаление opt-out cookie автологина:
    При успешном входе удаляется cookie
    ``AUTO_LOGIN_OPT_OUT_COOKIE_NAME``. Это возвращает автологин
    по IP-адресу в активное состояние. Сценарий использования:
    на общем устройстве пользователь A нажал «Выйти» (установив
    opt-out), затем пользователь B вошёл под своим аккаунтом
    через форму. При следующем визите middleware
    ``auto_login_middleware`` снова сможет выполнить автологин
    для устройства.

    Таймаут (скорректированный план):
    Блокирующая операция хеширования пароля (100 000 итераций
    ``PBKDF2-HMAC-SHA256``) обёрнута в ``run_with_timeout``
    с дескриптором ``auth.login``. При срабатывании таймаута
    публикуется событие ``OperationTimedOut`` на уровне WARNING,
    а клиенту возвращается HTTP 504.

    Проверка ``ctx.event_bus``
    (скорректированный план по типизации):
    ``APIContext.event_bus`` имеет тип ``IEventBus | None``:
    в тестах и сценариях без шины допускается ``None``. Обработчик
    проверяет наличие шины явно и возвращает HTTP 503 при её
    отсутствии — это устраняет неконтролируемый ``AttributeError``
    и сужает тип для статического анализа.

    Операции:

    +----+----------------------------------------------------+
    | №  | Описание                                           |
    +====+====================================================+
    | 1  | ``is_safe_redirect_path(next)`` → проверка         |
    |    | безопасности пути редиректа.                       |
    +----+----------------------------------------------------+
    | 2  | Проверка ``ctx.event_bus is None`` → HTTP 503.    |
    +----+----------------------------------------------------+
    | 3  | ``run_with_timeout(run_in_executor(api_executor,   |
    |    | auth.login), operation="auth.login")``             |
    |    | → хеширование пароля в пуле потоков с таймаутом.   |
    +----+----------------------------------------------------+
    | 4  | При ``TimeoutError`` →                             |
    |    | ``HTTPException 504``.                             |
    +----+----------------------------------------------------+
    | 5  | ``should_use_secure_cookie(request)`` →            |
    |    | определение флага ``secure`` для cookie.           |
    +----+----------------------------------------------------+
    | 6  | Установка cookie с флагами ``httponly=True``,      |
    |    | ``samesite=lax``, ``secure``.                      |
    +----+----------------------------------------------------+
    | 7  | Удаление opt-out cookie автологина (при наличии).  |
    +----+----------------------------------------------------+
    | 8  | Редирект на ``next``.                              |
    +----+----------------------------------------------------+
    | 9  | При ``ValueError`` → редирект на ``/login``        |
    |    | с сообщением об ошибке.                            |
    +----+----------------------------------------------------+

    Примечание:
    Флаг ``secure`` у cookie определяется через
    ``should_use_secure_cookie(request)`` из
    ``dds_web/security.py``. Флаг устанавливается,
    если соединение защищено (HTTPS или за прокси
    с ``X-Forwarded-Proto: https``).

    Примечание:
    Операция хеширования пароля обёрнута в ``run_with_timeout``
    с дескриптором ``auth.login`` и таймаутом
    ``core_config.OPERATION_TIMEOUTS["auth.login"]`` (10 секунд).
    Это предотвращает зависание при некорректной работе
    пула потоков или чрезмерной нагрузке на CPU. При
    срабатывании таймаута публикуется событие
    ``OperationTimedOut`` на уровне WARNING.

    Args:
        request: HTTP-запрос (для определения флага ``secure``).
        username: Имя пользователя (из form data).
        password: Пароль (из form data).
        next: Путь для возврата после входа (из form data).
        auth: Сервис аутентификации.
        ctx: Контейнер зависимостей.

    Returns:
        Redirect на страницу ``next`` (при успехе) или на ``/login``
        с сообщением об ошибке (при неудаче).

    Raises:
        HTTPException 503: Если шина событий не инициализирована
            в контексте (не может быть опубликовано
            ``OperationTimedOut`` при таймауте).
        HTTPException 504: Если хеширование пароля не завершилось
            за отведённое время (таймаут ``auth.login``).
    """
    # Проверка безопасности параметра next
    if not is_safe_redirect_path(next):
        next = "/"

    # Явная проверка и сужение типа: ``APIContext.event_bus``
    # объявлен как ``IEventBus | None`` (опциональная зависимость
    # для тестов). В production-пути ``lifespan.py`` всегда
    # передаёт полноценную шину, но обработчик обязан проверить
    # её наличие — это устраняет неконтролируемый AttributeError
    # и обеспечивает корректный тип для run_with_timeout.
    if ctx.event_bus is None:
        raise HTTPException(
            status_code=503,
            detail="Шина событий не инициализирована.",
        )
    event_bus = ctx.event_bus

    try:
        # Блокирующая операция хеширования пароля.
        # Выполняется через run_with_timeout с api_executor
        # для предотвращения блокировки event loop и
        # предотвращения зависания (скорректированный план).
        loop = asyncio.get_running_loop()
        token = await run_with_timeout(
            loop.run_in_executor(
                ctx.api_executor,
                auth.login,
                username,
                password,
            ),
            operation="auth.login",
            event_bus=event_bus,
            context=username,
            recovery_action="Вход прерван по таймауту.",
        )

        # Определить флаг secure для cookie
        secure_flag = should_use_secure_cookie(request)

        # Создать redirect и установить cookie
        response = RedirectResponse(url=next, status_code=303)
        response.set_cookie(
            key=SESSION_COOKIE_NAME,
            value=token,
            httponly=True,  # Защита от XSS
            samesite="lax",  # Защита от CSRF
            secure=secure_flag,  # Защита от перехвата (скорректированный план)
            max_age=auth.session_ttl,  # Используем публичное свойство
            path="/",
        )

        # Удалить opt-out cookie автологина: успешный ручной вход
        # возвращает автологин в активное состояние.
        response.delete_cookie(
            key=AUTO_LOGIN_OPT_OUT_COOKIE_NAME,
            path="/",
        )

        return response
    except TimeoutError:
        raise HTTPException(
            status_code=504,
            detail="Сервер перегружен. Попробуйте позже.",
        )
    except ValueError:
        from urllib.parse import quote

        safe_next = quote(next, safe="/")
        return RedirectResponse(
            url=f"/login?error=Неверный+логин+или+пароль&next={safe_next}",
            status_code=303,
        )


@pages_router.post("/logout")
async def logout_submit(
    request: Request,
    *,
    auth: AuthDep,
) -> RedirectResponse:
    """Обрабатывает выход.

    Инвалидирует все возможные сессии клиента и удаляет cookie
    с сессионным токеном. Для инвалидации извлекаются все токены
    из запроса через ``extract_all_tokens`` — это покрывает случай
    одновременного наличия cookie и заголовка ``Authorization``
    (Bearer), при котором предыдущая реализация обрабатывала
    оба источника вручную.

    Opt-out автологина:
    При выходе устанавливается cookie
    ``AUTO_LOGIN_OPT_OUT_COOKIE_NAME`` с TTL из
    ``core_config.AUTO_LOGIN_OPT_OUT_TTL_SECONDS`` (8 часов).
    Наличие этой cookie заставляет middleware
    ``auto_login_middleware`` пропускать автологин по IP-адресу.
    Это решает проблему «кнопка Выйти не работает»: без opt-out
    middleware немедленно залогинила бы пользователя заново
    по IP.

    Opt-out автоматически снимается при успешном ручном входе
    через ``/login`` (см. ``login_submit``) и по истечении TTL.

    Операции:

    +----+----------------------------------------------------+
    | №  | Описание                                           |
    +====+====================================================+
    | 1  | ``extract_all_tokens(request)`` → получение всех   |
    |    | токенов запроса (Bearer-заголовок и cookie).       |
    +----+----------------------------------------------------+
    | 2  | Для каждого токена: ``auth.logout(token)``         |
    |    | → завершение соответствующей сессии.               |
    +----+----------------------------------------------------+
    | 3  | ``response.delete_cookie(SESSION_COOKIE_NAME)``    |
    |    | → удаление cookie.                                 |
    +----+----------------------------------------------------+
    | 4  | ``response.set_cookie(                            |
    |    | AUTO_LOGIN_OPT_OUT_COOKIE_NAME, "1", ...)``        |
    |    | → установка opt-out cookie с TTL 8 часов.          |
    +----+----------------------------------------------------+
    | 5  | Редирект на ``/login``.                            |
    +----+----------------------------------------------------+

    Args:
        request: HTTP-запрос.
        auth: Сервис аутентификации.

    Returns:
        Redirect на страницу входа.
    """
    # Инвалидировать все сессии клиента (Bearer-заголовок и cookie).
    for token in extract_all_tokens(request):
        auth.logout(token)

    # Создать redirect и удалить cookie сессии.
    response = RedirectResponse(url="/login", status_code=303)
    response.delete_cookie(key=SESSION_COOKIE_NAME, path="/")

    # Установить opt-out cookie автологина: пользователь явно
    # вышел и не должен быть залогинен автоматически по IP.
    response.set_cookie(
        key=AUTO_LOGIN_OPT_OUT_COOKIE_NAME,
        value="1",
        httponly=True,
        samesite="lax",
        secure=should_use_secure_cookie(request),
        max_age=core_config.AUTO_LOGIN_OPT_OUT_TTL_SECONDS,
        path="/",
    )

    return response
