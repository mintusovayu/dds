def get_current_user(
    request: Request,
    *,
    auth: AuthDep,
) -> Session:
    """Возвращает текущего пользователя для API.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Извлечение токена из запроса.                       |
    +---+-----------------------------------------------------+
    | 2 | При отсутствии токена → ``HTTPException 401``.      |
    +---+-----------------------------------------------------+
    | 3 | Валидация сессии.                                   |
    +---+-----------------------------------------------------+
    | 4 | При невалидной сессии → ``HTTPException 401``.      |
    +---+-----------------------------------------------------+
    | 5 | Возврат сессии.                                     |
    +---+-----------------------------------------------------+

    Args:
        request: HTTP-запрос.
        auth: Сервис аутентификации.

    Returns:
        ``Session`` текущего пользователя.

    Raises:
        HTTPException 401: Если токен отсутствует или невалиден.
    """
    token = extract_token(request)
    if token is None:
        raise HTTPException(
            status_code=401,
            detail="Отсутствует аутентификация. "
            "Требуется заголовок Authorization или cookie сессии.",
        )

    session = auth.validate_session(token)
    if session is None:
        raise HTTPException(
            status_code=401,
            detail="Сессия недействительна или истекла.",
        )

    return session


def require_admin(
    *,
    session: Annotated[Session, Depends(get_current_user)],
) -> Session:
    """Проверяет права администратора для API.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Проверка ``session.role == UserRole.ADMIN``.        |
    +---+-----------------------------------------------------+
    | 2 | При отсутствии прав → ``HTTPException 403``.        |
    +---+-----------------------------------------------------+
    | 3 | Возврат сессии.                                     |
    +---+-----------------------------------------------------+

    Args:
        session: Сессия текущего пользователя.

    Returns:
        ``Session`` текущего пользователя.

    Raises:
        HTTPException 403: Если пользователь не администратор.
    """
    if session.role != UserRole.ADMIN:
        raise HTTPException(
            status_code=403,
            detail="Недостаточно прав. Требуется роль администратора.",
        )
    return session


