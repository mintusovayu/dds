def get_optional_session(
    request: Request,
    *,
    auth: AuthDep,
) -> Session | None:
    """Возвращает сессию без выбрасывания исключений.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Извлечение токена из запроса.                       |
    +---+-----------------------------------------------------+
    | 2 | При отсутствии токена → возврат ``None``.           |
    +---+-----------------------------------------------------+
    | 3 | Валидация сессии.                                   |
    +---+-----------------------------------------------------+
    | 4 | Возврат сессии или ``None``.                        |
    +---+-----------------------------------------------------+

    Args:
        request: HTTP-запрос.
        auth: Сервис аутентификации.

    Returns:
        ``Session`` или ``None``.
    """
    token = extract_token(request)
    if token is None:
        return None
    return auth.validate_session(token)


def require_login(
    request: Request,
    *,
    auth: AuthDep,
) -> Session:
    """Защищает HTML-страницы, требуя валидную сессию.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Извлечение токена из запроса.                       |
    +---+-----------------------------------------------------+
    | 2 | При отсутствии токена →                             |
    |   | ``LoginRequiredException``.                         |
    +---+-----------------------------------------------------+
    | 3 | Валидация сессии.                                   |
    +---+-----------------------------------------------------+
    | 4 | При невалидной сессии →                             |
    |   | ``LoginRequiredException``.                         |
    +---+-----------------------------------------------------+
    | 5 | Возврат сессии.                                     |
    +---+-----------------------------------------------------+

    Args:
        request: HTTP-запрос.
        auth: Сервис аутентификации.

    Returns:
        ``Session`` текущего пользователя.

    Raises:
        LoginRequiredException: Если сессия отсутствует или невалидна.
    """
    token = extract_token(request)
    if token is None:
        raise LoginRequiredException(
            redirect_path=str(request.url.path),
        )

    session = auth.validate_session(token)
    if session is None:
        raise LoginRequiredException(
            redirect_path=str(request.url.path),
        )

    return session


