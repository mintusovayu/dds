"""
Аутентификация и авторизация веб-интерфейса DDS.

Этот модуль содержит механизмы аутентификации пользователей
и разграничения прав доступа. Поддерживаются две схемы
аутентификации:

- Bearer-токен в заголовке Authorization (для API endpoints).
- Сессионный токен в cookies (для HTML-страниц).

Пароли хранятся в хешированном виде (PBKDF2-HMAC-SHA256 с солью).
Сессионные токены генерируются через ``secrets.token_hex()``
и хранятся в памяти сервера.

Удаление Service Locator (скорректированный план, Фаза 2):
Модульный глобал ``_auth_service`` и функции ``set_auth_service()``
/ ``get_auth_service()`` без аргументов удалены. FastAPI dependency
:func:`get_auth_service` принимает :class:`~fastapi.Request` и
читает сервис из ``request.app.state.auth_service``; значение
записывается в lifespan при старте приложения. Это устраняет
скрытую глобальную связь между зависимостями аутентификации
и делает их тестируемыми через
``app.dependency_overrides[get_auth_service]``.

Разделение ответственности:

- HTML-страницы: при отсутствии сессии → редирект на ``/login``
  через ``LoginRequiredException`` и exception handler.
- API endpoints: при отсутствии сессии → 401 JSON через
  ``HTTPException``.

Парольная политика:

При добавлении пользователя пароль проходит проверку надёжности:

+----------------------------------+----------------------------------+
| Правило                          | Описание                         |
+==================================+==================================+
| Минимальная длина                | Пароль должен содержать не       |
|                                  | менее ``PASSWORD_MIN_LENGTH``    |
|                                  | символов.                        |
+----------------------------------+----------------------------------+
| Запрет тривиальных паролей       | Пароль не должен входить в       |
|                                  | чёрный список распространённых   |
|                                  | паролей.                         |
+----------------------------------+----------------------------------+
| Запрет совпадения с логином      | Пароль не должен совпадать       |
|                                  | с именем пользователя.           |
+----------------------------------+----------------------------------+
| Запрет чисто цифровых паролей    | Пароль не должен состоять        |
|                                  | исключительно из цифр.           |
+----------------------------------+----------------------------------+

При нарушении любого правила ``add_user()`` выбрасывает
``ValueError`` с описанием нарушения.

Поддержка env-паролей (скорректированный план):

Помимо пароля в открытом виде (``add_user``), поддерживается
добавление пользователя с готовым хешем и солью
(``add_user_with_hash``). Это позволяет получать пароли из
переменных окружения ``DDS_USER_<NAME>_PASSWORD_HASH`` и
``DDS_USER_<NAME>_PASSWORD_SALT``, не храня их в открытом виде
в ``config.json``. Формат хеша фиксирован: PBKDF2-HMAC-SHA256,
100 000 итераций, hex-encoded (64 символа). Валидация формата
выполняется через ``_HASH_PATTERN``.

Смена пароля:

Метод ``change_password()`` позволяет аутентифицированному
пользователю сменить пароль. При смене пароля:

+----------------------------------+----------------------------------+
| Шаг                              | Описание                         |
+==================================+==================================+
| Проверка пользователя            | Пользователь должен существовать |
|                                  | в реестре.                       |
+----------------------------------+----------------------------------+
| Проверка старого пароля          | Старый пароль хешируется         |
|                                  | с сохранённой солью и            |
|                                  | сравнивается через               |
|                                  | ``secrets.compare_digest``.      |
+----------------------------------+----------------------------------+
| Валидация нового пароля          | Новый пароль проходит полную     |
|                                  | проверку через                   |
|                                  | ``_validate_password_strength()``|
+----------------------------------+----------------------------------+
| Генерация новой соли             | При каждой смене пароля          |
|                                  | генерируется новая соль.         |
+----------------------------------+----------------------------------+
| Хеширование и обновление         | Новый пароль хешируется          |
|                                  | с новой солью, запись            |
|                                  | пользователя обновляется.        |
+----------------------------------+----------------------------------+

Автологин по IP-адресу:

Модуль предоставляет низкоуровневую поддержку автологина по
IP-адресу. Сама логика принятия решения (какой IP какому
пользователю соответствует) находится в
``dds_web/auto_login.py``; модуль ``auth.py`` предоставляет
только механизмы:

- Константа ``AUTO_LOGIN_OPT_OUT_COOKIE_NAME`` — имя cookie,
  устанавливаемой при явном выходе.
- Поле ``Session.is_auto`` — признак, что сессия создана
  автоматически.
- Метод ``create_session_for_user()`` — единая точка создания
  сессий (для парольного входа и автологина).
- Метод ``user_exists()`` — проверка существования пользователя
  без проверки пароля.
- Модификация ``extract_token()`` — сначала проверяет токен,
  инжектированный middleware автологина в
  ``request.state.auto_login_token``.

Принципы:

- Модуль находится в presentation layer и не содержит бизнес-логики.
- Пароли не хранятся в открытом виде.
- Сессионные токены имеют ограниченный срок действия.
- Разграничение прав: администратор и пользователь.
- Cookies устанавливаются с флагами ``httponly`` и ``samesite=lax``
  для защиты от XSS и CSRF.
- При смене пароля генерируется новая соль.
- Проверка старого пароля выполняется через
  ``secrets.compare_digest`` для предотвращения timing-атак.
- Cookie-константы определены в этом модуле (не в
  ``auto_login.py``), чтобы избежать circular imports.
- Сервис аутентификации передаётся через DI:
  :func:`get_auth_service` читает его из ``request.app.state``.
  Модульные глобалы (Service Locator) не используются.

Классы:

``AuthService`` — сервис аутентификации и авторизации.
``LoginRequiredException`` — исключение для редиректа на ``/login``.

Зависимости FastAPI:

``get_current_user`` — для API: выбрасывает ``HTTPException 401``.
``require_login`` — для HTML: выбрасывает ``LoginRequiredException``.
``require_admin`` — проверка прав администратора.
``get_optional_session`` — возвращает ``Session`` или ``None``.

Извлечение токенов:

``extract_all_tokens()`` — возвращает все токены из запроса.
``extract_token()`` — возвращает первый токен из запроса.
"""

