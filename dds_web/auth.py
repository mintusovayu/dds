def get_auth_service(request: Request) -> AuthService:
    """Возвращает сервис аутентификации из ``request.app.state``.

    FastAPI dependency для доступа к :class:`AuthService`, созданному
    в ``lifespan`` при старте приложения. Значение сохраняется
    в ``app.state.auth_service`` (см.
    ``dds_web/lifespan.py::create_app_with_lifespan``), что
    обеспечивает инверсию зависимостей: presentation layer
    (зависимости аутентификации) получает сервис через DI, а не
    через модульный глобал. Это устраняет скрытую глобальную связь
    и позволяет тестам подменять сервис через
    ``app.dependency_overrides[get_auth_service]``.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Чтение ``request.app.state.auth_service`` через     |
    |   | ``getattr(..., None)`` — защита от отсутствия       |
    |   | атрибута (например, при вызове зависимости без      |
    |   | lifespan в unit-тесте).                             |
    +---+-----------------------------------------------------+
    | 2 | Если значение ``None`` — ``HTTPException 503``.     |
    +---+-----------------------------------------------------+
    | 3 | Возврат сервиса.                                    |
    +---+-----------------------------------------------------+

    Args:
        request: HTTP-запрос FastAPI. ``request.app.state`` —
            пространство имён приложения, заполняемое в lifespan.

    Returns:
        Экземпляр :class:`AuthService`, созданный при старте.

    Raises:
        HTTPException 503: Если сервис аутентификации не
            инициализирован (lifespan не выполнен, либо
            зависимость вызвана до startup).
    """
    auth = getattr(request.app.state, "auth_service", None)
    if auth is None:
        raise HTTPException(
            status_code=503,
            detail="Сервис аутентификации не инициализирован.",
        )
    return auth


# Типизированная зависимость для AuthService
AuthDep = Annotated[AuthService, Depends(get_auth_service)]

