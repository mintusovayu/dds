def extract_all_tokens(request: Request) -> list[str]:
    """Извлекает все токены из запроса (Bearer + cookie).

    Возвращает список токенов из двух источников:
    заголовка ``Authorization: Bearer {token}`` и cookie
    ``SESSION_COOKIE_NAME``. Порядок: сначала Bearer, затем cookie.

    Используется в ``logout_submit`` для инвалидации всех возможных
    сессий клиента, включая случай одновременного наличия cookie
    и Bearer-заголовка.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Проверка заголовка ``Authorization: Bearer {token}``.|
    |   | При совпадении — добавление токена в список.        |
    +---+-----------------------------------------------------+
    | 2 | Проверка cookie ``SESSION_COOKIE_NAME``.             |
    |   | При наличии — добавление токена в список.           |
    +---+-----------------------------------------------------+
    | 3 | Возврат списка найденных токенов.                   |
    +---+-----------------------------------------------------+

    Args:
        request: HTTP-запрос.

    Returns:
        Список токенов в порядке: Bearer, cookie. Пустой список,
        если ни один источник не содержит токена.
    """
    tokens: list[str] = []

    auth_header = request.headers.get("Authorization")
    if auth_header:
        parts = auth_header.split(" ", 1)
        if len(parts) == 2 and parts[0] == "Bearer":
            tokens.append(parts[1])

    cookie_token = request.cookies.get(SESSION_COOKIE_NAME)
    if cookie_token:
        tokens.append(cookie_token)

    return tokens


def extract_token(request: Request) -> str | None:
    """Извлекает первый токен из запроса.

    Возвращает первый токен, найденный в запросе. Порядок
    приоритетов:

    1. Токен, инжектированный ``auto_login_middleware`` в
       ``request.state.auto_login_token``. Это позволяет
       ``require_login`` видеть только что созданную сессию в
       том же запросе, в котором сработал автологин (session
       cookie станет видимой браузеру только на следующем
       запросе).
    2. Bearer-заголовок.
    3. Session cookie.

    Используется в зависимостях аутентификации
    (``get_current_user``, ``require_login``,
    ``get_optional_session``) для определения активной сессии.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Проверка ``getattr(request.state,                    |
    |   | "auto_login_token", None)``. При наличии — возврат. |
    +---+-----------------------------------------------------+
    | 2 | Вызов ``extract_all_tokens(request)``.              |
    +---+-----------------------------------------------------+
    | 3 | Возврат первого элемента списка или ``None``,       |
    |   | если список пуст.                                   |
    +---+-----------------------------------------------------+

    Args:
        request: HTTP-запрос.

    Returns:
        Токен или ``None``, если токен не найден.
    """
    # 1. Токен, инжектированный auto-login middleware.
    #    request.state читает из scope["state"], куда middleware
    #    записывает токен до вызова call_next.
    injected = getattr(request.state, "auto_login_token", None)
    if injected:
        return injected

    # 2. Обычная логика (Bearer приоритетнее cookie).
    tokens = extract_all_tokens(request)
    return tokens[0] if tokens else None


