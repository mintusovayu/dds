# ----------------------------------------------------------------------

_HASH_PATTERN = re.compile(r"^[0-9a-f]{64}$")
"""Регулярное выражение для проверки hex-формата хеша пароля.

Соответствует результату ``hashlib.pbkdf2_hmac("sha256", ...).hex()``:
64 hex-символа нижнего регистра. Используется в
``AuthService.add_user_with_hash`` для валидации хешей, полученных
из внешних источников (переменных окружения). Отклоняет пустые
строки, хеши другого алгоритма и произвольный мусор.
"""


