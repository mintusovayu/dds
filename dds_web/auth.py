class LoginRequiredException(Exception):  # noqa: N818 — Exception-суффикс
    """Исключение, сигнализирующее о необходимости авторизации.

    Выбрасывается зависимостью ``require_login`` при отсутствии
    валидной сессии на HTML-страницах. Обрабатывается exception
    handler в ``run.py``, который выполняет редирект на ``/login``
    с параметром ``next`` для возврата на исходную страницу.

    Attributes:
        redirect_path: Путь к исходной странице, на которую нужно
            вернуться после успешного входа.
    """

    def __init__(self, redirect_path: str = "/") -> None:
        """Инициализирует исключение.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ``redirect_path``.                       |
        +---+-----------------------------------------------------+
        | 2 | Вызов ``super().__init__()`` с сообщением.          |
        +---+-----------------------------------------------------+

        Args:
            redirect_path: Путь для возврата после входа.
                По умолчанию ``"/"`` (главная страница).
        """
        self.redirect_path = redirect_path
        super().__init__("Требуется авторизация")


# ----------------------------------------------------------------------
# Модели аутентификации
# ----------------------------------------------------------------------


class UserRole(StrEnum):
    """Роль пользователя.

    +----------------------------------+----------------------------------+
    | Роль                             | Описание                         |
    +==================================+==================================+
    | ``ADMIN``                        | Полный доступ: запуск            |
    |                                  | сканирования, управление         |
    |                                  | модулями, изменение настроек.    |
    +----------------------------------+----------------------------------+
    | ``USER``                         | Доступ только к поиску           |
    |                                  | и просмотру документов.          |
    +----------------------------------+----------------------------------+
    """

    ADMIN = "admin"
    USER = "user"


@dataclass
class User:
    """Пользователь системы.

    +----------------------------------+----------------------------------+
    | Атрибут                          | Описание                         |
    +==================================+==================================+
    | ``username``                     | Имя пользователя (уникальное).   |
    +----------------------------------+----------------------------------+
    | ``password_hash``                | Хеш пароля (PBKDF2-HMAC-SHA256). |
    +----------------------------------+----------------------------------+
    | ``salt``                         | Соль для хеширования пароля.     |
    +----------------------------------+----------------------------------+
    | ``role``                         | Роль пользователя.               |
    +----------------------------------+----------------------------------+
    """

    username: str
    password_hash: str
    salt: str
    role: UserRole = UserRole.USER


@dataclass
class Session:
    """Сессия пользователя.

    +----------------------------------+----------------------------------+
    | Атрибут                          | Описание                         |
    +==================================+==================================+
    | ``token``                        | Сессионный токен.                |
    +----------------------------------+----------------------------------+
    | ``username``                     | Имя пользователя.                |
    +----------------------------------+----------------------------------+
    | ``role``                         | Роль пользователя.               |
    +----------------------------------+----------------------------------+
    | ``created_at``                   | Время создания (UNIX).           |
    +----------------------------------+----------------------------------+
    | ``expires_at``                   | Время истечения (UNIX).          |
    +----------------------------------+----------------------------------+
    | ``is_auto``                      | ``True``, если сессия создана    |
    |                                  | автоматически по IP-адресу.      |
    |                                  | ``False`` при парольном входе.   |
    +----------------------------------+----------------------------------+
    """

    token: str
    username: str
    role: UserRole
    created_at: float
    expires_at: float
    is_auto: bool = False


# ----------------------------------------------------------------------
# Сервис аутентификации
# ----------------------------------------------------------------------


class AuthService:
    """Сервис аутентификации и авторизации.

    Управляет пользователями, сессиями и проверкой прав доступа.
    Данные хранятся в памяти сервера.

    Парольная политика:

    При добавлении пользователя пароль проверяется на соответствие
    минимальным требованиям надёжности. Проверка выполняется
    методом ``_validate_password_strength()``.

    +----------------------------------+----------------------------------+
    | Правило                          | Описание                         |
    +==================================+==================================+
    | Минимальная длина                | Не менее                         |
    |                                  | ``core_config.PASSWORD_MIN_LENGTH``|
    |                                  | символов.                        |
    +----------------------------------+----------------------------------+
    | Чёрный список                    | Пароль не входит в               |
    |                                  | ``core_config.PASSWORD_COMMON_   |
    |                                  | BLACKLIST``.                     |
    +----------------------------------+----------------------------------+
    | Совпадение с логином             | Пароль не совпадает с            |
    |                                  | ``username`` (без учёта          |
    |                                  | регистра).                       |
    +----------------------------------+----------------------------------+
    | Чисто цифровой                   | Пароль не состоит исключительно  |
    |                                  | из цифр.                         |
    +----------------------------------+----------------------------------+

    Поддержка env-паролей (скорректированный план):

    Метод ``add_user_with_hash()`` позволяет добавить пользователя
    с готовым хешем и солью, минуя проверку пароля в открытом виде.
    Формат хеша фиксирован (PBKDF2-HMAC-SHA256, 64 hex-символа),
    валидируется через ``_HASH_PATTERN``. Используется в
    ``dds_web/lifespan.py::create_auth_service`` для поддержки
    переменных окружения ``DDS_USER_<NAME>_PASSWORD_HASH`` и
    ``DDS_USER_<NAME>_PASSWORD_SALT``.

    Смена пароля:

    Метод ``change_password()`` позволяет сменить пароль
    пользователя. Новый пароль проходит полную валидацию
    по парольной политике. При каждой смене пароля генерируется
    новая соль.

    Автологин по IP-адресу:

    Метод ``create_session_for_user()`` создаёт сессию без
    проверки пароля. Используется как автологином, так и
    парольным входом (``login`` делегирует в него). Флаг
    ``is_auto`` различает источник сессии.

    Пример использования::

        auth = AuthService(session_ttl_seconds=3600)
        auth.add_user("admin", "SecureP@ss123", UserRole.ADMIN)
        token = auth.login("admin", "SecureP@ss123")
        user = auth.validate_session(token)

        # Добавление с готовым хешем (из env).
        auth.add_user_with_hash(
            "user1",
            "a1b2...64hex",
            "deadbeef...salt",
            UserRole.USER,
        )

        # Смена пароля
        auth.change_password("admin", "SecureP@ss123", "NewSecureP@ss456")

        # Создание сессии без пароля (для автологина)
        token_auto = auth.create_session_for_user("admin", is_auto=True)

        # Проверка существования пользователя
        if auth.user_exists("admin"):
            ...

    Attributes:

    +---------------------+------------------------------------------+
    | Атрибут             | Описание                                 |
    +=====================+==========================================+
    | ``_users``          | Словарь пользователей.                   |
    |                     | Ключ — ``username``.                     |
    +---------------------+------------------------------------------+
    | ``_sessions``       | Словарь активных сессий.                 |
    |                     | Ключ — ``token``.                        |
    +---------------------+------------------------------------------+
    | ``_session_ttl``    | Время жизни сессии в секундах.           |
    +---------------------+------------------------------------------+
    """

    def __init__(self, session_ttl_seconds: int = 3600) -> None:
        """Инициализирует сервис аутентификации.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Инициализация пустого словаря ``_users``.           |
        +---+-----------------------------------------------------+
        | 2 | Инициализация пустого словаря ``_sessions``.        |
        +---+-----------------------------------------------------+
        | 3 | Сохранение ``session_ttl_seconds``.                 |
        +---+-----------------------------------------------------+

        Args:
            session_ttl_seconds: Время жизни сессии в секундах.
                По умолчанию 3600 (1 час).
        """
        self._users: dict[str, User] = {}
        self._sessions: dict[str, Session] = {}
        self._session_ttl = session_ttl_seconds

    @property
    def session_ttl(self) -> int:
        """Возвращает время жизни сессии в секундах.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Возврат ``_session_ttl``.                           |
        +---+-----------------------------------------------------+

        Returns:
            Текущее значение ``_session_ttl``.
        """
        return self._session_ttl

    def add_user(
        self,
        username: str,
        password: str,
        role: UserRole = UserRole.USER,
    ) -> None:
        """Добавляет пользователя с проверкой надёжности пароля.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка уникальности ``username``.                 |
        +---+-----------------------------------------------------+
        | 2 | Проверка надёжности пароля через                    |
        |   | ``_validate_password_strength()``.                  |
        +---+-----------------------------------------------------+
        | 3 | Генерация соли через ``secrets.token_hex(16)``.     |
        +---+-----------------------------------------------------+
        | 4 | Хеширование пароля через ``_hash_password()``.      |
        +---+-----------------------------------------------------+
        | 5 | Сохранение пользователя в ``_users``.               |
        +---+-----------------------------------------------------+

        Args:
            username: Имя пользователя (уникальное).
            password: Пароль в открытом виде (хешируется).
            role: Роль пользователя.

        Raises:
            ValueError: Если пользователь с таким именем уже
                существует.
            ValueError: Если пароль не соответствует требованиям
                надёжности. Сообщение содержит описание нарушения.
        """
        if username in self._users:
            raise ValueError(f"Пользователь уже существует: {username}")

        self._validate_password_strength(username, password)

        salt = secrets.token_hex(16)
        password_hash = self._hash_password(password, salt)

        self._users[username] = User(
            username=username,
            password_hash=password_hash,
            salt=salt,
            role=role,
        )

    def add_user_with_hash(
        self,
        username: str,
        password_hash: str,
        salt: str,
        role: UserRole = UserRole.USER,
    ) -> None:
        """Добавляет пользователя с готовым хешем и солью.

        Используется для поддержки env-паролей: хеш и соль
        передаются извне (например, из переменных окружения
        ``DDS_USER_<NAME>_PASSWORD_HASH`` и
        ``DDS_USER_<NAME>_PASSWORD_SALT``), минуя ввод пароля
        в открытом виде.

        Формат ``password_hash`` фиксирован: PBKDF2-HMAC-SHA256,
        100 000 итераций, hex-encoded (64 символа). Валидация
        выполняется через ``_HASH_PATTERN``. Другие алгоритмы
        и длины хеша отклоняются.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка уникальности ``username``.                 |
        +---+-----------------------------------------------------+
        | 2 | Валидация формата ``password_hash`` через           |
        |   | ``_HASH_PATTERN`` (64 hex-символа).                 |
        +---+-----------------------------------------------------+
        | 3 | Валидация формата ``salt`` (непустая строка,        |
        |   | минимум 16 символов).                               |
        +---+-----------------------------------------------------+
        | 4 | Сохранение пользователя в ``_users``.               |
        +---+-----------------------------------------------------+

        Примечание:
            Парольная политика (``_validate_password_strength``)
            здесь не применяется: проверка пароля в открытом виде
            невозможна. Ответственность за надёжность пароля
            лежит на администраторе, задавшем хеш во внешнем
            источнике.

        Args:
            username: Имя пользователя (уникальное).
            password_hash: Хеш пароля в hex-формате (64 символа
                нижнего регистра), полученный через
                ``hashlib.pbkdf2_hmac("sha256", ...).hex()``.
            salt: Соль, использованная при хешировании. Строка
                длиной не менее 16 символов (обычно результат
                ``secrets.token_hex(16)``).
            role: Роль пользователя.

        Raises:
            ValueError: Если пользователь с таким именем уже
                существует.
            ValueError: Если ``password_hash`` не соответствует
                формату (не 64 hex-символа).
            ValueError: Если ``salt`` пустой или короче 16 символов.
        """
        if username in self._users:
            raise ValueError(f"Пользователь уже существует: {username}")

        if not _HASH_PATTERN.match(password_hash):
            raise ValueError(
                f"Неверный формат password_hash для '{username}': "
                f"ожидается 64 hex-символа (PBKDF2-HMAC-SHA256)."
            )

        if not salt or len(salt) < 16:
            raise ValueError(f"Неверный формат salt для '{username}': минимум 16 символов.")

        self._users[username] = User(
            username=username,
            password_hash=password_hash,
            salt=salt,
            role=role,
        )

    def user_exists(self, username: str) -> bool:
        """Проверяет существование пользователя.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка наличия ``username`` в ``_users``.         |
        +---+-----------------------------------------------------+
        | 2 | Возврат результата.                                 |
        +---+-----------------------------------------------------+

        Примечание:
            Метод не проверяет пароль и не выполняет никаких
            ресурсоёмких операций. Используется в модуле
            ``auto_login.py`` для валидации ``ip_user_map``
            при старте приложения и при резолве IP-адреса в
            username.

        Args:
            username: Имя пользователя.

        Returns:
            ``True``, если пользователь зарегистрирован.
            ``False`` в противном случае.
        """
        return username in self._users

    def change_password(
        self,
        username: str,
        old_password: str,
        new_password: str,
    ) -> None:
        """Меняет пароль пользователя.

        Проверяет текущий пароль, валидирует новый пароль по
        парольной политике и выполняет замену хеша. При каждой
        смене пароля генерируется новая соль.

        Операции:

        +----+-----------------------------------------------------+
        | №  | Описание                                            |
        +====+=====================================================+
        | 1  | Поиск пользователя по ``username``.                 |
        |    | Если пользователь не найден — выбрасывается       |
        |    | ``ValueError``.                                 |
        +----+-----------------------------------------------------+
        | 2  | Хеширование ``old_password`` с сохранённой        |
        |    | солью пользователя через ``_hash_password()``.    |
        +----+-----------------------------------------------------+
        | 3  | Сравнение хеша старого пароля с сохранённым       |
        |    | через ``secrets.compare_digest()`` для            |
        |    | предотвращения timing-атак. Если хеши не          |
        |    | совпадают — выбрасывается ``ValueError``.         |
        +----+-----------------------------------------------------+
        | 4  | Валидация нового пароля через                     |
        |    | ``_validate_password_strength()``. Если пароль    |
        |    | не соответствует требованиям — выбрасывается      |
        |    | ``ValueError`` с описанием нарушения.             |
        +----+-----------------------------------------------------+
        | 5  | Генерация новой соли через                        |
        |    | ``secrets.token_hex(16)``.                        |
        +----+-----------------------------------------------------+
        | 6  | Хеширование ``new_password`` с новой солью        |
        |    | через ``_hash_password()``.                       |
        +----+-----------------------------------------------------+
        | 7  | Обновление записи пользователя в ``_users``:      |
        |    | замена ``password_hash`` и ``salt``.              |
        +----+-----------------------------------------------------+
        | 8  | Возврат ``None`` (успешная смена пароля).         |
        +----+-----------------------------------------------------+

        Примечание:
        При смене пароля генерируется новая соль. Это предотвращает
        переиспользование старых хешей и обеспечивает защиту
        от атак на основе ранее скомпрометированных данных.

        Примечание:
        Активные сессии пользователя не аннулируются при смене
        пароля. Пользователь продолжает работать в текущей сессии.
        При необходимости аннулирования сессий вызывающий код
        должен выполнить это отдельно.

        Примечание:
        Метод является блокирующей операцией (хеширование пароля
        через ``PBKDF2-HMAC-SHA256`` с 100 000 итераций). При
        вызове из асинхронного контекста должен выполняться
        через ``run_in_executor`` с ``api_executor`` и обёрнут
        в ``run_with_timeout`` с дескриптором ``auth.login``.

        Args:
            username: Имя пользователя, для которого выполняется
                смена пароля.
            old_password: Текущий пароль пользователя для
                подтверждения.
            new_password: Новый пароль. Должен соответствовать
                парольной политике.

        Raises:
            ValueError: Если пользователь не найден.
            ValueError: Если старый пароль неверен.
            ValueError: Если новый пароль не соответствует
                требованиям надёжности. Сообщение содержит
                описание нарушения.
        """
        # Шаг 1: Поиск пользователя
        user = self._users.get(username)
        if user is None:
            raise ValueError(f"Пользователь не найден: {username}")

        # Шаг 2–3: Проверка старого пароля
        old_password_hash = self._hash_password(old_password, user.salt)
        if not secrets.compare_digest(old_password_hash, user.password_hash):
            raise ValueError("Неверный текущий пароль.")

        # Шаг 4: Валидация нового пароля
        self._validate_password_strength(username, new_password)

        # Шаг 5–6: Генерация новой соли и хеширование нового пароля
        new_salt = secrets.token_hex(16)
        new_password_hash = self._hash_password(new_password, new_salt)

        # Шаг 7: Обновление записи пользователя
        self._users[username] = User(
            username=username,
            password_hash=new_password_hash,
            salt=new_salt,
            role=user.role,
        )

    def create_session_for_user(
        self,
        username: str,
        is_auto: bool = True,
    ) -> str | None:
        """Создаёт сессию для пользователя без проверки пароля.

        Единая точка создания сессий. Используется как автологином
        по IP-адресу (``is_auto=True``), так и парольным входом
        (``login`` делегирует в этот метод с ``is_auto=False``).

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Поиск пользователя по ``username``.                 |
        |   | Если не найден — возврат ``None``.                  |
        +---+-----------------------------------------------------+
        | 2 | Генерация токена через ``secrets.token_hex(32)``.   |
        +---+-----------------------------------------------------+
        | 3 | Создание ``Session`` с ``is_auto`` и TTL из         |
        |   | ``_session_ttl``.                                   |
        +---+-----------------------------------------------------+
        | 4 | Сохранение сессии в ``_sessions``.                  |
        +---+-----------------------------------------------------+
        | 5 | Возврат токена.                                     |
        +---+-----------------------------------------------------+

        Примечание:
            Метод не проверяет пароль. Это означает, что
            вызывающий код полностью отвечает за аутентификацию
            пользователя до вызова метода. В текущей архитектуре
            метод вызывается только из двух мест: из ``login``
            (после проверки пароля) и из
            ``auto_login_middleware`` (после проверки IP-адреса).

        Примечание:
            Метод не является потокобезопасным относительно
            параллельных вызовов, но в текущей архитектуре
            DDS работает в single-worker режиме uvicorn,
            и все вызовы происходят в одном event loop.
            Запись в ``_sessions`` атомарна между проверками
            (нет ``await`` внутри метода).

        Args:
            username: Имя пользователя. Должен быть
                зарегистрирован в ``_users``.
            is_auto: Признак автоматического создания сессии.
                ``True`` (по умолчанию) — сессия создана
                автологином. ``False`` — парольным входом.

        Returns:
            Сессионный токен, если пользователь существует.
            ``None``, если пользователь не найден.
        """
        user = self._users.get(username)
        if user is None:
            return None

        token = secrets.token_hex(32)
        now = time.time()

        self._sessions[token] = Session(
            token=token,
            username=username,
            role=user.role,
            created_at=now,
            expires_at=now + self._session_ttl,
            is_auto=is_auto,
        )

        return token

    def login(self, username: str, password: str) -> str:
        """Выполняет вход пользователя.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Поиск пользователя по ``username``.                 |
        +---+-----------------------------------------------------+
        | 2 | Хеширование введённого пароля с солью пользователя. |
        +---+-----------------------------------------------------+
        | 3 | Сравнение хешей через ``secrets.compare_digest()``. |
        +---+-----------------------------------------------------+
        | 4 | Создание сессии через ``create_session_for_user``    |
        |   | с ``is_auto=False``.                                |
        +---+-----------------------------------------------------+
        | 5 | Возврат токена.                                     |
        +---+-----------------------------------------------------+

        Примечание:
            Метод делегирует создание сессии в
            :meth:`create_session_for_user`. Это обеспечивает
            единый путь создания сессий для парольного входа
            и автологина, устраняя дублирование.

        Args:
            username: Имя пользователя.
            password: Пароль в открытом виде.

        Returns:
            Сессионный токен.

        Raises:
            ValueError: Если логин или пароль неверны.
        """
        user = self._users.get(username)
        if user is None:
            raise ValueError("Неверный логин или пароль.")

        password_hash = self._hash_password(password, user.salt)

        if not secrets.compare_digest(password_hash, user.password_hash):
            raise ValueError("Неверный логин или пароль.")

        token = self.create_session_for_user(username, is_auto=False)
        if token is None:
            # Защита от гонки: пользователь мог быть удалён между
            # проверками. В текущей архитектуре удаление пользователей
            # не предусмотрено, но ветка оставлена для надёжности.
            raise ValueError("Неверный логин или пароль.")

        return token

    def logout(self, token: str) -> None:
        """Завершает сессию пользователя.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Удаление сессии из ``_sessions`` по ``token``.      |
        +---+-----------------------------------------------------+

        Args:
            token: Сессионный токен.
        """
        self._sessions.pop(token, None)

    def validate_session(self, token: str) -> Session | None:
        """Проверяет валидность сессии.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Поиск сессии по ``token``.                          |
        +---+-----------------------------------------------------+
        | 2 | Если сессия не найдена → возврат ``None``.          |
        +---+-----------------------------------------------------+
        | 3 | Если сессия истекла → удаление, возврат ``None``.   |
        +---+-----------------------------------------------------+
        | 4 | Возврат сессии.                                     |
        +---+-----------------------------------------------------+

        Args:
            token: Сессионный токен.

        Returns:
            ``Session``, если сессия валидна. ``None``, если сессия
            не найдена или истекла.
        """
        session = self._sessions.get(token)
        if session is None:
            return None

        if time.time() > session.expires_at:
            del self._sessions[token]
            return None

        return session

    def cleanup_expired_sessions(self) -> int:
        """Удаляет истёкшие сессии.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Формирование списка токенов с истёкшим сроком.      |
        +---+-----------------------------------------------------+
        | 2 | Удаление каждой истёкшей сессии.                    |
        +---+-----------------------------------------------------+
        | 3 | Возврат количества удалённых сессий.                |
        +---+-----------------------------------------------------+

        Returns:
            Количество удалённых сессий.
        """
        now = time.time()
        expired = [token for token, session in self._sessions.items() if now > session.expires_at]

        for token in expired:
            del self._sessions[token]

        return len(expired)

