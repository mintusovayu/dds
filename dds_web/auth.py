    def _validate_password_strength(
        self,
        username: str,
        password: str,
    ) -> None:
        """Проверяет пароль на соответствие требованиям надёжности.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка минимальной длины:                         |
        |   | ``len(password) >= PASSWORD_MIN_LENGTH``.           |
        +---+-----------------------------------------------------+
        | 2 | Проверка по чёрному списку:                         |
        |   | ``password.lower() not in PASSWORD_COMMON_BLACKLIST``.|
        +---+-----------------------------------------------------+
        | 3 | Проверка совпадения с логином:                      |
        |   | ``password.lower() != username.lower()``.           |
        +---+-----------------------------------------------------+
        | 4 | Проверка чисто цифрового пароля:                    |
        |   | ``not password.isdigit()``.                         |
        +---+-----------------------------------------------------+

        При нарушении любого правила выбрасывается ``ValueError``
        с описанием конкретного нарушения.

        Args:
            username: Имя пользователя (для проверки совпадения).
            password: Пароль для проверки.

        Raises:
            ValueError: Если пароль короче минимальной длины.
            ValueError: Если пароль входит в чёрный список.
            ValueError: Если пароль совпадает с именем пользователя.
            ValueError: Если пароль состоит только из цифр.
        """
        min_length = core_config.PASSWORD_MIN_LENGTH

        if len(password) < min_length:
            raise ValueError(
                f"Пароль слишком короткий: минимальная длина "
                f"{min_length} символов, введено {len(password)}."
            )

        if password.lower() in core_config.PASSWORD_COMMON_BLACKLIST:
            raise ValueError(
                "Пароль входит в список распространённых паролей. "
                "Используйте более надёжный пароль."
            )

        if password.lower() == username.lower():
            raise ValueError("Пароль не должен совпадать с именем пользователя.")

        if password.isdigit():
            raise ValueError(
                "Пароль не должен состоять только из цифр. Добавьте буквы и специальные символы."
            )

    def _hash_password(self, password: str, salt: str) -> str:
        """Хеширует пароль с солью через PBKDF2-HMAC-SHA256.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Вызов ``hashlib.pbkdf2_hmac()`` с 100 000 итераций.|
        +---+-----------------------------------------------------+
        | 2 | Возврат шестнадцатеричной строки хеша.              |
        +---+-----------------------------------------------------+

        Args:
            password: Пароль в открытом виде.
            salt: Соль.

        Returns:
            Шестнадцатеричная строка хеша.
        """
        return hashlib.pbkdf2_hmac(
            "sha256",
            password.encode("utf-8"),
            salt.encode("utf-8"),
            iterations=100_000,
        ).hex()


