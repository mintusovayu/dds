"""
Тесты нормализации текста в domain-слое.

Назначение
----------
Проверка контракта :func:`dds_core.domain.text_normalization.normalize_text`
и :func:`dds_core.domain.text_normalization.denormalize_text`, а также
целостности словарей :data:`CYRILLIC_TO_LATIN_MAP` и
:data:`LATIN_TO_CYRILLIC_MAP`.

Модуль перенесён из ``dds_core/application/text_normalizer.py`` в
``dds_core/domain/text_normalization.py`` в Фазе 3 (Domain cleanup).
Тесты проверяют:

1. **Поведение** ``normalize_text`` / ``denormalize_text``
   — понижение регистра, замена кириллицы на латиницу, обратная
   замена, идемпотентность.
2. **Инварианты словарей** — обратное соответствие
   ``LATIN_TO_CYRILLIC_MAP`` корректно построено из
   ``CYRILLIC_TO_LATIN_MAP``; множества ключей и значений
   согласованы.
3. **Краевые случаи** — пустая строка, строка без кириллицы,
   строка без латиницы, смешанный текст, спецсимволы.

Ожидаемые значения: частичная замена
------------------------------------

Ключевая особенность тестов — **ожидаемые значения содержат
смешанную кириллицу и латиницу**. Это прямое следствие контракта
:func:`~dds_core.domain.text_normalization.normalize_text`:
заменяются только символы из :data:`CYRILLIC_TO_LATIN_MAP`
(12 пар визуально похожих символов: ``а→a``, ``в→b``, ``е→e``,
``к→k``, ``м→m``, ``н→h``, ``о→o``, ``р→p``, ``с→c``, ``т→t``,
``у→y``, ``х→x``). Остальные кириллические символы (``г``, ``д``,
``ш``, ``п``, ``б`` и другие) не входят в таблицу и сохраняются
без изменений.

Это осознанное решение задачи **нечувствительности к раскладке
клавиатуры**, а не «перевода на латиницу». Пользователь, набравший
``ЕС-423-1`` в русской раскладке и ``EC-423-1`` в английской,
получит одинаковые результаты поиска. Полная транслитерация не
требуется и не выполняется. См. ADR-003.

Аналогично :func:`~dds_core.domain.text_normalization.denormalize_text`
выполняет посимвольную обратную замену. Из-за этого:

- Результат не всегда читается как исходный кириллический текст.
  Пример: ``denormalize_text("пример texta")`` даёт ``"пример техта"``
  (потому что ``x → х``, а не ``кс``).
- Round-trip ``denormalize_text(normalize_text(s))`` **не является
  identity** для строк с заглавными буквами: ``normalize_text``
  вызывает ``str.lower()``, что необратимо теряет регистр.

Оба свойства зафиксированы в отдельных тестах.

Проверяемые сценарии
--------------------

+-------------------------------------+--------------------------------+
| Группа                              | Что проверяется                |
+=====================================+================================+
| ``normalize_text``: регистр          | Строка приводится к нижнему    |
|                                      | регистру.                      |
+-------------------------------------+--------------------------------+
| ``normalize_text``: замена           | Каждая пара из                 |
| кириллицы                            | ``CYRILLIC_TO_LATIN_MAP``      |
|                                      | применяется; другие символы    |
|                                      | сохраняются.                   |
+-------------------------------------+--------------------------------+
| ``normalize_text``: примеры          | Совпадение с примерами из      |
| из docstring                         | docstring функции.             |
+-------------------------------------+--------------------------------+
| ``normalize_text``: краевые          | Пустая строка, только пробелы, |
| случаи                               | только цифры/пунктуация.       |
+-------------------------------------+--------------------------------+
| ``denormalize_text``: замена         | Каждая пара из                 |
| латиницы                             | ``LATIN_TO_CYRILLIC_MAP``      |
|                                      | применяется; другие символы    |
|                                      | сохраняются.                   |
+-------------------------------------+--------------------------------+
| ``denormalize_text``: примеры        | Совпадение с примерами из      |
| из docstring                         | docstring функции.             |
+-------------------------------------+--------------------------------+
| Round-trip для нижнего регистра      | ``denormalize_text(            |
|                                      | normalize_text(s))`` для       |
|                                      | строк в нижнем регистре        |
|                                      | восстанавливает кириллицу.     |
+-------------------------------------+--------------------------------+
| Round-trip теряет регистр            | Заглавные буквы после          |
|                                      | round-trip становятся          |
|                                      | строчными.                     |
+-------------------------------------+--------------------------------+
| Round-trip не является identity      | Для строк с исходной латиницей |
| для исходной латиницы                | round-trip даёт кириллицу.     |
+-------------------------------------+--------------------------------+
| Идемпотентность                      | Повторный вызов не изменяет    |
|                                      | результат.                     |
+-------------------------------------+--------------------------------+
| Инварианты словарей                  | Обратный словарь построен из   |
|                                      | прямого; соответствие          |
|                                      | ``<->`` согласовано.           |
+-------------------------------------+--------------------------------+

Стратегия тестирования
----------------------
- **Параметризация через ``pytest.mark.parametrize``** для
  проверки каждой пары из словарей: если кто-то добавит новую
  пару в ``CYRILLIC_TO_LATIN_MAP``, тест автоматически её
  проверит.
- **Примеры из docstring** дублируются в тестах, чтобы гарантировать
  соответствие между описанием и поведением. Если реализация
  изменится, а docstring — нет, тест поймает расхождение.
- **Round-trip** проверяется отдельно для строк в нижнем
  регистре (где он работает как identity) и для строк с
  заглавными буквами (где регистр теряется). Это документирует
  фактическое поведение и защищает от случайного «улучшения»
  ``denormalize_text``.

Границы
-------
- **Использование в модулях проекта** (``pymupdf_text_extractor``,
  ``highlights_service``, ``fts5_search_backend``) — не входит
  в область: покрывается соответствующими тестами этих модулей
  (матрица трансформации координат, тесты FTS5-бэкенда и т. д.).
- **Производительность** ``normalize_text`` — вне области
  (микро-бенчмарки не оправданы для функции уровня O(n·k), где
  k — количество пар в словаре).
- **Unicode-нормализация** (NFC/NFD) — не входит: функция
  работает с конкретными символами, не с формами Unicode.

Запуск
------
::

    pytest tests/test_text_normalization_domain.py -v

Принципы:
    - модуль не выполняет логирования;
    - не читает и не пишет файлы;
    - не имеет побочных эффектов при импорте;
    - каждый тест изолирован, не зависит от порядка выполнения;
    - тесты детерминированы: одинаковый вход → одинаковый результат.
"""

from __future__ import annotations

import pytest
from dds_core.domain.text_normalization import (
    CYRILLIC_TO_LATIN_MAP,
    LATIN_TO_CYRILLIC_MAP,
    denormalize_text,
    normalize_text,
)

# =====================================================================
# Раздел 1. normalize_text: регистр
# =====================================================================


def test_normalize_text_lowercases_ascii_uppercase() -> None:
    """Заглавные ASCII-буквы приводятся к нижнему регистру."""
    assert normalize_text("HELLO") == "hello"


def test_normalize_text_lowercases_cyrillic_uppercase() -> None:
    """Заглавные кириллические буквы приводятся к нижнему регистру.

    Пример ``"ДОМ"`` разбирается следующим образом: сначала
    ``str.lower()`` даёт ``"дом"``; затем замены по
    :data:`CYRILLIC_TO_LATIN_MAP`: ``д`` не входит в таблицу,
    ``о→o``, ``м→m``. Результат — ``"дom"`` (смешанная
    кириллица/латиница).
    """
    assert normalize_text("ДОМ") == "дom"


def test_normalize_text_mixed_case() -> None:
    """Смешанный регистр нормализуется согласованно."""
    assert normalize_text("Hello World") == "hello world"


# =====================================================================
# Раздел 2. normalize_text: замена кириллицы
# =====================================================================


@pytest.mark.parametrize(
    ("cyrillic", "latin"),
    sorted(CYRILLIC_TO_LATIN_MAP.items()),
    ids=[f"{cyr}-to-{lat}" for cyr, lat in sorted(CYRILLIC_TO_LATIN_MAP.items())],
)
def test_normalize_text_replaces_each_cyrillic_pair(
    cyrillic: str,
    latin: str,
) -> None:
    """Каждая пара ``кириллица → латиница`` применяется.

    Параметризация по всем элементам :data:`CYRILLIC_TO_LATIN_MAP`.
    Если в словарь добавят новую пару, тест автоматически её
    подхватит.
    """
    assert normalize_text(cyrillic) == latin


def test_normalize_text_preserves_non_mapped_characters() -> None:
    """Символы вне словаря остаются без изменений.

    Цифры, знаки пунктуации, пробелы, а также кириллические буквы,
    не входящие в :data:`CYRILLIC_TO_LATIN_MAP` (например, ``б``,
    ``г``, ``д``), должны оставаться в исходном виде.
    """
    # "д", "б", "г", "ж" — не входят в CYRILLIC_TO_LATIN_MAP
    assert normalize_text("дбгж") == "дбгж"


def test_normalize_text_preserves_digits_and_punctuation() -> None:
    """Цифры и знаки пунктуации не затрагиваются."""
    assert normalize_text("123-456.789!") == "123-456.789!"


