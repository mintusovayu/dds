# =====================================================================
# Раздел 7. Round-trip
# =====================================================================


@pytest.mark.parametrize(
    "raw",
    [
        "ес-423-1",  # кириллица в нижнем регистре + цифры и дефисы
        "пример текста",  # смешанный кириллический в нижнем регистре
        "гидрошпонка",  # типичный технический термин в нижнем регистре
        "снип 2.02.01-83",  # аббревиатура + точки + дефисы
    ],
    ids=["es-423-1", "primer", "hydro", "snip"],
)
def test_round_trip_restores_cyrillic_for_lowercase(raw: str) -> None:
    """``denormalize_text(normalize_text(s))`` восстанавливает кириллицу.

    Проверяется для строк **в нижнем регистре**, содержащих только
    символы, которые могут быть восстановлены посимвольно
    (кириллица из :data:`LATIN_TO_CYRILLIC_MAP` значений, цифры,
    пунктуация, пробелы).

    Для строк с заглавными буквами round-trip не является identity
    (регистр теряется на этапе ``str.lower()``) — этот случай
    покрывается отдельным тестом
    :func:`test_round_trip_loses_uppercase`.
    """
    normalized = normalize_text(raw)
    restored = denormalize_text(normalized)
    assert restored == raw


@pytest.mark.parametrize(
    ("raw", "expected_after_round_trip"),
    [
        # Заглавные кириллические: теряются.
        ("ЕС-423-1", "ес-423-1"),
        ("Пример текста", "пример текста"),
        ("Гидрошпонка", "гидрошпонка"),
        ("СНиП 2.02.01-83", "снип 2.02.01-83"),
    ],
    ids=["ES", "Example", "Hydro", "SNIP"],
)
def test_round_trip_loses_uppercase(
    raw: str,
    expected_after_round_trip: str,
) -> None:
    """Round-trip теряет регистр.

    ``normalize_text`` выполняет ``str.lower()``, что необратимо
    уничтожает информацию о регистре исходной строки.
    ``denormalize_text`` выполняет только посимвольную замену
    латиницы на кириллицу и не восстанавливает регистр.

    Тест фиксирует это как **ожидаемое поведение**: восстановление
    регистра не является задачей функций нормализации. Все
    потребители (индексация, сниппеты, подсветка) работают с
    текстом в нижнем регистре; исходный регистр сохраняется в
    колонке ``text_content`` FTS-индекса, а не в ``normalized_text``.
    """
    normalized = normalize_text(raw)
    restored = denormalize_text(normalized)
    assert restored == expected_after_round_trip


def test_round_trip_does_not_affect_original_latin() -> None:
    """Round-trip для строк с латиницей не является identity.

    Это ожидаемое поведение: нормализация не различает исходную
    латиницу и латиницу, полученную из кириллицы. Обратная замена
    меняет **все** латинские буквы, входящие в
    :data:`LATIN_TO_CYRILLIC_MAP`, на кириллицу.

    Проверка документирует поведение и защищает от случайного
    «улучшения» ``denormalize_text`` до полной identity.
    """
    original = "ec-423-1"  # изначально латиница
    normalized = normalize_text(original)
    restored = denormalize_text(normalized)
    # "e" → "е", "c" → "с"; результат — кириллица.
    assert restored == "ес-423-1"
    assert restored != original


# =====================================================================
# Раздел 8. Идемпотентность
# =====================================================================


@pytest.mark.parametrize(
    "raw",
    [
        "ЕС-423-1",
        "Пример текста",
        "123-456.789!",
        "",
        "   ",
    ],
    ids=["es", "example", "digits", "empty", "spaces"],
)
def test_normalize_text_is_idempotent(raw: str) -> None:
    """Повторная нормализация не изменяет результат.

    ``normalize_text(normalize_text(s)) == normalize_text(s)``.
    Инвариант гарантирует, что функция применяет замены
    детерминированно и не зависит от предыдущего состояния.
    """
    once = normalize_text(raw)
    twice = normalize_text(once)
    assert once == twice


# =====================================================================
# Раздел 9. Инварианты словарей
# =====================================================================


def test_latin_to_cyrillic_is_reverse_of_cyrillic_to_latin() -> None:
    """Обратный словарь построен из прямого.

    Для каждой пары ``(cyrillic, latin)`` из
    :data:`CYRILLIC_TO_LATIN_MAP` должно выполняться
    ``LATIN_TO_CYRILLIC_MAP[latin] == cyrillic``.
    """
    for cyrillic, latin in CYRILLIC_TO_LATIN_MAP.items():
        assert LATIN_TO_CYRILLIC_MAP[latin] == cyrillic


def test_maps_have_same_size() -> None:
    """Прямой и обратный словари имеют одинаковый размер.

    Равенство размеров гарантирует отсутствие коллизий: ни одна
    пара кириллических символов не должна отображаться на один
    латинский символ.
    """
    assert len(CYRILLIC_TO_LATIN_MAP) == len(LATIN_TO_CYRILLIC_MAP)


def test_cyrillic_map_values_are_unique() -> None:
    """Значения прямого словаря уникальны.

    Если два кириллических символа отображались бы на один
    латинский, обратное отображение было бы неоднозначным, а
    round-trip — недетерминированным.
    """
    values = list(CYRILLIC_TO_LATIN_MAP.values())
    assert len(values) == len(set(values))


def test_maps_contain_only_lowercase_single_characters() -> None:
    """Ключи и значения — односимвольные строки нижнего регистра.

    Это соответствует логике ``normalize_text``: сначала
    применяется ``str.lower()``, затем замена по словарю. Если
    словарь содержал бы заглавные символы или многосимвольные
    строки, соответствие сломается.
    """
    for cyrillic, latin in CYRILLIC_TO_LATIN_MAP.items():
        assert len(cyrillic) == 1
        assert len(latin) == 1
        assert cyrillic == cyrillic.lower()
        assert latin == latin.lower()
