# =====================================================================
# Раздел 4. normalize_text: краевые случаи
# =====================================================================


def test_normalize_text_empty_string() -> None:
    """Пустая строка → пустая строка."""
    assert normalize_text("") == ""


def test_normalize_text_whitespace_only() -> None:
    """Строка из пробелов не изменяется."""
    assert normalize_text("   \t\n  ") == "   \t\n  "


def test_normalize_text_only_digits() -> None:
    """Только цифры → без изменений."""
    assert normalize_text("0123456789") == "0123456789"


def test_normalize_text_does_not_mutate_input() -> None:
    """Строки в Python неизменяемы — исходное значение не меняется.

    Проверка формальная, но фиксирует контракт «функция не имеет
    побочных эффектов»: даже если бы Python позволял мутировать
    строки, ``normalize_text`` не должен был бы этого делать.
    """
    original = "Пример Текста"
    _ = normalize_text(original)
    assert original == "Пример Текста"


