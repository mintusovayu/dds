"""
Пакет бенчмарков производительности Deep Doc Search.

Назначение
----------
Изолированное пространство для замеров производительности ядра DDS:
сканирование каталога, рендер страниц PDF, поиск по FTS5, подсветка
совпадений, fork-latency для process-per-task runner'а. Результаты
используются для обнаружения регрессий при рефакторинге и для
контроля выполнения критериев фаз плана v9.

Структура пакета
----------------
::

    tests/benchmarks/
    ├── __init__.py         Этот файл. Маркер пакета + документация.
    ├── bench_fast.py       Быстрые бенчмарки: search, render A4/A1,
    │                       build_word_index (small), highlights,
    │                       fork_latency.
    ├── bench_slow.py       Медленный бенчмарк: scan.full (1000 PDF).
    └── baseline.json       Baseline-значения (абсолютные + относительные).

Разделение «быстрые» / «медленные» бенчмарки обусловлено разницей
времени: быстрые (≤ 5 секунд на метрику) запускаются на каждый PR
через ``bench.yml``; медленные (scan.full ≈ 2 минуты на прогон)
запускаются только на push в main, по расписанию и при
опти-ин-метке ``bench-slow`` на PR — через ``bench-slow.yml``.

Методология замеров
-------------------
Все бенчмарки построены на ``pytest-benchmark`` (версия ≥ 4.0):

- **Быстрые метрики**: ``--benchmark-min-rounds=10`` — минимум
  10 прогонов для статистической значимости Mann-Whitney U test.
- **Медленные метрики**: ``--benchmark-min-rounds=3`` — минимум
  для непараметрического теста при n ≥ 3 с каждой стороны.
- **Warmup** включён для быстрых (JIT-эффекты, кэш интерпретатора)
  и выключен для медленных (scan.full — I/O-bound, прогрев не
  устранит дисперсию от файлового кэша ОС).
- **``--benchmark-disable-gc``**: GC отключается во время замера
  для снижения дисперсии; включается между замерами.

Сравнение с baseline выполняется в CI-скриптах (не в этом пакете):
результат ``pytest-benchmark`` сравнивается с ``baseline.json``
через Mann-Whitney U test (``scipy.stats.mannwhitneyu``, p < 0.05).
Пороги деградации:

- **≤ 15%** — OK.
- **> 15%, p < 0.05** — WARNING (не блокирует merge).
- **> 30%, p < 0.05** — FAIL (блокирует merge).

Запуск
------
Быстрые бенчмарки::

    pytest tests/benchmarks/bench_fast.py \\
        --benchmark-min-rounds=10 \\
        --benchmark-warmup=on \\
        --benchmark-disable-gc

Медленные бенчмарки::

    pytest tests/benchmarks/bench_slow.py \\
        --benchmark-min-rounds=3 \\
        --benchmark-warmup=off \\
        --benchmark-disable-gc

Для проверки производительности с сохранением результатов в JSON::

    pytest tests/benchmarks/bench_fast.py \\
        --benchmark-json=benchmark_results.json \\
        --benchmark-min-rounds=10

Интеграция с CI
---------------
- ``.github/workflows/bench.yml`` — быстрые бенчмарки, self-hosted
  runner ``dds-bench``, триггер на pull_request к main при
  изменении ``dds_core/``, ``dds_web/``, ``tests/benchmarks/``,
  ``requirements*.txt``.
- ``.github/workflows/bench-slow.yml`` — медленные бенчмарки,
  self-hosted runner ``dds-bench``, триггеры: push в main,
  еженедельно (пн 03:00 UTC), opt-in метка ``bench-slow`` на PR.

Оба workflow используют один и тот же self-hosted runner с
фиксированной конфигурацией (см. ``baseline.json → ci_runner``),
иначе относительные baseline-значения несопоставимы.

Требования
----------
Зависимости пакета — в ``requirements-dev.txt``:

- ``pytest-benchmark>=4.0.0`` — инфраструктура замеров;
- ``scipy>=1.11.0`` — Mann-Whitney U test;
- ``pymupdf>=1.23.0`` — генерация PDF-датасета для scan.full
  и рендер страниц.

Датасет ``bench_slow.py`` (1000 PDF) генерируется на лету из
in-memory шаблонов через PyMuPDF. Параметры генерации фиксированы
через ``DDS_BENCH_SCAN_DOCS`` и ``DDS_BENCH_SCAN_SEED`` —
детерминизм между прогонами.

Границы ответственности пакета
------------------------------
Что **входит**:

- функции ``test_*`` с фикстурой ``benchmark`` (pytest-benchmark);
- генерация временных датасетов через ``tmp_path_factory``;
- настройка изолированной среды (temp SQLite, пустой rd_directory,
  минимальные reference-справочники) для бенчмарков, требующих
  полноценного запуска компонентов DDS.

Что **не входит**:

- Сравнение с baseline и классификация (OK/WARNING/FAIL) —
  реализовано в CI-скриптах (heredoc Python внутри workflow).
- Обновление ``baseline.json`` — выполняется вручную разработчиком
  при изменении железа runner'а или датасета.
- Публикация отчётов — задача GitHub Actions (``upload-artifact``,
  ``GITHUB_STEP_SUMMARY``).
- UI-бенчмарки (рендер в браузере) — вне области пакета.

Правила написания бенчмарков
----------------------------
1. **Никаких побочных эффектов между метриками.** Каждая метрика —
   изолированный тест, использующий собственные временные ресурсы
   (``tmp_path``, ``tmp_path_factory``).
2. **Никаких ``time.sleep`` для стабилизации.** Дисперсия
   контролируется через ``--benchmark-disable-gc`` и warmup; sleep
   искажает медиану.
3. **Никаких внешних сервисов** (БД по сети, HTTP к другим
   сервисам). Все зависимости — локальные, создаются в тесте.
4. **Детерминированные датасеты.** Random с фиксированным seed;
   параметры генерации — через env (``DDS_BENCH_*``).
5. **Изоляция от production.** Временные файлы — в ``tmp_path``;
   никаких записей в ``dds_database.db`` или ``rd_directory``.
6. **Метрики — репрезентативны.** Замеряемая операция должна
   покрывать значимую часть реального workload (например,
   render A4 @ 300 DPI, не render пустой страницы).
7. **Никаких проверок корректности в бенчмарках.** Assertions на
   результате допустимы только для валидации setup (например,
   ``assert result == 42`` в fork_latency), но не для проверки
   бизнес-логики — для этого есть обычные тесты.
"""

# Модуль не содержит исполняемого кода. Это осознанное решение:
# - пакет служит только контейнером для bench_fast.py, bench_slow.py
#   и baseline.json;
# - общие фикстуры (например, process_runner для fork_latency)
#   определяются локально в bench_fast.py, так как используются
#   только в одном модуле;
# - pytest-маркеры проекта (в том числе ``slow``) регистрируются
#   в pyproject.toml (секция ``[tool.pytest.ini_options] markers``),
#   а не здесь — единая точка конфигурации pytest в проекте.
