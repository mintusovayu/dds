def test_capture_stderr_returns_result_and_captures_output() -> None:
    """Smoke-проверка: функция возвращает результат и перехватывает вывод.

    Проверяет базовый контракт :func:`_capture_stderr`:

    - возвращает кортеж ``(результат_func, перехваченный_stderr)``;
    - результат совпадает с возвратом ``func``;
    - запись ``func`` в fd 2 попадает в перехваченный вывод.

    Этот тест не зависит от ``_stderr_lock`` — он проверяет
    корректность самой функции перехвата. Используется как
    «защита от регресса»: если кто-то сломает логику
    перехвата, ошибка обнаружится здесь, а не только в
    тестах сериализации.
    """
    result, output = _capture_stderr(_write_marker_and_sleep, 0.0)

    assert result == "ok"
    assert _STDERR_MARKER.decode("utf-8").strip() in output


def test_capture_stderr_is_serialized() -> None:
    """Инвариант: ``_capture_stderr`` не выполняется параллельно.

    Сценарий:

    - ``_NUM_THREADS`` потоков параллельно вызывают
      ``_capture_stderr`` по ``_ITERATIONS_PER_THREAD`` раз каждый;
    - вызываемая функция регистрирует вход/выход в
      :class:`_ConcurrencyTracker`;
    - если ``_stderr_lock`` работает, ``max_observed == 1``;
    - если lock отсутствует или сломан, ``max_observed >= 2``
      (потоки пересекаются внутри критической секции).

    Сон ``_INNER_SLEEP_SECONDS`` внутри функции создаёт окно
    пересечения: без него потоки могли бы выполняться слишком
    быстро для устойчивого детекта гонки.

    Тест детерминирован при работающем lock'е: сериализация
    гарантирует ``max_observed == 1`` при любом планировании
    потоков. При сломанном lock'е тест падает с высокой
    вероятностью (вероятность отсутствия пересечений за 200
    итераций с 4 потоками пренебрежимо мала).
    """
    tracker = _ConcurrencyTracker()

    def _worker() -> None:
        """Один поток: ``_ITERATIONS_PER_THREAD`` вызовов ``_capture_stderr``."""
        for _ in range(_ITERATIONS_PER_THREAD):
            _capture_stderr(
                _tracked_call,
                _write_marker_and_sleep,
                tracker,
                _INNER_SLEEP_SECONDS,
            )

    with ThreadPoolExecutor(max_workers=_NUM_THREADS) as executor:
        futures = [executor.submit(_worker) for _ in range(_NUM_THREADS)]
        # ``.result()`` пробрасывает исключения из воркеров, если они были.
        for future in futures:
            future.result()

    assert tracker.max_observed == 1, (
        f"Ожидалось не более 1 одновременного выполнения "
        f"_capture_stderr, наблюдено {tracker.max_observed}. "
        f"Блокировка _stderr_lock не сериализует вызовы."
    )
