"""
Тесты сериализации перехвата stderr в PyMuPDF-экстракторе.

Назначение
----------
Проверка инварианта, введённого в Фазе 1: функция
:func:`_capture_stderr` в ``dds_core/infrastructure/pymupdf_text_extractor.py``
сериализует свою критическую секцию через модульную блокировку
``_stderr_lock``. Одновременно в рамках процесса не может
выполняться более одного вызова ``_capture_stderr``.

Проблема, которую решает lock
-----------------------------
PyMuPDF пишет диагностику напрямую в файловый дескриптор 2 (fd 2) —
**процессный** ресурс, не потоковый. ``_capture_stderr`` временно
подменяет fd 2 через ``os.dup2`` для перехвата сообщений. При
параллельных вызовах из ``scan_executor`` (например, одновременные
``POST /render`` и ``POST /highlights``) два потока подменяли fd
друг другу, что приводило к перепутанному выводу и потере
диагностики. Lock устраняет гонку (см. ADR-001).

Проверяемый инвариант
---------------------
Для любого набора параллельных вызовов ``_capture_stderr``
максимальное количество выполнений «внутри» критической секции
не превышает 1. Инвариант детектируется через thread-safe счётчик,
инкрементируемый/декрементируемый внутри вызываемой функции (то
есть уже под захваченным lock'ом).

Стратегия тестирования
----------------------
- **Синтетическая функция-исполнитель.** :func:`_write_marker_and_sleep`
  имитирует работу PyMuPDF: пишет маркер в fd 2 и спит короткое
  время. Сон создаёт окно, в котором второй поток мог бы войти в
  критическую секцию, если бы lock не работал.
- **Thread-safe трекер.** :class:`_ConcurrencyTracker` фиксирует
  максимум одновременных выполнений. Инкремент/декремент защищены
  ``threading.Lock``, чтобы измерялся именно инвариант
  ``_capture_stderr``, а не собственные гонки трекера.
- **ThreadPoolExecutor.** N потоков × M итераций. Параметры
  подобраны так, чтобы окно пересечения (sleep 1 мс) гарантированно
  возникало при отсутствии lock и было достаточно для детекта.
- **Два теста.** Первый проверяет базовый контракт функции
  (возврат результата и перехват вывода) — защита от регресса
  в самой логике перехвата. Второй проверяет инвариант
  сериализации.

Границы
-------
- **Логика PyMuPDF** (парсинг, рендер) не тестируется: она
  покрыта другими тестами и smoke-сценариями.
- **Корректность ``os.dup2``** в разных ОС — вне области; поведение
  POSIX-примитивов предполагается стандартным.
- **Производительность** сериализации (throughput) — не измеряется;
  оценка будет в бенчмарках Фазы 4 при замене lock'а на
  process-изоляцию.

Запуск
------
::

    pytest tests/test_pymupdf_stderr_lock.py -v

Принципы:
    - модуль не выполняет логирования;
    - не читает и не пишет production-файлы;
    - не изменяет глобальное состояние (кроме fd 2 на время
      вызова ``_capture_stderr``, что является предметом теста);
    - каждый тест изолирован, не зависит от порядка выполнения.
"""

from __future__ import annotations

import os
import threading
import time
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor
from typing import Any

from dds_core.infrastructure.pymupdf_text_extractor import _capture_stderr

# =====================================================================
# Константы
# =====================================================================

_NUM_THREADS = 4
"""Количество потоков, параллельно вызывающих ``_capture_stderr``.

Четырёх достаточно для устойчивого детекта гонки: при отсутствии
lock вероятность, что хотя бы два потока пересекутся внутри
критической секции за ``_ITERATIONS_PER_THREAD`` итераций, близка
к 1.
"""

_ITERATIONS_PER_THREAD = 50
"""Количество вызовов ``_capture_stderr`` в каждом потоке.

Всего вызовов: ``_NUM_THREADS × _ITERATIONS_PER_THREAD = 200``.
При полной сериализации и ``_INNER_SLEEP_SECONDS = 0.001`` суммарное
время теста ≈ 200 мс плюс overhead ``os.dup``/``os.pipe``.
"""

_INNER_SLEEP_SECONDS = 0.001
"""Длительность сна внутри синтетической функции-исполнителя.

Сон создаёт временное окно, в котором второй поток мог бы войти
в критическую секцию, если бы блокировка не работала. 1 мс —
достаточно для устойчивого детекта гонки без замедления теста.
"""

_STDERR_MARKER = b"test stderr output\n"
"""Маркер, записываемый в fd 2 синтетической функцией.

Используется в smoke-тесте: проверяет, что запись в fd 2 попадает
в перехваченный канал.
"""


# =====================================================================
# Helpers
# =====================================================================


class _ConcurrencyTracker:
    """Thread-safe счётчик одновременных выполнений.

    Инкремент при входе в защищённую секцию, декремент при выходе.
    Фиксирует максимум одновременно наблюдаемых входов.

    Инкремент и декремент защищены собственным ``threading.Lock``:
    задача трекера — измерять инвариант ``_capture_stderr``, а не
    собственные гонки. Без этой защиты измерения были бы шумными.

    Attributes:
        _lock: Внутренняя блокировка трекера.
        _current: Текущее число «внутри секции».
        _max_observed: Максимум ``_current`` за всё время жизни.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._current = 0
        self._max_observed = 0

    def enter(self) -> None:
        """Регистрирует вход в защищённую секцию.

        Инкрементирует ``_current`` и обновляет ``_max_observed``,
        если достигнут новый максимум.
        """
        with self._lock:
            self._current += 1
            if self._current > self._max_observed:
                self._max_observed = self._current

    def exit(self) -> None:
        """Регистрирует выход из защищённой секции."""
        with self._lock:
            self._current -= 1

    @property
    def max_observed(self) -> int:
        """Возвращает максимум одновременно наблюдаемых входов."""
        with self._lock:
            return self._max_observed


def _write_marker_and_sleep(sleep_seconds: float) -> str:
    """Пишет маркер в fd 2 и спит заданное время.

    Имитирует работу PyMuPDF: запись диагностики в fd 2 и задержку,
    в течение которой второй поток мог бы войти в критическую
    секцию ``_capture_stderr``.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | ``os.write(2, _STDERR_MARKER)`` — запись маркера    |
    |   | в перехваченный fd 2.                               |
    +---+-----------------------------------------------------+
    | 2 | ``time.sleep(sleep_seconds)`` — создание временного |
    |   | окна для возможного перекрытия.                     |
    +---+-----------------------------------------------------+
    | 3 | Возврат строки ``"ok"``.                            |
    +---+-----------------------------------------------------+

    Args:
        sleep_seconds: Длительность сна в секундах. Значение ``0``
            отключает сон (используется в smoke-тесте).

    Returns:
        Строка ``"ok"``. Используется в smoke-тесте для проверки,
        что ``_capture_stderr`` корректно возвращает результат
        вызываемой функции.
    """
    os.write(2, _STDERR_MARKER)
    if sleep_seconds > 0:
        time.sleep(sleep_seconds)
    return "ok"


def _tracked_call(
    func: Callable[..., Any],
    tracker: _ConcurrencyTracker,
    *args: Any,
) -> Any:
    """Вызывает ``func`` с обёрткой трекера.

    Регистрирует вход в критическую секцию перед вызовом ``func``
    и выход после. Если :func:`_capture_stderr` не сериализует
    вызовы, трекер зафиксирует одновременный вход нескольких
    потоков в эту функцию.

    Args:
        func: Функция для вызова.
        tracker: Трекер одновременных выполнений.
        *args: Позиционные аргументы, передаваемые в ``func``.

    Returns:
        Результат ``func(*args)``.
    """
    tracker.enter()
    try:
        return func(*args)
    finally:
        tracker.exit()


