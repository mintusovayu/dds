#   test_smoke_playwright.py и artifacts/;
# - все session-scoped fixtures (изоляция окружения, запуск
#   run.py, браузер) определены в conftest.py — это
#   идиоматичное место для pytest-фикстур;
# - pytest-маркеры (включая `smoke`, `slow`) регистрируются в
#   pyproject.toml (секция [tool.pytest.ini_options] markers),
#   а не здесь — единая точка конфигурации pytest в проекте;
# - константы порта (DDS_SMOKE_PORT) и таймаутов readiness
#   читаются из env в conftest.py, а не импортируются из
