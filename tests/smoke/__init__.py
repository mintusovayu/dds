"""
Пакет smoke-тестов Deep Doc Search.

Назначение
----------
Smoke-тесты проверяют **работоспособность UI** после каждой фазы
рефакторинга: реальное приложение DDS запускается как subprocess,
headless Chromium эмулирует ключевые пользовательские сценарии,
результаты валидируются по DOM и скриншотам.

Пакет — обязательная часть Фазы 0 плана v9 (позиция 21). Критерий
завершения каждой фазы — «Smoke-тесты Playwright зелёные».

Что проверяется
---------------
Перечень покрываемых сценариев см. в ``test_smoke_playwright.py``
(каждая функция ``test_*`` — отдельный пользовательский поток).
Общие классы проверок:

- **Загрузка страниц**: главная после логина, форма входа.
- **Поиск**: пустой запрос (режим «показать все»), запрос с
  фильтрами, отображение результатов.
- **Просмотр документа**: открытие вкладки по правому клику,
  переключение режима «Рендер / Текст», отображение подсветки
  совпадений (бирюзовые прямоугольники).
- **Настройки**: открытие панели, смена темы.
- **Статус-бар**: корректное отображение запроса, фильтров и
  счётчика документов.

Полный список — в docstring каждого теста.

Отличие от других тестов
------------------------
+--------------------------+------------------------------------------+
| Тип теста                | Что проверяет                            |
+==========================+==========================================+
| Unit / integration       | Модули и функции в изоляции;             |
| (``tests/test_*.py``)    | запускаются в процессе pytest.           |
+--------------------------+------------------------------------------+
| Benchmarks               | Производительность ядра;                 |
| (``tests/benchmarks/``)  | запускаются в процессе pytest.           |
+--------------------------+------------------------------------------+
| **Smoke**                | **Реальное приложение через subprocess;**|
| (``tests/smoke/``)       | **эмуляция пользователя в браузере.**    |
+--------------------------+------------------------------------------+

Smoke-тесты дороже unit (запуск uvicorn, Chromium, изоляция файловой
системы), но дают end-to-end уверенность: UI работает, формы
сабмитятся, fetch-запросы доходят до сервера, ответы рендерятся.

Структура пакета
----------------
::

    tests/smoke/
    ├── __init__.py                  Этот файл. Маркер пакета.
    ├── conftest.py                  Session-scoped fixtures:
    │                                 - изоляция окружения (tmp cwd,
    │                                   tmp SQLite, пустой rd,
    │                                   минимальный references JSON);
    │                                 - генерация smoke-config.json;
    │                                 - запуск run.py как subprocess
    │                                   на порту 8765;
    │                                 - ожидание readiness;
    │                                 - headless Chromium;
    │                                 - сбор артефактов при падении.
    ├── test_smoke_playwright.py     Сами тесты (сценарии пользователя).
    └── artifacts/                   Артефакты падений (генерируются
                                     conftest'ом при провале теста):
                                       screenshots, video, trace.

Архитектура запуска
-------------------
1. pytest собирает тесты из этого пакета.
2. Session fixture ``dds_app_server`` из ``conftest.py``:
   - создаёт изолированный рабочий каталог через ``tmp_path_factory``;
   - генерирует ``smoke-config.json`` с путями к временным ресурсам;
   - запускает ``python run.py --config <smoke-config>`` как
     subprocess на порту ``DDS_SMOKE_PORT`` (по умолчанию 8765);
   - поллит ``GET /api/scan/status`` до readiness (таймаут
     ``DDS_SMOKE_READY_TIMEOUT``, по умолчанию 60 секунд);
   - сохраняет ``stdout`` и ``stderr`` приложения в
     ``tests/smoke/app.log``;
   - при teardown — ``terminate`` subprocess и сбор артефактов.
3. Session fixture ``browser`` запускает headless Chromium через
   Playwright; function-scoped fixture ``page`` даёт чистую
   страницу каждому тесту.
4. Тесты используют ``page.goto(...)`` и Playwright API для
   эмуляции кликов, ввода и проверок.

Изоляция окружения
------------------
Smoke-тесты **не используют** production-``config.json``. Причина:
реальный конфиг содержит production-пути (``rd_directory``,
``db_path``), и тесты не должны их касаться. Изолированный
smoke-конфиг содержит:

- ``db_path`` — во временном каталоге;
- ``rd_directory`` — пустой временный каталог;
- ``reference_data_path`` — минимальный JSON со справочниками;
- ``port`` — 8765 (изолирован от 8000);
- ``auth`` — тестовые пользователи с известными паролями.

Порт 8765 выбран как не пересекающийся с production (8000) и с
типичными dev-портами. Настройка через ``DDS_SMOKE_PORT``.

Retry-механизм
--------------
Smoke-тесты подвержены **флаки-эффектам**: тайминги DOM-обновлений,
CSS-анимации, задержки fetch, сетевые задержки на CI-runner'ах.
Для снижения ложных падений workflow ``smoke.yml`` использует
``nick-invision/retry@v3`` с 3 попытками (1 + 2 retry) и паузой
10 секунд. **Три провала подряд — реальная проблема**, а не флак.

Retry применяется на уровне workflow, **не в этом пакете**.
Дублирование retry внутри тестов (например, ``pytest-rerunfailures``)
увеличило бы время и замаскировало бы системные проблемы.

Отношение к branch protection
-----------------------------
Workflow ``smoke.yml`` **не должен** быть required check.
Smoke-тесты могут быть нестабильны (браузерные race conditions,
тайминги анимаций); их падение даёт обратную связь, но не
блокирует merge. Это согласовано с планом Фазы 0.

Реализуется настройкой репозитория (branch protection rules),
а не содержимым этого файла.

Артефакты при падении
---------------------
При провале теста ``conftest.py`` сохраняет:

- ``artifacts/<test_name>/screenshot.png`` — снимок экрана;
- ``artifacts/<test_name>/video.webm`` — видеозапись прогона
  (Playwright ``context`` с ``record_video_dir``);
- ``artifacts/<test_name>/trace.zip`` — Playwright trace
  (пошаговое воспроизведение);
- ``tests/smoke/app.log`` — stdout + stderr приложения;
- ``tests/smoke/smoke-config.json`` — фактический конфиг для
  локального воспроизведения;
- ``dds.log`` — файловый лог приложения через RotatingFileHandler.

Все артефакты загружаются workflow'ом ``smoke.yml`` через
``actions/upload-artifact@v4`` с ``if: always()``.

Интеграция с CI
---------------
- ``.github/workflows/smoke.yml`` — единственный потребитель пакета.
  Триггеры: pull_request к main, push в main, workflow_dispatch.
  Runner: ``ubuntu-latest`` (в отличие от benchmarks, smoke не
  чувствителен к железу).
- Concurrency: ``cancel-in-progress: true`` — отмена предыдущих
  запусков на той же ветке предотвращает конфликт за порт 8765.
- Отчёт: ``$GITHUB_STEP_SUMMARY`` + artifacts.

Требования
----------
Зависимости пакета — в ``requirements-dev.txt``:

- ``playwright>=1.40.0`` — драйвер браузера;
- ``pytest>=7.0.0``, ``pytest-asyncio>=0.21.0`` — инфраструктура;
- ``pymupdf>=1.23.0`` — для генерации тестового PDF в некоторых
  сценариях (если требуется).

После установки пакета требуется установить Chromium::

    python -m playwright install --with-deps chromium

Запуск локально
---------------
::

    pytest tests/smoke/ -v

Для отладки с видимым браузером::

    DDS_SMOKE_HEADLESS=0 pytest tests/smoke/ -v --headed

Для быстрого прогона одного сценария::

    pytest tests/smoke/test_smoke_playwright.py::test_login_page -v

Границы ответственности пакета
------------------------------
Что **входит**:

- тесты пользовательских сценариев (``test_smoke_playwright.py``);
- fixtures изоляции окружения, запуска приложения, браузера
  (``conftest.py``);
- сбор артефактов при падении.

Что **не входит**:

- Полноценное тестирование сканирования (1000 PDF) — отдельный
  benchmark, см. ``tests/benchmarks/bench_slow.py``.
- Нагрузочное тестирование — вне области smoke.
- Кроссплатформенность — smoke запускается только на Linux
  (ubuntu-latest); UI-проверка на одной платформе достаточна.
- Регистрация pytest-маркеров (например, ``smoke``) —
  регистрируется в ``pyproject.toml`` (единая точка конфигурации).

Правила написания smoke-тестов
------------------------------
1. **Каждый тест — независимый пользовательский сценарий.**
   Не полагайтесь на порядок выполнения; используйте свежий
   ``page`` (function-scoped).
2. **Никаких ``time.sleep`` для ожиданий.** Используйте
   Playwright-локаторы с автоподсветкой (``expect(...).to_be_visible()``
   и аналоги) — они учитывают реальную готовность DOM.
3. **Никаких production-ресурсов.** Всё через изолированное
   окружение (conftest); не обращайтесь к ``dds_database.db``,
   реальному ``rd_directory``, внешним сервисам.
4. **Никаких длинных прогонов.** Smoke-тест ≤ 30 секунд.
   Длительные операции (сканирование 1000 PDF) — не здесь.
5. **Валидация через user-visible состояния.** Проверяйте то,
   что видит пользователь (текст, видимость элементов,
   `aria`-атрибуты), а не внутренние JS-переменные.
6. **Один ассерт — одна гипотеза.** Набор проверок в тесте
   относится к одному сценарию; не смешивайте несколько
   несвязанных проверок.
7. **Детерминизм.** Фиксированный seed для любых генераторов
   данных; никаких зависимостей от реального времени.
"""

