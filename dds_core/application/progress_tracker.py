"""
Отслеживание прогресса сканирования.

Инкапсулирует блокировку, счётчики и троттлинг публикации.
Устраняет дублирование между ``_hash_worker`` и
``_extract_worker`` в ``ScanPipeline``.

Публикация выполняется ВНЕ блокировки: блокировка
удерживается только на время чтения данных и обновления
метки времени.

Отслеживание зависших процессов (скорректированный план):
Трекер ведёт счётчик процессов извлечения, зависших по
таймауту (``_stuck_processes_count``). Воркер извлечения
в ``ScanPipeline`` вызывает ``record_stuck_process()`` при
каждом срабатывании таймаута на ``run_in_executor``. При
достижении порога ``_max_extract_workers`` конвейер
переключается на потоковый fallback (``_executor_broken = True``).

Принципы:
- Модуль находится в application layer и не содержит бизнес-логики.
- Зависит только от абстракции ``IEventBus`` и моделей доменного слоя.
- Потокобезопасность обеспечивается ``threading.Lock``.
"""

from __future__ import annotations

import threading
import time

from ..domain.events import ScanProgressUpdated
from ..domain.interfaces import IEventBus
from ..domain.models import (
    HashOutcome,
    ScanPhase,
    ScanProgress,
    ScanStatus,
)


class ScanProgressTracker:
    """Потокобезопасный трекер прогресса сканирования.

    Отслеживает состояние счётчиков обработанных файлов
    (проиндексировано, дубликаты, пропущено, ошибки) и
    публикует события ``ScanProgressUpdated`` с троттлингом
    не чаще одного раза в секунду.

    Отслеживание зависших процессов (скорректированный план):
    Трекер ведёт счётчик процессов извлечения, зависших по
    таймауту. Это позволяет конвейеру ``ScanPipeline`` принимать
    решение о переключении на потоковый fallback при накоплении
    зависших процессов в ``ProcessPoolExecutor``.

    Attributes:

    +-------------------------+-------------------------------------------+
    | Атрибут                 | Описание                                  |
    +=========================+===========================================+
    | ``_event_bus``          | Шина событий для публикации прогресса.    |
    +-------------------------+-------------------------------------------+
    | ``_correlation_id``     | Идентификатор корреляции текущего         |
    |                         | запуска.                                  |
    +-------------------------+-------------------------------------------+
    | ``_lock``               | Блокировка для защиты состояния.          |
    +-------------------------+-------------------------------------------+
    | ``_last_publish_time``  | Время последней публикации события.       |
    +-------------------------+-------------------------------------------+
    | ``_stuck_processes_count`` | Количество процессов, зависших по       |
    |                         | таймауту извлечения.                      |
    +-------------------------+-------------------------------------------+
    | ``_progress``           | Текущее состояние прогресса               |
    |                         | (``ScanProgress``).                       |
    +-------------------------+-------------------------------------------+
    """

    def __init__(self, event_bus: IEventBus) -> None:
        """Инициализирует трекер прогресса.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ссылки на шину событий.                  |
        +---+-----------------------------------------------------+
        | 2 | Инициализация ``_correlation_id`` пустой строкой.   |
        +---+-----------------------------------------------------+
        | 3 | Создание ``threading.Lock``.                        |
        +---+-----------------------------------------------------+
        | 4 | Установка ``_last_publish_time = 0.0``.             |
        +---+-----------------------------------------------------+
        | 5 | Установка ``_stuck_processes_count = 0``.           |
        +---+-----------------------------------------------------+
        | 6 | Создание начального ``ScanProgress`` со статусом   |
        |   | ``RUNNING`` и фазой ``PRIMARY``.                    |
        +---+-----------------------------------------------------+

        Args:
            event_bus: Шина событий для публикации прогресса.
        """
        self._event_bus = event_bus
        self._correlation_id: str = ""
        self._lock = threading.Lock()
        self._last_publish_time: float = 0.0
        self._stuck_processes_count: int = 0
        self._progress = ScanProgress(
            phase=ScanPhase.PRIMARY,
            status=ScanStatus.RUNNING,
        )

    def configure(self, correlation_id: str) -> None:
        """Устанавливает параметры для текущего запуска.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ``correlation_id``.                      |
        +---+-----------------------------------------------------+
        | 2 | Сброс ``_last_publish_time`` в 0.0.                 |
        +---+-----------------------------------------------------+
        | 3 | Сброс ``_stuck_processes_count`` в 0.               |
        +---+-----------------------------------------------------+
        | 4 | Под блокировкой замена ``_progress`` новым          |
        |   | экземпляром ``ScanProgress`` со статусом           |
        |   | ``RUNNING`` и фазой ``PRIMARY``.                    |
        +---+-----------------------------------------------------+

        Вызывается в начале ``run_async`` для привязки событий
        к конкретному запуску сканирования.

        Args:
            correlation_id: Идентификатор корреляции.
        """
        self._correlation_id = correlation_id
        self._last_publish_time = 0.0
        self._stuck_processes_count = 0
        with self._lock:
            self._progress = ScanProgress(
                phase=ScanPhase.PRIMARY,
                status=ScanStatus.RUNNING,
            )

    def set_total_files(self, total: int) -> None:
        """Устанавливает общее количество файлов.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Установка ``total_files`` в текущем прогрессе.      |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Вызывается этапом сканирования каталога после получения
        списка файлов.

        Args:
            total: Общее количество файлов.
        """
        with self._lock:
            self._progress.total_files = total

    def set_current_file(self, file_path: str) -> None:
        """Устанавливает текущий обрабатываемый файл.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Установка ``current_file`` в текущем прогрессе.     |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Используется воркерами для отображения имени файла,
        обрабатываемого в данный момент.

        Args:
            file_path: Путь к обрабатываемому файлу.
        """
        with self._lock:
            self._progress.current_file = file_path

    def set_status(self, status: ScanStatus) -> None:
        """Устанавливает статус сканирования.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Установка ``status`` в текущем прогрессе.           |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Используется при завершении сканирования или при
        превышении порога ошибок.

        Args:
            status: Новый статус сканирования.
        """
        with self._lock:
            self._progress.status = status

    def get_status(self) -> ScanStatus:
        """Возвращает текущий статус сканирования.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Чтение ``status`` из текущего прогресса.            |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки и возврат статуса.          |
        +---+-----------------------------------------------------+

        Returns:
            Текущий статус сканирования.
        """
        with self._lock:
            return self._progress.status

    def get_error_count(self) -> int:
        """Возвращает количество ошибок.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Чтение ``error_files`` из текущего прогресса.       |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки и возврат значения.         |
        +---+-----------------------------------------------------+

        Returns:
            Количество файлов, обработанных с ошибкой.
        """
        with self._lock:
            return self._progress.error_files

    def record_stuck_process(self) -> None:
        """Регистрирует зависший процесс извлечения.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Инкремент ``_stuck_processes_count``.               |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Вызывается воркером извлечения в ``ScanPipeline`` при
        срабатывании таймаута на ``run_in_executor``. Позволяет
        конвейеру отслеживать накопление зависших процессов в
        ``ProcessPoolExecutor`` и принимать решение о переключении
        на потоковый fallback.

        Потокобезопасность:
        Метод защищён ``threading.Lock`` и может вызываться
        из нескольких потоков одновременно.
        """
        with self._lock:
            self._stuck_processes_count += 1

    def get_stuck_processes_count(self) -> int:
        """Возвращает количество зависших процессов.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Чтение ``_stuck_processes_count``.                  |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки и возврат значения.         |
        +---+-----------------------------------------------------+

        Вызывается воркером извлечения в ``ScanPipeline`` для
        проверки, не превышено ли количество зависших процессов.
        При достижении порога ``_max_extract_workers`` конвейер
        устанавливает ``_executor_broken = True`` и переключается
        на потоковый fallback.

        Returns:
            Количество процессов, зависших по таймауту.
        """
        with self._lock:
            return self._stuck_processes_count

    def record_hash_outcome(
        self,
        outcome: HashOutcome,
        current_file: str = "",
    ) -> None:
        """Обновляет счётчики по исходу хеширования.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | В зависимости от ``outcome``:                       |
        |   | a. ``SKIPPED_UNCHANGED`` → увеличить                |
        |   |    ``skipped_files`` на 1.                          |
        |   | b. ``DUPLICATE`` → увеличить ``duplicate_files``    |
        |   |    на 1.                                            |
        |   | c. ``ERROR`` → увеличить ``error_files`` на 1.      |
        +---+-----------------------------------------------------+
        | 3 | Установка ``current_file`` из аргумента.            |
        +---+-----------------------------------------------------+
        | 4 | Вызов ``_recalc()`` для пересчёта                    |
        |   | ``processed_files``.                                |
        +---+-----------------------------------------------------+
        | 5 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Вызывается воркером хеширования после обработки файла.

        Args:
            outcome: Исход операции хеширования (``HashOutcome``).
            current_file: Путь к обработанному файлу.
        """
        with self._lock:
            if outcome == HashOutcome.SKIPPED_UNCHANGED:
                self._progress.skipped_files += 1
            elif outcome == HashOutcome.DUPLICATE:
                self._progress.duplicate_files += 1
            elif outcome == HashOutcome.ERROR:
                self._progress.error_files += 1
            self._progress.current_file = current_file
            self._recalc()

    def record_extract_result(
        self,
        success: int,
        failed: int,
        current_file: str = "",
    ) -> None:
        """Обновляет счётчики по результату записи батча.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Увеличение ``indexed_files`` на ``success``.        |
        +---+-----------------------------------------------------+
        | 3 | Увеличение ``error_files`` на ``failed``.           |
        +---+-----------------------------------------------------+
        | 4 | Установка ``current_file`` из аргумента.            |
        +---+-----------------------------------------------------+
        | 5 | Вызов ``_recalc()`` для пересчёта                    |
        |   | ``processed_files``.                                |
        +---+-----------------------------------------------------+
        | 6 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Вызывается воркером извлечения после записи группы
        документов.

        Args:
            success: Количество успешно записанных документов.
            failed: Количество документов с ошибкой.
            current_file: Путь к текущему файлу (для отображения).
        """
        with self._lock:
            self._progress.indexed_files += success
            self._progress.error_files += failed
            self._progress.current_file = current_file
            self._recalc()

    def _recalc(self) -> None:
        """Пересчитывает ``processed_files`` (под блокировкой).

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Вычисление суммы ``indexed_files``,                 |
        |   | ``duplicate_files``, ``skipped_files`` и            |
        |   | ``error_files``.                                   |
        +---+-----------------------------------------------------+
        | 2 | Установка результата в ``processed_files``.         |
        +---+-----------------------------------------------------+

        Вызывается только внутри методов, удерживающих блокировку.
        """
        self._progress.processed_files = (
            self._progress.indexed_files
            + self._progress.duplicate_files
            + self._progress.skipped_files
            + self._progress.error_files
        )

    def publish_throttled(
        self,
        scan_id: int,
        stage: str,
        force: bool = False,
    ) -> None:
        """Публикует прогресс не чаще 1 раза в секунду.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Получение текущего времени.                         |
        +---+-----------------------------------------------------+
        | 2 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 3 | Если не ``force`` и с момента последней публикации  |
        |   | прошло менее 1 секунды → выход без публикации.      |
        +---+-----------------------------------------------------+
        | 4 | Если ``total_files == 0`` и не ``force`` → выход.    |
        +---+-----------------------------------------------------+
        | 5 | Обновление ``_last_publish_time`` текущим временем. |
        +---+-----------------------------------------------------+
        | 6 | Создание копии ``ScanProgress`` (снапшота).          |
        +---+-----------------------------------------------------+
        | 7 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+
        | 8 | Если снапшот создан, публикация события             |
        |   | ``ScanProgressUpdated`` с данными из снапшота.      |
        +---+-----------------------------------------------------+

        Публикация выполняется ВНЕ блокировки для минимизации
        времени удержания.

        Args:
            scan_id: Идентификатор сканирования.
            stage: Этап конвейера (например, ``"hashing"``
                или ``"indexing"``).
            force: Если ``True``, публиковать без учёта троттлинга.
        """
        now = time.monotonic()
        snapshot: ScanProgress | None = None

        with self._lock:
            if not force and now - self._last_publish_time < 1.0:
                return
            if self._progress.total_files == 0 and not force:
                return
            self._last_publish_time = now
            snapshot = ScanProgress(
                phase=self._progress.phase,
                status=self._progress.status,
                total_files=self._progress.total_files,
                processed_files=self._progress.processed_files,
                current_file=self._progress.current_file,
                error_files=self._progress.error_files,
                indexed_files=self._progress.indexed_files,
                duplicate_files=self._progress.duplicate_files,
                skipped_files=self._progress.skipped_files,
            )

        if snapshot is not None:
            self._event_bus.publish(
                ScanProgressUpdated(
                    correlation_id=self._correlation_id,
                    source="ScanPipeline",
                    stage=stage,
                    scan_id=scan_id,
                    phase=snapshot.phase.value,
                    processed_files=snapshot.processed_files,
                    total_files=snapshot.total_files,
                    current_file=snapshot.current_file,
                    status=snapshot.status.value,
                    indexed_files=snapshot.indexed_files,
                    duplicate_files=snapshot.duplicate_files,
                    skipped_files=snapshot.skipped_files,
                    error_files=snapshot.error_files,
                )
            )

    def get_progress(self) -> ScanProgress:
        """Возвращает копию текущего прогресса.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Создание копии ``ScanProgress`` с текущими полями. |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки и возврат копии.            |
        +---+-----------------------------------------------------+

        Returns:
            Копия текущего состояния прогресса.
        """
        with self._lock:
            return ScanProgress(
                phase=self._progress.phase,
                status=self._progress.status,
                total_files=self._progress.total_files,
                processed_files=self._progress.processed_files,
                current_file=self._progress.current_file,
                error_files=self._progress.error_files,
                indexed_files=self._progress.indexed_files,
                duplicate_files=self._progress.duplicate_files,
                skipped_files=self._progress.skipped_files,
            )
