"""
Утилита публикации событий таймаута.

Единая точка публикации ``OperationTimedOut`` для всех
блокирующих операций системы. Предоставляет два интерфейса:

- ``publish_timeout()`` — низкоуровневая публикация события.
- ``run_with_timeout()`` — обёртка корутины с таймаутом
  и автоматической публикацией события.

Принципы:

+----------------------------------+----------------------------------+
| Принцип                          | Реализация                       |
+==================================+==================================+
| Архитектурная чистота            | Модуль находится в application   |
|                                  | layer. Не содержит               |
|                                  | бизнес-логики.                   |
+----------------------------------+----------------------------------+
| Инверсия зависимостей            | Зависит от абстракции            |
|                                  | ``IEventBus``, а не от           |
|                                  | конкретной шины событий.         |
+----------------------------------+----------------------------------+
| Единственная точка               | Все обработчики                  |
| публикации таймаутов             | ``asyncio.TimeoutError``         |
|                                  | должны использовать данный       |
|                                  | модуль для публикации событий.   |
+----------------------------------+----------------------------------+
| Прозрачность                     | Каждое срабатывание таймаута     |
|                                  | публикуется как событие          |
|                                  | ``OperationTimedOut`` на уровне  |
|                                  | WARNING.                         |
+----------------------------------+----------------------------------+

Примечание о непрерываемости блокирующих операций
(скорректированный план, шаг 4.1):

``run_with_timeout`` использует ``asyncio.wait_for``, который
при срабатывании таймаута **отменяет asyncio.Future**, но
**не прерывает** фактическую операцию в нижележащем пуле:

- **ThreadPoolExecutor**: ``asyncio.wait_for`` отменяет
  ``Future``, но поток продолжает выполнение до фактического
  завершения блокирующей функции. Поток освободится
  самостоятельно после возврата из функции; ресурс
  переиспользуется через пул.
- **ProcessPoolExecutor**: аналогично — ``Future`` отменяется,
  но дочерний процесс продолжает работу. Это допустимо:
  при отмене сканирования новые задачи в пул не подаются, а
  для отслеживания накопления зависших процессов используется
  ``ScanProgressTracker.record_stuck_process()``.

Следствия для вызывающего кода:

- клиент получает ответ (например, HTTP 504) **сразу** при
  срабатывании таймаута — ожидание ответа от пула прекращается;
- ресурс (поток/процесс) освобождается **позже**, когда операция
  фактически завершится;
- при систематических таймаутах пул может оказаться занятым
  «зависшими» операциями; мониторинг ``get_pool_stats()`` и
  события ``operation.timed_out`` помогают выявить проблему.

Это поведение — фундаментальное ограничение ``ThreadPoolExecutor``
и ``ProcessPoolExecutor``, не устранимое без отказа от пулов
(например, в пользу ``multiprocessing.Process`` с ``terminate()``).

Зависимости:

+----------------------------------+----------------------------------+
| Зависимость                      | Источник                         |
+==================================+==================================+
| ``config.OPERATION_TIMEOUTS``    | ``dds_core/domain/config.py``    |
+----------------------------------+----------------------------------+
| ``events.OperationTimedOut``     | ``dds_core/domain/events.py``    |
+----------------------------------+----------------------------------+
| ``interfaces.IEventBus``         | ``dds_core/domain/interfaces.py``|
+----------------------------------+----------------------------------+

Пример использования::

    from .timeout_guard import run_with_timeout

    result = await run_with_timeout(
        loop.run_in_executor(executor, blocking_func, *args),
        operation="scan.extract",
        event_bus=event_bus,
        context=task.relative_path,
        recovery_action="Файл помечен как ошибочный.",
    )

    # Или вручную:
    from .timeout_guard import publish_timeout

    try:
        await asyncio.wait_for(coro, timeout=30.0)
    except asyncio.TimeoutError:
        publish_timeout(
            event_bus,
            operation="search.query",
            timeout_seconds=30.0,
            elapsed_seconds=30.0,
            context=query,
            recovery_action="Поиск прерван по таймауту.",
        )
        raise
"""

from __future__ import annotations

import asyncio
from collections.abc import Awaitable
from typing import Any

from ..domain import config
from ..domain.events import OperationTimedOut
from ..domain.interfaces import IEventBus


def publish_timeout(
    event_bus: IEventBus,
    operation: str,
    timeout_seconds: float,
    elapsed_seconds: float,
    context: str = "",
    recovery_action: str = "",
) -> None:
    """Публикует событие ``OperationTimedOut``.

    Единая точка публикации. Все обработчики
    ``asyncio.TimeoutError`` должны вызывать эту функцию
    для обеспечения единообразной диагностики таймаутов.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Формирование ``OperationTimedOut`` с дескриптором   |
    |   | операции, таймаутом, контекстом и описанием       |
    |   | действия восстановления.                          |
    +---+-----------------------------------------------------+
    | 2 | Публикация события через ``event_bus.publish()``. |
    +---+-----------------------------------------------------+

    Примечание:

    Событие публикуется на уровне WARNING (определяется
    в ``logging_subscriber.default_level_mapping()``).
    Подписчик логирования запишет событие в лог-файл
    только если текущий уровень логирования не выше
    WARNING.

    Потокобезопасность:

    Метод ``event_bus.publish()`` является потокобезопасным
    (использует ``loop.call_soon_threadsafe``), поэтому
    ``publish_timeout`` может вызываться из любого потока.

    Архитектурная чистота:

    Функция не содержит бизнес-логики. Она формирует
    событие и передаёт его в шину. Интерпретация события
    (логирование, мониторинг, алерты) — ответственность
    подписчиков.

    Инверсия зависимостей:

    Функция принимает ``IEventBus`` (абстракцию), а не
    ``AsyncEventBus`` (конкретную реализацию). Это позволяет
    тестировать функцию с мок-объектами без запуска
    реальной шины.

    Args:
        event_bus: Шина событий для публикации. Реализация
            ``IEventBus``. Событие будет доставлено всем
            подписчикам, заинтересованным в типе
            ``"operation.timed_out"``.
        operation: Дескриптор операции. Ключ в реестре
            ``config.OPERATION_TIMEOUTS``. Например,
            ``"scan.extract"``, ``"search.query"``,
            ``"auth.login"``. Дескриптор однозначно
            идентифицирует операцию для диагностики.
        timeout_seconds: Установленный таймаут в секундах.
            Значение, которое было передано в
            ``asyncio.wait_for``.
        elapsed_seconds: Фактическое время до срабатывания
            таймаута в секундах. Обычно равно
            ``timeout_seconds``, но может отличаться при
            использовании динамических таймаутов.
        context: Дополнительные данные для диагностики.
            Например, путь к файлу, поисковый запрос,
            имя пользователя. Пустая строка по умолчанию.
        recovery_action: Описание действия, предпринятого
            после таймаута. Например, «Файл помечен как
            ошибочный», «Поиск прерван». Пустая строка
            по умолчанию.
    """
    event_bus.publish(
        OperationTimedOut(
            correlation_id="",
            source="TimeoutGuard",
            stage="timeout",
            operation=operation,
            timeout_seconds=timeout_seconds,
            elapsed_seconds=elapsed_seconds,
            context=context,
            recovery_action=recovery_action,
        )
    )


async def run_with_timeout(
    coro: Awaitable[Any],
    operation: str,
    event_bus: IEventBus,
    timeout_seconds: float | None = None,
    context: str = "",
    recovery_action: str = "Операция прервана по таймауту.",
) -> Any:
    """Выполняет корутину с таймаутом и публикацией события.

    Принимает корутину (включая результат
    ``loop.run_in_executor()``), оборачивает в
    ``asyncio.wait_for``, при ``TimeoutError`` публикует
    ``OperationTimedOut`` и пробрасывает исключение.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Определение таймаута: если ``timeout_seconds``      |
    |   | равен ``None``, значение берётся из реестра         |
    |   | ``config.OPERATION_TIMEOUTS`` по ключу              |
    |   | ``operation``. Если ключ отсутствует,               |
    |   | используется значение по умолчанию ``30.0``.        |
    +---+-----------------------------------------------------+
    | 2 | Если таймаут равен ``0`` или отрицательный —        |
    |   | таймаут отключён. Корутина выполняется без          |
    |   | ограничения времени.                                |
    +---+-----------------------------------------------------+
    | 3 | ``asyncio.wait_for(coro, timeout=timeout_seconds)``  |
    |   | — выполнение корутины с ограничением времени.       |
    +---+-----------------------------------------------------+
    | 4 | При ``asyncio.TimeoutError``:                        |
    |   | a. Публикация ``OperationTimedOut`` через           |
    |   |    ``publish_timeout()``.                           |
    |   | b. Проброс исключения для обработки вызывающим      |
    |   |    кодом.                                           |
    +---+-----------------------------------------------------+
    | 5 | При ``asyncio.CancelledError``:                      |
    |   | a. Событие ``OperationTimedOut`` НЕ публикуется.    |
    |   | b. Исключение пробрасывается без обработки.         |
    |   | Отмена извне (``task.cancel()``) не является        |
    |   | таймаутом операции.                                 |
    +---+-----------------------------------------------------+

    Примечание о непрерываемости блокирующих операций
    (скорректированный план, шаг 4.1):

    При таймауте ``asyncio.wait_for`` отменяет ``Future``,
    возвращаемый ``loop.run_in_executor()``, но **не прерывает**
    фактическую операцию в нижележащем пуле:

    - В ``ThreadPoolExecutor`` поток продолжает выполнение
      блокирующей функции до её естественного завершения.
      ``Future`` помечается ``cancelled``, но поток не
      останавливается — ресурс освободится самостоятельно
      после возврата из функции.
    - В ``ProcessPoolExecutor`` дочерний процесс продолжает
      работу. Это допустимо: при отмене сканирования новые
      задачи в пул не подаются, а накопление зависших
      процессов отслеживается через
      ``ScanProgressTracker.record_stuck_process()``.

    Следствия:

    - клиент получает ответ (например, HTTP 504) **сразу**
      при срабатывании таймаута;
    - ресурс пула освобождается **позже** — когда операция
      фактически завершится;
    - при систематических таймаутах пул может оказаться
      занятым «зависшими» операциями; для диагностики
      используйте ``get_pool_stats()`` (показывает
      занятость) и анализ событий ``operation.timed_out``
      в логе (показывает частоту).

    Это фундаментальное ограничение ``ThreadPoolExecutor``
    и ``ProcessPoolExecutor``. Преодоление требует отказа
    от пулов (например, ``multiprocessing.Process`` с
    ``terminate()`` или асинхронного I/O для конкретной
    операции), что не оправдано сложностью для текущих
    use case DDS.

    Примечание по ``CancelledError``:

    ``asyncio.CancelledError`` НЕ является таймаутом.
    Это штатная отмена задачи извне (например, при
    ``task.cancel()`` в ``cancel_scan``). Событие
    ``OperationTimedOut`` в этом случае не публикуется,
    чтобы не загрязнять лог ложными срабатываниями.
    Исключение пробрасывается для корректного завершения
    ``TaskGroup`` и публикации ``ScanCancelled``.

    Архитектурная чистота:

    Функция не содержит бизнес-логики. Она оборачивает
    корутину в таймаут и публикует событие при
    срабатывании. Обработка таймаута (повторная попытка,
    переключение на fallback, пометка файла как ошибочного)
    — ответственность вызывающего кода.

    Инверсия зависимостей:

    Функция принимает ``IEventBus`` (абстракцию) и
    ``Awaitable`` (абстракцию над корутиной). Конкретная
    реализация шины и конкретная блокирующая операция
    передаются извне.

    Пример использования с ``run_in_executor``::

        loop = asyncio.get_running_loop()
        result = await run_with_timeout(
            loop.run_in_executor(
                executor,
                blocking_func,
                arg1,
                arg2,
            ),
            operation="scan.extract",
            event_bus=event_bus,
            context=task.relative_path,
            recovery_action="Файл помечен как ошибочный.",
        )

    Пример использования с корутиной::

        result = await run_with_timeout(
            some_async_function(),
            operation="search.query",
            event_bus=event_bus,
            context=query,
        )

    Пример с отключённым таймаутом::

        # Таймаут 0 отключает ограничение
        result = await run_with_timeout(
            coro,
            operation="index.refresh",
            event_bus=event_bus,
            timeout_seconds=0,
        )

    Args:
        coro: Корутина для выполнения. Может быть результатом
            ``loop.run_in_executor()`` (``asyncio.Future``)
            или обычной корутиной. Тип ``Awaitable[Any]``
            покрывает оба случая.
        operation: Дескриптор операции. Ключ в реестре
            ``config.OPERATION_TIMEOUTS``. Используется
            для определения таймаута (если ``timeout_seconds``
            не задан явно) и для идентификации операции
            в событии ``OperationTimedOut``.
        event_bus: Шина событий для публикации. Реализация
            ``IEventBus``.
        timeout_seconds: Явный таймаут в секундах. Если
            ``None`` — берётся из реестра
            ``config.OPERATION_TIMEOUTS`` по ключу
            ``operation``. Если ключ отсутствует в реестре,
            используется значение по умолчанию ``30.0``.
            Если ``0`` или отрицательный — таймаут отключён.
        context: Дополнительные данные для диагностики.
            Например, путь к файлу, поисковый запрос.
            Передаётся в событие ``OperationTimedOut``.
            Пустая строка по умолчанию.
        recovery_action: Описание действия, предпринятого
            после таймаута. Передаётся в событие
            ``OperationTimedOut``. По умолчанию:
            ``"Операция прервана по таймауту."``.

    Returns:
        Результат выполнения корутины.

    Raises:
        asyncio.TimeoutError: При срабатывании таймаута.
            Событие ``OperationTimedOut`` публикуется
            перед пробросом исключения.
        asyncio.CancelledError: При отмене задачи извне.
            Событие НЕ публикуется. Исключение
            пробрасывается без обработки.
        Exception: Любое исключение, выброшенное корутиной,
            пробрасывается без обработки.
    """
    # Определение таймаута из реестра или аргумента
    if timeout_seconds is None:
        timeout_seconds = config.OPERATION_TIMEOUTS.get(operation, 30.0)

    # Таймаут 0 или отрицательный — ограничение отключено
    if timeout_seconds <= 0:
        return await coro

    try:
        return await asyncio.wait_for(coro, timeout=timeout_seconds)
    except TimeoutError:
        publish_timeout(
            event_bus=event_bus,
            operation=operation,
            timeout_seconds=timeout_seconds,
            elapsed_seconds=timeout_seconds,
            context=context,
            recovery_action=recovery_action,
        )
        raise
