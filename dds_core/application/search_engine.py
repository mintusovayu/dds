"""
Поисковый движок DDS.

Этот модуль содержит класс SearchEngine, который обеспечивает
полнотекстовый поиск по проиндексированным документам. Модуль
находится в application layer и использует абстракцию ISearchBackend
для выполнения поиска, не зная о конкретной реализации
(SQLite FTS5, Elasticsearch и т.д.).

Используется capability-based подход: SearchEngine проверяет
возможности бэкенда через get_capabilities() и использует только
поддерживаемые функции.

Серверная группировка результатов:

Поисковый бэкенд возвращает результаты, сгруппированные по
документу: одна строка на документ с массивом страниц с их
сниппетами. ``SearchEngine`` не выполняет дополнительной
группировки — он лишь передаёт результаты через свой интерфейс.
Метод ``search_with_count`` возвращает кортеж
``(список документов, количество уникальных документов)``.

Фильтрация:
Поисковый движок принимает объект SearchFilters, который может
содержать как стандартные фильтры (по пути файла, по данным модулей),
так и фильтры по метаданным имени файла: код объекта, код дисциплины,
код типа документа, а также режим отбора только несоответствующих
документов. Эти фильтры передаются в бэкенд без изменений.

Поддержка пустого запроса:
Если ``query`` пустая строка, поисковый движок не выбрасывает
исключение, а передаёт её в бэкенд. В этом случае бэкенд
возвращает документы, соответствующие только фильтрам (или все
документы, если фильтры отсутствуют).

LRU-кэш текста страниц (скорректированный план, шаг 3.2):

``SearchEngine.get_page_text`` кэширует результаты чтения из
``text_index_fts`` в LRU-кэше ``OrderedDict`` с ключом
``(doc_id, page_number, file_hash)``. Включение ``file_hash``
обеспечивает **автоинвалидацию** при переиндексации файла:
изменение хеша делает старые записи недостижимыми, и они
постепенно вытесняются LRU.

Размер кэша задаётся ``config.PAGE_TEXT_CACHE_SIZE`` (по умолчанию
500 страниц). При переполнении вытесняется наименее недавно
использованная запись.

Сигнатура ``get_page_text`` расширена параметром ``file_hash``:
вызывающий код обязан передать актуальное значение. Это устраняет
необходимость в отдельном кэше ``doc_id → file_hash`` (который
мог бы устареть при переиндексации) и делает инвалидацию
естественной частью ключа.

Явная инвалидация кэша при удалении документа выполняется
методом ``invalidate_page_text_cache(doc_id)``. Вызывается из
``dds_web/api.py::delete_document``.

Потокобезопасность кэша:

Все операции над ``OrderedDict`` защищены ``threading.Lock``.
При гонке (два потока одновременно промахиваются по одному
ключу) возможно двойное чтение из БД — операция идемпотентна,
результат совпадает, поэтому дополнительная синхронизация
не требуется.

Принципы:
    - Модуль зависит от абстракций (ISearchBackend, IDatabase),
      а не от конкретных реализаций (инверсия зависимостей).
    - Конкретные реализации передаются через конструктор.
    - Модуль не содержит бизнес-логики индексирования.
    - Модуль не выполняет логирование. Логирование — ответственность
      presentation layer.

Классы:
    SearchEngine — поисковый движок.
"""

from __future__ import annotations

import threading
from collections import OrderedDict

from ..domain import config
from ..domain.interfaces import IDatabase, ISearchBackend
from ..domain.models import Document, SearchFilters, SearchResult

# ----------------------------------------------------------------------
# Поисковый движок
# ----------------------------------------------------------------------


class SearchEngine:
    """Поисковый движок DDS.

    Обеспечивает полнотекстовый поиск по проиндексированным
    документам. Использует абстракцию ISearchBackend для
    выполнения поиска и IDatabase для получения метаданных
    документов.

    Результаты поиска сгруппированы по документу: одна строка
    на документ с массивом страниц с их сниппетами. Группировка
    выполняется на уровне поискового бэкенда.

    Поддерживаемые фильтры:
    - по пути файла (SQL LIKE);
    - по данным модулей (через VIEW);
    - по коду объекта, коду дисциплины, коду типа документа;
    - режим отбора только несоответствующих документов
      (unmatched_only).

    Пустой запрос:
    Если ``query`` является пустой строкой, поиск выполняется
    только по фильтрам (или вообще по всем документам, если
    фильтров нет). Это позволяет реализовать режим «показать
    все документы».

    LRU-кэш текста страниц:
    ``get_page_text`` использует LRU-кэш с ключом
    ``(doc_id, page_number, file_hash)``. Размер — из
    ``config.PAGE_TEXT_CACHE_SIZE``. При удалении документа
    кэш инвалидируется через ``invalidate_page_text_cache``.

    Пример использования:

        engine = SearchEngine(search_backend, db_adapter)
        results = engine.search("гидрошпонка", limit=20)
        results, total = engine.search_with_count(
            "",
            filters=SearchFilters(object_code="7350"),
        )
        doc_info = engine.get_document_info("doc_001")
        text = engine.get_page_text("doc_001", 0, doc_info.file_hash)

    Attributes:
        _backend: Поисковый бэкенд.
        _db: Абстракция базы данных для получения метаданных.
        _page_text_cache: LRU-кэш текста страниц. Ключ —
            ``(doc_id, page_number, file_hash)``, значение — текст.
            Порядок — от старых к новым; при переполнении
            удаляется первый элемент.
        _page_text_cache_lock: Блокировка для потокобезопасного
            доступа к кэшу.
        _page_text_cache_size: Максимальный размер кэша
            (из ``config.PAGE_TEXT_CACHE_SIZE``).
    """

    def __init__(
        self,
        backend: ISearchBackend,
        db: IDatabase,
    ) -> None:
        """Инициализирует поисковый движок.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ссылки на ``ISearchBackend``.            |
        +---+-----------------------------------------------------+
        | 2 | Сохранение ссылки на ``IDatabase``.                 |
        +---+-----------------------------------------------------+
        | 3 | Инициализация пустого LRU-кэша текста страниц.      |
        +---+-----------------------------------------------------+
        | 4 | Создание ``threading.Lock`` для защиты кэша.        |
        +---+-----------------------------------------------------+
        | 5 | Чтение ``config.PAGE_TEXT_CACHE_SIZE`` в поле       |
        |   | ``_page_text_cache_size``.                          |
        +---+-----------------------------------------------------+

        Args:
            backend: Реализация ISearchBackend для выполнения
                полнотекстового поиска.
            db: Реализация IDatabase для получения метаданных
                документов и текста страниц.
        """
        self._backend = backend
        self._db = db

        # LRU-кэш текста страниц: ключ (doc_id, page, file_hash) → текст.
        # file_hash в ключе обеспечивает автоинвалидацию при
        # переиндексации: старые записи становятся недостижимыми.
        self._page_text_cache: OrderedDict[tuple[str, int, str], str] = OrderedDict()
        self._page_text_cache_lock = threading.Lock()
        self._page_text_cache_size: int = config.PAGE_TEXT_CACHE_SIZE

    def search(
        self,
        query: str,
        filters: SearchFilters | None = None,
        limit: int = config.SEARCH_DEFAULT_LIMIT,
        offset: int = 0,
    ) -> list[SearchResult]:
        """Выполняет поиск документов.

        Возвращает список сгруппированных результатов: по одному
        :class:`SearchResult` на документ, с массивом страниц
        внутри.

        Args:
            query: Поисковый запрос. Может быть пустой строкой.
            filters: Фильтры для комбинированного поиска.
                Может содержать фильтры по пути файла, данным модулей,
                а также по метаданным имени файла
                (object_code, discipline_code, document_type_code,
                unmatched_only). ``None`` — без фильтрации.
            limit: Максимальное количество документов.
            offset: Смещение по документам.

        Returns:
            Список :class:`SearchResult`, по одному на документ,
            отсортированных по релевантности (или по имени файла
            для пустого запроса). Пустой список, если ничего
            не найдено.
        """
        # Не выбрасываем исключение при пустом запросе.
        query = query.strip() if query else ""
        return self._backend.search(
            query=query,
            filters=filters,
            limit=limit,
            offset=offset,
        )

    def search_with_count(
        self,
        query: str,
        filters: SearchFilters | None = None,
        limit: int = config.SEARCH_DEFAULT_LIMIT,
        offset: int = 0,
    ) -> tuple[list[SearchResult], int]:
        """Выполняет поиск документов с подсчётом общего количества.

        Возвращает сгруппированные результаты: по одному
        :class:`SearchResult` на документ, с массивом страниц
        внутри. Используется для постраничного вывода по документам.

        Семантика ``total``:

        - ``total`` — количество **уникальных документов**,
          соответствующих запросу и фильтрам, а не количество
          страниц или совпадений.
        - Пагинация (``limit``/``offset``) также работает по
          документам: ``offset`` отсчитывается в документах.

        Args:
            query: Поисковый запрос. Может быть пустой строкой.
            filters: Фильтры для комбинированного поиска
                (включая фильтры по метаданным).
            limit: Максимальное количество документов.
            offset: Смещение по документам.

        Returns:
            Кортеж ``(результаты, общее количество документов)``.

        """
        query = query.strip() if query else ""
        results = self._backend.search(
            query=query,
            filters=filters,
            limit=limit,
            offset=offset,
        )

        if "count" in self._backend.get_capabilities():
            total = self._backend.count(query=query, filters=filters)
        else:
            # Если бэкенд не поддерживает count, используем
            # приблизительную оценку
            total = len(results) + offset

        return results, total

    def get_document_info(self, doc_id: str) -> Document | None:
        """Возвращает метаданные документа.

        Args:
            doc_id: Идентификатор документа.

        Returns:
            Document с метаданными документа, или None,
            если документ не найден.
        """
        results = self._db.execute(
            "SELECT doc_id, file_path, file_hash, file_size, "
            "page_count, indexed_at, last_modified "
            "FROM documents WHERE doc_id = ?",
            (doc_id,),
        )
        if not results:
            return None

        row = results[0]
        return Document(
            doc_id=str(row[0]),
            file_path=str(row[1]),
            file_hash=str(row[2]),
            file_size=int(row[3]),
            page_count=int(row[4]),
            indexed_at=str(row[5]),
            last_modified=str(row[6]),
        )

    def get_page_text(
        self,
        doc_id: str,
        page_number: int,
        file_hash: str,
    ) -> str:
        """Возвращает текст страницы документа с использованием LRU-кэша.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Формирование ключа кэша из ``(doc_id, page_number,   |
        |   | file_hash)``.                                       |
        +---+-----------------------------------------------------+
        | 2 | Проверка кэша под блокировкой. При попадании —      |
        |   | перемещение записи в конец ``OrderedDict``          |
        |   | (становится свежей) и возврат значения.             |
        +---+-----------------------------------------------------+
        | 3 | При промахе — ``SELECT text_content FROM            |
        |   | text_index_fts WHERE doc_id = ? AND page_number = ?``|
        +---+-----------------------------------------------------+
        | 4 | Запись результата в кэш под блокировкой;            |
        |   | вытеснение наименее свежих записей при превышении   |
        |   | ``_page_text_cache_size``.                          |
        +---+-----------------------------------------------------+
        | 5 | Возврат текста.                                     |
        +---+-----------------------------------------------------+

        Args:
            doc_id: Идентификатор документа.
            page_number: Номер страницы (0-based).
            file_hash: Хеш файла документа. Часть ключа кэша для
                автоинвалидации при переиндексации. Вызывающий код
                обязан передать актуальное значение (обычно берётся
                из ``doc.file_hash``, полученного через
                ``get_document_info``).

        Returns:
            Текст страницы. Пустая строка, если страница не найдена
            или в FTS-индексе отсутствует запись для неё.
        """
        key = (doc_id, page_number, file_hash)

        # 1. Проверка кэша.
        with self._page_text_cache_lock:
            if key in self._page_text_cache:
                self._page_text_cache.move_to_end(key)
                return self._page_text_cache[key]

        # 2. Чтение из FTS-индекса (вне блокировки, чтобы не
        # блокировать другие потоки на время SQL-запроса).
        rows = self._db.execute(
            "SELECT text_content FROM text_index_fts WHERE doc_id = ? AND page_number = ?",
            (doc_id, page_number),
        )
        text = str(rows[0][0]) if rows else ""

        # 3. Запись в кэш под блокировкой + вытеснение.
        with self._page_text_cache_lock:
            self._page_text_cache[key] = text
            self._page_text_cache.move_to_end(key)
            while len(self._page_text_cache) > self._page_text_cache_size:
                self._page_text_cache.popitem(last=False)

        return text

    def invalidate_page_text_cache(self, doc_id: str) -> None:
        """Удаляет из кэша все записи для указанного документа.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват ``_page_text_cache_lock``.                   |
        +---+-----------------------------------------------------+
        | 2 | Формирование списка ключей с ``key[0] == doc_id``.  |
        +---+-----------------------------------------------------+
        | 3 | Удаление каждой такой записи из ``OrderedDict``.    |
        +---+-----------------------------------------------------+
        | 4 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Примечание:
            При переиндексации инвалидация не требуется: изменение
            ``file_hash`` делает старые записи недостижимыми
            (новые обращения используют новый ключ). Метод
            предназначен для случаев полного удаления документа —
            вызывается из ``dds_web/api.py::delete_document`` после
            ``ScanOrchestrator.remove_document``.

        Args:
            doc_id: Идентификатор документа, записи которого нужно
                удалить из кэша.
        """
        with self._page_text_cache_lock:
            keys_to_remove = [k for k in self._page_text_cache if k[0] == doc_id]
            for k in keys_to_remove:
                del self._page_text_cache[k]

    def get_backend_capabilities(self) -> set[str]:
        """Возвращает возможности поискового бэкенда.

        Используется веб-интерфейсом для определения
        доступных функций поиска.

        Returns:
            Множество строк с именами возможностей.
        """
        return self._backend.get_capabilities()
