"""
LRU-кэш индексов слов страниц.

Кэширует результаты ``ITextDocument.build_word_index()`` для
повторного использования между запросами подсветки. Ключ —
``(doc_id, page_number, file_hash)``.

Включение ``file_hash`` в ключ обеспечивает **автоматическую
инвалидацию** при переиндексации файла: при изменении хеша старые
записи становятся недостижимыми и постепенно вытесняются LRU.
Это позволяет не реализовывать явную инвалидацию по
``doc_id`` / ``page_number``.

Потокобезопасность:

Все операции над ``OrderedDict`` защищены ``threading.Lock``.
При гонке (два потока одновременно промахиваются по одному
ключу) возможно двойное построение индекса — операция
идемпотентна, результат совпадает, поэтому дополнительная
синхронизация не требуется.

Принципы:
- Не зависит от конкретной реализации ``ITextDocument``:
  работает только с :class:`WordIndex`.
- Не управляет открытием PDF — ответственность вызывающего
  кода (инфраструктурного слоя).
- Не содержит бизнес-логики: только хранение и извлечение.
- Потокобезопасен.

Классы:
    ``WordIndexCache`` — LRU-кэш индексов слов.
"""

from __future__ import annotations

import threading
from collections import OrderedDict

from ..domain.models import WordIndex


class WordIndexCache:
    """Потокобезопасный LRU-кэш индексов слов.

    Хранит до ``max_size`` записей в ``OrderedDict``. При
    переполнении вытесняется **наименее недавно использованная**
    запись. Обращение через :meth:`get` перемещает запись в
    конец словаря (становится самой свежей).

    Ключ кэша — ``(doc_id, page_number, file_hash)``. Включение
    ``file_hash`` обеспечивает автоинвалидацию при переиндексации
    файла: изменение хеша делает старые записи недостижимыми.

    Пример использования::

        cache = WordIndexCache(max_size=500)

        # Попытка получить из кэша.
        index = cache.get("doc_001", 3, "abc123")
        if index is None:
            index = build_index(...)   # вычисляем
            cache.put("doc_001", 3, "abc123", index)

        # Диагностика.
        stats = cache.get_stats()
        # {"size": 1, "max_size": 500, "hits": 0, "misses": 1}

    Attributes:
        _cache: Словарь записей. Ключ — кортеж
            ``(doc_id, page_number, file_hash)``. Порядок — от
            старых к новым; при переполнении удаляется первый.
        _lock: Блокировка для потокобезопасного доступа.
        _max_size: Максимальный размер кэша.
        _hits: Счётчик попаданий (для диагностики).
        _misses: Счётчик промахов (для диагностики).
    """

    def __init__(self, max_size: int) -> None:
        """Инициализирует кэш.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Валидация ``max_size > 0``.                         |
        +---+-----------------------------------------------------+
        | 2 | Создание пустого ``OrderedDict``.                   |
        +---+-----------------------------------------------------+
        | 3 | Создание ``threading.Lock``.                        |
        +---+-----------------------------------------------------+
        | 4 | Инициализация счётчиков ``_hits = 0``,              |
        |   | ``_misses = 0``.                                    |
        +---+-----------------------------------------------------+

        Args:
            max_size: Максимальное количество страниц в кэше.
                Должно быть положительным.

        Raises:
            ValueError: Если ``max_size`` меньше или равен нулю.
        """
        if max_size <= 0:
            raise ValueError(f"max_size должен быть положительным, получено: {max_size}")

        self._cache: OrderedDict[tuple[str, int, str], WordIndex] = OrderedDict()
        self._lock = threading.Lock()
        self._max_size = max_size
        self._hits = 0
        self._misses = 0

    def get(
        self,
        doc_id: str,
        page_number: int,
        file_hash: str,
    ) -> WordIndex | None:
        """Возвращает индекс из кэша или ``None``.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Формирование ключа из аргументов.                   |
        +---+-----------------------------------------------------+
        | 2 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 3 | Если ключ присутствует:                             |
        |   | a. Перемещение записи в конец ``OrderedDict``       |
        |   |    (отметка «свежая»).                              |
        |   | b. Инкремент ``_hits``.                             |
        |   | c. Возврат индекса.                                 |
        +---+-----------------------------------------------------+
        | 4 | Иначе — инкремент ``_misses`` и возврат ``None``.   |
        +---+-----------------------------------------------------+

        Примечание:
            Возвращаемый :class:`WordIndex` — **общая ссылка**.
            Мутация объекта запрещена: изменение испортит кэш
            для всех последующих запросов.

        Args:
            doc_id: Идентификатор документа.
            page_number: Номер страницы (0-based).
            file_hash: Хеш файла документа. Часть ключа, обеспечивает
                автоинвалидацию при переиндексации.

        Returns:
            :class:`WordIndex`, если запись есть в кэше, иначе
            ``None``.
        """
        key = (doc_id, page_number, file_hash)
        with self._lock:
            if key in self._cache:
                self._cache.move_to_end(key)
                self._hits += 1
                return self._cache[key]
            self._misses += 1
            return None

    def put(
        self,
        doc_id: str,
        page_number: int,
        file_hash: str,
        index: WordIndex,
    ) -> None:
        """Сохраняет индекс в кэш.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Формирование ключа.                                 |
        +---+-----------------------------------------------------+
        | 2 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 3 | Запись ``index`` в ``OrderedDict``.                 |
        +---+-----------------------------------------------------+
        | 4 | Перемещение записи в конец (свежая).                |
        +---+-----------------------------------------------------+
        | 5 | Пока размер > ``max_size``:                         |
        |   | a. Удаление первой записи (наименее свежей).        |
        +---+-----------------------------------------------------+
        | 6 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Примечание:
            При повторной записи с тем же ключом старое значение
            перезаписывается. Это допустимо: вызывающий код
            передаёт актуальный индекс.

        Args:
            doc_id: Идентификатор документа.
            page_number: Номер страницы (0-based).
            file_hash: Хеш файла документа.
            index: Индекс слов страницы. Хранится по ссылке;
                мутация после сохранения запрещена.
        """
        key = (doc_id, page_number, file_hash)
        with self._lock:
            self._cache[key] = index
            self._cache.move_to_end(key)
            while len(self._cache) > self._max_size:
                self._cache.popitem(last=False)

    def clear(self) -> None:
        """Очищает кэш.

        Используется при teardown приложения и в тестах.
        Счётчики ``_hits`` и ``_misses`` **не сбрасываются**:
        они отражают статистику за всё время жизни экземпляра.
        """
        with self._lock:
            self._cache.clear()

    def get_stats(self) -> dict:
        """Возвращает статистику кэша для диагностики.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Формирование словаря с текущим состоянием.          |
        +---+-----------------------------------------------------+
        | 3 | Возврат словаря.                                    |
        +---+-----------------------------------------------------+

        Returns:
            Словарь с ключами:

            +--------------+----------------------------------------+
            | Ключ         | Описание                               |
            +==============+========================================+
            | ``size``     | Текущее количество записей.            |
            +--------------+----------------------------------------+
            | ``max_size`` | Максимальный размер кэша.              |
            +--------------+----------------------------------------+
            | ``hits``     | Количество попаданий за время жизни    |
            |              | экземпляра.                            |
            +--------------+----------------------------------------+
            | ``misses``   | Количество промахов за время жизни     |
            |              | экземпляра.                            |
            +--------------+----------------------------------------+

            Пример::

                {
                    "size": 42,
                    "max_size": 500,
                    "hits": 128,
                    "misses": 15,
                }
        """
        with self._lock:
            return {
                "size": len(self._cache),
                "max_size": self._max_size,
                "hits": self._hits,
                "misses": self._misses,
            }

    @property
    def size(self) -> int:
        """Возвращает текущее количество записей в кэше.

        Returns:
            Количество записей. Значение может устареть к моменту
            чтения, если другие потоки работают с кэшем. Для
            точной диагностики предпочтительно использовать
            :meth:`get_stats`.
        """
        with self._lock:
            return len(self._cache)

    @property
    def max_size(self) -> int:
        """Возвращает максимальный размер кэша.

        Значение неизменно в течение жизни экземпляра.

        Returns:
            Максимальное количество записей.
        """
        return self._max_size
