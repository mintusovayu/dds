"""
Извлечение терминов подсветки из сниппета FTS5.

Модуль содержит чистую функцию :func:`extract_terms_from_snippet`,
которая извлекает термины совпадений из строки сниппета, возвращённой
функцией SQLite FTS5 ``snippet()``. Термины в сниппете обрамлены
нейтральными маркерами, заданными в :mod:`dds_core.domain.config`
(``SNIPPET_HIGHLIGHT_START`` / ``SNIPPET_HIGHLIGHT_END``).

Назначение
----------

До Фазы 6 термины извлекались на клиенте (``dds_web/static/js/search.js``)
через регулярное выражение по маркерам. Это создавало протечку
FTS5-специфики в presentation layer: клиент знал о формате сниппетов
и был обязан повторять ту же логику извлечения, что и сервер.

Фаза 6 переносит извлечение на сервер. Единая точка контроля —
этот модуль. Формат маркеров задаётся в одном месте (``config``),
изменение формата не требует правок в JS.

Место в архитектуре
-------------------

Модуль находится в **application layer**: правило извлечения
терминов — часть обработки результатов поиска, а не инфраструктуры.
Он не зависит ни от конкретной PDF-библиотеки, ни от FTS5-движка —
на входе обычная строка. Это позволяет использовать его и в
infrastructure (``FTS5SearchBackend`` заполняет ``PageHit.terms``),
и в будущих бэкендах (Elasticsearch, Meilisearch) без изменений.

Модуль не зависит от других модулей проекта, кроме
:mod:`dds_core.domain.config` (константы маркеров). Это согласовано
с архитектурным контрактом ``application-isolation``.

Алгоритм
--------

Функция выполняет линейный обход строки сниппета:

1. Ищет ближайший маркер ``SNIPPET_HIGHLIGHT_START`` от текущей позиции.
2. Если не найден — завершает обход.
3. Ищет ближайший ``SNIPPET_HIGHLIGHT_END`` после найденного ``START``.
4. Если ``END`` не найден — завершает обход (непарный ``START`` игнорируется).
5. Извлекает фрагмент между маркерами, применяет ``.strip()``.
6. Пропускает пустые фрагменты.
7. Сдвигает позицию за ``END`` и повторяет.

Дедупликация выполняется через ``dict.fromkeys`` — сохраняет порядок
первого появления.

Примечание о вложенных маркерах:
    FTS5 ``snippet()`` не порождает вложенных маркеров. Если в
    исходном тексте страницы встречается фрагмент, визуально
    совпадающий с маркером (например, документ содержит
    буквальную строку ``[[DDS_HIGHLIGHT_START]]``), поведение
    функции определяется алгоритмом ``str.find``: первый ``START``
    формирует пару с ближайшим ``END``. Содержимое такой
    «искусственной» пары будет возвращено как термин. Это
    осознанное решение: обработка коллизий между реальным
    содержимым документа и служебными маркерами не входит
    в задачу.

Принципы
--------

- **Чистая функция.** Детерминированная, без побочных эффектов,
  не мутирует вход. Может вызываться из нескольких потоков
  одновременно.
- **Иммутабельный результат.** Возвращается ``tuple[str, ...]``:
  hashable, pickle-совместимо, безопасно для кэширования.
- **Без regex.** Обход через ``str.find``: линейная сложность,
  отсутствие необходимости экранировать маркеры, отсутствие
  backtracking-рисков.
- **Не логирует.** Ошибок здесь быть не может — вход всегда
  валиден. Логирование — ответственность вызывающего кода.
- **Не зависит от FTS5.** Модуль не импортирует ни SQLite, ни
  FTS5-специфичные модули. Маркеры — обычные строки.

Использование
-------------

.. code-block:: python

    from dds_core.application.snippet_terms_extractor import (
        extract_terms_from_snippet,
    )

    # Сниппет из FTS5 (после denormalize_text):
    snippet = "… найдено [[DDS_HIGHLIGHT_START]]корпус[[DDS_HIGHLIGHT_END]] …"
    terms = extract_terms_from_snippet(snippet)
    # ("корпус",)

См. также
---------

- :mod:`dds_core.domain.config` — константы
  ``SNIPPET_HIGHLIGHT_START`` / ``SNIPPET_HIGHLIGHT_END``.
- ``dds_core/infrastructure/fts5_search_backend.py`` — потребитель,
  заполняющий ``PageHit.terms``.
- ``docs/architecture-decisions/ADR-006-server-side-terms.md`` —
  обоснование переноса извлечения на сервер.
"""

from __future__ import annotations

from ..domain import config as core_config

# ----------------------------------------------------------------------
# Извлечение терминов из сниппета
# ----------------------------------------------------------------------


def extract_terms_from_snippet(snippet: str) -> tuple[str, ...]:
    """Извлекает уникальные термины из сниппета FTS5.

    Термины — фрагменты между маркерами
    :data:`config.SNIPPET_HIGHLIGHT_START` и
    :data:`config.SNIPPET_HIGHLIGHT_END`. Порядок появления
    сохраняется, дубликаты удаляются.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Если ``snippet`` пуст → возврат ``()``.             |
    +---+-----------------------------------------------------+
    | 2 | Установка ``pos = 0`` (текущая позиция обхода).     |
    +---+-----------------------------------------------------+
    | 3 | Цикл:                                               |
    |   | a. ``start = snippet.find(START_MARKER, pos)``.     |
    |   | b. Если ``start == -1`` — выход из цикла.           |
    |   | c. ``end = snippet.find(                        ``   |
    |   |    ``END_MARKER, start + len(START_MARKER))``.      |
    |   | d. Если ``end == -1`` — выход из цикла (непарный    |
    |   |    ``START``).                                      |
    |   | e. ``term = snippet[                            ``   |
    |   |    ``start + len(START_MARKER):end].strip()``.      |
    |   | f. Если ``term`` непуст → добавить в ``terms``.     |
    |   | g. ``pos = end + len(END_MARKER)``.                 |
    +---+-----------------------------------------------------+
    | 4 | Дедупликация: ``dict.fromkeys(terms)``.             |
    +---+-----------------------------------------------------+
    | 5 | Возврат ``tuple(...)``.                             |
    +---+-----------------------------------------------------+

    Примечание:
        Функция **не нормализует** термины. Нормализация —
        ответственность потребителя (``HighlightsService``
        нормализует входной список терминов перед поиском
        в ``WordIndex``). Это разделяет задачи: извлечение —
        структурная операция, нормализация — семантическая.

    Примечание:
        Функция **не денормализует** термины. Если сниппет
        передан уже денормализованным (обычный сценарий из
        ``FTS5SearchBackend``), термины будут в денормализованной
        форме и пригодны для отображения пользователю в
        подсказках. Если сниппет нормализован (гипотетический
        сценарий), термины будут нормализованными — это тоже
        допустимо, так как ``HighlightsService`` устойчив к
        обоим формам.

    Args:
        snippet: Строка сниппета FTS5 с маркерами подсветки.
            Может быть пустой. Может не содержать маркеров.

    Returns:
        Кортеж уникальных терминов в порядке появления.
        Пустой кортеж, если ``snippet`` пуст, маркеров нет или
        между маркерами только пробелы.

    Example:
        Пустой сниппет или сниппет без маркеров::

            >>> extract_terms_from_snippet("")
            ()
            >>> extract_terms_from_snippet("обычный текст без подсветки")
            ()

        Один термин::

            >>> extract_terms_from_snippet(
            ...     "… [[DDS_HIGHLIGHT_START]]корпус[[DDS_HIGHLIGHT_END]] …"
            ... )
            ('корпус',)

        Несколько терминов (порядок появления)::

            >>> s = ("[[DDS_HIGHLIGHT_START]]a[[DDS_HIGHLIGHT_END]] "
            ...      "… [[DDS_HIGHLIGHT_START]]b[[DDS_HIGHLIGHT_END]]")
            >>> extract_terms_from_snippet(s)
            ('a', 'b')

        Дедупликация::

            >>> s = ("[[DDS_HIGHLIGHT_START]]x[[DDS_HIGHLIGHT_END]] "
            ...      "[[DDS_HIGHLIGHT_START]]x[[DDS_HIGHLIGHT_END]]")
            >>> extract_terms_from_snippet(s)
            ('x',)
    """
    if not snippet:
        return ()

    start_marker = core_config.SNIPPET_HIGHLIGHT_START
    end_marker = core_config.SNIPPET_HIGHLIGHT_END
    start_marker_len = len(start_marker)
    end_marker_len = len(end_marker)

    terms: list[str] = []
    pos = 0

    while True:
        start = snippet.find(start_marker, pos)
        if start == -1:
            break

        content_start = start + start_marker_len
        end = snippet.find(end_marker, content_start)
        if end == -1:
            # Непарный START — прекращаем обход. Все последующие
            # START тоже непарные (иначе первый END был бы найден
            # раньше), поэтому продолжать бессмысленно.
            break

        term = snippet[content_start:end].strip()
        if term:
            terms.append(term)

        pos = end + end_marker_len

    return tuple(dict.fromkeys(terms))
