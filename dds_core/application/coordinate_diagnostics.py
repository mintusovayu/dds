"""
Диагностика и коррекция системы координат страницы.

Модуль содержит две чистые функции для работы с системой
координат страницы PDF при построении подсветки совпадений:

- :func:`diagnose_word_index` — диагностика аномальной системы
  координат по готовому :class:`WordIndex`.
- :func:`transform_bbox` — преобразование координат прямоугольника
  из ошибочной системы координат (bottom-left с перепутанными
  осями) в стандартную (top-left).

Проблема:
    В некоторых PDF-документах система координат отличается от
    стандартной top-left. Вместо этого используется bottom-left
    система с перепутанными осями:

    - Ось X направлена вертикально (снизу вверх).
    - Ось Y направлена горизонтально (слева направо).

    Это приводит к тому, что координаты слов из
    ``page.get_text("words")`` не соответствуют их визуальному
    положению на странице. Поиск, индексация и рендер PNG работают
    корректно (они не используют координаты слов), но подсветка
    совпадений отображается в неправильных местах.

    Тип аномалии однозначен: если она обнаружена, преобразование
    всегда одинаковое. Определение «какого-то другого» типа
    ошибки не требуется.

Формула преобразования:
    Эталонная модель (см. ``diagnostics.py`` и ``transformer.py``
    внешней программы) описывает преобразование сегментов
    следующим образом:

    - Для вертикальных сегментов (в терминах PyMuPDF-координат —
      сегментов с постоянным x, но визуально горизонтальных):
      новая «закреплённая» координата = ``page_height - old_fixed``;
      начальная и конечная координаты не меняются.
    - Для горизонтальных сегментов (в терминах PyMuPDF-координат —
      сегментов с постоянным y, но визуально вертикальных):
      «закреплённая» координата не меняется;
      новая start = ``page_height - old_end``;
      новая end   = ``page_height - old_start``.

    Перенесённое на bbox слова, преобразование имеет вид::

        new_x0 = old_y0
        new_x1 = old_y1
        new_y0 = page_height - old_x1
        new_y1 = page_height - old_x0

    Обоснование:
        В аномальной системе координат PyMuPDF возвращает:

        - ``x_screen = X_аномальный`` — вертикальная координата
          (снизу вверх);
        - ``y_screen = Y_аномальный`` — горизонтальная координата
          (слева направо, БЕЗ инверсии PyMuPDF).

        Для таких PDF-документов PyMuPDF сохраняет ориентацию Y
        контента (не инвертирует его), что отличает аномальные
        PDF-файлы от стандартных. Соответственно, визуальные
        координаты выражаются через screen-координаты так::

            x_visual = y_screen
            y_visual = page_height - x_screen

        Для bbox ``(x0, y0, x1, y1)``::

            x_visual ∈ [y0, y1]
            y_visual ∈ [page_height - x1, page_height - x0]

        Инвариант порядка сохраняется: ``new_x1 > new_x0``,
        ``new_y1 > new_y0``.

Диагностика:
    Используются два независимых текстовых признака:

    +------------------+--------------------------------------------+
    | Признак          | Описание                                   |
    +==================+============================================+
    | OOB              | Доля слов, выходящих за границы            |
    | (out-of-bounds)  | ``[0, page_width] × [0, page_height]``.    |
    +------------------+--------------------------------------------+
    | Dominance        | Доля «вертикальных» слов среди всех        |
    |                  | классифицированных. Слово вертикальное,    |
    |                  | если ``height > width * aspect_t``.        |
    +------------------+--------------------------------------------+

    Логика комбинирования (симметричная):

    +-------------+-------------+--------+----------------+
    | OOB         | Dominance   | flip   | confidence     |
    +=============+=============+========+================+
    | > порога    | > порога    | True   | ``"high"``     |
    +-------------+-------------+--------+----------------+
    | > порога    | ≤ порога    | True   | ``"medium"``   |
    +-------------+-------------+--------+----------------+
    | ≤ порога    | > порога    | True   | ``"medium"``   |
    +-------------+-------------+--------+----------------+
    | ≤ порога    | ≤ порога    | False  | ``"none"``     |
    +-------------+-------------+--------+----------------+

Принципы:
- Модуль находится в application layer и не зависит от
  инфраструктурных компонентов.
- Все пороги передаются как параметры функций (инверсия
  зависимостей). Модуль не импортирует ``config``.
- Модуль не выполняет логирование. Логирование — ответственность
  вызывающего кода (``HighlightsService``, API).
- Модуль не изменяет входные данные. Возвращаются новые объекты.
- Функции чистые: детерминированные, без побочных эффектов.
- Модуль потокобезопасен: не содержит изменяемого состояния.

Функции:
    ``diagnose_word_index`` — диагностика системы координат.
    ``transform_bbox`` — преобразование координат прямоугольника.
"""

from __future__ import annotations

from itertools import chain

from ..domain.models import WordIndex

# ----------------------------------------------------------------------
# Диагностика системы координат
# ----------------------------------------------------------------------


def diagnose_word_index(
    index: WordIndex,
    text_oob_threshold: float,
    text_dominance_threshold: float,
    aspect_t: float,
) -> tuple[bool, str]:
    """Определяет, использует ли страница аномальную систему координат.

    Анализирует слова из :attr:`WordIndex.by_normalized` и вычисляет
    два независимых признака аномалии: долю слов за границами
    страницы (OOB) и долю «вертикальных» слов (Dominance). На
    основе комбинации признаков возвращает флаг необходимости
    трансформации и уровень уверенности.

    Операции:

    +----+-----------------------------------------------------+
    | №  | Описание                                            |
    +====+=====================================================+
    | 1  | Сбор ``WordEntry`` из                             |
    |    | ``index.by_normalized.values()``.                   |
    +----+-----------------------------------------------------+
    | 2  | Если список пуст — возврат ``(False, "none")``.     |
    +----+-----------------------------------------------------+
    | 3  | Для каждого слова:                                  |
    |    | a. Вычисление ``w`` и ``h`` (ширина и высота        |
    |    |    bbox).                                           |
    |    | b. Проверка выхода за границы страницы →            |
    |    |    инкремент ``oob``.                               |
    |    | c. Классификация слова:                             |
    |    |    - ``h > 0`` и ``h > w * aspect_t`` →             |
    |    |      ``vertical++``;                                |
    |    |    - ``w > 0`` и ``w > h * aspect_t`` →             |
    |    |      ``horizontal++``;                              |
    |    |    - иначе — не учитывается.                        |
    +----+-----------------------------------------------------+
    | 4  | Вычисление долей ``oob_ratio`` и ``dominance``.     |
    +----+-----------------------------------------------------+
    | 5  | Комбинирование сигналов: оба → ``"high"``;          |
    |    | один → ``"medium"``; ни один → ``"none"``.          |
    +----+-----------------------------------------------------+
    | 6  | Возврат кортежа ``(flip, confidence)``.             |
    +----+-----------------------------------------------------+

    Примечание:
        Ранняя проверка ``rotation != 0`` удалена. Эталонная
        диагностика (``diagnostics.py``) такой проверки не
        выполняет и анализирует координаты независимо от
        значения ``page.rotation``. PyMuPDF возвращает координаты
        и ``page.rect`` в согласованной системе, поэтому
        диагностика корректно работает и на повёрнутых страницах.

    Примечание:
        Список ``entries`` собирается через ``chain.from_iterable``
        и может содержать одно и то же слово несколько раз, если
        оно встречается на странице в нескольких местах. Для
        статистической оценки долей это несущественно: повторы
        лишь увеличивают вес часто встречающихся слов, что не
        влияет на качественное различение аномальной и нормальной
        страниц.

    Args:
        index: :class:`WordIndex` страницы, построенный
            инфраструктурным слоем. Диагностика использует
            ``by_normalized`` (слова), ``page_width`` и
            ``page_height``.
        text_oob_threshold: Порог доли слов за границами
            страницы. Если ``oob_ratio > text_oob_threshold``,
            признак OOB сработал. Обычно ``0.05``.
        text_dominance_threshold: Порог доли «вертикальных» слов
            среди классифицированных. Если
            ``dominance > text_dominance_threshold``, признак
            Dominance сработал. Обычно ``0.7``.
        aspect_t: Порог отношения сторон для классификации слова
            как вертикального или горизонтального. Слово
            вертикальное, если ``height > width * aspect_t``.
            Обычно ``2.0``.

    Returns:
        Кортеж ``(flip, confidence)``:

        - ``flip`` — ``True``, если страница использует аномальную
          систему координат и координаты bbox необходимо
          трансформировать перед нормализацией.
        - ``confidence`` — уровень уверенности:

          - ``"high"`` — сработали оба признака.
          - ``"medium"`` — сработал ровно один признак.
          - ``"none"`` — не сработал ни один признак (или
            страница пустая).
    """
    # Шаг 1: сбор WordEntry из by_normalized.
    entries = list(chain.from_iterable(index.by_normalized.values()))

    # Шаг 2: пустая страница.
    if not entries:
        return False, "none"

    # Шаг 3: подсчёт признаков.
    page_width = index.page_width
    page_height = index.page_height

    oob = 0
    vertical = 0
    horizontal = 0

    for entry in entries:
        w = entry.x1 - entry.x0
        h = entry.y1 - entry.y0

        if entry.x0 < 0 or entry.x1 > page_width or entry.y0 < 0 or entry.y1 > page_height:
            oob += 1

        if h > 0 and h > w * aspect_t:
            vertical += 1
        elif w > 0 and w > h * aspect_t:
            horizontal += 1

    # Шаг 4: вычисление долей.
    total = len(entries)
    oob_ratio = oob / total

    denom = vertical + horizontal
    dominance = vertical / denom if denom > 0 else 0.0

    # Шаг 5: комбинирование сигналов.
    sig_oob = oob_ratio > text_oob_threshold
    sig_dom = dominance > text_dominance_threshold

    if sig_oob and sig_dom:
        return True, "high"
    if sig_oob or sig_dom:
        return True, "medium"
    return False, "none"


# ----------------------------------------------------------------------
# Преобразование координат прямоугольника
# ----------------------------------------------------------------------


def transform_bbox(
    bbox: tuple[float, float, float, float],
    page_height: float,
) -> tuple[float, float, float, float]:
    """Преобразует bbox из bottom-left в top-left систему координат.

    Применяет формулу::

        new_x0 = old_y0
        new_x1 = old_y1
        new_y0 = page_height - old_x1
        new_y1 = page_height - old_x0

    Обоснование формулы:
        Эталонная модель (``diagnostics.py`` и ``transformer.py``)
        описывает аномальную систему координат как bottom-left
        с перепутанными осями:

        - ось X направлена вертикально (снизу вверх);
        - ось Y направлена горизонтально (слева направо).

        Для таких PDF-документов PyMuPDF сохраняет ориентацию
        координат контента без инверсии Y: ``y_screen`` совпадает
        с ``Y_аномальный`` (горизонтальная координата), а
        ``x_screen`` — с ``X_аномальный`` (вертикальная координата).

        Соответствие визуальных и screen-координат::

            x_visual = y_screen
            y_visual = page_height - x_screen

        Для bbox ``(x0, y0, x1, y1)``:

        - ``x_visual`` ∈ ``[y0, y1]`` (диапазон не меняется);
        - ``y_visual`` ∈ ``[page_height - x1, page_height - x0]``
          (диапазон инвертируется и переставляется).

    Порядок координат сохраняется: ``new_x1 > new_x0`` и
    ``new_y1 > new_y0`` при условии, что на входе ``x1 > x0``
    и ``y1 > y0``. В противном случае (некорректный вход или
    некорректный результат) возвращается исходный ``bbox``
    без изменений — защита от «схлопывания» прямоугольника
    и от отображения подсветки в неверном месте.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Распаковка ``bbox`` в ``x0, y0, x1, y1``.           |
    +---+-----------------------------------------------------+
    | 2 | Защитная проверка входа: если ``x1 <= x0`` или      |
    |   | ``y1 <= y0`` — возврат ``bbox`` без изменений.      |
    +---+-----------------------------------------------------+
    | 3 | Вычисление новых координат по формуле               |
    |   | преобразования.                                     |
    +---+-----------------------------------------------------+
    | 4 | Защитная проверка выхода: если ``nx1 <= nx0`` или   |
    |   | ``ny1 <= ny0`` — возврат исходного ``bbox``.        |
    +---+-----------------------------------------------------+
    | 5 | Возврат ``(nx0, ny0, nx1, ny1)``.                   |
    +---+-----------------------------------------------------+

    Примечание:
        Функция не изменяет входные данные (кортеж неизменяем).
        Возвращается новый кортеж.

    Args:
        bbox: Прямоугольник в формате ``(x0, y0, x1, y1)``,
            где ``x0 ≤ x1`` и ``y0 ≤ y1``. Ожидается, что
            координаты находятся в аномальной (bottom-left)
            системе.
        page_height: Высота страницы в PDF-points. Используется
            для инверсии вертикальной координаты. Соответствует
            ``WordIndex.page_height``.

    Returns:
        Новый кортеж ``(x0, y0, x1, y1)`` в top-left системе
        координат. Если вход или результат некорректны,
        возвращается исходный ``bbox`` без изменений.
    """
    x0, y0, x1, y1 = bbox

    # Защита от некорректного входа.
    if x1 <= x0 or y1 <= y0:
        return bbox

    # Преобразование координат.
    nx0 = y0
    nx1 = y1
    ny0 = page_height - x1
    ny1 = page_height - x0

    # Защита от некорректного результата.
    if nx1 <= nx0 or ny1 <= ny0:
        return bbox

    return nx0, ny0, nx1, ny1
