"""
Токенизация поискового запроса в discriminated union токенов.

Модуль разбирает пользовательский поисковый запрос с учётом
синтаксиса поисковой грамматики DDS (логические операторы, фразы
в двойных кавычках, круглые скобки) в список типизированных
токенов. Токенизатор **структурный**: он не нормализует текст и
не знает о конкретном поисковом движке — только о форме запроса.

Назначение разделения
---------------------

Ранее логика токенизации и сборки MATCH-выражения FTS5 была
объединена в одном модуле ``dds_core.application.search_query_normalizer``.
Это нарушало инверсию зависимостей: application-слой знал о
FTS5-специфике (префикс колонки ``normalized_text:``), из-за чего
замена поискового бэкенда (например, на Elasticsearch) требовала
бы переписывания application-кода.

Текущее разделение:

- **application/query_tokenizer.py** (этот модуль) — только
  структурный разбор запроса в список токенов. Никаких префиксов
  колонок, никакой нормализации, никаких зависимостей от FTS5.
- **infrastructure/fts5/match_builder.py** — сборка MATCH-выражения
  FTS5 из токенов: применение префикса ``normalized_text:``,
  нормализация текста через :func:`dds_core.domain.text_normalization.normalize_text`.

Если поисковый бэкенд сменится на другой, application-код
(токенизатор) не изменится: новый бэкенд получит собственный
сборщик, работающий с тем же набором токенов.

Синтаксис запроса
-----------------

Токенизатор распознаёт четыре вида токенов:

+----------------------------------+----------------------------------+
| Токен                            | Описание                         |
+==================================+==================================+
| ``WordToken``                    | Обычное слово. Может содержать   |
|                                  | спецсимволы (``*``, ``-``) —      |
|                                  | они не интерпретируются          |
|                                  | токенизатором.                   |
+----------------------------------+----------------------------------+
| ``PhraseToken``                  | Фраза в двойных кавычках.        |
|                                  | Внутренние пробелы сохраняются.  |
+----------------------------------+----------------------------------+
| ``OperatorToken``                | Логический оператор: ``AND``,    |
|                                  | ``OR``, ``NOT``. Распознаётся    |
|                                  | без учёта регистра, приводится   |
|                                  | к верхнему.                      |
+----------------------------------+----------------------------------+
| ``ParenToken``                   | Круглая скобка: ``(`` или ``)``. |
+----------------------------------+----------------------------------+

Discriminated union (``QueryToken``) позволяет потребителям
применять ``isinstance``-проверки и ``match``-выражения с полным
сужением типа.

Принципы:
    - Модуль находится в application layer и не зависит от
      infrastructure.
    - Инверсия зависимостей: application предоставляет
      структурированное представление запроса, infrastructure
      преобразует его в целевой формат.
    - Чистая функция: детерминированная, без побочных эффектов,
      без изменяемого состояния.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# ----------------------------------------------------------------------
# Токены
# ----------------------------------------------------------------------


@dataclass(frozen=True)
class WordToken:
    """Обычное слово поискового запроса.

    Токенизатор не интерпретирует содержимое слова и не нормализует
    его. Спецсимволы поисковой грамматики (например, ``*`` для
    префиксного поиска) остаются частью текста и обрабатываются
    сборщиком целевого выражения.

    Attributes:
        text: Оригинальный текст слова (без нормализации).
    """

    text: str


@dataclass(frozen=True)
class PhraseToken:
    """Фраза в двойных кавычках.

    Внутренние пробелы сохраняются: ``"корпус крупного дробления"``
    даёт :class:`PhraseToken` с ``text="корпус крупного дробления"``.

    Attributes:
        text: Оригинальный текст фразы без кавычек (без нормализации).
    """

    text: str


@dataclass(frozen=True)
class OperatorToken:
    """Логический оператор поисковой грамматики.

    Распознаются три оператора: ``AND``, ``OR``, ``NOT``. При
    разборе операторы приводятся к верхнему регистру, поэтому
    :attr:`op` гарантированно содержит одно из трёх канонических
    значений.

    Attributes:
        op: Канонический оператор: ``"AND"``, ``"OR"`` или ``"NOT"``.
    """

    op: str


@dataclass(frozen=True)
class ParenToken:
    """Круглая скобка поискового запроса.

    Attributes:
        char: ``"("`` (открывающая) или ``")"`` (закрывающая).
    """

    char: str


QueryToken = WordToken | PhraseToken | OperatorToken | ParenToken
"""Discriminated union всех токенов поискового запроса.

Используется как тип элемента, возвращаемого
:func:`tokenize_search_query`, и как входной тип для сборщиков
целевых выражений (см. ``dds_core.infrastructure.fts5.match_builder``).
"""


# ----------------------------------------------------------------------
# Регулярное выражение для разбора запроса
# ----------------------------------------------------------------------

_TOKEN_PATTERN = re.compile(
    r'"(?P<phrase>[^"]*)"'  # фраза в кавычках
    r"|(?P<word>[^\s()]+)"  # обычное слово (может содержать спецсимволы)
    r"|(?P<paren>[()])"  # скобка
)
"""Регулярное выражение для разбора поискового запроса.

Поддерживает три группы:

- ``phrase`` — фрагмент между двойными кавычками (включая пробелы);
- ``word`` — последовательность непробельных символов, кроме
  круглых скобок;
- ``paren`` — одиночная круглая скобка.

Пробелы между токенами игнорируются.
"""

_OPERATORS = frozenset({"AND", "OR", "NOT"})
"""Логические операторы поисковой грамматики DDS.

Сравнение выполняется по верхнему регистру. Операторы, введённые
пользователем в нижнем регистре (``and``, ``or``, ``not``),
распознаются как :class:`OperatorToken` с канонической формой.
"""


# ----------------------------------------------------------------------
# Токенизация
# ----------------------------------------------------------------------


def tokenize_search_query(query: str) -> list[QueryToken]:
    """Разбирает поисковый запрос в список токенов.

    Операции:

    +----+-----------------------------------------------------+
    | №  | Описание                                            |
    +====+=====================================================+
    | 1  | Если ``query`` пуст (только пробелы) — возврат      |
    |    | пустого списка.                                      |
    +----+-----------------------------------------------------+
    | 2  | Обход всех совпадений :data:`_TOKEN_PATTERN`.       |
    +----+-----------------------------------------------------+
    | 3  | Для каждой группы совпадения:                       |
    |    | a. ``phrase`` → :class:`PhraseToken`.               |
    |    | b. ``word`` → если верхний регистр в                 |
    |    |    :data:`_OPERATORS` → :class:`OperatorToken`;      |
    |    |    иначе → :class:`WordToken`.                       |
    |    | c. ``paren`` → :class:`ParenToken`.                  |
    +----+-----------------------------------------------------+
    | 4  | Возврат списка токенов в порядке появления в        |
    |    | исходной строке.                                     |
    +----+-----------------------------------------------------+

    Примечание:
        Токенизатор не нормализует текст слов и фраз. Это
        ответственность сборщика целевого выражения — например,
        :func:`dds_core.infrastructure.fts5.match_builder.build_match_expression`,
        который применяет :func:`dds_core.domain.text_normalization.normalize_text`
        при сборке MATCH-выражения FTS5.

    Args:
        query: Поисковый запрос. Может содержать логические
            операторы (``AND``, ``OR``, ``NOT``), фразы в двойных
            кавычках и круглые скобки. Может быть пустым или
            содержать только пробелы.

    Returns:
        Список токенов в порядке появления в исходной строке.
        Пустой список, если запрос пуст или состоит только из
        пробелов.

    Example:
        >>> tokenize_search_query('гидрошпонка AND "корпус крупного дробления"')
        [WordToken(text='гидрошпонка'),
         OperatorToken(op='AND'),
         PhraseToken(text='корпус крупного дробления')]

        >>> tokenize_search_query('(EC-423-1 OR ec-423-1) NOT KM')
        [ParenToken(char='('),
         WordToken(text='EC-423-1'),
         OperatorToken(op='OR'),
         WordToken(text='ec-423-1'),
         ParenToken(char=')'),
         OperatorToken(op='NOT'),
         WordToken(text='KM')]

        >>> tokenize_search_query('')
        []
    """
    if not query.strip():
        return []

    tokens: list[QueryToken] = []

    for match in _TOKEN_PATTERN.finditer(query):
        if match.group("phrase") is not None:
            # Фраза в кавычках: текст сохраняется как есть,
            # нормализация — на стороне сборщика.
            tokens.append(PhraseToken(text=match.group("phrase")))
        elif match.group("word") is not None:
            word = match.group("word")
            upper_word = word.upper()
            if upper_word in _OPERATORS:
                tokens.append(OperatorToken(op=upper_word))
            else:
                tokens.append(WordToken(text=word))
        elif match.group("paren") is not None:
            tokens.append(ParenToken(char=match.group("paren")))

    return tokens
