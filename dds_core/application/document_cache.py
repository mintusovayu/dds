"""
Кэш таблицы ``documents`` в памяти для фазы хеширования.

Модуль содержит класс :class:`DocumentCache`, который загружает
всю таблицу ``documents`` одним SELECT-запросом (через
``IDocumentRepository.load_all()``) и строит два словаря для
поиска за O(1): по относительному пути и по хешу файла.

Назначение
----------

На этапе хеширования ``ScanPipeline`` обрабатывает каждый файл
каталога РД и для каждого файла выполняет до трёх запросов к БД:

1. Поиск документа по относительному пути (для проверки ленивого
   хеширования).
2. Поиск документа по хешу (для контроля дубликатов).
3. Регистрация нового хеша (для дедупликации внутри одного
   запуска).

При 10 000+ файлов это 30 000+ запросов к БД. ``DocumentCache``
заменяет их на один SELECT-запрос (загрузка всей таблицы
``documents``) + поиск в словаре за O(1).

Разделение записи и чтения (Фаза 8, ADR-008)
---------------------------------------------

До Фазы 8 метод :meth:`DocumentCache.load` содержал SQL-строку в
application-слое и использовал ``IDatabase.execute(...)`` напрямую.
Фаза 8 делегирует чтение в ``IDocumentRepository.load_all()``:
SQL сосредоточен в infrastructure, application-слой зависит
только от доменного контракта.

Формат внутреннего хранения
----------------------------

Внутренние словари хранят метаданные в виде 4-элементных кортежей
``(doc_id, file_hash, cached_size, cached_mtime)``, а не в виде
доменных моделей :class:`DocumentMetadata`. Это осознанное
решение:

- **Совместимость с существующими потребителями.** Метод
  ``ScanPipeline._hash_single_file`` ожидает 4-элементный кортеж
  от ``get_by_path`` — тот же формат, что возвращает
  ``ITextIndexer.get_document_metadata``. Сохранение формата
  устраняет каскадные правки в конвейере.
- **Минимизация blast radius.** Замена кортежа на
  ``DocumentMetadata`` внутри кэша потребовала бы правок в
  ``ScanPipeline``, что выходит за рамки Фазы 8.
- **Формат — часть публичного контракта.** Сигнатуры
  ``get_by_path`` и ``get_doc_id_by_hash`` не меняются в Фазе 8;
  это зафиксировано в реестре тестов и в
  ``ScanPipeline._hash_single_file``.

Преобразование ``DocumentMetadata → tuple`` выполняется один раз
при :meth:`load` — стоимость O(N), пренебрежимо мала по сравнению
с самим SELECT-запросом.

Принципы
--------

- Модуль зависит от абстракции ``IDocumentRepository`` (инверсия
  зависимостей), а не от ``IDatabase`` или конкретной реализации.
- Не содержит бизнес-логики — только загрузка и поиск.
- Потокобезопасен: словари защищены ``threading.Lock``.
- Не выполняет логирования. Логирование — ответственность
  вызывающего кода (``ScanPipeline``).

Классы:
    ``DocumentCache`` — in-memory кэш таблицы ``documents``.
"""

from __future__ import annotations

import threading

from ..domain.interfaces import IDocumentRepository

# ----------------------------------------------------------------------
# Кэш документов
# ----------------------------------------------------------------------


class DocumentCache:
    """Кэш таблицы ``documents`` для фазы хеширования.

    Загружает всю таблицу ``documents`` в память через
    ``IDocumentRepository.load_all()`` и предоставляет методы
    для поиска документов по относительному пути и хешу.

    Формат внутреннего хранения — 4-элементные кортежи
    ``(doc_id, file_hash, cached_size, cached_mtime)``, совместимые
    с сигнатурой ``ITextIndexer.get_document_metadata``. Это
    устраняет необходимость правок в ``ScanPipeline._hash_single_file``
    при переходе на репозиторий (Фаза 8).

    Пример использования::

        cache = DocumentCache(SqliteDocumentRepository(db))
        cache.load()
        cached = cache.get_by_path("раздел_01/чертёж.pdf")
        if cached is not None:
            doc_id, file_hash, cached_size, cached_mtime = cached
            ...

    Attributes:

    +--------------------------+------------------------------------------+
    | Атрибут                  | Описание                                 |
    +==========================+==========================================+
    | ``_document_repository`` | Абстракция read-side доступа             |
    |                          | к документам.                            |
    +--------------------------+------------------------------------------+
    | ``_lock``                | ``threading.Lock`` для                   |
    |                          | потокобезопасного обновления кэша.       |
    +--------------------------+------------------------------------------+
    | ``_by_path``             | Словарь: относительный путь →            |
    |                          | ``(doc_id, file_hash, cached_size,       |
    |                          | cached_mtime)``.                         |
    +--------------------------+------------------------------------------+
    | ``_by_hash``             | Словарь: хеш файла → ``doc_id``.         |
    +--------------------------+------------------------------------------+
    """

    def __init__(self, document_repository: IDocumentRepository) -> None:
        """Инициализирует кэш документов.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ссылки на ``IDocumentRepository``.       |
        +---+-----------------------------------------------------+
        | 2 | Создание ``threading.Lock``.                        |
        +---+-----------------------------------------------------+
        | 3 | Инициализация пустых словарей ``_by_path`` и        |
        |   | ``_by_hash``.                                       |
        +---+-----------------------------------------------------+

        Примечание:
            До Фазы 8 параметр конструктора имел тип
            ``IDatabase``. Замена на ``IDocumentRepository``
            устраняет SQL-строки из application-слоя
            (ADR-008). Соответствующая запись добавлена в
            ``docs/DEPRECATIONS.yaml``.

        Args:
            document_repository: Реализация ``IDocumentRepository``
                для read-side доступа к таблице ``documents``.
        """
        self._document_repository = document_repository
        self._lock = threading.Lock()
        self._by_path: dict[str, tuple[str, str, int, str]] = {}
        self._by_hash: dict[str, str] = {}

    def load(self) -> None:
        """Загружает таблицу ``documents`` в память.

        Делегирует чтение в ``IDocumentRepository.load_all()``,
        который выполняет один SELECT-запрос и возвращает словарь
        ``{file_path: DocumentMetadata}``. Результат преобразуется
        в два словаря для поиска за O(1): по относительному пути
        и по хешу файла.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | ``metadata_map = self._document_repository.          |
        |   | load_all()`` — словарь                               |
        |   | ``{file_path: DocumentMetadata}``.                   |
        +---+-----------------------------------------------------+
        | 2 | Построение ``by_path`` — преобразование              |
        |   | ``DocumentMetadata`` в 4-элементный кортеж           |
        |   | ``(doc_id, file_hash, cached_size, cached_mtime)``.  |
        +---+-----------------------------------------------------+
        | 3 | Построение ``by_hash`` — ``{file_hash: doc_id}``.   |
        +---+-----------------------------------------------------+
        | 4 | Под блокировкой замена старых словарей новыми.      |
        +---+-----------------------------------------------------+

        Примечание:
            Метод вызывается один раз перед запуском фазы
            хеширования (в ``ScanPipeline.run_async``, в блоке
            загрузки кэша с таймаутом ``scan.cache_load``).
            Словари заменяются целиком — это обеспечивает
            консистентность данных на момент загрузки: любой
            параллельный читатель видит либо старый снапшот,
            либо новый, но не промежуточное состояние.

        Примечание:
            Преобразование ``DocumentMetadata → tuple`` выполняется
            один раз здесь, а не в каждом вызове ``get_by_path``.
            Это сохраняет O(1) на поиск и делает формат словарей
            неизменным на всё время жизни кэша.
        """
        metadata_map = self._document_repository.load_all()
        by_path: dict[str, tuple[str, str, int, str]] = {}
        by_hash: dict[str, str] = {}
        for file_path, metadata in metadata_map.items():
            by_path[file_path] = (
                metadata.doc_id,
                metadata.file_hash,
                metadata.cached_size,
                metadata.cached_mtime,
            )
            by_hash[metadata.file_hash] = metadata.doc_id
        with self._lock:
            self._by_path = by_path
            self._by_hash = by_hash

    def get_by_path(
        self,
        path: str,
    ) -> tuple[str, str, int, str] | None:
        """Возвращает метаданные документа по относительному пути.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Поиск ``path`` в словаре ``_by_path``.              |
        +---+-----------------------------------------------------+
        | 2 | Возврат кортежа или ``None``.                       |
        +---+-----------------------------------------------------+

        Формат кортежа:

        +---------------+--------------------------------------------+
        | Позиция       | Описание                                   |
        +===============+============================================+
        | ``[0]``       | ``doc_id`` (строка).                       |
        +---------------+--------------------------------------------+
        | ``[1]``       | ``file_hash`` (строка, SHA-256).           |
        +---------------+--------------------------------------------+
        | ``[2]``       | ``cached_size`` (целое, размер в байтах).  |
        +---------------+--------------------------------------------+
        | ``[3]``       | ``cached_mtime`` (строка, ISO 8601).       |
        +---------------+--------------------------------------------+

        Формат согласован с ``ITextIndexer.get_document_metadata``,
        что позволяет ``ScanPipeline._hash_single_file``
        использовать оба источника взаимозаменяемо.

        Потокобезопасность:
            Чтение словаря атомарно в CPython благодаря GIL.
            Блокировка не требуется: ``_by_path`` заменяется
            целиком в :meth:`load`, а не мутируется.

        Args:
            path: Относительный путь к файлу документа
                (относительно каталога РД).

        Returns:
            Кортеж ``(doc_id, file_hash, cached_size, cached_mtime)``
            или ``None``, если документ не найден.
        """
        return self._by_path.get(path)

    def get_doc_id_by_hash(self, file_hash: str) -> str | None:
        """Возвращает ``doc_id`` по хешу файла.

        Используется для контроля дубликатов перед индексированием:
        если хеш уже зарегистрирован, файл считается дубликатом
        ранее проиндексированного документа.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Поиск ``file_hash`` в словаре ``_by_hash``.         |
        +---+-----------------------------------------------------+
        | 2 | Возврат ``doc_id`` или ``None``.                    |
        +---+-----------------------------------------------------+

        Потокобезопасность:
            Аналогично :meth:`get_by_path` — атомарное чтение
            словаря, замена целиком в :meth:`load`.

        Args:
            file_hash: Хеш файла документа (SHA-256).

        Returns:
            ``doc_id`` документа с данным хешем, или ``None``,
            если хеш не найден.
        """
        return self._by_hash.get(file_hash)

    def register_hash(self, file_hash: str, doc_id: str) -> None:
        """Регистрирует хеш для дедупликации внутри одного запуска.

        Вызывается при обнаружении нового файла или переиндексации,
        чтобы последующие файлы с тем же содержимым (в рамках
        текущего запуска сканирования) были распознаны как дубликаты.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват ``_lock``.                                   |
        +---+-----------------------------------------------------+
        | 2 | Если ``file_hash`` отсутствует в ``_by_hash``:      |
        |   | добавляется запись ``file_hash → doc_id``.          |
        +---+-----------------------------------------------------+
        | 3 | Освобождение ``_lock``.                             |
        +---+-----------------------------------------------------+

        Идемпотентность:
            Повторный вызов с тем же ``file_hash`` — no-op: старая
            запись не перезаписывается. Это осознанное решение:
            первый встреченный ``doc_id`` для хеша считается
            каноническим.

        Потокобезопасность:
            Операция записи защищена ``threading.Lock``. ``hash-воркеры``
            конвейера могут вызывать метод одновременно, но
            благодаря блокировке словарь не повреждается.

        Args:
            file_hash: Хеш файла (SHA-256).
            doc_id: Идентификатор документа.
        """
        with self._lock:
            if file_hash not in self._by_hash:
                self._by_hash[file_hash] = doc_id
