"""
Кэш таблицы ``documents`` в памяти для фазы хеширования.

Загружает всю таблицу ``documents`` одним SELECT-запросом
и строит два словаря для поиска за O(1).
"""

from __future__ import annotations

import threading

from ..domain.interfaces import IDatabase


class DocumentCache:
    """Кэш таблицы ``documents`` для фазы хеширования.

    Загружает всю таблицу ``documents`` в память и предоставляет
    методы для поиска документов по относительному пути и хешу.

    Attributes:
        _db: Абстракция базы данных.
        _lock: Блокировка для потокобезопасного обновления кэша.
        _by_path: Словарь: относительный путь → (doc_id, file_hash,
            cached_size, cached_mtime).
        _by_hash: Словарь: хеш файла → doc_id.
    """

    def __init__(self, db: IDatabase) -> None:
        """Инициализирует кэш документов.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ссылки на ``IDatabase``.                 |
        +---+-----------------------------------------------------+
        | 2 | Создание ``threading.Lock``.                        |
        +---+-----------------------------------------------------+
        | 3 | Инициализация пустых словарей ``_by_path`` и        |
        |   | ``_by_hash``.                                      |
        +---+-----------------------------------------------------+

        Args:
            db: Реализация ``IDatabase`` для доступа к БД.
        """
        self._db = db
        self._lock = threading.Lock()
        self._by_path: dict[str, tuple[str, str, int, str]] = {}
        self._by_hash: dict[str, str] = {}

    def load(self) -> None:
        """Загружает таблицу ``documents`` в память одним SELECT-запросом.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Выполнение запроса                                 |
        |   | ``SELECT doc_id, file_path, file_hash,             |
        |   | cached_size, cached_mtime FROM documents``.         |
        +---+-----------------------------------------------------+
        | 2 | Построение временных словарей ``by_path`` и         |
        |   | ``by_hash``.                                       |
        +---+-----------------------------------------------------+
        | 3 | Под блокировкой замена старых словарей новыми.      |
        +---+-----------------------------------------------------+

        Примечание:
            Метод вызывается один раз перед запуском фазы
            хеширования. Словари заменяются целиком, что
            обеспечивает консистентность данных на момент загрузки.
        """
        rows = self._db.execute(
            "SELECT doc_id, file_path, file_hash, cached_size, cached_mtime FROM documents"
        )
        by_path: dict[str, tuple[str, str, int, str]] = {}
        by_hash: dict[str, str] = {}
        for row in rows:
            doc_id, fp, fh, cs, cm = (
                str(row[0]),
                str(row[1]),
                str(row[2]),
                int(row[3]),
                str(row[4]),
            )
            by_path[fp] = (doc_id, fh, cs, cm)
            by_hash[fh] = doc_id
        with self._lock:
            self._by_path = by_path
            self._by_hash = by_hash

    def get_by_path(
        self,
        path: str,
    ) -> tuple[str, str, int, str] | None:
        """Возвращает (doc_id, file_hash, cached_size, cached_mtime).

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+-----------------------------------------------------+
        | 1 | Поиск ``path`` в словаре ``_by_path``.              |
        +---+-----------------------------------------------------+
        | 2 | Возврат кортежа или ``None``.                       |
        +---+-----------------------------------------------------+

        Args:
            path: Относительный путь к файлу документа.

        Returns:
            Кортеж ``(doc_id, file_hash, cached_size, cached_mtime)``
            или ``None``, если документ не найден.
        """
        return self._by_path.get(path)

    def get_doc_id_by_hash(self, file_hash: str) -> str | None:
        """Возвращает doc_id по хешу файла.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+-----------------------------------------------------+
        | 1 | Поиск ``file_hash`` в словаре ``_by_hash``.         |
        +---+-----------------------------------------------------+
        | 2 | Возврат doc_id или ``None``.                        |
        +---+-----------------------------------------------------+

        Args:
            file_hash: Хеш файла документа.

        Returns:
            ``doc_id`` или ``None``, если хеш не найден.
        """
        return self._by_hash.get(file_hash)

    def register_hash(self, file_hash: str, doc_id: str) -> None:
        """Регистрирует хеш для дедупликации внутри одного запуска.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+-----------------------------------------------------+
        | 1 | Захват блокировки.                                  |
        +---+-----------------------------------------------------+
        | 2 | Если ``file_hash`` отсутствует в ``_by_hash``:      |
        |   | добавляется запись ``file_hash → doc_id``.          |
        +---+-----------------------------------------------------+
        | 3 | Освобождение блокировки.                            |
        +---+-----------------------------------------------------+

        Примечание:
            Вызывается при обнаружении нового файла или
            переиндексации, чтобы последующие файлы с тем же
            содержимым были распознаны как дубликаты.

        Args:
            file_hash: Хеш файла.
            doc_id: Идентификатор документа.
        """
        with self._lock:
            if file_hash not in self._by_hash:
                self._by_hash[file_hash] = doc_id
