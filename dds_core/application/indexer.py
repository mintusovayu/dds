"""
Индексатор текстового слоя документов.

Этот модуль содержит класс ``TextIndexer``, который выполняет
индексирование текстового слоя PDF-документов в базу данных DDS.
Модуль находится в application layer и оркестрирует взаимодействие
между инфраструктурными компонентами (``ITextExtractor``,
``IIndexWriter``) и абстракцией чтения из БД (``IDatabase``).

Для индексирования используются два публичных метода:

- ``prepare_index_plan`` — открывает документ, извлекает текст,
  формирует доменную модель ``DocumentIndexPlan``, но НЕ выполняет
  записи в БД.
- ``write_index_plans`` — принимает список планов и передаёт их в
  ``IIndexWriter.write_plans_batch``, который выполняет запись с
  использованием ``SAVEPOINT`` для атомарности каждого документа
  и батчевых ``COMMIT`` каждые N планов.

Это позволяет конвейеру сканирования накапливать подготовленные
планы и записывать их пачками, снижая количество коммитов.

Разделение записи и чтения (Фаза 5, ADR-005):

``TextIndexer`` получает в конструктор два независимых интерфейса:

+----------------------------------+----------------------------------+
| Интерфейс                        | Ответственность                  |
+==================================+==================================+
| ``IIndexWriter``                 | Запись планов индексации и       |
|                                  | удаление документов.             |
+----------------------------------+----------------------------------+
| ``IDatabase``                    | Поиск документов по хешу, пути;  |
|                                  | чтение метаданных.               |
+----------------------------------+----------------------------------+

Такое разделение сохраняет Single Responsibility Principle:
``IIndexWriter`` описывает write-контракт, ``IDatabase`` — общий
контракт доступа к БД (в т.ч. для чтения). Рефакторинг read-side
на специализированный интерфейс — задача Фазы 8.

Инкапсуляция работы с документом:

``TextIndexer`` взаимодействует только с интерфейсом
``ITextDocument`` (через ``ITextExtractor``), не зная о внутренней
структуре конкретной PDF-библиотеки. Это обеспечивает инверсию
зависимостей: замена PDF-библиотеки потребует изменения только
инфраструктурного слоя.

Поддержка ленивого хеширования:

При индексировании документа в поля ``cached_size`` и
``cached_mtime`` таблицы ``documents`` сохраняются размер файла
и дата последнего изменения. При повторном сканировании каталога
РД оркестратор сканирования сравнивает текущие метаданные файла
с сохранёнными значениями. Если метаданные не изменились,
хеширование файла пропускается, что значительно ускоряет
повторное сканирование.

Потокобезопасность:

Методы индексатора могут вызываться из нескольких потоков
одновременно при параллельном сканировании через ``ScanPipeline``.
Потокобезопасность записи в БД обеспечивается ``SQLiteAdapter``,
который использует ``threading.Lock`` для сериализации операций
записи. Сам индексатор не содержит изменяемого состояния,
поэтому является потокобезопасным.

Расширение ``get_document_metadata`` (скорректированный план,
шаг 4.4 рефакторинга v5.0):

Сигнатура ``get_document_metadata`` расширена с
``tuple[int, str] | None`` (cached_size, cached_mtime) до
``tuple[str, str, int, str] | None`` (doc_id, file_hash,
cached_size, cached_mtime). Причина: в ветке fallback метода
``ScanPipeline._hash_single_file`` (когда ``DocumentCache``
недоступен) ``cached[1]`` (file_hash) всегда была пустой
строкой — реализация собирала кортеж вручную как
``(doc_id_from_path or "", "", cached_meta[0], cached_meta[1])``,
что скрывало реальный баг и нарушало инвариант 4-элементного
кортежа. Расширение сигнатуры метода ``get_document_metadata``
позволяет получить все четыре поля одним SELECT-запросом, без
дополнительного обращения к БД через ``get_document_by_path``.

Классы:
    ``TextIndexer`` — индексатор текстового слоя.
"""

from __future__ import annotations

from ..domain import config
from ..domain.index_plan import DocumentIndexPlan
from ..domain.index_writer import IIndexWriter
from ..domain.interfaces import IDatabase, ITextExtractor
from .index_plan_builder import build_index_plan

# ----------------------------------------------------------------------
# Индексатор текстового слоя
# ----------------------------------------------------------------------


class TextIndexer:
    """Индексатор текстового слоя документов.

    Оркестрирует извлечение текста из PDF-документов и запись
    результатов в базу данных. Использует абстракции
    ``ITextExtractor`` и ``IIndexWriter`` (а также ``IDatabase``
    для read-операций), не зная о конкретных реализациях.

    Разделение записи и чтения (Фаза 5):

    Запись планов индексации делегируется ``IIndexWriter``
    (например, ``SqliteIndexWriter``). Чтение метаданных (поиск
    документа по хешу, пути, чтение кэшированных метаданных)
    выполняется через ``IDatabase``.

    Инкапсуляция работы с документом:

    ``TextIndexer`` взаимодействует только с интерфейсом
    ``ITextDocument``, возвращаемым методом
    ``ITextExtractor.open_document()``. Это обеспечивает
    инверсию зависимостей: ``TextIndexer`` не знает о
    внутренней структуре объектов конкретной PDF-библиотеки
    (``fitz.Document``, ``fitz.Page``).

    Батчевая запись:

    Для массового индексирования предусмотрены методы
    ``prepare_index_plan`` и ``write_index_plans``, позволяющие
    конвейеру сканирования накапливать подготовленные планы и
    выполнять их пакетно через ``IIndexWriter.write_plans_batch``.

    При индексировании документа в таблицу ``documents``
    сохраняются поля ``cached_size`` и ``cached_mtime``
    (проставляются в ``DocumentIndexPlan`` при построении плана),
    содержащие размер файла и дату последнего изменения. Эти
    поля используются при повторном сканировании для ленивого
    хеширования.

    Потокобезопасность:

    Методы индексатора могут вызываться из нескольких потоков
    одновременно при параллельном сканировании. Потокобезопасность
    обеспечивается ``SQLiteAdapter`` через ``threading.Lock``.
    Индексатор не содержит изменяемого состояния.

    Attributes:

    +---------------------+------------------------------------------+
    | Атрибут             | Описание                                 |
    +=====================+==========================================+
    | ``_text_extractor`` | Абстракция извлечения текста.            |
    +---------------------+------------------------------------------+
    | ``_index_writer``   | Абстракция записи планов индексации.     |
    +---------------------+------------------------------------------+
    | ``_db``             | Абстракция базы данных (read-операции).  |
    +---------------------+------------------------------------------+
    """

    def __init__(
        self,
        text_extractor: ITextExtractor,
        index_writer: IIndexWriter,
        db: IDatabase,
    ) -> None:
        """Инициализирует индексатор.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ссылки на ``ITextExtractor``.            |
        +---+-----------------------------------------------------+
        | 2 | Сохранение ссылки на ``IIndexWriter``.              |
        +---+-----------------------------------------------------+
        | 3 | Сохранение ссылки на ``IDatabase`` (для чтений).    |
        +---+-----------------------------------------------------+

        Примечание:
            Конкретные реализации ``ITextExtractor``, ``IIndexWriter``
            и ``IDatabase`` передаются через конструктор (dependency
            injection). Индексатор не создаёт реализации
            самостоятельно.

        Args:
            text_extractor: Реализация ``ITextExtractor`` для
                извлечения текстового слоя. Должна реализовывать
                метод ``open_document()``, возвращающий
                ``ITextDocument``.
            index_writer: Реализация ``IIndexWriter`` для записи
                планов индексации и удаления документов.
            db: Реализация ``IDatabase`` для чтения метаданных
                документов (поиск по хешу, пути, cached-метаданные).
        """
        self._text_extractor = text_extractor
        self._index_writer = index_writer
        self._db = db

    def prepare_index_plan(
        self,
        doc_id: str,
        file_path: str,
        file_hash: str,
        file_size: int,
        last_modified: str,
        abs_file_path: str,
    ) -> DocumentIndexPlan | None:
        """Подготавливает план индексации документа без записи в БД.

        Делегирует вызов в
        :func:`~dds_core.application.index_plan_builder.build_index_plan`.
        Функция открывает документ, извлекает текст всех страниц,
        применяет нормализацию и формирует ``DocumentIndexPlan``.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Вызов ``build_index_plan`` с параметрами            |
        |   | и ``self._text_extractor``.                         |
        +---+-----------------------------------------------------+
        | 2 | Возврат результата (``DocumentIndexPlan`` или       |
        |   | ``None``).                                          |
        +---+-----------------------------------------------------+

        Примечание:
            Имя метода изменилось в Фазе 5: ранее
            ``prepare_document_queries`` возвращал список
            SQL-запросов; теперь ``prepare_index_plan`` возвращает
            доменную модель ``DocumentIndexPlan``. SQL-формирование
            вынесено в ``IIndexWriter``.

        Args:
            doc_id: Уникальный идентификатор документа.
            file_path: Относительный путь к файлу документа.
            file_hash: Хеш файла документа.
            file_size: Размер файла в байтах.
            last_modified: Дата и время последнего изменения файла
                в формате ISO 8601.
            abs_file_path: Абсолютный путь к файлу документа.

        Returns:
            ``DocumentIndexPlan``, либо ``None``, если документ
            не удалось открыть или обработать.
        """
        return build_index_plan(
            doc_id=doc_id,
            file_path=file_path,
            file_hash=file_hash,
            file_size=file_size,
            last_modified=last_modified,
            abs_file_path=abs_file_path,
            text_extractor=self._text_extractor,
        )

    def write_index_plans(
        self,
        plans: list[DocumentIndexPlan],
    ) -> tuple[int, int]:
        """Записывает батч планов индексации в БД.

        Принимает список планов ``DocumentIndexPlan`` и передаёт
        их в ``IIndexWriter.write_plans_batch``, который выполняет
        запись с использованием ``SAVEPOINT`` для атомарности
        каждого документа и батчевых ``COMMIT``.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Вызов                                               |
        |   | ``self._index_writer.write_plans_batch(plans,       |
        |   | commit_interval=config.SCAN_COMMIT_INTERVAL)``.     |
        +---+-----------------------------------------------------+
        | 2 | Возврат результата ``(success, failed)``.           |
        +---+-----------------------------------------------------+

        Примечание:
            ``commit_interval`` передаётся явно, чтобы гарантировать
            согласованность с production-конфигурацией независимо
            от дефолта, объявленного в ``IIndexWriter`` Protocol.
            Значение берётся из ``config.SCAN_COMMIT_INTERVAL``
            (по умолчанию 500).

        Args:
            plans: Список планов индексации. Пустой список —
                допустимый вход; возвращается ``(0, 0)``.

        Returns:
            Кортеж ``(успешных документов, ошибочных документов)``.
        """
        return self._index_writer.write_plans_batch(
            plans,
            commit_interval=config.SCAN_COMMIT_INTERVAL,
        )

    def remove_document(self, doc_id: str) -> None:
        """Удаляет документ из индекса.

        Делегирует вызов в ``IIndexWriter.remove_document``, который
        удаляет метаданные документа из таблицы ``documents`` и
        текст страниц из ``text_index_fts``.

        Если документ не существует, метод не выполняет никаких
        действий (идемпотентность).

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Вызов ``self._index_writer.remove_document(doc_id)``.|
        +---+-----------------------------------------------------+

        Примечание:
            Ранее метод вызывал приватный ``_remove_document_data``,
            который формировал SQL напрямую. В Фазе 5 SQL-логика
            перенесена в ``IIndexWriter`` (реализация —
            ``SqliteIndexWriter``).

        Args:
            doc_id: Идентификатор документа для удаления.
        """
        self._index_writer.remove_document(doc_id)

    def get_document_by_hash(self, file_hash: str) -> str | None:
        """Ищет документ по хешу файла.

        Используется для контроля дубликатов перед индексированием.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | ``SELECT doc_id FROM documents                      |
        |   | WHERE file_hash = ?``                               |
        +---+-----------------------------------------------------+
        | 2 | Если результат найден → возврат ``doc_id``.         |
        +---+-----------------------------------------------------+
        | 3 | Иначе → возврат ``None``.                           |
        +---+-----------------------------------------------------+

        Примечание:
            При ленивом хешировании этот метод вызывается только для
            файлов, метаданные которых изменились. Для неизменённых
            файлов хеширование пропускается, и этот метод не вызывается.

        Потокобезопасность:
            Метод может вызываться из нескольких потоков одновременно.
            Операции чтения в ``SQLiteAdapter`` не блокируются.

        Args:
            file_hash: Хеш файла документа.

        Returns:
            ``doc_id`` документа с данным хешем, или ``None``,
            если документ не найден.
        """
        results = self._db.execute(
            "SELECT doc_id FROM documents WHERE file_hash = ?",
            (file_hash,),
        )
        if results:
            return str(results[0][0])
        return None

    def get_document_by_path(self, file_path: str) -> str | None:
        """Ищет документ по относительному пути файла.

        Используется для определения, был ли документ уже
        проиндексирован.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | ``SELECT doc_id FROM documents                      |
        |   | WHERE file_path = ?``                               |
        +---+-----------------------------------------------------+
        | 2 | Если результат найден → возврат ``doc_id``.         |
        +---+-----------------------------------------------------+
        | 3 | Иначе → возврат ``None``.                           |
        +---+-----------------------------------------------------+

        Примечание:
            При ленивом хешировании этот метод вызывается только для
            файлов, метаданные которых изменились. Для неизменённых
            файлов хеширование пропускается, и этот метод не вызывается.

        Потокобезопасность:
            Метод может вызываться из нескольких потоков одновременно.
            Операции чтения в ``SQLiteAdapter`` не блокируются.

        Args:
            file_path: Относительный путь к файлу документа.

        Returns:
            ``doc_id`` документа с данным путём, или ``None``,
            если документ не найден.
        """
        results = self._db.execute(
            "SELECT doc_id FROM documents WHERE file_path = ?",
            (file_path,),
        )
        if results:
            return str(results[0][0])
        return None

    def get_document_metadata(self, file_path: str) -> tuple[str, str, int, str] | None:
        """Возвращает сохранённые метаданные документа для ленивого
        хеширования.

        Возвращает значения полей ``doc_id``, ``file_hash``,
        ``cached_size`` и ``cached_mtime`` для документа с указанным
        относительным путём. Эти значения используются в ветке
        fallback метода ``ScanPipeline._hash_single_file`` (когда
        ``DocumentCache`` недоступен). Ранее возвращался 2-элементный
        кортеж ``(cached_size, cached_mtime)``, а ``doc_id`` и
        ``file_hash`` собирались отдельными SELECT-запросами; это
        скрывало баг (``file_hash`` всегда был пустой строкой) и
        увеличивало число обращений к БД. Расширение сигнатуры
        устраняет обе проблемы.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | ``SELECT doc_id, file_hash, cached_size,             |
        |   | cached_mtime FROM documents WHERE file_path = ?``.   |
        +---+-----------------------------------------------------+
        | 2 | Если результат найден → возврат 4-элементного        |
        |   | кортежа ``(doc_id, file_hash, cached_size,           |
        |   | cached_mtime)``.                                     |
        +---+-----------------------------------------------------+
        | 3 | Иначе → возврат ``None``.                           |
        +---+-----------------------------------------------------+

        Примечание:
            Для документов, проиндексированных до применения миграции
            версии 2, возвращаются значения по умолчанию (0 и пустая
            строка для ``cached_size`` и ``cached_mtime``). Это
            приведёт к хешированию файла при первом повторном
            сканировании после миграции.

            Если документ с указанным путём не найден в таблице
            ``documents``, возвращается ``None``. Это означает, что
            файл является новым и должен быть проиндексирован.

        Используется конвейером параллельного сканирования
        (``ScanPipeline._hash_single_file``) при отсутствии
        ``DocumentCache``, а также оркестратором сканирования
        (``ScanOrchestrator``) в методах ``_process_single_file()``
        и ``get_index_status()``.

        Потокобезопасность:
            Метод может вызываться из нескольких потоков одновременно.
            Операции чтения в ``SQLiteAdapter`` не блокируются.

        Args:
            file_path: Относительный путь к файлу документа
                (относительно каталога РД).

        Returns:
            Кортеж ``(doc_id, file_hash, cached_size, cached_mtime)``
            или ``None``, если документ не найден. ``cached_size`` —
            размер файла в байтах (``int``), ``cached_mtime`` — дата
            последнего изменения в формате ISO 8601 (строка).

        Note:
            Breaking change относительно предыдущих версий:
            сигнатура изменилась с ``tuple[int, str] | None`` на
            ``tuple[str, str, int, str] | None``. Соответствующий
            контракт обновлён в ``dds_core/domain/interfaces.py``,
            потребитель — в ``dds_core/application/scan_pipeline.py``.
        """
        results = self._db.execute(
            "SELECT doc_id, file_hash, cached_size, cached_mtime "
            "FROM documents WHERE file_path = ?",
            (file_path,),
        )
        if results:
            row = results[0]
            return (
                str(row[0]),
                str(row[1]),
                int(row[2]),
                str(row[3]),
            )
        return None
