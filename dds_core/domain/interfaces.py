@runtime_checkable
class ISecondaryProcessor(Protocol):
    """
    Интерфейс модуля, обрабатывающего документы на вторичной фазе.

    Реализуется модулями, которые выполняют дополнительную обработку
    документов после первичного сканирования и индексирования.
    Например, модуль извлечения штампов (``dds_stamp_extractor``).

    DDS проверяет, реализует ли модуль этот интерфейс (через
    ``isinstance``), и вызывает методы на вторичной фазе сканирования.

    Порядок обработки:

    1. DDS вызывает ``filter_documents(documents)`` для пакета документов.
    2. Модуль возвращает список ``doc_id`` для обработки.
    3. DDS вызывает ``process_document()`` для каждого документа из списка.
    4. DDS отслеживает ошибки. Если ``MAX_CONSECUTIVE_ERRORS`` ошибок
       подряд — модуль деактивируется.

    Требования к ``process_document()``:

    - Метод должен быть идемпотентным: повторный вызов для
      того же документа должен обновлять данные, а не
      создавать дубликаты.
    - Метод должен проверять флаг ``shutdown_requested`` между
      операциями и завершаться при его установке.

    Реализации:
        ``dds_stamp_extractor.api.StampExtractorModule``
    """

    def filter_documents(self, documents: list[DocumentInfo]) -> list[str]:
        """
        Фильтрует документы для обработки.

        Вызывается DDS один раз на пакет документов (например,
        100 документов). Модуль возвращает список ``doc_id``,
        которые нужно обработать.

        Если модулю нужны дополнительные данные для фильтрации
        (например, данные из VIEW других модулей), он выполняет
        запросы к БД самостоятельно.

        Args:
            documents: Список документов с метаданными.

        Returns:
            Список ``doc_id`` документов, которые нужно обработать.
            Пустой список, если ни один документ не подходит.
        """
        ...

    def process_document(
        self,
        doc_id: str,
        file_path: str,
        file_hash: str,
    ) -> None:
        """
        Обрабатывает один документ.

        Вызывается DDS для каждого документа из списка,
        возвращённого ``filter_documents()``. Модуль выполняет
        обработку и записывает результаты в БД.

        Метод должен быть идемпотентным: повторный вызов для
        того же документа обновляет данные, а не создаёт дубликаты.

        Args:
            doc_id: Идентификатор документа в БД DDS.
            file_path: Путь к файлу документа.
            file_hash: Хеш файла документа. Используется для
                контроля дубликатов.

        Raises:
            Exception: Если обработка не удалась. DDS логирует
                ошибку и увеличивает счётчик последовательных
                ошибок. Если счётчик превышает
                ``MAX_CONSECUTIVE_ERRORS``, модуль деактивируется.
        """
        ...

    def request_shutdown(self) -> None:
        """
        Устанавливает флаг завершения.

        Вызывается DDS при отключении модуля. Модуль должен
        проверить флаг между обработками документов и завершиться
        после завершения текущего документа.

        После вызова этого метода модуль не должен начинать
        обработку новых документов.
        """
        ...

    def get_progress(self) -> ScanProgress | None:
        """
        Возвращает прогресс обработки документов.

        Вызывается DDS периодически для отображения прогресса
        в веб-интерфейсе.

        Returns:
            ``ScanProgress`` с текущим прогрессом обработки,
            или ``None``, если прогресс недоступен.
        """
        ...


