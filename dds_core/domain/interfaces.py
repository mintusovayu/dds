@runtime_checkable
class IDatabase(Protocol):
    """
    Абстракция базы данных.

    Реализуется инфраструктурным слоем (например, ``sqlite_adapter.py``).
    Ядро DDS и модули используют этот интерфейс для доступа к БД,
    не зная о конкретной реализации.

    В первой версии реализуется через SQLite. В будущей версии
    возможна замена на PostgreSQL без изменения кода ядра и модулей.

    Требования к реализации:

    - Поддержка WAL-режима для одновременного чтения и записи.
    - Потокобезопасность (несколько потоков могут выполнять
      запросы одновременно).
    - Все методы записи выполняются в транзакциях.

    Реализации:
        ``dds_core/infrastructure/sqlite_adapter.py``
    """

    def execute(self, query: str, params: tuple = ()) -> list:
        """
        Выполняет запрос на чтение.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Получение соединения из пула чтения.                |
        +---+-----------------------------------------------------+
        | 2 | Выполнение SQL-запроса с параметрами.               |
        +---+-----------------------------------------------------+
        | 3 | Извлечение результатов запроса.                     |
        +---+-----------------------------------------------------+
        | 4 | Возврат соединения в пул.                           |
        +---+-----------------------------------------------------+
        | 5 | Возврат результатов.                                |
        +---+-----------------------------------------------------+

        Args:
            query: SQL-запрос (``SELECT``).
            params: Параметры запроса (для защиты от SQL-инъекций).

        Returns:
            Список кортежей с результатами запроса.
            Пустой список, если результатов нет.
        """
        ...

    def execute_write(self, query: str, params: tuple = ()) -> None:
        """
        Выполняет запрос на запись.

        Запрос выполняется в транзакции. Если запрос не удался,
        транзакция откатывается.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Захват блокировки записи.                           |
        +---+-----------------------------------------------------+
        | 2 | Выполнение SQL-запроса с параметрами.               |
        +---+-----------------------------------------------------+
        | 3 | Фиксация транзакции (``COMMIT``).                   |
        +---+-----------------------------------------------------+
        | 4 | Освобождение блокировки записи.                     |
        +---+-----------------------------------------------------+

        При ошибке:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Откат транзакции (``ROLLBACK``).                    |
        +---+-----------------------------------------------------+
        | 2 | Публикация события ``DatabaseError`` (если шина     |
        |   | доступна).                                          |
        +---+-----------------------------------------------------+
        | 3 | Проброс исключения.                                 |
        +---+-----------------------------------------------------+

        Args:
            query: SQL-запрос (``INSERT``, ``UPDATE``, ``DELETE``,
                ``CREATE``, ``DROP``).
            params: Параметры запроса (для защиты от SQL-инъекций).

        Raises:
            Exception: Если запрос не удался. Транзакция откатывается.
        """
        ...

    def execute_write_returning_id(self, query: str, params: tuple = ()) -> int:
        """
        Выполняет запрос на запись и возвращает идентификатор последней вставленной строки.

        Атомарность гарантирована: ``INSERT`` и получение ``lastrowid``
        выполняются в рамках одного соединения под блокировкой записи.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка, что write-соединение существует.          |
        +---+-----------------------------------------------------+
        | 2 | Захват ``_write_lock``.                             |
        +---+-----------------------------------------------------+
        | 3 | Выполнение запроса и фиксация транзакции.           |
        +---+-----------------------------------------------------+
        | 4 | Возврат ``cursor.lastrowid``.                       |
        +---+-----------------------------------------------------+

        При ошибке:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Откат транзакции (``ROLLBACK``).                    |
        +---+-----------------------------------------------------+
        | 2 | Публикация события ``DatabaseError`` (если шина     |
        |   | доступна).                                          |
        +---+-----------------------------------------------------+
        | 3 | Проброс исключения.                                 |
        +---+-----------------------------------------------------+

        Args:
            query: SQL-запрос (``INSERT``).
            params: Параметры запроса.

        Returns:
            Целочисленный идентификатор последней вставленной строки.

        Raises:
            RuntimeError: Если адаптер закрыт.
            sqlite3.Error: Если запрос не удался.
        """
