@runtime_checkable
class ITextDocument(Protocol):
    """
    Абстракция текстового документа.

    Представляет открытый документ, из которого можно извлечь
    текстовое содержимое постранично, сгенерировать PNG-рендер
    страницы и построить нормализованный индекс слов для подсветки.
    Реализуется инфраструктурным слоем (например, обёрткой над
    ``fitz.Document`` в PyMuPDF).

    Ядро DDS (в частности, ``TextIndexer`` и веб-слой предпросмотра)
    использует этот интерфейс, не зная о конкретной PDF-библиотеке.

    Жизненный цикл документа:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | ``ITextExtractor.open_document(file_path)``          |
    |   | → создаёт и возвращает ``ITextDocument``.            |
    +---+-----------------------------------------------------+
    | 2 | ``ITextDocument.page_count()`` → количество страниц. |
    +---+-----------------------------------------------------+
    | 3 | ``ITextDocument.get_page_text(i)`` → текст страницы. |
    |   | Вызывается для каждой страницы от ``0`` до           |
    |   | ``page_count() - 1``.                               |
    +---+-----------------------------------------------------+
    | 4 | При необходимости: ``ITextDocument.render_page(i, dpi)`` |
    |   | → PNG-рендер страницы.                              |
    +---+-----------------------------------------------------+
    | 5 | При необходимости: ``ITextDocument.build_word_index(i)`` |
    |   | → индекс слов для подсветки.                        |
    +---+-----------------------------------------------------+
    | 6 | ``ITextDocument.close()`` → освобождение ресурсов.   |
    |   | Должен вызываться после завершения работы            |
    |   | с документом.                                        |
    +---+-----------------------------------------------------+

    Требования к реализации:

    +----------------------------------+----------------------------------+
    | Требование                       | Обоснование                      |
    +==================================+==================================+
    | ``close()`` идемпотентен         | Повторный вызов не должен        |
    |                                  | вызывать ошибок. Это защищает    |
    |                                  | от двойного закрытия в блоках    |
    |                                  | ``finally``.                     |
    +----------------------------------+----------------------------------+
    | ``get_page_text()`` возвращает   | Страницы без текстового слоя     |
    | пустую строку для страниц без    | (изображения, сканы без OCR)     |
    | текста                           | не должны прерывать              |
    |                                  | индексирование документа.        |
    +----------------------------------+----------------------------------+
    | Повреждённые страницы не         | Одна повреждённая страница не    |
    | прерывают обработку документа    | должна блокировать               |
    |                                  | индексирование остальных         |
    |                                  | страниц документа.               |
    +----------------------------------+----------------------------------+
    | ``render_page()`` возвращает     | PNG-рендер передаётся в браузер  |
    | PNG-байты                        | без дополнительной обработки.    |
    |                                  | DPI может быть автоматически     |
    |                                  | уменьшен при превышении лимита   |
    |                                  | ``MAX_RENDER_PIXELS``.           |
    +----------------------------------+----------------------------------+
    | ``build_word_index()`` строит    | Нормализация выполняется при     |
    | индекс с нормализованными        | построении: поиск подсветки      |
    | словами                          | устойчив к смешению кириллицы    |
    |                                  | и латиницы.                      |
    +----------------------------------+----------------------------------+

    Примечание:
        Ранее ``TextIndexer`` напрямую оперировал объектами
        страниц и документов конкретной PDF-библиотеки (тип ``Any``),
        вызывая ``doc.load_page()``, ``page.get_text()``, ``doc.close()``.
        Это нарушало инверсию зависимостей. Введение
        ``ITextDocument`` инкапсулирует все детали работы с документом
        внутри реализации.

        Методы ``render_page`` и ``build_word_index`` добавлены для
        поддержки предпросмотра документа в веб-интерфейсе. Размещение
        их в ``ITextDocument`` (а не в отдельном интерфейсе) обусловлено
        тем, что все операции выполняются над уже открытым PDF-документом.

    Реализации:
        ``dds_core/infrastructure/pymupdf_text_extractor.py``
        (класс ``PyMuPDFTextDocument``)
    """

