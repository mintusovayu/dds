"""
Интерфейсы (абстракции) ядра DDS.

Этот модуль определяет протоколы (интерфейсы), которые реализуются
инфраструктурным слоем и модулями. Ядро DDS зависит только от этих
абстракций, а не от конкретных реализаций. Это обеспечивает инверсию
зависимостей (Dependency Inversion Principle).

Принципы:
- Ядро DDS не зависит от инфраструктурного кода (SQLite, PyMuPDF).
- Инфраструктурный слой реализует интерфейсы ядра.
- Модули реализуют интерфейс ``IModule`` и опционально ``ISecondaryProcessor``.
- Конкретная реализация передаётся через конструктор (dependency injection).
- Интерфейсы помечены декоратором ``@runtime_checkable`` для возможности
  проверки реализации через ``isinstance()`` при отладке.

Обязательные интерфейсы модулей:
    ``IModule``              — жизненный цикл модуля.

Опциональные интерфейсы модулей:
    ``ISecondaryProcessor``  — обработка документов на вторичной фазе.

Внутренние интерфейсы ядра:
    ``IDatabase``            — абстракция базы данных.
    ``ITextDocument``        — абстракция текстового документа.
    ``ITextExtractor``       — абстракция извлечения текста из PDF.
    ``ISearchBackend``       — абстракция поискового бэкенда.
    ``IScanner``             — абстракция сканера каталога.
    ``IHasher``              — абстракция хеширования файлов.
    ``IEventBus``            — абстракция шины событий.
    ``ITextIndexer``         — абстракция индексатора текстового слоя.
    ``IProcessTaskRunner``   — абстракция исполнителя subprocess-задач.
    ``IDocumentCache``       — абстракция кэша таблицы documents.
    ``IModuleLifecycle``     — абстракция управления жизненным циклом модулей.

Расширение ``ITextDocument`` (предпросмотр документа):
    ``ITextDocument`` дополнен двумя методами для реализации рендера
    страницы и построения нормализованного индекса слов:

    - ``render_page(page_index, dpi)`` — PNG-рендер страницы.
    - ``build_word_index(page_index)`` — нормализованный индекс слов.

    Оба метода используются веб-слоем для предпросмотра документа
    с подсветкой совпадений. Размещение методов именно в
    ``ITextDocument`` (а не в отдельном интерфейсе) обусловлено
    тем, что все операции выполняются над уже открытым PDF-документом,
    а создание отдельного ``IPageRenderer`` потребовало бы
    параллельного жизненного цикла того же файла.

Скорректированный план (шаг 2.1 рефакторинга v5.0):

В протоколе ``IModuleLifecycle`` удалён метод
``get_all_module_statuses`` и добавлен метод ``get_all_module_info``.
Причина: единственный потребитель (``dds_web/api.py::list_modules``)
использует ``get_all_module_info`` — метод, возвращающий полную
информацию о модулях (version, api_version, status, scan_phase,
description). ``get_all_module_statuses`` был устаревшим
промежуточным API и не использовался. Приведение Protocol
в соответствие с фактическим контрактом реализации устраняет
расхождение.

Скорректированный план (шаг 4.4 рефакторинга v5.0):

Сигнатура ``ITextIndexer.get_document_metadata`` расширена с
``tuple[int, str] | None`` (размер, дата изменения) до
``tuple[str, str, int, str] | None`` (doc_id, file_hash,
cached_size, cached_mtime). Причина: в ``scan_pipeline._hash_single_file``
использовалась ветка fallback, в которой ``cached[1]`` (file_hash)
всегда была пустой строкой — ``cached = (doc_id_from_path or "", "",
cached_meta[0], cached_meta[1])``. Это скрывало реальный баг и
нарушало инвариант кортежа. Расширение сигнатуры позволяет
потребителю получать ``file_hash`` из БД напрямую, без
дополнительных SELECT-запросов.

Изменение является breaking change для кастомных реализаций
``ITextIndexer``: реализация ``TextIndexer`` (в
``dds_core/application/indexer.py``) и потребитель
(``dds_core/application/scan_pipeline.py``) обновлены в
соответствующих шагах плана.

Добавление ``IProcessTaskRunner`` (Фаза 4):

Протокол ``IProcessTaskRunner`` введён для инверсии зависимостей
между ``application`` и ``infrastructure``. ``ScanPipeline``
(application layer) выполняет извлечение текста в subprocess через
исполнителя, не зная о конкретной реализации
(``ProcessTaskRunner`` с ``forkserver`` и ``mp.Queue``). Это
устраняет нарушение контракта ``application-isolation``: без
Protocol ``ScanPipeline`` импортировал бы
``dds_core.infrastructure.process_task_runner`` напрямую.

Конкретная реализация передаётся через DI в composition root
(``dds_web/lifespan.py``). Worker-функция (например,
``extract_document_queries``) передаётся как ``Callable`` — без
импорта ``dds_core.subprocess_tasks`` из application, что
сохраняет контракт ``subprocess-tasks-isolation``.

Сигнатура ``run`` (усиление до точной типизации):

Протокол ``IProcessTaskRunner.run`` типизирован generic-параметром
``_T`` и ``Literal["interactive", "batch"]`` для ``kind``. Это
соответствует сигнатуре реализации ``ProcessTaskRunner.run`` из
``dds_core/infrastructure/process_task_runner.py`` (см.
``TypeVar _T`` и ``Literal``-параметр). Ранняя версия Protocol
использовала более широкие типы (``Callable[..., Any]`` и
``kind: str``), что нарушало LSP: реализация оказывалась **уже**
контракта, и статические анализаторы не могли считать
``ProcessTaskRunner`` подтипом ``IProcessTaskRunner``.

Усиление Protocol (не ослабление реализации) сохраняет
типобезопасность: возвращаемое значение ``run`` связано с типом
``func`` (``Callable[..., _T] -> _T``), а ``kind`` ограничен
двумя допустимыми значениями.
"""

