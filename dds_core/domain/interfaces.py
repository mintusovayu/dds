@runtime_checkable
class IModule(Protocol):
    """Интерфейс жизненного цикла модуля.

    Реализуется всеми модулями DDS без исключения. Ядро DDS
    использует этот интерфейс для инициализации, завершения
    работы и управления модулями.

    Жизненный цикл модуля:

    1. DDS создаёт экземпляр модуля через ``entry_point``.
    2. DDS вызывает ``initialize(config)``.
    3. Модуль создаёт таблицы, VIEW, загружает конфигурацию.
    4. DDS проверяет наличие объектов из ``managed_tables`` в БД.
    5. DDS применяет миграции (``data_version``).
    6. Модуль переводится в статус ``"active"``.
    7. При остановке DDS вызывает ``shutdown()``.
    8. При удалении DDS вызывает ``cleanup()``.

    Требования к ``initialize()``:

    - Метод должен быть идемпотентным: повторный вызов после
      неудачной инициализации должен работать корректно.
    - Метод не должен выполнять необратимые операции до
      проверки всех предусловий.
    - Если метод выбрасывает исключение, модуль должен
      оставить систему в консистентном состоянии.

    Реализации:
        ``dds_stamp_extractor.api.StampExtractorModule``
        ``dds_tqr_tracker.api.TQRTrackerModule`` (будущий)
    """

    def initialize(self, config: ModuleConfig) -> None:
        """
        Инициализирует модуль.

        Создаёт таблицы и VIEW в БД, загружает конфигурацию,
        выделяет необходимые ресурсы. Вызывается DDS один раз
        при загрузке модуля.

        Args:
            config: Конфигурация модуля, собранная DDS из
                ``config.json`` и валидированная по ``config_schema``
                из ``manifest.json``.

        Raises:
            Exception: Если инициализация не удалась. Модуль
                должен оставить систему в консистентном состоянии.
                DDS выполнит откат: ``cleanup()`` + удаление
                ``managed_tables``.
        """
        ...

    def shutdown(self) -> None:
        """
        Завершает работу модуля.

        Закрывает соединения с БД, освобождает ресурсы,
        завершает фоновые задачи. Вызывается DDS при остановке
        системы или при отключении модуля.

        После вызова ``shutdown()`` модуль не может быть использован
        для обработки документов. Для повторного использования
        необходимо вызвать ``initialize()`` снова.
        """
        ...

    def get_module_info(self) -> ModuleInfo:
        """
        Возвращает текущую информацию о модуле.

        Используется DDS для отображения статуса модуля
        в веб-интерфейсе и для записи в ``module_registry``.

        Returns:
            ``ModuleInfo`` с текущим статусом модуля.
        """
        ...

    def get_managed_tables(self) -> list[str]:
        """
        Возвращает список объектов БД, управляемых модулем.

        Объекты включают таблицы и VIEW, создаваемые модулем
        при инициализации. Список используется DDS для:

        - Проверки наличия объектов после ``initialize()``.
        - Очистки данных при удалении модуля (если ``cleanup()``
          не реализован или не удался).

        Returns:
            Список имён объектов БД. Пустой список, если модуль
            не использует БД.
        """
        ...

    def cleanup(self) -> None:
        """
        Удаляет данные модуля из БД.

        Вызывается DDS при удалении модуля. Модуль должен
        удалить все таблицы и VIEW, перечисленные в
        ``get_managed_tables()``.

        Если метод не реализован или выбрасывает исключение,
        DDS удаляет объекты из ``managed_tables`` напрямую через SQL.

        Примечание:
            Этот метод может не реализовываться модулями,
            которые не используют БД. В этом случае метод
            не выполняет никаких действий.
        """
        ...

    def get_migrations(self) -> dict[int, str]:
        """
        Возвращает SQL-миграции данных модуля.

        Миграции применяются DDS при обновлении модуля,
        если ``data_version`` в ``manifest.json`` увеличилась.
        Каждая миграция выполняется в транзакции. Если миграция
        не удалась, выполняется ``ROLLBACK``, и модуль не активируется.

        Returns:
            Словарь миграций. Ключ — целевая версия данных
            (``data_version``). Значение — SQL для миграции
            с предыдущей версии на эту. Пустой словарь,
            если миграций нет.

        Пример:
            ::

                {
                    2: "ALTER TABLE stamp_data ADD COLUMN new_field TEXT",
                    3: "CREATE VIEW ... ; INSERT INTO ... SELECT ...",
                }
        """
        ...


