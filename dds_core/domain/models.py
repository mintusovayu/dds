@dataclass
class HashResult:
    """
    Результат операции хеширования файла.
    Используется для передачи данных между этапами конвейера сканирования
    (от хешера к экстрактору). Инкапсулирует исход операции и данные,
    необходимые для дальнейшей обработки или пропуска файла.
    Attributes:
    +-------------------+----------------------------------------------+
    | Атрибут           | Описание                                     |
    +===================+==============================================+
    | outcome           | Исход операции (HashOutcome).                |
    +-------------------+----------------------------------------------+
    | abs_file_path     | Абсолютный путь к файлу на диске.            |
    +-------------------+----------------------------------------------+
    | relative_path     | Относительный путь к файлу (от каталога РД). |
    +-------------------+----------------------------------------------+
    | file_hash         | Хеш файла (SHA-256). Пустая строка, если     |
    |                   | файл пропущен (SKIPPED/ERROR).               |
    +-------------------+----------------------------------------------+
    | file_size         | Размер файла в байтах.                       |
    +-------------------+----------------------------------------------+
    | last_modified     | Дата последнего изменения (ISO 8601).        |
    +-------------------+----------------------------------------------+
    | doc_id            | Идентификатор документа в БД (если найдено   |
    |                   | совпадение по пути для переиндексации).      |
    +-------------------+----------------------------------------------+
    | error_message     | Сообщение об ошибке (если outcome == ERROR). |
    +-------------------+----------------------------------------------+
    """

    outcome: HashOutcome
    abs_file_path: str = ""
    relative_path: str = ""
    file_hash: str = ""
    file_size: int = 0
    last_modified: str = ""
    doc_id: str = ""
    error_message: str = ""


