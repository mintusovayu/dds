"""
Модели данных ядра DDS.

Этот модуль содержит все модели данных, используемые в ядре DDS.
Модели являются простыми структурами данных (dataclasses) без
бизнес-логики. Бизнес-логика реализуется в application layer.

Принципы:
- Модели не содержат бизнес-логики.
- Модели не зависят от инфраструктурных компонентов.
- Модели являются неизменяемыми там, где это возможно.
- Модели используются во всех слоях архитектуры.

Модели:

Перечисления:
    ScanPhase — фаза сканирования (primary/secondary).
    ScanStatus — статус сканирования.
    ModuleStatus — статус модуля.
    IndexState — состояние индексации системы.
    HashOutcome — результат операции ленивого хеширования.

Документ и текстовый индекс:
    Document — метаданные документа.
    DocumentInfo — информация о документе для передачи.

Поиск:
    PageHit — совпадение на странице документа.
    SearchResult — сгруппированный результат поиска по документу.
    SearchFilters — фильтры для комбинированного поиска.

Сканирование:
    ScanProgress — прогресс сканирования.
    IndexStatus — фактическое состояние индексации.
    HashResult — результат хеширования файла для конвейера.

Модули:
    ModuleConfig — конфигурация модуля.
    ModuleDependency — зависимость модуля.
    ModuleManifest — манифест модуля.
    ModuleInfo — информация о модуле.

Предпросмотр документа (рендер и подсветка):
    WordEntry — слово страницы с координатами и нормализованной формой.
    WordIndex — индекс слов одной страницы.
    PageHighlight — прямоугольник подсветки в нормализованных координатах.

Скорректированный план (шаг 4.2 рефакторинга v5.0):

Из класса ``SearchResult`` удалены два property:

- ``best_page`` — возвращало страницу с наименьшим номером.
- ``representative_snippet`` — возвращало сниппет страницы с
  наименьшим номером.

Причина: оба property не использовались в коде. Единственные
потребители (клиентский ``search.js`` и внутренние обработчики
поиска) обращаются к ``result.pages[0]`` напрямую после
сортировки на стороне сервера (страницы внутри ``SearchResult``
отсортированы по возрастанию ``page_number`` бэкендом
``FTS5SearchBackend``). Property были добавлены как
преждевременная абстракция и не нашли применения; удаление
устраняет мёртвый код.

Скорректированный план (Фаза 3 рефакторинга v9):

В класс ``WordEntry`` добавлено поле ``block_no: int`` — номер
блока, к которому относится строка. Причина: ключ
``WordIndex.by_line`` — кортеж ``(block_no, line_no)``, потому что
PyMuPDF нумерует строки отдельно в каждом блоке, начиная с 0.
Ранее ``block_no`` отсутствовал в модели, и группировка по
``by_line`` выполнялась через параллельный список
``block_line_pairs`` с хрупким инвариантом «индекс i в обоих
списках соответствует одному слову». Добавление поля устраняет
инвариант: ``WordEntry`` теперь самодостаточен, а группировка
строится напрямую через ``entry.block_no``.
"""

