# ----------------------------------------------------------------------
# Перечисления
# ----------------------------------------------------------------------
class ScanPhase(str, Enum):
    """
    Фаза сканирования.
    Attributes:
    PRIMARY: Первичная фаза — индексирование текстового слоя.
    Выполняется для всех PDF-файлов в каталоге РД.
    После завершения этой фазы поиск становится доступен.
    SECONDARY: Вторичная фаза — обработка модулями.
    Выполняется для проиндексированных документов.
    Модули извлекают дополнительные данные (штампы, таблицы).
    """

    PRIMARY = "primary"
    SECONDARY = "secondary"


class ScanStatus(str, Enum):
    """
    Статус сканирования.
    Attributes:
    IDLE: Сканирование ещё не запускалось.
    RUNNING: Сканирование выполняется.
    COMPLETED: Сканирование завершено успешно.
    INTERRUPTED: Сканирование прервано пользователем или сбоем.
    ERROR: Сканирование завершено с ошибкой.
    """

    IDLE = "idle"
    RUNNING = "running"
    COMPLETED = "completed"
    INTERRUPTED = "interrupted"
    ERROR = "error"


class ModuleStatus(str, Enum):
    """
    Статус модуля.
    Attributes:
    DISCOVERED: Модуль обнаружен в каталоге dds_modules/.
    LOADING: Модуль в процессе загрузки.
    ACTIVE: Модуль загружен и готов к работе.
    ERROR: Модуль в состоянии ошибки.
    MIGRATION_ERROR: Ошибка миграции данных модуля.
    DEACTIVATED: Модуль деактивирован (зависимость отключена
    или администратор деактивировал).
    SHUTDOWN: Модуль завершил работу.
    REMOVED: Модуль удалён из реестра.
    """

    DISCOVERED = "discovered"
    LOADING = "loading"
    ACTIVE = "active"
    ERROR = "error"
    MIGRATION_ERROR = "migration_error"
    DEACTIVATED = "deactivated"
    SHUTDOWN = "shutdown"
    REMOVED = "removed"


class IndexState(str, Enum):
    """
    Состояние индексации системы.
    Определяется на основе фактических данных в БД и файловой
    системе, а не на основе таблицы scan_state.
    Attributes:
    UNKNOWN: Кэш состояния индексации не заполнен или устарел.
    Требуется пересчёт (нажатие кнопки «Обновить»).
    EMPTY: Система пуста. Нет проиндексированных документов,
    и в каталоге РД есть файлы для индексации.
    FULLY_INDEXED: Все файлы в каталоге РД проиндексированы.
    Поиск доступен по всем документам.
    PARTIALLY_INDEXED: Часть файлов проиндексирована, часть — нет.
    Поиск доступен по проиндексированным документам.
    Требуется сканирование для индексации оставшихся файлов.
    NEEDS_UPDATE: Есть новые или изменённые файлы, которые
    не проиндексированы или требуют переиндексации.
    Поиск доступен по ранее проиндексированным документам.
    NO_SOURCE_FILES: В каталоге РД нет файлов для индексации.
    """

    UNKNOWN = "unknown"
    EMPTY = "empty"
    FULLY_INDEXED = "fully_indexed"
    PARTIALLY_INDEXED = "partially_indexed"
    NEEDS_UPDATE = "needs_update"
    NO_SOURCE_FILES = "no_source_files"


class HashOutcome(str, Enum):
    """
    Результат операции ленивого хеширования файла.
    Определяет дальнейшую судьбу файла в конвейере сканирования
    и используется для точного подсчета статистики прогресса.
    Attributes:
    +-----------------------+--------------------------------------+
    | Исход                 | Описание                             |
    +=======================+======================================+
    | TO_INDEX              | Файл новый или изменённый, требует   |
    |                       | извлечения текста и записи в БД.     |
    +-----------------------+--------------------------------------+
    | DUPLICATE             | Файл не изменился по хешу, но хеш    |
    |                       | уже есть в БД (дубликат контента).   |
    +-----------------------+--------------------------------------+
    | SKIPPED_UNCHANGED     | Метаданные файла (размер, дата)      |
    |                       | совпали с кэшем в БД. Хеширование    |
    |                       | пропущено для ускорения.             |
    +-----------------------+--------------------------------------+
    | ERROR                 | Произошла ошибка при чтении файла    |
    |                       | или вычислении хеша.                 |
    +-----------------------+--------------------------------------+
    """

    TO_INDEX = "to_index"
    DUPLICATE = "duplicate"
    SKIPPED_UNCHANGED = "skipped_unchanged"
    ERROR = "error"


