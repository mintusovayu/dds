@dataclass
class ModuleConfig:
    """
    Конфигурация модуля.
    Передаётся модулю при инициализации через IModule.initialize().
    Attributes:
    db_path: Путь к файлу базы данных DDS.
    parameters: Словарь параметров конфигурации модуля.
    Параметры определяются в manifest.json (config_schema).
    event_bus: Объект шины событий (IEventBus), предоставляющий
    модулю возможность публиковать события. Может быть None,
    если модуль не использует события.
    """

    db_path: str
    parameters: dict[str, object] = field(default_factory=dict)
    event_bus: "IEventBus | None" = None  # noqa: UP037

    def get(self, key: str, default: object = None) -> object:
        """
        Возвращает параметр конфигурации.
        Args:
        key: Имя параметра.
        default: Значение по умолчанию, если параметр отсутствует.
        Returns:
        Значение параметра или default.
        """
        return self.parameters.get(key, default)

    def get_str(self, key: str, default: str = "") -> str:
        """
        Возвращает строковый параметр конфигурации.
        Args:
        key: Имя параметра.
        default: Значение по умолчанию.
        Returns:
        Строковое значение параметра.
        """
        value = self.parameters.get(key, default)
        return str(value) if value is not None else default

    def get_bool(self, key: str, default: bool = False) -> bool:
        """
        Возвращает булев параметр конфигурации.
        Args:
        key: Имя параметра.
        default: Значение по умолчанию.
        Returns:
        Булево значение параметра.
        """
        value = self.parameters.get(key, default)
        if isinstance(value, bool):
            return value
        if isinstance(value, str):
            return value.lower() in ("true", "1", "yes")
        return default

    def get_int(self, key: str, default: int = 0) -> int:
        """Возвращает целочисленный параметр конфигурации.

        Args:
            key: Имя параметра.
            default: Значение по умолчанию.

        Returns:
            Целочисленное значение параметра.
        """
        value = self.parameters.get(key, default)
        # bool — подкласс int, проверяем раньше.
        if isinstance(value, bool):
            return int(value)
        if isinstance(value, (int, float)):
            return int(value)
        if isinstance(value, str):
            try:
                return int(value)
            except ValueError:
                return default
        return default


