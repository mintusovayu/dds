@dataclass
class PageHit:
    """
    Одно совпадение на странице документа.
    Используется внутри сгруппированного :class:`SearchResult`
    для представления страницы, на которой найдено совпадение,
    и её сниппета.
    Attributes:
    +---------------------+------------------------------------------+
    | Атрибут             | Описание                                 |
    +=====================+==========================================+
    | ``page_number``     | Номер страницы (0-based).                |
    +---------------------+------------------------------------------+
    | ``snippet``         | Фрагмент текста страницы с подсветкой    |
    |                     | совпадений. Совпадения выделены          |
    |                     | нейтральными маркерами, определёнными    |
    |                     | в ``config`` (``SNIPPET_HIGHLIGHT_START``|
    |                     | и ``SNIPPET_HIGHLIGHT_END``).            |
    +---------------------+------------------------------------------+
    """

    page_number: int
    snippet: str


@dataclass
class SearchResult:
    """
    Сгруппированный результат полнотекстового поиска по документу.
    Представляет один документ и все страницы этого документа,
    на которых найдены совпадения. Используется в поисковом
    бэкенде, application layer и API.
    Серверная группировка позволяет отображать в таблице результатов
    одну строку на документ с перечислением страниц. Сниппет
    страницы с наименьшим номером используется как
    «представительный» для свёрнутой строки.
    Attributes:
    +---------------------+------------------------------------------+
    | Атрибут             | Описание                                 |
    +=====================+==========================================+
    | ``doc_id``          | Идентификатор документа.                 |
    +---------------------+------------------------------------------+
    | ``file_path``       | Относительный путь к файлу документа.    |
    |                     | Извлекается из таблицы ``documents``.    |
    +---------------------+------------------------------------------+
    | ``pages``           | Список :class:`PageHit` — страниц,       |
    |                     | на которых найдены совпадения.           |
    |                     | Отсортирован по возрастанию              |
    |                     | ``page_number``. Дедуплицирован.         |
    +---------------------+------------------------------------------+
    | ``relevance_score`` | Лучшая (минимальная) оценка BM25 среди   |
    |                     | страниц документа. Чем меньше значение,  |
    |                     | тем выше релевантность.                  |
    +---------------------+------------------------------------------+
    Примечание:
        Для результатов пустого запроса (режим «показать все»)
        ``relevance_score`` устанавливается в ``0.0`` для всех
        документов. Такое значение не используется для сортировки;
        порядок документов определяется сервером по ``file_path``.
    Примечание:
        Список ``pages`` гарантированно отсортирован по
        возрастанию ``page_number`` на уровне поискового бэкенда
        (``FTS5SearchBackend``). Потребители (клиентский
        ``search.js``, обработчики API) обращаются к странице с
        наименьшим номером как ``result.pages[0]`` напрямую.
        Ранее существовавшие property ``best_page`` и
        ``representative_snippet`` были удалены в шаге 4.2
        рефакторинга v5.0 как неиспользуемые.
    """

    doc_id: str
    file_path: str
    pages: list[PageHit] = field(default_factory=list)
    relevance_score: float = 0.0


@dataclass
class SearchFilters:
    """
    Фильтры для комбинированного поиска.
    Позволяет ограничить результаты поиска по пути файла,
    по данным модулей и по метаданным документов, полученным
    при парсинге имени файла.
    Attributes:
    file_path_pattern: Шаблон пути файла (SQL LIKE).
        Например, "%корпус%" найдёт все документы,
        содержащие "корпус" в пути.
        None — без фильтрации по пути.
    module_filters: Фильтры по данным модулей.
        Словарь: имя VIEW -> словарь условий.
        Пустой словарь — без фильтрации по модулям.
    object_code: Код объекта из имени файла (например, "7350").
        Фильтр по полю ``object_code`` таблицы documents.
        None — без фильтрации.
    discipline_code: Код дисциплины из имени файла (например, "265").
        Фильтр по полю ``discipline_code`` таблицы documents.
        None — без фильтрации.
    document_type_code: Код типа документа из имени файла
        (например, "DTL").
        Фильтр по полю ``document_type_code`` таблицы documents.
        None — без фильтрации.
    unmatched_only: Флаг, при установке которого отбираются только
        документы с ``unmatched_flag = 1``, т.е. те, которые не
        соответствуют ни одному из активных фильтров или справочнику.
        Используется для контроля полноты таблиц-справочников.
        По умолчанию False.
    """

    file_path_pattern: str | None = None
    module_filters: dict[str, dict[str, object]] = field(default_factory=dict)
    object_code: str | None = None
    discipline_code: str | None = None
    document_type_code: str | None = None
    unmatched_only: bool = False


