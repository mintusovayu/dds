@dataclass
class ScanProgress:
    """
    Прогресс сканирования.
    Отображает состояние текущего или последнего сканирования.
    Используется для отображения прогресса в веб-интерфейсе.
    Обеспечивает детальную разбивку обработанных файлов для
    прозрачности работы конвейера.
    Attributes:
    +---------------------+--------------------------------------------+
    | Атрибут             | Описание                                   |
    +=====================+============================================+
    | phase               | Фаза сканирования (primary/secondary).     |
    +---------------------+--------------------------------------------+
    | status              | Статус сканирования.                       |
    +---------------------+--------------------------------------------+
    | total_files         | Общее количество файлов для обработки.     |
    +---------------------+--------------------------------------------+
    | processed_files     | Общее количество обработанных файлов       |
    |                     | (сумма всех нижеследующих счетчиков).      |
    +---------------------+--------------------------------------------+
    | indexed_files       | Количество файлов, успешно извлеченных и   |
    |                     | записанных в БД (новые или измененные).    |
    +---------------------+--------------------------------------------+
    | duplicate_files     | Количество файлов, пропущенных как         |
    |                     | дубликаты (хеш совпал с существующим в БД).|
    +---------------------+--------------------------------------------+
    | skipped_files       | Количество файлов, пропущенных без         |
    |                     | хеширования (метаданные совпали с кэшем).  |
    +---------------------+--------------------------------------------+
    | error_files         | Количество файлов, обработанных с ошибкой  |
    |                     | (поврежденные, недоступные и т.д.).        |
    +---------------------+--------------------------------------------+
    | current_file        | Путь к текущему обрабатываемому файлу.     |
    +---------------------+--------------------------------------------+
    """

    phase: ScanPhase = ScanPhase.PRIMARY
    status: ScanStatus = ScanStatus.IDLE
    total_files: int = 0
    processed_files: int = 0
    current_file: str = ""
    # Детальные счетчики конвейера
    indexed_files: int = 0
    duplicate_files: int = 0
    skipped_files: int = 0
    error_files: int = 0

    @property
    def progress_percent(self) -> float:
        """
        Возвращает прогресс в процентах (0.0–100.0).
        Returns:
        Процент обработки. 0.0, если total_files == 0.
        """
        if self.total_files == 0:
            return 0.0
        return (self.processed_files / self.total_files) * 100.0


@dataclass
class IndexStatus:
    """
    Фактическое состояние индексации системы.
    Определяется на основе анализа данных в БД и файловой системы,
    а не на основе таблицы scan_state. Это источник истины для
    отображения состояния системы.
    Attributes:
    +--------------------------+-----------------------------------------+
    | Атрибут                  | Описание                                |
    +==========================+=========================================+
    | state                    | Состояние индексации (IndexState).      |
    +--------------------------+-----------------------------------------+
    | total_files_in_directory | Общее количество файлов в каталоге РД.  |
    +--------------------------+-----------------------------------------+
    | indexed_files            | Количество проиндексированных файлов    |
    |                          | (уникальные записи в БД).               |
    +--------------------------+-----------------------------------------+
    | duplicate_files_on_disk  | Количество файлов на диске, которые     |
    |                          | являются дубликатами уже проиндекси-    |
    |                          | рованных файлов (их контент есть в БД). |
    +--------------------------+-----------------------------------------+
    | new_files                | Количество новых (непроиндексированных) |
    |                          | файлов, которых нет в БД даже как дубл. |
    +--------------------------+-----------------------------------------+
    | modified_files           | Количество изменённых файлов            |
    |                          | (хеш на диске не совпадает с хешем в БД)|
    +--------------------------+-----------------------------------------+
    | unindexed_files          | Количество непроиндексированных файлов  |
    |                          | (new_files + modified_files).           |
    +--------------------------+-----------------------------------------+
    | search_available         | Доступен ли поиск.                      |
    |                          | True, если есть хотя бы один документ.  |
    +--------------------------+-----------------------------------------+
    | message                  | Человекочитаемое сообщение о состоянии. |
    +--------------------------+-----------------------------------------+
    """

    state: IndexState = IndexState.EMPTY
    total_files_in_directory: int = 0
    indexed_files: int = 0
    duplicate_files_on_disk: int = 0
    new_files: int = 0
    modified_files: int = 0
    unindexed_files: int = 0
    search_available: bool = False
    message: str = ""

    @property
    def progress_percent(self) -> float:
        """
        Возвращает прогресс индексации в процентах (0.0–100.0).
        Returns:
        Процент проиндексированных файлов от общего количества.
        0.0, если total_files_in_directory == 0.
        """
        if self.total_files_in_directory == 0:
            return 0.0
        return (self.indexed_files / self.total_files_in_directory) * 100.0

    @property
    def is_fully_indexed(self) -> bool:
        """
        Возвращает True, если все файлы проиндексированы.
        Returns:
        True, если состояние FULLY_INDEXED.
        """
        return self.state == IndexState.FULLY_INDEXED


