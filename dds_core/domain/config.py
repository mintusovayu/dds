"""
Константы конфигурации ядра DDS.

Этот модуль содержит значения по умолчанию для всех констант,
используемых в ядре системы Deep Doc Search. Константы сгруппированы
по функциональным областям и имеют подробные docstring с описанием
назначения, единиц измерения и обоснования значений.

Принципы:
- Все константы определены в одном месте (единая точка конфигурации).
- Каждая константа имеет подробный docstring.
- Константы типизированы.
- Константы не содержат бизнес-логики — только значения по умолчанию.
- Реальная конфигурация читается из config.json в application layer.
  Константы этого модуля используются как значения по умолчанию,
  если параметр не указан в config.json.
- Domain layer не зависит от файловой системы. Пути по умолчанию
  относительные или параметризованные.

Группы констант:
1. База данных.
2. Сканирование каталога.
3. Параллельная обработка (Фаза 3).
4. Хеширование документов.
5. Полнотекстовый поиск.
6. Управление модулями.
7. Обработка ошибок.
8. Событийная шина и логирование (включая оптимизацию запросов).
9. Аутентификация и безопасность.
10. Таймауты блокирующих операций.
11. Справочники для фильтрации.
12. Предпросмотр документа (рендер и подсветка).
13. Диагностика системы координат страницы.

Скорректированный план (рефакторинг v5.0):

- Добавлена константа ``DB_JOURNAL_SIZE_LIMIT`` для PRAGMA
  ``journal_size_limit`` (шаг 5.5). ``DB_TEMP_STORE`` **не добавляется**:
  переключение ``temp_store=MEMORY`` на больших БД создаёт риск OOM
  (сортировки и GROUP BY материализуются в RAM).
- Удалён ключ ``index.refresh_single_hash`` из ``OPERATION_TIMEOUTS``
  (шаг 4.1): не используется в коде после рефакторинга.
- Добавлена константа ``PAGE_TEXT_CACHE_SIZE`` для LRU-кэша текста
  страниц ``SearchEngine.get_page_text`` (шаг 3.2).
"""

