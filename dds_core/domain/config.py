COORD_DIAGNOSTICS_ENABLED: bool = True
"""
Включает автоматическую диагностику системы координат при
построении подсветки.

Используется в :class:`~dds_core.application.highlights_service.HighlightsService`.
Если ``True``, при поступлении запроса подсветки с
``apply_transform=None`` выполняется диагностика страницы через
:func:`~dds_core.application.coordinate_diagnostics.diagnose_word_index`.
При обнаружении аномалии координаты bbox трансформируются в
стандартную (top-left) систему перед нормализацией.

Если ``False``, диагностика не выполняется; флаг трансформации
определяется исключительно параметром ``apply_transform`` запроса
(``True``/``False``). В этом случае возможна только ручная
коррекция через чекбокс «Ротация координат» на вкладке документа.

Обоснование значения ``True``: аномалии системы координат встречаются
в нестандартных CAD-экспортах и требуют автоматической коррекции
для корректного отображения подсветки. Отключение диагностики
рекомендуется только для отладки.

Значение: ``True``.
"""

COORD_TEXT_OOB_THRESHOLD: float = 0.05
"""
Порог доли слов, выходящих за границы страницы (признак OOB).

Используется в
:func:`~dds_core.application.coordinate_diagnostics.diagnose_word_index`.

Если доля слов, чей bbox не укладывается в
``[0, page_width] × [0, page_height]``, превышает этот порог —
признак OOB считается сработавшим.

Обоснование значения ``0.05``: в нормальных PDF слова, выходящие
за границы страницы, практически отсутствуют (за исключением
редких случаев выносок или колонтитулов с отрицательными
координатами). В аномальных PDF доля таких слов обычно
превышает 20–30% из-за несоответствия осей. Порог 5% даёт
устойчивое различение при защите от единичных выбросов.

Значение: ``0.05``.
"""

COORD_TEXT_DOMINANCE_THRESHOLD: float = 0.7
"""
Порог доли «вертикальных» слов (признак Dominance).

Используется в
:func:`~dds_core.application.coordinate_diagnostics.diagnose_word_index`.

Слово классифицируется как «вертикальное», если его высота
превышает ширину более чем в ``COORD_ASPECT_T`` раз. Если доля
таких слов среди всех классифицированных (вертикальных и
горизонтальных) превышает этот порог — признак Dominance
считается сработавшим.

Обоснование значения ``0.7``: в нормальном документе преобладают
горизонтальные слова, доля вертикальных редко превышает 10–20%
(например, заголовки в боковиках таблиц). В аномальном PDF
почти все слова выглядят «вертикальными» (доля > 80%), так как
оси перепутаны. Порог 70% даёт устойчивое различение.

Значение: ``0.7``.
"""

COORD_ASPECT_T: float = 2.0
"""
Порог отношения сторон для классификации слова как
вертикального или горизонтального.

Используется в
:func:`~dds_core.application.coordinate_diagnostics.diagnose_word_index`.

Слово считается «вертикальным», если ``height > width * COORD_ASPECT_T``.
Слово считается «горизонтальным», если ``width > height * COORD_ASPECT_T``.
Слова с промежуточными пропорциями (квадратные и близкие к ним)
не учитываются в знаменателе для расчёта доли доминирования.

Обоснование значения ``2.0``: типичное слово в текстовом слое
PDF имеет соотношение сторон 3:1 и более (горизонтальное) или
1:3 и более (вертикальное). Порог 2:1 отсекает слова с близкими
пропорциями (например, одиночные символы, короткие аббревиатуры),
которые не дают надёжного сигнала о системе координат.

Значение: ``2.0``.
"""
