"""
Интерфейсы репозиториев справочников.

Модуль определяет абстракции для доступа к справочникам кодов
и псевдонимов, используемым при фильтрации документов. Справочники
хранят множества допустимых значений для шифра объекта, номера
дисциплины и типа документа, а также их псевдонимы.

Реализации этих интерфейсов находятся в инфраструктурном слое
и читают данные из соответствующих таблиц базы данных (например,
``object_reference``, ``discipline_reference``,
``document_type_reference``). Компоненты прикладного уровня
(такие как ``DocumentMetadataService`` и ``ReferenceDataService``)
зависят от этих абстракций, что обеспечивает инверсию зависимостей
и упрощает модульное тестирование.

Принципы:
- Только объявление контракта, без конкретной реализации.
- Не зависит от схемы хранения справочников.
- Может использоваться с любым типом базы данных.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable


@runtime_checkable
class ReferenceRepository(Protocol):
    """Абстракция доступа к справочнику кодов и псевдонимов.

    Реализуется инфраструктурным компонентом, который читает
    конкретную таблицу справочника. Используется для:

    - получения всех канонических кодов;
    - разрешения псевдонима в код (без учёта языка);
    - получения отображения «псевдоним → код» (всех или для
      указанного языка).

    Example:
        class SqliteObjectReferenceRepository:
            def __init__(self, db):
                self._db = db

            def get_codes(self) -> set[str]:
                rows = self._db.execute(
                    "SELECT code FROM object_reference"
                )
                return {row[0] for row in rows}

            def resolve_alias(self, alias: str) -> str | None:
                rows = self._db.execute(
                    "SELECT code FROM object_reference_alias WHERE alias = ?",
                    (alias,),
                )
                return rows[0][0] if rows else None

            def get_alias_to_code_map(
                self, lang: str | None = None
            ) -> dict[str, str]:
                if lang is None:
                    rows = self._db.execute(
                        "SELECT alias, code FROM object_reference_alias"
                    )
                else:
                    rows = self._db.execute(
                        "SELECT alias, code FROM object_reference_alias "
                        "WHERE lang = ?",
                        (lang,),
                    )
                return {row[0]: row[1] for row in rows}
    """

