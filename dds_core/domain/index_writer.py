"""
Интерфейс записи плана индексации в базу данных.

Модуль определяет Protocol :class:`IIndexWriter`, который
реализуется инфраструктурным слоем (конкретный бэкенд БД) и
используется application-слоем для записи результатов индексации.
Домен не знает о конкретной реализации (SQLite FTS5, PostgreSQL
и т.д.) — он работает только через этот интерфейс.

Разделение записи и чтения:

+----------------------------------+----------------------------------+
| Операция                         | Интерфейс                        |
+==================================+==================================+
| Запись плана индексации          | :class:`IIndexWriter`            |
+----------------------------------+----------------------------------+
| Удаление документа из индекса    | :class:`IIndexWriter`            |
+----------------------------------+----------------------------------+
| Поиск документа по хешу/пути     | ``IDatabase``                    |
+----------------------------------+----------------------------------+
| Чтение метаданных документа      | ``IDatabase``                    |
+----------------------------------+----------------------------------+

``IIndexWriter`` описывает **write-контракт** индексации:
как записать подготовленный ``DocumentIndexPlan`` и как удалить
документ. Read-операции остаются в ``IDatabase`` — их рефакторинг
вне области Фазы 5 (см. план рефакторинга).

Жизненный цикл записи:

+---+-----------------------------------------------------+
| № | Описание                                            |
+===+=====================================================+
| 1 | ``application.index_plan_builder.build_index_plan`` |
|   | формирует ``DocumentIndexPlan`` (открывает PDF,      |
|   | извлекает текст, нормализует).                       |
+---+-----------------------------------------------------+
| 2 | ``TextIndexer.prepare_index_plan`` делегирует в      |
|   | ``build_index_plan``.                                |
+---+-----------------------------------------------------+
| 3 | ``ScanPipeline`` накапливает планы в буфер и         |
|   | передаёт их в ``TextIndexer.write_index_plans``.     |
+---+-----------------------------------------------------+
| 4 | ``TextIndexer.write_index_plans`` делегирует в       |
|   | ``IIndexWriter.write_plans_batch``.                  |
+---+-----------------------------------------------------+
| 5 | Реализация ``IIndexWriter`` преобразует план в       |
|   | SQL-запросы и выполняет их в БД.                     |
+---+-----------------------------------------------------+

Инварианты:

- **Идемпотентность** ``write_plan``: повторная запись плана с тем
  же ``doc_id`` перезаписывает существующую запись (INSERT OR REPLACE),
  а не создаёт дубликат.
- **Атомарность** ``write_plan``: план записывается целиком или не
  записывается вовсе. При ошибке — откат (в реализации через
  SAVEPOINT или транзакцию).
- **Изоляция** ``write_plans_batch``: ошибка в одном плане не
  откатывает успешно записанные планы. ``SAVEPOINT`` на каждый план.
- **Идемпотентность** ``remove_document``: удаление несуществующего
  ``doc_id`` не выбрасывает исключение.

Реализации:
    ``dds_core/infrastructure/sqlite_index_writer.py`` →
    ``SqliteIndexWriter``.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from .index_plan import DocumentIndexPlan


@runtime_checkable
class IIndexWriter(Protocol):
    """Интерфейс записи плана индексации документа в БД.

    Реализуется инфраструктурным слоем. Application-слой использует
    этот интерфейс через ``TextIndexer``, не зная о конкретном
    бэкенде БД (SQLite FTS5, PostgreSQL и т.д.).

    Реализации:
        ``dds_core/infrastructure/sqlite_index_writer.py`` →
        ``SqliteIndexWriter``.
    """

    def write_plan(self, plan: DocumentIndexPlan) -> None:
        """Записывает план индексации одного документа в БД.

        Операции:

        +----+----------------------------------------------------+
        | №  | Описание                                           |
        +====+====================================================+
        | 1  | Преобразование ``DocumentIndexPlan`` в список      |
        |    | SQL-запросов (INSERT в ``documents`` и             |
        |    | ``text_index_fts``).                               |
        +----+----------------------------------------------------+
        | 2  | Выполнение всех запросов атомарно                  |
        |    | (SAVEPOINT или транзакция в зависимости от         |
        |    | реализации).                                       |
        +----+----------------------------------------------------+
        | 3  | При ошибке — откат, проброс исключения.            |
        +----+----------------------------------------------------+

        Идемпотентность:
            Повторная запись плана с тем же ``doc_id`` перезаписывает
            существующую запись. Реализация использует
            ``INSERT OR REPLACE`` для ``documents`` и
            ``DELETE FROM text_index_fts`` перед INSERT-ами страниц.

        Атомарность:
            План записывается целиком или не записывается вовсе.
            Частично записанный документ не остаётся в БД после
            ошибки.

        Args:
            plan: План индексации документа. Содержит метаданные
                документа (``doc_id``, ``file_path``, ``file_hash``,
                ``file_size``, ``last_modified``, ``page_count``,
                ``indexed_at``) и кортеж записей страниц с
                оригинальным и нормализованным текстом.

        Raises:
            Exception: Любая ошибка записи в БД. Транзакция
                откатывается. Конкретный тип исключения зависит
                от реализации.
        """
        ...

    def write_plans_batch(
        self,
        plans: list[DocumentIndexPlan],
        commit_interval: int = 200,
    ) -> tuple[int, int]:
        """Записывает батч планов с промежуточными коммитами.

        Операции:

        +----+----------------------------------------------------+
        | №  | Описание                                           |
        +====+====================================================+
        | 1  | Преобразование каждого плана в список SQL-запросов.|
        +----+----------------------------------------------------+
        | 2  | Для каждого плана — SAVEPOINT, выполнение запросов,|
        |    | RELEASE SAVEPOINT.                                 |
        +----+----------------------------------------------------+
        | 3  | При ошибке в одном плане — ROLLBACK TO SAVEPOINT,  |
        |    | инкремент счётчика ``failed``, переход к           |
        |    | следующему плану.                                  |
        +----+----------------------------------------------------+
        | 4  | Каждые ``commit_interval`` планов — промежуточный  |
        |    | COMMIT (снижает накопление незакоммиченных         |
        |    | изменений при массовом индексировании).            |
        +----+----------------------------------------------------+
        | 5  | Финальный COMMIT.                                  |
        +----+----------------------------------------------------+
        | 6  | Возврат кортежа ``(success, failed)``.             |
        +----+----------------------------------------------------+

        Изоляция:
            Ошибка в одном плане не откатывает успешно записанные
            планы. Каждый план обёрнут в SAVEPOINT, ошибка
            локализована в границах одного документа.

        Args:
            plans: Список планов индексации. Пустой список —
                допустимый вход; возвращается ``(0, 0)``.
            commit_interval: Количество планов между промежуточными
                ``COMMIT``. Значение ``1`` — коммит после каждого
                плана; значение больше длины списка — единственный
                финальный COMMIT. По умолчанию ``200``.
                Значение должно быть положительным.

        Returns:
            Кортеж ``(успешно записанных, ошибочных)``. Сумма
            равна длине ``plans``.

        Raises:
            Exception: При фатальной ошибке транзакции
                (например, БД закрыта). Ошибки отдельных планов
                не пробрасываются — они инкрементируют ``failed``.
        """
        ...

    def remove_document(self, doc_id: str) -> None:
        """Удаляет документ из индекса.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Удаление страниц документа из полнотекстового        |
        |   | индекса (``text_index_fts``).                        |
        +---+-----------------------------------------------------+
        | 2 | Удаление метаданных документа из ``documents``.      |
        +---+-----------------------------------------------------+
        | 3 | Обе операции атомарны (одна транзакция).             |
        +---+-----------------------------------------------------+

        Идемпотентность:
            Удаление несуществующего ``doc_id`` не выбрасывает
            исключение. Это позволяет вызывать метод безусловно
            (например, при повторной синхронизации).

        Args:
            doc_id: Идентификатор документа для удаления.

        Raises:
            Exception: Любая ошибка записи в БД. Конкретный тип
                исключения зависит от реализации.
        """
