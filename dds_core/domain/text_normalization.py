"""
Модуль нормализации текста для поиска, нечувствительного к раскладке
клавиатуры.

Содержит функции:

- :func:`normalize_text` — приводит строку к нижнему регистру и заменяет
  визуально похожие кириллические символы на латинские.
- :func:`denormalize_text` — выполняет обратную замену латинских символов,
  которые были получены в результате нормализации, на соответствующие
  кириллические. Используется для восстановления читаемого вида сниппетов.

Почему модуль находится в domain
--------------------------------

Правило нормализации — **доменное**, а не прикладное:

- Оно определяет **семантику** поиска в DDS: какие символы считаются
  эквивалентными при сопоставлении запроса и текста документа.
- Оно должно быть **единым контрактом** для трёх слоёв одновременно:
  infrastructure (индексация в ``pymupdf_text_extractor``, построение
  ``WordIndex``), application (сниппеты, сервис подсветки), presentation
  (отображение сниппетов на клиенте).
- Изменение правила (например, добавление новых соответствий между
  кириллицей и латиницей) — это изменение доменной логики, которое
  должно быть видно на уровне domain, а не спрятано в application.

Ранее модуль находился в ``dds_core/application/text_normalizer.py``.
Это приводило к архитектурному компромиссу: infrastructure-слой
(``pymupdf_text_extractor``) импортировал функцию из application-слоя,
нарушая направление зависимостей (infrastructure → application).
Перенос в domain устраняет компромисс: теперь и application, и
infrastructure зависят от domain (правильное направление).

Частичная (не полная) замена
----------------------------

Обе функции выполняют **посимвольную** замену по фиксированным
таблицам (:data:`CYRILLIC_TO_LATIN_MAP` — 12 пар визуально похожих
символов, :data:`LATIN_TO_CYRILLIC_MAP` — обратное отображение).
Символы, отсутствующие в таблице, остаются без изменений.

Это осознанное решение задачи **нечувствительности к раскладке
клавиатуры**, а не «перевода на латиницу». Пользователь, набравший
``ЕС-423-1`` в русской раскладке и ``EC-423-1`` в английской,
получит одинаковые результаты поиска. Полная транслитерация не
требуется и не выполняется. См. ADR-003.

Следствия для потребителей
--------------------------

- **Результат не читается как исходный кириллический текст.**
  Например, ``normalize_text("Пример текста")`` даёт ``"пpиmep
  tekcta"`` (а не ``"пример texta"``): символы ``п`` и ``и``
  не входят в таблицу и остаются кириллическими; ``р→p``,
  ``м→m``, ``е→e``, ``т→t``, ``к→k``, ``с→c``, ``а→a``.

- **Round-trip не сохраняет регистр.**
  ``normalize_text`` вызывает ``str.lower()``, что необратимо
  теряет регистр исходной строки. ``denormalize_text`` выполняет
  только посимвольную замену и не восстанавливает регистр.
  Все потребители работают с текстом в нижнем регистре; исходный
  регистр сохраняется в колонке ``text_content`` FTS-индекса,
  а не в ``normalized_text``.

- **Round-trip не является identity для исходной латиницы.**
  Нормализация не различает исходную латиницу и латиницу,
  полученную из кириллицы. Обратная замена меняет **все**
  латинские буквы, входящие в :data:`LATIN_TO_CYRILLIC_MAP`,
  на кириллицу.

Принципы:
- Архитектурная чистота: модуль находится в domain layer и не зависит
  ни от application, ни от infrastructure.
- Инверсия зависимостей: функции не импортируют другие модули проекта.
- Простота и предсказуемость: только замена символов по таблицам.
- Чистые функции: детерминированные, без побочных эффектов, без
  изменяемого состояния.
"""

from __future__ import annotations

# ----------------------------------------------------------------------
# Таблица замены кириллических символов на визуально похожие латинские
# ----------------------------------------------------------------------

CYRILLIC_TO_LATIN_MAP: dict[str, str] = {
    "а": "a",
    "в": "b",
    "е": "e",
    "к": "k",
    "м": "m",
    "н": "h",
    "о": "o",
    "р": "p",
    "с": "c",
    "т": "t",
    "у": "y",
    "х": "x",
}
"""Словарь соответствия кириллических символов (нижний регистр)
визуально похожим латинским. Используется в :func:`normalize_text`.

Таблица намеренно **частичная**: она покрывает только символы,
которые могут быть набраны в неправильной раскладке и при этом
визуально совпадают с латинскими. Полный набор кириллических
символов не требуется — задача нормализации не «перевод на
латиницу», а «приведение к единому виду независимо от раскладки».
"""

# Обратный словарь: латиница -> кириллица.
LATIN_TO_CYRILLIC_MAP: dict[str, str] = {
    latin: cyrillic for cyrillic, latin in CYRILLIC_TO_LATIN_MAP.items()
}
"""Словарь обратного соответствия: латинский символ -> кириллический.
Используется в :func:`denormalize_text`.
"""


def normalize_text(text: str) -> str:
    """Нормализует текст для нечувствительного к раскладке поиска.

    Функция выполняет следующие операции:

    1. Приводит строку к нижнему регистру (``str.lower()``).
    2. Заменяет каждый кириллический символ, присутствующий
       в :data:`CYRILLIC_TO_LATIN_MAP`, на соответствующий
       латинский символ.
    3. Символы, отсутствующие в таблице, остаются без изменений.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | ``text.lower()`` — приведение к нижнему регистру.    |
    +---+-----------------------------------------------------+
    | 2 | Для каждой пары ``(cyrillic, latin)`` из            |
    |   | :data:`CYRILLIC_TO_LATIN_MAP`: ``str.replace``      |
    |   | заменяет все вхождения ``cyrillic`` на ``latin``.   |
    +---+-----------------------------------------------------+
    | 3 | Возврат результата.                                 |
    +---+-----------------------------------------------------+

    Примечание:
        Замена — **частичная**. Символы, отсутствующие в
        :data:`CYRILLIC_TO_LATIN_MAP`, остаются кириллическими.
        Это осознанное решение (см. module docstring): задача —
        нечувствительность к раскладке, а не транслитерация.

    Args:
        text: Исходная строка для нормализации.

    Returns:
        Нормализованная строка. Регистр — нижний; кириллические
        символы из таблицы заменены на латинские; остальные
        символы сохранены.

    Example:
        Классический случай — технический код в неправильной
        раскладке: пользователь хотел набрать ``EC-423-1``
        латиницей, но набрал ``ЕС-423-1`` кириллицей.
        Нормализация приводит оба варианта к единому виду::

            >>> normalize_text("ЕС-423-1")
            'ec-423-1'
            >>> normalize_text("EC-423-1")
            'ec-423-1'

        Пример частичной замены (не транслитерации) — слово
        ``гидрошпонка``: символы ``г``, ``и``, ``д``, ``ш``, ``п``
        не входят в таблицу и остаются кириллическими; заменяются
        ``р→p``, ``о→o``, ``н→h``, ``к→k``, ``а→a``::

            >>> normalize_text("гидрошпонка")
            'гидpoшпohka'
    """
    lowered = text.lower()
    # Последовательная замена по словарю.
    # Для повышения производительности можно использовать str.translate,
    # но для коротких текстов поиска и страниц документов
    # цикл с replace достаточно быстр.
    for cyrillic, latin in CYRILLIC_TO_LATIN_MAP.items():
        lowered = lowered.replace(cyrillic, latin)
    return lowered


def denormalize_text(text: str) -> str:
    """Выполняет обратную замену латинских символов на кириллические.

    Заменяет латинские буквы, которые могли быть получены в результате
    нормализации, на соответствующие кириллические. Применяется к тексту
    сниппетов, чтобы пользователь видел привычное кириллическое написание,
    даже если поиск выполнялся по нормализованной колонке.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Для каждой пары ``(latin, cyrillic)`` из            |
    |   | :data:`LATIN_TO_CYRILLIC_MAP`: ``str.replace``      |
    |   | заменяет все вхождения ``latin`` на ``cyrillic``.   |
    +---+-----------------------------------------------------+
    | 2 | Возврат результата.                                 |
    +---+-----------------------------------------------------+

    Примечание:
        Замена — **посимвольная**. Результат не всегда читается
        как исходный кириллический текст: например, ``x``
        заменяется на ``х``, а не на ``кс``. Это ожидаемое
        поведение посимвольной обратной замены, а не ошибка
        (см. module docstring).

    Примечание:
        Функция не восстанавливает регистр: ``normalize_text``
        вызывает ``str.lower()``, информация о регистре теряется
        необратимо. Все потребители работают с текстом в нижнем
        регистре.

    Args:
        text: Строка, содержащая латинские символы (например,
            сниппет, полученный из колонки ``normalized_text``).

    Returns:
        Строка с восстановленными кириллическими символами.
        Латинские буквы, входящие в :data:`LATIN_TO_CYRILLIC_MAP`,
        заменены; остальные символы сохранены.

    Example:
        Классический случай — восстановление читаемого вида
        технического кода, который был нормализован для поиска::

            >>> denormalize_text("ec-423-1")
            'ес-423-1'

        Пример посимвольной замены, которая не даёт «исходного»
        текста: слово ``texta`` содержит ``x``, а ``x → х`` (не
        ``кс``), поэтому результат визуально отличается от
        предполагаемого исходного слова ``текста``::

            >>> denormalize_text("texta")
            'техта'
    """
    for latin, cyrillic in LATIN_TO_CYRILLIC_MAP.items():
        text = text.replace(latin, cyrillic)
    return text
