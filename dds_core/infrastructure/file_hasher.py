"""
Хеширование файлов документов.

Этот модуль реализует интерфейс IHasher доменного слоя,
обеспечивая вычисление хешей файлов документов. Хеш используется
для контроля дубликатов и определения необходимости
переиндексации.

Модуль находится в инфраструктурном слое и является единственной
точкой хеширования файлов. Доменный слой не знает о конкретном
алгоритме хеширования — он использует только интерфейс IHasher.

Алгоритм работы:
    1. Файл открывается в режиме чтения (binary).
    2. Файл читается блоками по HASH_CHUNK_SIZE байт.
    3. Каждый блок обновляет объект хеширования.
    4. После чтения всего файла возвращается шестнадцатеричная
       строка хеша.

    Такой подход позволяет хешировать файлы любого размера
    без загрузки всего файла в память.

Принципы:
    - Модуль реализует интерфейс доменного слоя (инверсия зависимостей).
    - Модуль является единственной точкой хеширования файлов.
    - Модуль не содержит бизнес-логики (контроль дубликатов,
      переиндексация — ответственность application layer).
    - Модуль не выполняет логирование. Логирование — ответственность
      application layer.

Реализуемые интерфейсы:
    IHasher — абстракция хеширования файлов.
"""

from __future__ import annotations

import hashlib

from ..domain import config

# ----------------------------------------------------------------------
# Хеширование файлов
# ----------------------------------------------------------------------


class FileHasher:
    """Хеширование файлов документов.

    Реализует интерфейс IHasher. Вычисляет хеш файла блоками,
    что позволяет обрабатывать файлы любого размера без загрузки
    всего файла в память.

    Пример использования:

        hasher = FileHasher()
        file_hash = hasher.compute_hash("/path/to/document.pdf")

    Attributes:
        _algorithm: Имя алгоритма хеширования.
        _chunk_size: Размер блока чтения в байтах.
    """

    def __init__(
        self,
        algorithm: str | None = None,
        chunk_size: int | None = None,
    ) -> None:
        """Инициализирует хешер файлов.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Определение алгоритма хеширования: если             |
        |   | ``algorithm`` не передан, используется              |
        |   | ``config.HASH_ALGORITHM``.                          |
        +---+-----------------------------------------------------+
        | 2 | Определение размера блока чтения: если              |
        |   | ``chunk_size`` не передан, используется             |
        |   | ``config.HASH_CHUNK_SIZE``.                         |
        +---+-----------------------------------------------------+
        | 3 | Проверка, что выбранный алгоритм поддерживается     |
        |   | библиотекой ``hashlib``.                            |
        +---+-----------------------------------------------------+

        Args:
            algorithm: Имя алгоритма хеширования. По умолчанию
                используется ``HASH_ALGORITHM`` из config.
                Поддерживаются все алгоритмы из ``hashlib``
                (например, ``"sha256"``, ``"sha512"``, ``"md5"``).
            chunk_size: Размер блока чтения в байтах. По умолчанию
                используется ``HASH_CHUNK_SIZE`` из config.

        Raises:
            ValueError: Если указанный алгоритм не поддерживается
                ``hashlib``.
        """
        self._algorithm = algorithm if algorithm is not None else config.HASH_ALGORITHM
        self._chunk_size = chunk_size if chunk_size is not None else config.HASH_CHUNK_SIZE

        # Проверить, что алгоритм поддерживается
        if self._algorithm not in hashlib.algorithms_available:
            raise ValueError(
                f"Алгоритм хеширования '{self._algorithm}' не поддерживается. "
                f"Доступные алгоритмы: {sorted(hashlib.algorithms_available)}"
            )

    def compute_hash(self, file_path: str) -> str:
        """Вычисляет хеш файла.

        Файл читается блоками по ``self._chunk_size`` байт.
        Каждый блок обновляет объект хеширования. После чтения
        всего файла возвращается шестнадцатеричная строка хеша.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Создание объекта хеширования ``hashlib.new``        |
        |   | с выбранным алгоритмом.                             |
        +---+-----------------------------------------------------+
        | 2 | Открытие файла в бинарном режиме.                   |
        +---+-----------------------------------------------------+
        | 3 | Цикл чтения файла блоками по ``self._chunk_size``:  |
        |   | a. ``chunk = f.read(self._chunk_size)``.            |
        |   | b. Если ``chunk`` пуст — выход из цикла.            |
        |   | c. ``hasher.update(chunk)``.                        |
        |   | d. Увеличение счётчика прочитанных байт.            |
        +---+-----------------------------------------------------+
        | 4 | После цикла проверка, что файл не пуст.             |
        +---+-----------------------------------------------------+
        | 5 | Возврат шестнадцатеричной строки хеша.              |
        +---+-----------------------------------------------------+

        Args:
            file_path: Путь к файлу для хеширования.

        Returns:
            Шестнадцатеричная строка хеша. Например,
            ``"a3f2b8c9d1e4..."`` для SHA-256.

        Raises:
            FileNotFoundError: Если файл не найден.
            OSError: Если файл недоступен для чтения.
            ValueError: Если файл пуст (размер 0 байт).
                Пустые файлы не должны индексироваться.
        """
        hasher = hashlib.new(self._algorithm)
        bytes_read = 0

        with open(file_path, "rb") as f:
            while True:
                chunk = f.read(self._chunk_size)
                if not chunk:
                    break
                hasher.update(chunk)
                bytes_read += len(chunk)

        if bytes_read == 0:
            raise ValueError(
                f"Файл пуст (0 байт): {file_path}. Пустые файлы не подлежат индексированию."
            )

        return hasher.hexdigest()
