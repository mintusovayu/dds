"""
SQLite-репозиторий справочников кодов и псевдонимов.

Модуль предоставляет конкретную реализацию интерфейса
``ReferenceRepository`` для доступа к справочникам, хранящимся
в двух связанных таблицах SQLite:

- основная таблица (например, ``object_reference``) — содержит
  канонические коды и их описания;
- таблица псевдонимов (например, ``object_reference_alias``) —
  содержит псевдонимы, связанные с кодами через внешний ключ,
  и язык псевдонима (``lang``).

Каждая основная таблица имеет колонки ``code`` (первичный ключ)
и ``description`` (описание, по умолчанию пустая строка).
Таблица псевдонимов имеет колонки ``alias`` (первичный ключ),
``code`` (внешний ключ на основную таблицу) и ``lang``
(язык псевдонима; может быть ``NULL``).

Примечание по языковой фильтрации:
- Записи с ``lang = 'en'`` считаются английскими псевдонимами.
- Записи с ``lang = 'ru'`` — русскими.
- Записи с ``lang IS NULL`` (например, оставшиеся после миграции
  со старых версий) считаются русскими по умолчанию, чтобы
  не терять существующие данные.

Репозиторий используется для:

- получения всех канонических кодов (``get_codes()``);
- разрешения псевдонима в код (``resolve_alias()``) — поиск
  по всем языкам;
- получения отображения «псевдоним → код» (``get_alias_to_code_map()``)
  с опциональной фильтрацией по языку.

Принципы:
- Зависит только от абстракции ``IDatabase`` (DIP).
- Не содержит бизнес-логики, кроме выборки данных.
- Потокобезопасен, так как не хранит изменяемого состояния.

Пример использования::

    db = SQLiteAdapter("dds_database.db")
    object_repo = SqliteReferenceRepository(
        db,
        main_table_name="object_reference",
        alias_table_name="object_reference_alias",
    )
    codes = object_repo.get_codes()
    alias_map_ru = object_repo.get_alias_to_code_map(lang="ru")
    alias_map_en = object_repo.get_alias_to_code_map(lang="en")
    alias_map_all = object_repo.get_alias_to_code_map()
"""

from __future__ import annotations

from ..domain.interfaces import IDatabase


class SqliteReferenceRepository:
    """Реализация ``ReferenceRepository`` поверх SQLite.

    Работает с двумя таблицами: основной таблицей кодов и таблицей
    псевдонимов, связанных по колонке ``code``. Поддерживается
    фильтрация псевдонимов по языку (колонка ``lang``).

    Attributes:
        _db: Абстракция базы данных.
        _main_table_name: Имя основной таблицы справочника.
        _alias_table_name: Имя таблицы псевдонимов справочника.
    """

    def __init__(
        self,
        db: IDatabase,
        main_table_name: str,
        alias_table_name: str,
    ) -> None:
        """Инициализирует репозиторий.

        Args:
            db: Реализация ``IDatabase`` для выполнения SQL-запросов.
            main_table_name: Имя таблицы, содержащей колонки
                ``code`` и ``description``.
            alias_table_name: Имя таблицы, содержащей колонки
                ``alias``, ``code`` и ``lang``.
        """
        self._db = db
        self._main_table_name = main_table_name
        self._alias_table_name = alias_table_name

    def get_codes(self) -> set[str]:
        """Возвращает множество всех канонических кодов справочника.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Выполняется запрос ``SELECT code FROM <main_table>``.|
        +---+-----------------------------------------------------+
        | 2 | Результат преобразуется в множество строк.          |
        +---+-----------------------------------------------------+

        Returns:
            Множество кодов (строк). Если таблица пуста,
            возвращается пустое множество.
        """
        rows = self._db.execute(f"SELECT code FROM {self._main_table_name}")
        return {str(row[0]) for row in rows}

    def resolve_alias(self, alias: str) -> str | None:
        """Разрешает псевдоним в канонический код (поиск по всем языкам).

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Выполняется запрос ``SELECT code FROM <alias_table>  |
        |   | WHERE alias = ?``.                                  |
        +---+-----------------------------------------------------+
        | 2 | Если найдена строка, возвращается код из первой     |
        |   | строки. Иначе возвращается ``None``.                |
        +---+-----------------------------------------------------+

        Args:
            alias: Псевдоним для поиска.

        Returns:
            Канонический код, если псевдоним найден, иначе ``None``.
        """
        rows = self._db.execute(
            f"SELECT code FROM {self._alias_table_name} WHERE alias = ?",
            (alias,),
        )
        if rows:
            return str(rows[0][0])
        return None

    def get_alias_to_code_map(
        self,
        lang: str | None = None,
    ) -> dict[str, str]:
        """Возвращает отображение «псевдоним → код».

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Если ``lang`` равен ``None``, выполняется запрос     |
        |   | ``SELECT alias, code FROM <alias_table>`` (все       |
        |   | псевдонимы).                                        |
        +---+-----------------------------------------------------+
        | 2 | Если ``lang="en"``, выбираются записи с ``lang='en'``.|
        +---+-----------------------------------------------------+
        | 3 | Если ``lang="ru"``, выбираются записи с ``lang='ru'``|
        |   | или ``lang IS NULL`` (для сохранения старых данных). |
        +---+-----------------------------------------------------+
        | 4 | Результат преобразуется в словарь.                  |
        +---+-----------------------------------------------------+

        Args:
            lang: Язык псевдонимов (``"en"``, ``"ru"`` или ``None``).
                Если ``None`` — возвращаются все псевдонимы.

        Returns:
            Словарь, где ключ — псевдоним, значение — код.
            Если псевдонимов нет, возвращается пустой словарь.
        """
        if lang is None:
            rows = self._db.execute(f"SELECT alias, code FROM {self._alias_table_name}")
        elif lang == "en":
            rows = self._db.execute(
                f"SELECT alias, code FROM {self._alias_table_name} WHERE lang = 'en'"
            )
        elif lang == "ru":
            # Считаем записи с NULL русскими (для обратной совместимости)
            rows = self._db.execute(
                f"SELECT alias, code FROM {self._alias_table_name} "
                "WHERE lang = 'ru' OR lang IS NULL"
            )
        else:
            # Неизвестный язык — возвращаем пустой словарь или все?
            # Лучше вернуть пустой, чтобы не вводить в заблуждение.
            return {}

        return {str(row[0]): str(row[1]) for row in rows}
