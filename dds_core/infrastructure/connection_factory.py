"""
Фабрика создания SQLite-соединений.

Этот модуль содержит функцию `create_sqlite_connection`, которая
создаёт и настраивает соединение с базой данных SQLite. Все
соединения, используемые в `SQLiteAdapter`, должны создаваться
через эту фабрику для обеспечения единообразия настроек
производительности и целостности.

Модуль находится в инфраструктурном слое и не содержит
бизнес-логики. Фабрика используется классами `ConnectionPool`
и `SQLiteAdapter`.

Принципы:
    - Единственная точка создания соединений с настроенными PRAGMA.
    - Инкапсуляция деталей подключения и настройки SQLite.
    - Отсутствие побочных эффектов, кроме создания соединения.

Скорректированный план (шаг 5.5 рефакторинга v5.0):

Добавлен PRAGMA ``journal_size_limit``, ограничивающий рост
WAL-журнала при интенсивной записи. Значение берётся из
``config.DB_JOURNAL_SIZE_LIMIT`` (по умолчанию 64 МБ).
SQLite автоматически усечёт WAL-журнал после очередного
чекпоинта, если его размер превышает указанное значение.

PRAGMA ``temp_store=MEMORY`` **не добавляется**: переключение
временных таблиц и сортировок в RAM на больших БД (десятки ГБ)
создаёт риск OOM. Значение по умолчанию SQLite (компиляционная
настройка, обычно FILE) безопаснее для production.
"""

from __future__ import annotations

import sqlite3

from ..domain import config


def create_sqlite_connection(db_path: str) -> sqlite3.Connection:
    """Создаёт и настраивает соединение с базой данных SQLite.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | ``sqlite3.connect(db_path, timeout=...,             |
    |   | check_same_thread=False)`` — открыть соединение.   |
    +---+-----------------------------------------------------+
    | 2 | ``PRAGMA journal_mode=WAL`` — включить режим        |
    |   | Write-Ahead Logging.                                |
    +---+-----------------------------------------------------+
    | 3 | ``PRAGMA synchronous=NORMAL`` — установить режим    |
    |   | синхронизации (ускорение записи).                   |
    +---+-----------------------------------------------------+
    | 4 | ``PRAGMA cache_size=-65536`` — установить кэш       |
    |   | страниц 64 МБ.                                      |
    +---+-----------------------------------------------------+
    | 5 | ``PRAGMA mmap_size=268435456`` — установить размер  |
    |   | memory-mapped I/O 256 МБ.                           |
    +---+-----------------------------------------------------+
    | 6 | ``PRAGMA wal_autocheckpoint=10000`` — установить    |
    |   | порог авто-чекпоинта WAL.                           |
    +---+-----------------------------------------------------+
    | 7 | ``PRAGMA journal_size_limit=67108864`` — установить |
    |   | максимальный размер WAL-журнала (64 МБ).            |
    +---+-----------------------------------------------------+
    | 8 | Если ``DB_FOREIGN_KEYS_ENABLED`` истинно, выполнить |
    |   | ``PRAGMA foreign_keys=ON``.                         |
    +---+-----------------------------------------------------+
    | 9 | Вернуть настроенное соединение.                     |
    +---+-----------------------------------------------------+

    Потокобезопасность:
        Соединение создаётся с параметром ``check_same_thread=False``,
        что позволяет использовать его из разных потоков. Однако
        внешний код (например, ``ConnectionPool``) должен гарантировать,
        что в каждый момент времени соединение используется только
        одним потоком. Это достигается выдачей соединения из пула
        эксклюзивно.

    Примечание о WAL:
        Значения ``DB_WAL_AUTOCHECKPOINT`` (порог авто-чекпоинта)
        и ``DB_JOURNAL_SIZE_LIMIT`` (лимит размера журнала)
        работают совместно. При интенсивной записи SQLite выполняет
        чекпоинт каждые ``wal_autocheckpoint`` страниц, после чего
        усекает журнал до ``journal_size_limit``. Это предотвращает
        неограниченный рост файла ``*.db-wal``.

    Args:
        db_path: Путь к файлу базы данных SQLite. Если файл
            не существует, он будет создан при первом подключении.
            Для тестов можно передать ``":memory:"`` для создания
            in-memory базы данных.

    Returns:
        Настроенное соединение с базой данных SQLite.

    Raises:
        sqlite3.Error: Если подключение или настройка не удалась.
    """
    conn = sqlite3.connect(
        db_path,
        check_same_thread=False,
        timeout=config.DB_BUSY_TIMEOUT_MS / 1000.0,
    )

    conn.execute(f"PRAGMA journal_mode={config.DB_JOURNAL_MODE}")
    conn.execute(f"PRAGMA synchronous={config.DB_SYNCHRONOUS_MODE}")
    conn.execute(f"PRAGMA cache_size={config.DB_CACHE_SIZE_PAGES}")
    conn.execute(f"PRAGMA mmap_size={config.DB_MMAP_SIZE}")
    conn.execute(f"PRAGMA wal_autocheckpoint={config.DB_WAL_AUTOCHECKPOINT}")
    conn.execute(f"PRAGMA journal_size_limit={config.DB_JOURNAL_SIZE_LIMIT}")

    if config.DB_FOREIGN_KEYS_ENABLED:
        conn.execute("PRAGMA foreign_keys=ON")

    return conn
