"""
Асинхронная шина событий DDS.
Модуль реализует шину событий, предназначенную для передачи событий
между компонентами системы с минимальной задержкой и поддержкой
потокобезопасной публикации. Шина использует асинхронную очередь
``asyncio.Queue`` внутри event loop и обеспечивает доставку событий
подписчикам через их собственные очереди.
Ключевые особенности:
+-------------------------------+---------------------------------------+
| Особенность                   | Описание                              |
+===============================+=======================================+
| Потокобезопасная публикация   | Вызов ``publish`` из любого потока    |
|                               | безопасен. Событие всегда ставится    |
|                               | в очередь через                       |
|                               | ``loop.call_soon_threadsafe``.         |
+-------------------------------+---------------------------------------+
| Изоляция подписчиков          | Каждый подписчик получает события    |
|                               | в собственную очередь. Медленный     |
|                               | потребитель не блокирует шину.       |
+-------------------------------+---------------------------------------+
| Фильтрация по типам           | При подписке можно указать множество  |
|                               | интересующих типов событий.          |
+-------------------------------+---------------------------------------+
| Обратное давление             | Очередь каждого подписчика имеет     |
|                               | ограниченный размер. При переполнении |
|                               | событие для этого подписчика          |
|                               | отбрасывается.                        |
+-------------------------------+---------------------------------------+
| Диагностика потерь            | Шина ведёт счётчики потерянных       |
|                               | событий (основная очередь и очереди   |
|                               | подписчиков). Метод                   |
|                               | ``get_queue_stats()`` возвращает      |
|                               | статистику для мониторинга.           |
+-------------------------------+---------------------------------------+
| Проверка наличия подписчиков  | Метод                                |
|                               | ``has_subscribers_for_prefix()``      |
|                               | позволяет проверить, есть ли          |
|                               | подписчики на события с заданным      |
|                               | префиксом, для условной публикации.   |
+-------------------------------+---------------------------------------+
Принципы:
- Шина не знает о логике подписчиков, только доставляет события.
- Все операции с подписками выполняются в event loop.
- Публикация не требует блокировок и не бросает исключений
в вызывающем коде (включая переполнение очереди).
- Потери событий фиксируются счётчиками, но не генерируют
рекурсивных событий ``EventBusOverflow`` для предотвращения
каскадных отказов.
Пример использования::
bus = AsyncEventBus()
await bus.start()
# Подписка на события сканирования
sub = bus.subscribe({"scan.started", "scan.completed"})
# Проверка подписчиков на HTTP-события
if bus.has_subscribers_for_prefix("http."):
    bus.publish(RequestStarted(...))
# Публикация (может быть из любого потока)
bus.publish(ScanStarted(scan_id=1))
# Получение события
event = await sub.get()
# Диагностика потерь
stats = bus.get_queue_stats()
await bus.stop()
"""

from __future__ import annotations

import asyncio

from ..domain.events import Event


class Subscription:
    """
    Подписка на события шины.
    Предоставляет асинхронный интерфейс для получения событий,
    соответствующих заданному фильтру.
    Атрибуты:
    +---------------------+------------------------------------------+
    | Атрибут             | Описание                                 |
    +=====================+==========================================+
    | ``_bus``            | Ссылка на шину событий.                  |
    +---------------------+------------------------------------------+
    | ``event_types``     | Множество типов событий для фильтрации.  |
    |                     | Если ``None`` — принимаются все события. |
    +---------------------+------------------------------------------+
    | ``queue``           | Асинхронная очередь событий для данного  |
    |                     | подписчика.                              |
    +---------------------+------------------------------------------+
    """

    def __init__(
        self,
        bus: AsyncEventBus,
        event_types: set[str] | None,
        max_queue_size: int,
    ) -> None:
        """
        Инициализирует подписку.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ссылки на шину ``bus``.                  |
        +---+-----------------------------------------------------+
        | 2 | Сохранение множества типов событий                   |
        |   | ``event_types``.                                    |
        +---+-----------------------------------------------------+
        | 3 | Создание ``asyncio.Queue(maxsize=max_queue_size)``   |
        |   | для данного подписчика.                             |
        +---+-----------------------------------------------------+
        Args:
            bus: шина событий.
            event_types: множество типов событий для фильтрации.
                Если ``None`` — принимаются все события.
            max_queue_size: максимальный размер очереди подписчика.
        """
        self._bus = bus
        self.event_types = event_types
        self.queue: asyncio.Queue[Event] = asyncio.Queue(maxsize=max_queue_size)

    async def get(self) -> Event:
        """
        Возвращает следующее событие из очереди подписчика.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | ``await self.queue.get()`` — блокирующее ожидание   |
        |   | события из очереди.                                 |
        +---+-----------------------------------------------------+
        | 2 | Возврат полученного события.                        |
        +---+-----------------------------------------------------+
        Блокирует выполнение до появления события. Если очередь
        пуста, ожидает новое событие.
        Returns:
            Событие, соответствующее фильтру подписки.
        """
        return await self.queue.get()

    def unsubscribe(self) -> None:
        """
        Удаляет подписку из шины.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Вызов ``self._bus._unsubscribe(self)``.             |
        +---+-----------------------------------------------------+
        После вызова подписчик перестаёт получать события.
        Повторный вызов безопасен.
        """
        self._bus._unsubscribe(self)


class AsyncEventBus:
    """
    Асинхронная шина событий.
    Принимает события от производителей и доставляет их подписчикам
    в асинхронном режиме. Реализована на основе ``asyncio.Queue``.
    Атрибуты:
    +-------------------------------+--------------------------------------+
    | Атрибут                       | Описание                             |
    +===============================+======================================+
    | ``_queue``                    | Основная очередь событий шины.       |
    +-------------------------------+--------------------------------------+
    | ``_subscribers``              | Список активных подписок.            |
    +-------------------------------+--------------------------------------+
    | ``_task``                     | Задача, выполняющая цикл доставки.   |
    +-------------------------------+--------------------------------------+
    | ``_running``                  | Флаг работы шины.                    |
    +-------------------------------+--------------------------------------+
    | ``_loop``                     | Event loop, в котором работает шина. |
    +-------------------------------+--------------------------------------+
    | ``_dropped_events_total``     | Счётчик событий, потерянных из-за    |
    |                               | переполнения основной очереди.       |
    +-------------------------------+--------------------------------------+
    | ``_subscriber_dropped_total`` | Счётчик событий, потерянных из-за    |
    |                               | переполнения очередей подписчиков.   |
    +-------------------------------+--------------------------------------+
    """

    def __init__(self, max_queue_size: int = 1000) -> None:
        """
        Инициализирует шину.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Создание ``asyncio.Queue(maxsize=max_queue_size)``   |
        |   | для основной очереди событий.                       |
        +---+-----------------------------------------------------+
        | 2 | Инициализация пустого списка подписчиков.           |
        +---+-----------------------------------------------------+
        | 3 | Инициализация ``_task = None``.                     |
        +---+-----------------------------------------------------+
        | 4 | Установка ``_running = False``.                     |
        +---+-----------------------------------------------------+
        | 5 | Установка ``_loop = None``.                         |
        +---+-----------------------------------------------------+
        | 6 | Инициализация счётчиков потерь нулями.              |
        +---+-----------------------------------------------------+
        Args:
            max_queue_size: максимальный размер основной очереди.
                При переполнении новые события отбрасываются.
        """
        self._queue: asyncio.Queue[Event] = asyncio.Queue(maxsize=max_queue_size)
        self._subscribers: list[Subscription] = []
        self._task: asyncio.Task | None = None
        self._running = False
        self._loop: asyncio.AbstractEventLoop | None = None
        self._dropped_events_total: int = 0
        self._subscriber_dropped_events_total: int = 0

    def publish(self, event: Event) -> None:
        """
        Публикует событие в шине.
        Метод полностью потокобезопасен. Если шина не запущена
        (``_loop is None`` или ``_running == False``), событие
        игнорируется. Публикация из любого потока (включая
        ``asyncio.to_thread``) выполняется через
        ``loop.call_soon_threadsafe()``, что гарантирует безопасную
        вставку в очередь.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка ``_loop is None or not _running``.         |
        |   | Если шина не запущена — выход.                      |
        +---+-----------------------------------------------------+
        | 2 | Определение замыкания ``_safe_put``.                |
        +---+-----------------------------------------------------+
        | 3 | Попытка ``self._queue.put_nowait(event)``.          |
        +---+-----------------------------------------------------+
        | 4 | При ``asyncio.QueueFull``:                          |
        |   | a. Инкремент ``_dropped_events_total``.             |
        |   | b. Событие отбрасывается.                           |
        |   | Исключение не бросается.                            |
        +---+-----------------------------------------------------+
        | 5 | Планирование ``_safe_put`` через                    |
        |   | ``self._loop.call_soon_threadsafe``.                |
        +---+-----------------------------------------------------+
        Примечание:
            При переполнении основной очереди событие отбрасывается
            молча. Счётчик ``_dropped_events_total`` увеличивается,
            но событие ``EventBusOverflow`` НЕ публикуется для
            предотвращения рекурсивной нагрузки. Диагностика
            выполняется через метод ``get_queue_stats()``.
        Args:
            event: Событие для публикации.
        """
        if self._loop is None or not self._running:
            return

        def _safe_put() -> None:
            try:
                self._queue.put_nowait(event)
            except asyncio.QueueFull:
                # Очередь переполнена — событие отбрасывается.
                # Увеличиваем счётчик потерь для диагностики.
                self._dropped_events_total += 1

        self._loop.call_soon_threadsafe(_safe_put)

    def subscribe(
        self,
        event_types: set[str] | None = None,
        max_queue_size: int = 100,
    ) -> Subscription:
        """
        Создаёт подписку на события.
        Подписка имеет собственную очередь, в которую шина будет
        помещать события, прошедшие фильтр. Если ``event_types``
        равно ``None``, подписчик получает все события.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Создание ``Subscription(self, event_types,          |
        |   | max_queue_size)``.                                  |
        +---+-----------------------------------------------------+
        | 2 | Добавление подписки в ``_subscribers``.             |
        +---+-----------------------------------------------------+
        | 3 | Возврат объекта подписки.                           |
        +---+-----------------------------------------------------+
        Подписка должна быть удалена через ``unsubscribe()``
        по завершении использования.
        Примечание:
            Если очередь подписчика переполнена, события для этого
            подписчика отбрасываются, а счётчик
            ``_subscriber_dropped_events_total`` увеличивается.
            Это не блокирует доставку другим подписчикам.
        Args:
            event_types: множество строковых идентификаторов событий.
                Если ``None`` — без фильтрации.
            max_queue_size: максимальный размер очереди подписчика.
        Returns:
            Объект подписки, через который можно получать события.
        """
        sub = Subscription(self, event_types, max_queue_size)
        self._subscribers.append(sub)
        return sub

    def has_subscribers_for_prefix(self, prefix: str) -> bool:
        """
        Проверяет наличие подписчиков на события с заданным префиксом.
        Используется для условной публикации событий, когда
        публикация не требуется, если нет заинтересованных подписчиков.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Для каждой активной подписки:                       |
        |   | a. Если подписка не имеет фильтра типов             |
        |   |    (``event_types is None``), возврат ``True``.      |
        |   | b. Если хотя бы один тип начинается с ``prefix``,   |
        |   |    возврат ``True``.                                |
        +---+-----------------------------------------------------+
        | 2 | Если ни одна подписка не соответствует, возврат     |
        |   | ``False``.                                          |
        +---+-----------------------------------------------------+
        Args:
            prefix: Строковый префикс (например, ``"http."``).
        Returns:
            ``True``, если есть хотя бы один подписчик,
            заинтересованный в событиях с данным префиксом.
            ``False`` в противном случае.
        """
        for sub in self._subscribers:
            if sub.event_types is None:
                return True
            if any(t.startswith(prefix) for t in sub.event_types):
                return True
        return False

    def _unsubscribe(self, sub: Subscription) -> None:
        """
        Удаляет подписку из списка активных.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка наличия ``sub`` в ``_subscribers``.        |
        +---+-----------------------------------------------------+
        | 2 | Если присутствует — удаление из списка.             |
        +---+-----------------------------------------------------+
        Вызывается из метода ``Subscription.unsubscribe``.
        Повторный вызов безопасен.
        Args:
            sub: подписка для удаления.
        """
        if sub in self._subscribers:
            self._subscribers.remove(sub)

    async def start(self) -> None:
        """
        Запускает шину в текущем event loop.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Сохранение ссылки на текущий event loop через       |
        |   | ``asyncio.get_running_loop()``.                     |
        +---+-----------------------------------------------------+
        | 2 | Установка ``_running = True``.                      |
        +---+-----------------------------------------------------+
        | 3 | Создание задачи ``asyncio.create_task(self._run())``|
        |   | и сохранение в ``_task``.                           |
        +---+-----------------------------------------------------+
        Должен вызываться один раз перед публикацией событий.
        """
        self._loop = asyncio.get_running_loop()
        self._running = True
        self._task = asyncio.create_task(self._run())

    async def stop(self) -> None:
        """
        Останавливает шину и завершает задачу доставки.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Установка ``_running = False``.                     |
        +---+-----------------------------------------------------+
        | 2 | Если ``_task is not None``:                         |
        |   | a. Отмена задачи ``_task.cancel()``.                |
        |   | b. Ожидание завершения с подавлением                |
        |   |    ``CancelledError``.                              |
        |   | c. Установка ``_task = None``.                      |
        +---+-----------------------------------------------------+
        После вызова шина прекращает обработку новых событий.
        Ожидает завершения задачи доставки (отменяет её, если
        она ожидает события).
        """
        self._running = False
        if self._task is not None:
            self._task.cancel()
            try:
                await self._task
            except asyncio.CancelledError:
                pass
            self._task = None

    def get_queue_stats(self) -> dict[str, int]:
        """
        Возвращает статистику шины событий для диагностики.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Формирование словаря со статистикой.                |
        +---+-----------------------------------------------------+
        | 2 | Возврат словаря.                                    |
        +---+-----------------------------------------------------+
        Возвращаемый словарь содержит:
        +----------------------------------+---------------------------+
        | Ключ                             | Описание                  |
        +==================================+===========================+
        | ``"queue_size"``                 | Текущий размер основной   |
        |                                  | очереди событий.          |
        +----------------------------------+---------------------------+
        | ``"dropped_events_total"``       | Общее количество событий, |
        |                                  | потерянных из-за          |
        |                                  | переполнения основной     |
        |                                  | очереди.                  |
        +----------------------------------+---------------------------+
        | ``"subscriber_count"``           | Количество активных       |
        |                                  | подписчиков.              |
        +----------------------------------+---------------------------+
        | ``"subscriber_dropped_total"``   | Общее количество событий, |
        |                                  | потерянных из-за          |
        |                                  | переполнения очередей     |
        |                                  | подписчиков.              |
        +----------------------------------+---------------------------+
        | ``"running"``                    | Флаг работы шины          |
        |                                  | (1 — работает, 0 — нет). |
        +----------------------------------+---------------------------+
        Примечание:
            Метод потокобезопасен для чтения, так как читает только
            целочисленные счётчики и размер очереди. В контексте
            многопоточного доступа значения являются приближёнными
            на момент чтения, но достаточны для мониторинга.
            Событие ``EventBusOverflow`` НЕ публикуется
            автоматически для предотвращения рекурсивной нагрузки
            при переполнении. Вместо этого используется данный
            метод для диагностики.
        Returns:
            Словарь со статистикой шины событий.
        """
        return {
            "queue_size": self._queue.qsize(),
            "dropped_events_total": self._dropped_events_total,
            "subscriber_count": len(self._subscribers),
            "subscriber_dropped_total": self._subscriber_dropped_events_total,
            "running": 1 if self._running else 0,
        }

    async def _run(self) -> None:
        """
        Цикл доставки событий подписчикам.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Пока ``_running`` истинно:                          |
        +---+-----------------------------------------------------+
        | 2 | ``event = await self._queue.get()`` — блокирующее   |
        |   | ожидание события из основной очереди.               |
        +---+-----------------------------------------------------+
        | 3 | Для каждого подписчика в ``_subscribers``:          |
        |   | a. Проверка соответствия события фильтру            |
        |   |    подписчика через ``_matches``.                   |
        |   | b. Если соответствует — попытка                     |
        |   |    ``sub.queue.put_nowait(event)``.                 |
        |   | c. При ``asyncio.QueueFull``:                       |
        |   |    - Инкремент ``_subscriber_dropped_events_total``.|
        |   |    - Событие пропускается только для этого          |
        |   |      подписчика.                                    |
        +---+-----------------------------------------------------+
        Читает события из основной очереди и раскладывает их
        по очередям подписчиков с учётом фильтров. Если очередь
        подписчика заполнена, событие отбрасывается, а счётчик
        потерь увеличивается.
        Примечание:
            При переполнении очереди конкретного подписчика событие
            отбрасывается только для него. Доставка другим
            подписчикам продолжается нормально. Это обеспечивает
            изоляцию медленных потребителей от остальных.
        """
        while self._running:
            event = await self._queue.get()
            for sub in self._subscribers:
                if self._matches(sub, event):
                    try:
                        sub.queue.put_nowait(event)
                    except asyncio.QueueFull:
                        # Переполнение у конкретного подписчика.
                        # Событие пропускается только для него.
                        # Увеличиваем счётчик потерь для диагностики.
                        self._subscriber_dropped_events_total += 1

    @staticmethod
    def _matches(sub: Subscription, event: Event) -> bool:
        """
        Проверяет, соответствует ли событие фильтру подписки.
        Операции:
        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Если ``sub.event_types is None`` → возврат ``True`` |
        |   | (подписчик принимает все события).                  |
        +---+-----------------------------------------------------+
        | 2 | Проверка ``event.event_type in sub.event_types``.   |
        +---+-----------------------------------------------------+
        | 3 | Возврат результата проверки.                        |
        +---+-----------------------------------------------------+
        Args:
            sub: подписка.
            event: событие.
        Returns:
            ``True``, если событие должно быть доставлено подписчику.
            ``False`` в противном случае.
        """
        if sub.event_types is None:
            return True
        return event.event_type in sub.event_types
