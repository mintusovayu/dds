"""
Сборка FTS5 MATCH-выражения из списка токенов поискового запроса.

Модуль принимает структурированное представление запроса —
список :class:`~dds_core.application.query_tokenizer.QueryToken`
от :func:`~dds_core.application.query_tokenizer.tokenize_search_query`
— и формирует строку, пригодную для использования в конструкции
``MATCH`` FTS5.

Специфика FTS5, сосредоточенная в этом модуле:

+----------------------------------+----------------------------------+
| Особенность                      | Реализация                       |
+==================================+==================================+
| **Колонка нормализованного       | К каждому слову и фразе           |
| текста**                         | добавляется префикс               |
|                                  | ``normalized_text:`` — поиск      |
|                                  | выполняется только по             |
|                                  | нормализованной колонке          |
|                                  | ``text_index_fts``.               |
+----------------------------------+----------------------------------+
| **Нормализация текста**          | Текст слова или фразы             |
|                                  | пропускается через                |
|                                  | :func:`dds_core.domain.           |
|                                  | text_normalization.               |
|                                  | normalize_text` (lower +          |
|                                  | замена визуально похожих          |
|                                  | кириллических символов на         |
|                                  | латинские по таблице              |
|                                  | ``CYRILLIC_TO_LATIN_MAP``).       |
+----------------------------------+----------------------------------+
| **Фразы в двойных кавычках**     | :class:`PhraseToken`               |
|                                  | оборачивается в ``"..."`` вместе  |
|                                  | с префиксом колонки:              |
|                                  | ``normalized_text: "..."``.       |
+----------------------------------+----------------------------------+
| **Операторы и скобки**           | Переносятся как есть:              |
|                                  | ``AND``, ``OR``, ``NOT``, ``(``,   |
|                                  | ``)``. FTS5 интерпретирует их     |
|                                  | согласно синтаксису ``MATCH``.    |
|                                  | Префикс колонки к ним не           |
|                                  | применяется.                       |
+----------------------------------+----------------------------------+

Частичная (не полная) нормализация кириллицы
---------------------------------------------

``normalize_text`` выполняет **частичную** замену: только символы
из :data:`~dds_core.domain.text_normalization.CYRILLIC_TO_LATIN_MAP`
(12 пар визуально похожих символов: ``а→a``, ``в→b``, ``е→e``,
``к→k``, ``м→m``, ``н→h``, ``о→o``, ``р→p``, ``с→c``, ``т→t``,
``у→y``, ``х→x``). Символы, отсутствующие в таблице (``г``, ``д``,
``ш``, ``п``, ``б`` и другие), остаются кириллическими.

Например, для слова ``гидрошпонка``: ``г``, ``и``, ``д``, ``ш``,
``п`` не заменяются; ``р→p``, ``о→o``, ``н→h``, ``к→k``, ``а→a``.
Результат — ``гидpoшпohka`` (визуально смешанная кириллица и
латиница).

Это осознанное решение задачи **нечувствительности к раскладке
клавиатуры**, а не «перевода на латиницу». Пользователь,
набравший ``ЕС-423-1`` в русской раскладке и ``EC-423-1`` в
английской, получит одинаковые результаты поиска. Полная
транслитерация не требуется и не выполняется. Примеры в
docstring ниже отражают именно это поведение. См. ADR-003.

Разделение ответственности
--------------------------

Модуль — **инфраструктурный**. Он знает о FTS5-специфике
(префикс колонки, синтаксис ``MATCH``), но не о структуре
запроса. Структуру запроса разбирает
:func:`~dds_core.application.query_tokenizer.tokenize_search_query`
— application-модуль, не зависящий от конкретного поискового
движка. Такое разделение позволяет заменить FTS5 на другой
бэкенд, не затрагивая application-код: новый бэкенд получит
собственный сборщик, работающий с тем же набором токенов
:data:`~dds_core.application.query_tokenizer.QueryToken`.

Принципы:
    - Модуль зависит от application (токенизатор) и domain
      (нормализация текста), но не от других модулей
      infrastructure.
    - Discriminated union ``QueryToken`` позволяет сборщику
      явно различать типы через ``isinstance``: при добавлении
      нового типа токена (например, ``WildcardToken``)
      сборщик получит явный сигнал о необходимости обработки.
    - Чистые функции: детерминированные, без побочных эффектов,
      без изменяемого состояния.
"""

from __future__ import annotations

from dds_core.application.query_tokenizer import (
    OperatorToken,
    ParenToken,
    PhraseToken,
    QueryToken,
    WordToken,
    tokenize_search_query,
)
from dds_core.domain.text_normalization import normalize_text

# ----------------------------------------------------------------------
# Сборка MATCH-выражения
# ----------------------------------------------------------------------

_FTS5_NORMALIZED_COLUMN: str = "normalized_text"
"""Имя колонки FTS5, по которой выполняется поиск.

Соответствует колонке ``normalized_text`` виртуальной таблицы
``text_index_fts`` (см. ``dds_core/infrastructure/database.py``).
Поиск всегда ведётся по этой колонке — это обеспечивает
нечувствительность к раскладке клавиатуры.
"""


def build_match_expression(tokens: list[QueryToken]) -> str:
    """Собирает FTS5 MATCH-выражение из списка токенов.

    Операции:

    +----+-----------------------------------------------------+
    | №  | Описание                                            |
    +====+=====================================================+
    | 1  | Если ``tokens`` пуст — возврат пустой строки.       |
    +----+-----------------------------------------------------+
    | 2  | Для каждого токена:                                 |
    |    | a. :class:`WordToken` → нормализация + префикс      |
    |    |    ``normalized_text:``.                            |
    |    | b. :class:`PhraseToken` → нормализация + фраза в    |
    |    |    кавычках с префиксом                             |
    |    |    ``normalized_text: "..."``.                      |
    |    | c. :class:`OperatorToken` → оператор как есть.      |
    |    | d. :class:`ParenToken` → скобка как есть.           |
    +----+-----------------------------------------------------+
    | 3  | Объединение частей через пробел.                    |
    +----+-----------------------------------------------------+

    Примечание:
        Порядок элементов в результирующей строке совпадает с
        порядком токенов — FTS5 интерпретирует выражение
        последовательно, включая операторы и скобки.

    Примечание:
        Нормализация текста — частичная (см. module docstring):
        заменяются только символы из ``CYRILLIC_TO_LATIN_MAP``.
        Например, ``гидрошпонка`` → ``гидpoшпohka`` (не
        ``gidroshponka``). Примеры ниже отражают именно это
        поведение.

    Args:
        tokens: Список токенов поискового запроса, полученный
            от
            :func:`~dds_core.application.query_tokenizer.tokenize_search_query`.
            Может быть пустым.

    Returns:
        Строка MATCH-выражения FTS5. Пустая строка, если ``tokens``
        пуст — это соответствует семантике «пустой запрос».

    Example:
        >>> from dds_core.application.query_tokenizer import tokenize_search_query
        >>> tokens = tokenize_search_query('гидрошпонка AND "корпус крупного дробления"')
        >>> build_match_expression(tokens)
        'normalized_text: гидpoшпohka AND normalized_text: "kopпyc kpyпhoгo дpoблehия"'

        >>> build_match_expression([])
        ''
    """
    if not tokens:
        return ""

    parts: list[str] = []

    for token in tokens:
        if isinstance(token, WordToken):
            normalized_word = normalize_text(token.text)
            parts.append(f"{_FTS5_NORMALIZED_COLUMN}: {normalized_word}")
        elif isinstance(token, PhraseToken):
            normalized_phrase = normalize_text(token.text)
            parts.append(f'{_FTS5_NORMALIZED_COLUMN}: "{normalized_phrase}"')
        elif isinstance(token, OperatorToken):
            parts.append(token.op)
        elif isinstance(token, ParenToken):
            parts.append(token.char)

    return " ".join(parts)


def normalize_search_query(query: str) -> str:
    """Преобразует поисковый запрос в FTS5 MATCH-выражение.

    Удобная обёртка над
    :func:`~dds_core.application.query_tokenizer.tokenize_search_query`
    и :func:`build_match_expression`, сохраняющая привычный API
    для потребителя (``dds_core/infrastructure/fts5_search_backend.py``).
    Заменяет удалённую функцию ``normalize_search_query`` из
    ``dds_core/application/search_query_normalizer.py`` без
    изменения поведения.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | ``tokenize_search_query(query)`` → список токенов.  |
    +---+-----------------------------------------------------+
    | 2 | ``build_match_expression(tokens)`` → MATCH-строка.  |
    +---+-----------------------------------------------------+
    | 3 | Возврат результата.                                 |
    +---+-----------------------------------------------------+

    Примечание:
        Функция идемпотентна: повторный вызов с той же строкой
        даёт тот же результат. Не имеет побочных эффектов.

    Примечание:
        Нормализация текста — частичная (см. module docstring).
        Примеры ниже отражают именно это поведение.

    Args:
        query: Поисковый запрос. Может содержать логические
            операторы (``AND``, ``OR``, ``NOT``), фразы в двойных
            кавычках и круглые скобки. Может быть пустым.

    Returns:
        Строка MATCH-выражения FTS5. Пустая строка при пустом
        запросе.

    Example:
        >>> normalize_search_query('гидрошпонка AND "корпус крупного дробления"')
        'normalized_text: гидpoшпohka AND normalized_text: "kopпyc kpyпhoгo дpoблehия"'

        >>> normalize_search_query('(ЕС-423-1 OR EC-423-1) NOT KM')
        '( normalized_text: ec-423-1 OR normalized_text: ec-423-1 ) NOT normalized_text: km'

        >>> normalize_search_query('')
        ''
    """
    tokens = tokenize_search_query(query)
    return build_match_expression(tokens)
