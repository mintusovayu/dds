"""
Сборка FTS5 MATCH-выражения из последовательности токенов поискового
запроса.

Модуль принимает структурированное представление запроса —
последовательность
:class:`~dds_core.application.query_tokenizer.QueryToken`
от :func:`~dds_core.application.query_tokenizer.tokenize_search_query`
— и формирует строку, пригодную для использования в конструкции
``MATCH`` FTS5.

Специфика FTS5, сосредоточенная в этом модуле:

+----------------------------------+----------------------------------+
| Особенность                      | Реализация                       |
+==================================+==================================+
| **Колонка нормализованного       | К каждому слову и фразе           |
| текста**                         | добавляется префикс               |
|                                  | ``normalized_text:`` — поиск      |
|                                  | выполняется только по             |
|                                  | нормализованной колонке           |
|                                  | ``text_index_fts``.               |
+----------------------------------+----------------------------------+
| **Нормализация текста**          | Текст слова или фразы             |
|                                  | пропускается через                |
|                                  | :func:`dds_core.domain.           |
|                                  | text_normalization.               |
|                                  | normalize_text` (lower +          |
|                                  | замена визуально похожих          |
|                                  | кириллических символов на         |
|                                  | латинские по таблице              |
|                                  | ``CYRILLIC_TO_LATIN_MAP``).       |
+----------------------------------+----------------------------------+
| **Экранирование спецсимволов**   | Одиночные слова (``WordToken``),  |
| (Фаза 8, ADR-008)                | содержащие FTS5-спецсимволы       |
|                                  | (``-``, ``+``, ``*``, ``:``,      |
|                                  | ``^``, ``(){}``, ``"``),          |
|                                  | оборачиваются в двойные кавычки   |
|                                  | с удвоением внутренних ``"``.     |
|                                  | См. :func:`_build_word_match`.     |
+----------------------------------+----------------------------------+
| **Префиксный поиск**             | Trailing ``*`` в одиночном слове  |
| (Фаза 8)                         | сохраняет prefix-семантику FTS5:  |
|                                  | ``гидро*`` → ``гидpo*`` (без      |
|                                  | кавычек). При сочетании           |
|                                  | спецсимволов и trailing ``*``     |
|                                  | последний отбрасывается —         |
|                                  | см. :func:`_build_word_match`.     |
+----------------------------------+----------------------------------+
| **Фразы в двойных кавычках**     | :class:`PhraseToken`              |
|                                  | оборачивается в ``"..."`` вместе  |
|                                  | с префиксом колонки:              |
|                                  | ``normalized_text: "..."``.       |
|                                  | Экранирование не применяется —    |
|                                  | токенизатор не позволяет ``"``    |
|                                  | внутри фразы (regex ``[^"]*``).   |
+----------------------------------+----------------------------------+
| **Операторы и скобки**           | Переносятся как есть:             |
|                                  | ``AND``, ``OR``, ``NOT``, ``(``,  |
|                                  | ``)``. FTS5 интерпретирует их     |
|                                  | согласно синтаксису ``MATCH``.    |
|                                  | Префикс колонки к ним не          |
|                                  | применяется.                      |
+----------------------------------+----------------------------------+

Частичная (не полная) нормализация кириллицы
---------------------------------------------

``normalize_text`` выполняет **частичную** замену: только символы
из :data:`~dds_core.domain.text_normalization.CYRILLIC_TO_LATIN_MAP`
(12 пар визуально похожих символов: ``а→a``, ``в→b``, ``е→e``,
``к→k``, ``м→m``, ``н→h``, ``о→o``, ``р→p``, ``с→c``, ``т→t``,
``у→y``, ``х→x``). Символы, отсутствующие в таблице (``г``, ``д``,
``ш``, ``п``, ``б`` и другие), остаются кириллическими.

Например, для слова ``гидрошпонка``: ``г``, ``и``, ``д``, ``ш``,
``п`` не заменяются; ``р→p``, ``о→o``, ``н→h``, ``к→k``, ``а→a``.
Результат — ``гидpoшпohka`` (визуально смешанная кириллица и
латиница).

Это осознанное решение задачи **нечувствительности к раскладке
клавиатуры**, а не «перевода на латиницу». Пользователь,
набравший ``ЕС-423-1`` в русской раскладке и ``EC-423-1`` в
английской, получит одинаковые результаты поиска. Полная
транслитерация не требуется и не выполняется. См. ADR-003.

Экранирование FTS5-спецсимволов (Фаза 8)
-----------------------------------------

Одиночные слова (``WordToken``), содержащие в тексте символы
``-``, ``+``, ``:``, ``^``, ``"``, ``(){}`` или ``*`` (в середине
токена), интерпретируются FTS5 как синтаксические операторы.
Пример: ``EC-423-1`` парсится как ``ec`` ``-`` ``423`` ``-``
``1``, что приводит к ошибке
``sqlite3.OperationalError: no such column: 423``.

Функция :func:`_build_word_match` оборачивает такие слова в
двойные кавычки (FTS5-quoting), превращая их в единый
phrase-термин. Внутренние ``"`` удваиваются по правилам FTS5.
Префикс ``normalized_text:`` при этом остаётся снаружи кавычек.

Префиксный поиск: trailing ``*`` обрабатывается отдельно. Для
слов без спецсимволов он переносится за нормализованный текст
(``гидpo*`` — prefix-семантика сохранена). Для слов со
спецсимволами trailing ``*`` отбрасывается — prefix-поиск после
unicode61-токенизации ``EC-423-*`` не имеет однозначной
семантики. Это осознанное ограничение, задокументированное в
:func:`_build_word_match`.

Разделение ответственности
--------------------------

Модуль — **инфраструктурный**. Он знает о FTS5-специфике
(префикс колонки, синтаксис ``MATCH``, экранирование), но не
о структуре запроса. Структуру запроса разбирает
:func:`~dds_core.application.query_tokenizer.tokenize_search_query`
— application-модуль, не зависящий от конкретного поискового
движка. Такое разделение позволяет заменить FTS5 на другой
бэкенд, не затрагивая application-код: новый бэкенд получит
собственный сборщик, работающий с тем же набором токенов
:data:`~dds_core.application.query_tokenizer.QueryToken`.

Типизация параметра ``tokens``
------------------------------

Параметр ``tokens`` функции :func:`build_match_expression`
типизирован как :class:`collections.abc.Sequence`, а не ``list``.
Причина: ``list`` **инвариантен**, и ``list[WordToken]`` не
является ``list[QueryToken]``, что приводит к ошибке типизации
при передаче однородных списков.
:class:`collections.abc.Sequence` **ковариантен**:
``Sequence[WordToken]`` является ``Sequence[QueryToken]``,
поэтому функция принимает как гетерогенные ``list[QueryToken]``,
так и однородные ``list[WordToken]`` без явных аннотаций.

Принципы:
    - Модуль зависит от application (токенизатор) и domain
      (нормализация текста), но не от других модулей
      infrastructure.
    - Discriminated union ``QueryToken`` позволяет сборщику
      явно различать типы через ``isinstance``: при добавлении
      нового типа токена (например, ``WildcardToken``)
      сборщик получит явный сигнал о необходимости обработки.
    - Чистые функции: детерминированные, без побочных эффектов,
      без изменяемого состояния.
"""

from __future__ import annotations

from collections.abc import Sequence

from dds_core.application.query_tokenizer import (
    OperatorToken,
    ParenToken,
    PhraseToken,
    QueryToken,
    WordToken,
    tokenize_search_query,
)
from dds_core.domain.text_normalization import normalize_text

# ----------------------------------------------------------------------
# Константы
# ----------------------------------------------------------------------

_FTS5_NORMALIZED_COLUMN: str = "normalized_text"
"""Имя колонки FTS5, по которой выполняется поиск.

Соответствует колонке ``normalized_text`` виртуальной таблицы
``text_index_fts`` (см. ``dds_core/infrastructure/database.py``).
Поиск всегда ведётся по этой колонке — это обеспечивает
нечувствительность к раскладке клавиатуры.
"""

_FTS5_SPECIAL_CHARS: frozenset[str] = frozenset('-+*:^(){}"')
"""Символы FTS5-синтаксиса, требующие экранирования в одиночном слове.

Список по документации SQLite FTS5:

- ``-`` — разделитель / NOT-подобный оператор;
- ``+`` — AND-оператор;
- ``*`` — prefix-оператор (для символа в середине слова;
  trailing ``*`` обрабатывается отдельно в
  :func:`_build_word_match`);
- ``:`` — префикс колонки;
- ``^`` — оператор «первое слово колонки»;
- ``()`` и ``{}`` — группировка (``{}`` зарезервированы);
- ``"`` — граница фразы.

Если хотя бы один из символов присутствует в нормализованном
тексте ``WordToken``, слово оборачивается в двойные кавычки.
"""


# ----------------------------------------------------------------------
# Формирование FTS5-части для одного слова
# ----------------------------------------------------------------------


def _build_word_match(raw_text: str) -> str:
    """Формирует FTS5-часть MATCH-выражения для :class:`WordToken`.

    Обрабатывает три случая:

    +----------------------------------+----------------------------------+
    | Вход                             | Результат                        |
    +==================================+==================================+
    | Слово без спецсимволов, без ``*`` | ``normalize_text(core)``         |
    | (``гидрошпонка``)                | (``гидpoшпohka``)                |
    +----------------------------------+----------------------------------+
    | Слово без спецсимволов с         | ``normalize_text(core) + "*"``   |
    | trailing ``*`` (``гидро*``)      | (``гидpo*`` — prefix-поиск)      |
    +----------------------------------+----------------------------------+
    | Слово со спецсимволами           | ``'"' + normalize_text(core)     |
    | (``EC-423-1``, ``a"b``)          | ``.replace('"', '""') + '"'``    |
    |                                  | (``"ec-423-1"``, ``"a""b"``)     |
    +----------------------------------+----------------------------------+
    | Спецсимволы + trailing ``*``     | То же, что выше — trailing ``*`` |
    | (``EC-423-*``)                   | **отбрасывается**                |
    |                                  | (``"ec-423-"``)                  |
    +----------------------------------+----------------------------------+

    Операции:

    +----+-----------------------------------------------------+
    | №  | Описание                                            |
    +====+=====================================================+
    | 1  | ``has_prefix = raw_text.endswith("*")``.            |
    +----+-----------------------------------------------------+
    | 2  | ``core = raw_text[:-1]`` при ``has_prefix``, иначе  |
    |    | ``core = raw_text``.                                 |
    +----+-----------------------------------------------------+
    | 3  | ``normalized = normalize_text(core)``.              |
    +----+-----------------------------------------------------+
    | 4  | Проверка наличия спецсимволов в ``normalized``      |
    |    | через пересечение с :data:`_FTS5_SPECIAL_CHARS`.    |
    +----+-----------------------------------------------------+
    | 5  | Если спецсимволов нет:                              |
    |    | ``return normalized + ("*" if has_prefix else "")``.|
    +----+-----------------------------------------------------+
    | 6  | Если спецсимволы есть:                              |
    |    | a. ``escaped = normalized.replace('"', '""')``.     |
    |    | b. ``return f'"{escaped}"'`` (без trailing ``*``).  |
    +----+-----------------------------------------------------+

    **Обоснование отбрасывания trailing ``*`` при спецсимволах.**
    FTS5-синтаксис ``"phrase"*`` имеет неоднозначную семантику:
    префикс применяется только к последнему токену фразы, а после
    unicode61-токенизации ``EC-423-*`` распадается на несколько
    токенов, и prefix-семантика становится непредсказуемой.
    Отбрасывание ``*`` даёт стабильный phrase-поиск вместо
    сюрпризов для пользователя.

    **Порядок замены.** Внутренние ``"`` удваиваются **до**
    оборачивания в кавычки. Если поменять порядок, удвоение
    затронет и внешние кавычки, что сломает экранирование.

    Args:
        raw_text: Оригинальный текст слова (до нормализации).
            Может содержать спецсимволы FTS5 и/или trailing ``*``.

    Returns:
        Строка для подстановки в MATCH-выражение после префикса
        ``normalized_text:``. Для слов без спецсимволов — просто
        нормализованный текст (опционально с ``*``). Для слов со
        спецсимволами — нормализованный текст, обёрнутый в
        двойные кавычки.

    Example:
        ::

            >>> _build_word_match("гидрошпонка")
            'гидpoшпohka'
            >>> _build_word_match("гидро*")
            'гидpo*'
            >>> _build_word_match("EC-423-1")
            '"ec-423-1"'
            >>> _build_word_match("EC-423-*")
            '"ec-423-"'
            >>> _build_word_match('a"b')
            '"a""b"'
    """
    has_prefix = raw_text.endswith("*")
    core = raw_text[:-1] if has_prefix else raw_text
    normalized = normalize_text(core)

    if not any(ch in _FTS5_SPECIAL_CHARS for ch in normalized):
        return normalized + ("*" if has_prefix else "")

    # Спецсимволы есть — оборачиваем. Trailing '*' отбрасывается.
    escaped = normalized.replace('"', '""')
    return f'"{escaped}"'


# ----------------------------------------------------------------------
# Сборка MATCH-выражения
# ----------------------------------------------------------------------


def build_match_expression(tokens: Sequence[QueryToken]) -> str:
    """Собирает FTS5 MATCH-выражение из последовательности токенов.

    Операции:

    +----+-----------------------------------------------------+
    | №  | Описание                                            |
    +====+=====================================================+
    | 1  | Если ``tokens`` пуст — возврат пустой строки.       |
    +----+-----------------------------------------------------+
    | 2  | Для каждого токена:                                 |
    |    | a. :class:`WordToken` → :func:`_build_word_match`   |
    |    |    с префиксом колонки.                             |
    |    | b. :class:`PhraseToken` → нормализация + фраза в    |
    |    |    кавычках с префиксом                             |
    |    |    ``normalized_text: "..."``.                      |
    |    | c. :class:`OperatorToken` → оператор как есть.      |
    |    | d. :class:`ParenToken` → скобка как есть.           |
    +----+-----------------------------------------------------+
    | 3  | Объединение частей через пробел.                    |
    +----+-----------------------------------------------------+

    Примечание:
        Порядок элементов в результирующей строке совпадает с
        порядком токенов — FTS5 интерпретирует выражение
        последовательно, включая операторы и скобки.

    Примечание:
        Нормализация текста — частичная (см. module docstring):
        заменяются только символы из ``CYRILLIC_TO_LATIN_MAP``.
        Например, ``гидрошпонка`` → ``гидpoшпohka`` (не
        ``gidroshponka``). Примеры ниже отражают именно это
        поведение.

    Примечание:
        Экранирование FTS5-спецсимволов выполняется только для
        :class:`WordToken` (через :func:`_build_word_match`).
        :class:`PhraseToken` уже обёрнут в кавычки на уровне
        токенизатора — дополнительное экранирование не требуется,
        так как regex ``[^"]*`` не допускает ``"`` внутри фразы.

    Примечание:
        Параметр типизирован как :class:`collections.abc.Sequence`
        (не ``list``): ``list`` инвариантен, и ``list[WordToken]``
        не является ``list[QueryToken]``. ``Sequence`` ковариантен —
        это позволяет передавать как гетерогенные
        ``list[QueryToken]``, так и однородные ``list[WordToken]``
        без явных аннотаций.

    Args:
        tokens: Последовательность токенов поискового запроса,
            полученная от
            :func:`~dds_core.application.query_tokenizer.tokenize_search_query`.
            Может быть пустой.

    Returns:
        Строка MATCH-выражения FTS5. Пустая строка, если ``tokens``
        пуст — это соответствует семантике «пустой запрос».

    Example:
        ::

            >>> tokens = tokenize_search_query('гидрошпонка AND "корпус крупного дробления"')
            >>> build_match_expression(tokens)
            'normalized_text: гидpoшпohka AND normalized_text: "kopпyc kpyпhoгo дpoблehия"'

            >>> tokens = tokenize_search_query('EC-423-1')
            >>> build_match_expression(tokens)
            'normalized_text: "ec-423-1"'

            >>> build_match_expression([])
            ''
    """
    if not tokens:
        return ""

    parts: list[str] = []

    for token in tokens:
        if isinstance(token, WordToken):
            parts.append(f"{_FTS5_NORMALIZED_COLUMN}: {_build_word_match(token.text)}")
        elif isinstance(token, PhraseToken):
            normalized_phrase = normalize_text(token.text)
            parts.append(f'{_FTS5_NORMALIZED_COLUMN}: "{normalized_phrase}"')
        elif isinstance(token, OperatorToken):
            parts.append(token.op)
        elif isinstance(token, ParenToken):
            parts.append(token.char)

    return " ".join(parts)


def normalize_search_query(query: str) -> str:
    """Преобразует поисковый запрос в FTS5 MATCH-выражение.

    Удобная обёртка над
    :func:`~dds_core.application.query_tokenizer.tokenize_search_query`
    и :func:`build_match_expression`, сохраняющая привычный API
    для потребителя (``dds_core/infrastructure/fts5_search_backend.py``).

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | ``tokenize_search_query(query)`` → список токенов.  |
    +---+-----------------------------------------------------+
    | 2 | ``build_match_expression(tokens)`` → MATCH-строка.  |
    +---+-----------------------------------------------------+
    | 3 | Возврат результата.                                 |
    +---+-----------------------------------------------------+

    Примечание:
        Функция идемпотентна: повторный вызов с той же строкой
        даёт тот же результат. Не имеет побочных эффектов.

    Примечание:
        Нормализация текста — частичная (см. module docstring).
        Примеры ниже отражают именно это поведение.

    Примечание (Фаза 8):
        Одиночные слова со спецсимволами FTS5 (``-``, ``+``,
        ``:``, ``^``, ``(){}``, ``"``) оборачиваются в двойные
        кавычки. Это устраняет ошибку ``no such column: 423``
        на запросах вида ``EC-423-1``.

    Args:
        query: Поисковый запрос. Может содержать логические
            операторы (``AND``, ``OR``, ``NOT``), фразы в двойных
            кавычках и круглые скобки. Может быть пустым.

    Returns:
        Строка MATCH-выражения FTS5. Пустая строка при пустом
        запросе.

    Example:
        ::

            >>> normalize_search_query('гидрошпонка AND "корпус крупного дробления"')
            'normalized_text: гидpoшпohka AND normalized_text: "kopпyc kpyпhoгo дpoблehия"'

            >>> normalize_search_query('(ЕС-423-1 OR EC-423-1) NOT KM')
            '( normalized_text: "ec-423-1" OR normalized_text: "ec-423-1" ) NOT normalized_text: km'

            >>> normalize_search_query('')
            ''
    """
    tokens = tokenize_search_query(query)
    return build_match_expression(tokens)
