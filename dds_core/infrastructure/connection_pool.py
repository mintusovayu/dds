"""
Пул соединений для чтения из базы данных SQLite.

Этот модуль содержит класс `ConnectionPool`, который управляет
пулом соединений с базой данных SQLite. Пул предназначен для
операций чтения, которые могут выполняться параллельно из
разных потоков.

Каждое соединение выдаётся эксклюзивно одному потоку на время
выполнения запроса и возвращается обратно после завершения.
Это гарантирует, что одно и то же соединение не используется
одновременно несколькими потоками.

Потокобезопасность обеспечивается использованием `queue.Queue`.

Принципы:
- Инкапсулирует управление соединениями.
- Не содержит бизнес-логики запросов.
- Предоставляет явные методы для получения и возврата.
- Гарантирует корректное освобождение ресурсов при закрытии.
- При повреждении соединения автоматически пересоздаёт его
  через фабрику, обеспечивая устойчивость пула к ошибкам.
"""

from __future__ import annotations

import queue
import sqlite3
from collections.abc import Callable

# Тип фабрики соединений
ConnectionFactory = Callable[[str], sqlite3.Connection]


class ConnectionPool:
    """Пул соединений для чтения.

    Управляет фиксированным количеством соединений, которые
    выдаются по запросу и возвращаются после использования.

    Атрибуты:

    +---------------------+------------------------------------------+
    | Атрибут             | Описание                                 |
    +=====================+==========================================+
    | ``_db_path``        | Путь к файлу базы данных.                |
    +---------------------+------------------------------------------+
    | ``_size``           | Количество соединений в пуле.            |
    +---------------------+------------------------------------------+
    | ``_queue``          | Очередь доступных соединений.            |
    +---------------------+------------------------------------------+
    | ``_closed``         | Флаг, указывающий, что пул закрыт.       |
    +---------------------+------------------------------------------+
    | ``_factory``        | Фабрика для создания соединений.         |
    +---------------------+------------------------------------------+

    Пример использования::

        pool = ConnectionPool("/path/to/db.sqlite", size=4)
        conn = pool.acquire_read()
        try:
            cursor = conn.execute("SELECT ...")
            # ...
        finally:
            pool.release_read(conn)

        # При завершении:
        pool.close_all()
    """

    def __init__(
        self,
        db_path: str,
        size: int,
        connection_factory: ConnectionFactory | None = None,
    ) -> None:
        """Инициализирует пул соединений.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Валидация ``size > 0``.                             |
        +---+-----------------------------------------------------+
        | 2 | Сохранение ``db_path`` и ``size``.                  |
        +---+-----------------------------------------------------+
        | 3 | Определение ``connection_factory`` (если ``None``,  |
        |   | используется ``create_sqlite_connection``).         |
        +---+-----------------------------------------------------+
        | 4 | Создание ``queue.Queue(maxsize=size)``.             |
        +---+-----------------------------------------------------+
        | 5 | Заполнение очереди ``size`` соединениями,           |
        |   | созданными через фабрику.                           |
        +---+-----------------------------------------------------+
        | 6 | Установка ``_closed = False``.                      |
        +---+-----------------------------------------------------+

        Потокобезопасность:
        Инициализация выполняется один раз при создании объекта.
        Очередь заполняется до начала использования пула.

        Args:
            db_path: Путь к файлу базы данных SQLite.
            size: Количество соединений в пуле. Должно быть
                положительным целым числом.
            connection_factory: Опциональная фабрика для создания
                соединений. Если не указана, используется
                ``create_sqlite_connection`` из ``connection_factory.py``.

        Raises:
            ValueError: Если ``size`` меньше или равен нулю.
            sqlite3.Error: Если создание соединения не удалось.
        """
        if size <= 0:
            raise ValueError(f"Размер пула должен быть положительным, получено: {size}")

        self._db_path = db_path
        self._size = size

        # Импорт фабрики по умолчанию, если она не передана.
        if connection_factory is None:
            from .connection_factory import (
                create_sqlite_connection as connection_factory,
            )

        self._factory = connection_factory

        # Создание очереди и заполнение соединениями.
        self._queue: queue.Queue[sqlite3.Connection] = queue.Queue(maxsize=size)
        for _ in range(size):
            conn = self._factory(self._db_path)
            self._queue.put(conn)

        self._closed = False

    def acquire_read(self) -> sqlite3.Connection:
        """Выдаёт соединение из пула для выполнения чтения.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка, что пул не закрыт: если ``_closed``       |
        |   | истинно, выбрасывается ``RuntimeError``.            |
        +---+-----------------------------------------------------+
        | 2 | ``self._queue.get()`` — блокирующее получение       |
        |   | соединения. Если пул пуст, поток блокируется       |
        |   | до освобождения соединения другим потоком.          |
        +---+-----------------------------------------------------+
        | 3 | Возврат полученного соединения.                     |
        +---+-----------------------------------------------------+

        Потокобезопасность:
        ``queue.Queue.get`` потокобезопасен и гарантирует, что
        каждое соединение выдаётся только одному потоку.

        Returns:
            Свободное соединение с базой данных SQLite.

        Raises:
            RuntimeError: Если пул закрыт.
        """
        if self._closed:
            raise RuntimeError("Пул соединений закрыт.")
        return self._queue.get()

    def release_read(self, conn: sqlite3.Connection) -> None:
        """Возвращает соединение в пул после завершения чтения.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Если пул закрыт, соединение не возвращается,       |
        |   | а сразу закрывается (см. ``close_all``).           |
        +---+-----------------------------------------------------+
        | 2 | Попытка отката незавершённой транзакции            |
        |   | (``conn.rollback()``) для гарантии чистого         |
        |   | состояния соединения перед возвратом в пул.        |
        +---+-----------------------------------------------------+
        | 3 | При успешном откате:                               |
        |   | ``self._queue.put(conn)`` — возврат соединения     |
        |   | в очередь для последующего использования.          |
        +---+-----------------------------------------------------+
        | 4 | При ошибке отката (``sqlite3.Error``):             |
        |   | a. Закрыть проблемное соединение (``conn.close()``).|
        |   | b. Создать новое соединение через фабрику          |
        |   |    (``self._factory(self._db_path)``).             |
        |   | c. Вернуть новое соединение в очередь.             |
        |   | d. Если создание нового соединения не удалось,     |
        |   |    пул теряет одно соединение. Битое соединение    |
        |   |    не возвращается в пул.                          |
        +---+-----------------------------------------------------+

        Потокобезопасность:
        ``queue.Queue.put`` потокобезопасен. Откат выполняется
        перед возвратом, чтобы следующее использование началось
        с чистого состояния.

        Устойчивость к ошибкам:
        Если соединение повреждено (например, из-за сбоя БД,
        разрыва соединения или внутреннего состояния ошибки),
        ``rollback()`` может завершиться исключением. В этом
        случае метод не выбрасывает исключение вызывающему коду,
        а пытается пересоздать соединение через фабрику. Это
        обеспечивает устойчивость пула к единичным повреждениям
        соединений без прерывания работы системы.

        Если пересоздание соединения не удалось, пул теряет одно
        соединение. Это может привести к увеличению времени
        ожидания в ``acquire_read``, но не к ошибке. При
        необходимости можно добавить мониторинг размера пула.

        Примечание:
            Чтение обычно не оставляет незавершённых транзакций,
            но ``rollback()`` вызывается как защитная мера на
            случай, если соединение было использовано не только
            для чтения или если произошла ошибка во время
            выполнения запроса.

        Args:
            conn: Соединение, которое необходимо вернуть в пул.
                Должно быть получено ранее методом ``acquire_read``.
        """
        if self._closed:
            # Пул закрыт, поэтому просто закрываем соединение.
            try:
                conn.close()
            except sqlite3.Error:
                # Подавляем ошибку, так как пул всё равно закрыт.
                pass
            return

        # Откат возможной незавершённой транзакции.
        # Чтение обычно не оставляет транзакций, но это защита.
        try:
            conn.rollback()
        except sqlite3.Error:
            # Соединение повреждено или находится в некорректном
            # состоянии. Закрываем его и пытаемся пересоздать.
            try:
                conn.close()
            except sqlite3.Error:
                # Подавляем ошибку закрытия: соединение уже
                # непригодно, и его закрытие не критично.
                pass

            # Попытка создать новое соединение через фабрику.
            try:
                new_conn = self._factory(self._db_path)
                self._queue.put(new_conn)
            except sqlite3.Error:
                # Не удалось создать новое соединение.
                # Пул теряет одно соединение. Битое соединение
                # не возвращается в пул, чтобы избежать
                # повторного использования повреждённого объекта.
                pass
            return

        # Откат успешен — возвращаем соединение в пул.
        self._queue.put(conn)

    def close_all(self) -> None:
        """Закрывает все соединения в пуле.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Установка ``_closed = True``.                       |
        +---+-----------------------------------------------------+
        | 2 | Цикл: пока очередь не пуста:                        |
        |   | a. ``self._queue.get_nowait()`` — извлечь           |
        |   |    соединение без блокировки.                       |
        |   | b. ``conn.close()`` — закрыть соединение.           |
        +---+-----------------------------------------------------+
        | 3 | При ошибке закрытия соединения — пропустить         |
        |   | (логирование оставлено вызывающему коду).           |
        +---+-----------------------------------------------------+

        После вызова ``close_all()`` пул больше не может быть
        использован: ``acquire_read`` будет выбрасывать
        ``RuntimeError``.

        Метод идемпотентен: повторный вызов безопасен.
        """
        if self._closed:
            return

        self._closed = True

        # Извлекаем и закрываем все соединения, пока очередь не пуста.
        while True:
            try:
                conn = self._queue.get_nowait()
            except queue.Empty:
                break

            try:
                conn.close()
            except sqlite3.Error:
                # Соединение уже может быть закрыто или повреждено.
                # Просто игнорируем, так как цель — освободить ресурсы.
                pass

    @property
    def is_closed(self) -> bool:
        """Возвращает ``True``, если пул закрыт."""
        return self._closed

    @property
    def size(self) -> int:
        """Возвращает количество соединений в пуле."""
        return self._size
