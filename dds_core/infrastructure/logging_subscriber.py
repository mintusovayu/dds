"""
Подписчик событий для логирования.

Модуль предоставляет класс :class:`LoggingSubscriber`, который
подписывается на события шины и преобразует их в записи лога через
стандартный модуль :mod:`logging`. Подписчик запускается как фоновая
задача и обрабатывает события в асинхронном цикле.

Формат лог-записи — структурированный JSON, содержащий все поля
события, сериализованные методом ``to_dict()``. Это обеспечивает
машинную обработку логов и совместимость с системами агрегации.

Оптимизация производительности (скорректированный план):

+-------------------------------+--------------------------------------+
| Оптимизация                   | Описание                             |
+===============================+======================================+
| Проверка уровня до            | Метод ``handle_event`` проверяет     |
| сериализации                  | ``logger.isEnabledFor(level)`` до    |
|                               | вызова ``json.dumps``. События,      |
|                               | уровень которых ниже порога          |
|                               | логгера, не сериализуются.           |
+-------------------------------+--------------------------------------+
| Фильтрация на этапе           | При подписке на шину передаётся      |
| подписки                      | только набор типов событий, уровень  |
|                               | которых не ниже текущего уровня      |
|                               | логгера. События, которые не будут   |
|                               | залогированы, не попадают в очередь  |
|                               | подписчика.                          |
+-------------------------------+--------------------------------------+
| Метод                         | Возвращает набор типов событий,      |
| ``event_types_for_level``     | которые будут залогированы при       |
|                               | заданном уровне. Используется при    |
|                               | подписке для предварительной         |
|                               | фильтрации.                          |
+-------------------------------+--------------------------------------+

Уровень логирования:
По умолчанию используется уровень ``WARNING`` (для production),
определённый в ``config.DEFAULT_LOG_LEVEL``. Это позволяет снизить
объём выводимой информации и уменьшить накладные расходы.
При необходимости уровень можно переопределить через параметр
``level`` конструктора.

Сопоставление событий уровням логирования:

+-------------------------------+-------------------------------+
| Тип события                   | Уровень                       |
+===============================+===============================+
| ``app.started``               | INFO                          |
+-------------------------------+-------------------------------+
| ``app.stopping``              | INFO                          |
+-------------------------------+-------------------------------+
| ``app.stopped``               | INFO                          |
+-------------------------------+-------------------------------+
| ``scan.started``              | INFO                          |
+-------------------------------+-------------------------------+
| ``scan.completed``            | INFO                          |
+-------------------------------+-------------------------------+
| ``scan.progress``             | DEBUG                         |
+-------------------------------+-------------------------------+
| ``scan.cancel_requested``     | INFO                          |
+-------------------------------+-------------------------------+
| ``scan.cancelled``            | INFO                          |
+-------------------------------+-------------------------------+
| ``operation.timed_out``       | WARNING                       |
+-------------------------------+-------------------------------+
| ``file.processing_failed``    | ERROR                         |
+-------------------------------+-------------------------------+
| ``db.query_slow``             | WARNING                       |
+-------------------------------+-------------------------------+
| ``db.error``                  | ERROR                         |
+-------------------------------+-------------------------------+
| ``search.performed``          | INFO                          |
+-------------------------------+-------------------------------+
| ``http.request_started``      | DEBUG                         |
+-------------------------------+-------------------------------+
| ``http.request_completed``    | INFO                          |
+-------------------------------+-------------------------------+
| ``auth.auto_login``           | INFO                          |
+-------------------------------+-------------------------------+
| ``coord.anomaly_detected``    | WARNING                       |
+-------------------------------+-------------------------------+
| ``module.loaded``             | INFO                          |
+-------------------------------+-------------------------------+
| ``module.load_failed``        | ERROR                         |
+-------------------------------+-------------------------------+
| ``module.error``              | ERROR                         |
+-------------------------------+-------------------------------+
| прочие                        | INFO                          |
+-------------------------------+-------------------------------+

Принципы:
- Подписчик не содержит бизнес-логики, только преобразование
  событий в лог-записи.
- Подписчик не блокирует шину: использует собственную очередь
  и отдельную задачу.
- Ошибки логирования не прерывают обработку событий.
- Сериализация выполняется только для событий, которые будут
  залогированы (проверка уровня до ``json.dumps``).
- При подписке передаётся только набор типов событий,
  соответствующих текущему уровню логирования.

Пример использования::

    subscriber = LoggingSubscriber()  # уровень по умолчанию WARNING
    await subscriber.start(event_bus)
    # ... работа системы ...
    await subscriber.stop()
"""

from __future__ import annotations

import asyncio
import json
import logging

from ..domain import config
from ..domain.events import Event
from .event_bus import AsyncEventBus, Subscription


class LoggingSubscriber:
    """
    Асинхронный подписчик, преобразующий события в лог-записи.

    Подписывается на шину событий, получает события через собственную
    подписку и логирует их с использованием стандартного ``logging``.
    Формат сообщения — JSON-строка, созданная из ``event.to_dict()``.

    Уровень логирования по умолчанию берётся из
    ``config.DEFAULT_LOG_LEVEL`` (обычно ``WARNING``). Его можно
    переопределить, передав параметр ``level``.

    Оптимизация производительности:

    +-------------------------------+----------------------------------+
    | Оптимизация                   | Описание                         |
    +===============================+==================================+
    | Проверка уровня до            | ``handle_event`` проверяет       |
    | сериализации                  | ``isEnabledFor`` до ``json.dumps``.|
    +-------------------------------+----------------------------------+
    | Фильтрация на этапе           | При подписке передаётся только   |
    | подписки                      | набор типов событий, уровень     |
    |                               | которых не ниже уровня логгера.  |
    +-------------------------------+----------------------------------+

    Attributes:

    +-------------------+----------------------------------------------+
    | Атрибут           | Описание                                     |
    +===================+==============================================+
    | ``_logger``       | Логгер, используемый для вывода.             |
    +-------------------+----------------------------------------------+
    | ``_level_mapping``| Словарь сопоставления типа события уровню.   |
    +-------------------+----------------------------------------------+
    | ``_subscription`` | Активная подписка (может быть ``None``).     |
    +-------------------+----------------------------------------------+
    | ``_task``         | Фоновая задача обработки (может быть         |
    |                   | ``None``).                                   |
    +-------------------+----------------------------------------------+
    """

    def __init__(
        self,
        logger: logging.Logger | None = None,
        level_mapping: dict[str, int] | None = None,
        level: int | str | None = None,
    ) -> None:
        """
        Инициализирует подписчика.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Создание или получение логгера. Если ``logger``     |
        |   | не задан, используется логгер с именем              |
        |   | ``"dds.events"``.                                   |
        +---+-----------------------------------------------------+
        | 2 | Установка словаря сопоставления уровней. Если       |
        |   | ``level_mapping`` не задан, используется            |
        |   | ``default_level_mapping()``.                        |
        +---+-----------------------------------------------------+
        | 3 | Определение уровня логирования. Если ``level``      |
        |   | не задан, используется ``config.DEFAULT_LOG_LEVEL``.|
        +---+-----------------------------------------------------+
        | 4 | Установка уровня логгера через ``setLevel``.        |
        +---+-----------------------------------------------------+
        | 5 | Инициализация ``_subscription = None`` и            |
        |   | ``_task = None``.                                   |
        +---+-----------------------------------------------------+

        Args:
            logger: логгер для вывода. Если ``None``, используется
                логгер с именем ``"dds.events"``.
            level_mapping: словарь сопоставления ``event_type`` уровню
                логирования. Если ``None``, используется стандартное
                сопоставление :func:`default_level_mapping`.
            level: уровень логирования. Может быть числом или строкой
                (например, ``"WARNING"``). Если ``None``, берётся из
                ``config.DEFAULT_LOG_LEVEL``.
        """
        self._logger = logger or logging.getLogger("dds.events")
        self._level_mapping = level_mapping or default_level_mapping()

        # Установка уровня логирования
        if level is None:
            level = config.DEFAULT_LOG_LEVEL
        resolved_level = self._resolve_level(level)
        self._logger.setLevel(resolved_level)

        self._subscription: Subscription | None = None
        self._task: asyncio.Task | None = None

    async def start(
        self,
        bus: AsyncEventBus,
        event_types: set[str] | None = None,
        max_queue_size: int = config.SUBSCRIBER_QUEUE_SIZE,
    ) -> None:
        """
        Запускает подписчика: подписывается на шину и запускает цикл обработки.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка, что подписчик ещё не запущен              |
        |   | (``_task is not None``). Если запущен — выход.      |
        +---+-----------------------------------------------------+
        | 2 | Если ``event_types`` не задан, вычисление набора    |
        |   | типов событий через ``event_types_for_level``       |
        |   | на основе текущего уровня логгера.                  |
        +---+-----------------------------------------------------+
        | 3 | Подписка на шину с заданным набором типов событий   |
        |   | через ``bus.subscribe()``.                          |
        +---+-----------------------------------------------------+
        | 4 | Создание задачи ``_consume_loop`` через             |
        |   | ``asyncio.create_task``.                            |
        +---+-----------------------------------------------------+

        Примечание:
        Если ``event_types`` не задан, подписчик подписывается
        только на события, уровень которых не ниже текущего
        уровня логгера. Это предотвращает получение событий,
        которые не будут залогированы, и снижает нагрузку на
        шину и очередь подписчика.

        Например, при уровне логгера ``WARNING`` подписчик
        не будет получать события уровня ``DEBUG`` и ``INFO``,
        такие как ``scan.progress``, ``http.request_started``,
        ``module.document_processed``.

        Args:
            bus: шина событий.
            event_types: множество типов событий для логирования.
                Если ``None``, набор типов вычисляется автоматически
                на основе текущего уровня логгера.
            max_queue_size: максимальный размер очереди подписки.
                По умолчанию берётся из ``config.SUBSCRIBER_QUEUE_SIZE``.
        """
        if self._task is not None:
            return  # уже запущен

        # Если набор типов событий не задан, вычислить его
        # на основе текущего уровня логгера.
        if event_types is None:
            event_types = self.event_types_for_level(self._logger.level)

        self._subscription = bus.subscribe(event_types, max_queue_size)
        self._task = asyncio.create_task(self._consume_loop())

    async def stop(self) -> None:
        """
        Останавливает подписчика: отписывается, отменяет задачу
        и обрабатывает оставшиеся события из очереди.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Если ``_subscription`` существует:                  |
        |   | a. Отписка через ``_subscription.unsubscribe()``.   |
        |   | b. Сохранение ссылки на подписку в локальную        |
        |   |    переменную для последующего дренажа.             |
        |   | c. Установка ``_subscription = None``.              |
        +---+-----------------------------------------------------+
        | 2 | Если ``_task`` существует:                          |
        |   | a. Отмена задачи через ``_task.cancel()``.          |
        |   | b. Ожидание завершения с подавлением                |
        |   |    ``CancelledError``.                              |
        |   | c. Установка ``_task = None``.                      |
        +---+-----------------------------------------------------+
        | 3 | Дренаж очереди подписки:                            |
        |   | a. Пока очередь не пуста:                           |
        |   |    - Извлечение события через ``get_nowait()``.    |
        |   |    - Обработка через ``handle_event()``.           |
        |   | b. При ``asyncio.QueueEmpty`` — выход из цикла.    |
        +---+-----------------------------------------------------+

        Примечание:
        Порядок важен: сначала отписка, чтобы шина перестала
        добавлять новые события в очередь подписчика; затем
        отмена задачи, чтобы прекратить фоновую обработку;
        в конце дренаж оставшихся событий. Это гарантирует,
        что события, опубликованные перед остановкой
        (например, ``ApplicationStopped``), будут обработаны.
        """
        # 1. Отписаться от шины
        if self._subscription is not None:
            self._subscription.unsubscribe()
            sub = self._subscription
            self._subscription = None
        else:
            sub = None

        # 2. Отменить задачу и дождаться завершения
        if self._task is not None:
            self._task.cancel()
            try:
                await self._task
            except asyncio.CancelledError:
                pass
            self._task = None

        # 3. Дренаж очереди подписки
        if sub is not None:
            while not sub.queue.empty():
                try:
                    event = sub.queue.get_nowait()
                    self.handle_event(event)
                except asyncio.QueueEmpty:
                    break

    def handle_event(self, event: Event) -> None:
        """
        Обрабатывает одно событие: логирует его с соответствующим уровнем.

        Метод вызывается в цикле обработки. Переопределение позволяет
        изменить поведение без изменения цикла.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Определение уровня события из ``_level_mapping``.   |
        |   | Если тип события отсутствует в словаре,             |
        |   | используется ``logging.INFO``.                      |
        +---+-----------------------------------------------------+
        | 2 | Проверка ``self._logger.isEnabledFor(level)``.      |
        |   | Если уровень события ниже порога логгера —          |
        |   | выход без сериализации.                             |
        +---+-----------------------------------------------------+
        | 3 | Сериализация события в JSON через                   |
        |   | ``json.dumps(event.to_dict(), ensure_ascii=False)``.|
        +---+-----------------------------------------------------+
        | 4 | Запись в логгер через ``self._logger.log()``.       |
        +---+-----------------------------------------------------+

        Примечание:
        Проверка уровня выполняется до сериализации. Это
        предотвращает лишние затраты на ``json.dumps`` для
        событий, которые не будут залогированы.

        Например, при уровне логгера ``WARNING`` события
        уровня ``DEBUG`` (``scan.progress``,
        ``http.request_started``, ``module.document_processed``)
        не будут сериализованы. Это снижает нагрузку на CPU
        и уменьшает количество аллокаций памяти.

        Args:
            event: событие для логирования.
        """
        level = self._level_mapping.get(event.event_type, logging.INFO)

        # Проверка уровня до сериализации.
        # Если уровень ниже порога логгера, событие не логируется.
        if not self._logger.isEnabledFor(level):
            return

        message = json.dumps(event.to_dict(), ensure_ascii=False)
        self._logger.log(level, message)

    def event_types_for_level(self, level: int | str) -> set[str]:
        """
        Возвращает набор типов событий, которые будут залогированы
        при заданном уровне логирования.

        Используется при подписке на шину событий, чтобы не получать
        события, которые не будут залогированы. Это снижает нагрузку
        на шину и очередь подписчика.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Преобразование уровня в числовое значение через     |
        |   | ``_resolve_level``.                                 |
        +---+-----------------------------------------------------+
        | 2 | Для каждого типа события в ``_level_mapping``       |
        |   | проверка: если уровень события >= заданного уровня, |
        |   | тип добавляется в результат.                        |
        +---+-----------------------------------------------------+
        | 3 | Возврат набора типов событий.                       |
        +---+-----------------------------------------------------+

        Пример:
        При уровне ``WARNING`` (30) метод вернёт типы событий
        с уровнями ``WARNING``, ``ERROR``, ``CRITICAL``,
        но не вернёт типы с уровнями ``DEBUG``, ``INFO``.

        Args:
            level: Уровень логирования. Может быть числом или строкой
                (например, ``"WARNING"``).

        Returns:
            Множество строковых идентификаторов типов событий,
            которые будут залогированы при заданном уровне.
            Пустое множество, если ни одно событие не проходит фильтр.
        """
        resolved_level = self._resolve_level(level)
        result: set[str] = set()
        for event_type, event_level in self._level_mapping.items():
            if event_level >= resolved_level:
                result.add(event_type)
        return result

    async def _consume_loop(self) -> None:
        """
        Цикл обработки событий из подписки.

        Получает события из очереди подписки и вызывает
        :meth:`handle_event` для каждого. Любые исключения при
        логировании подавляются, чтобы не прерывать цикл.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Проверка, что ``_subscription`` не ``None``.        |
        +---+-----------------------------------------------------+
        | 2 | Бесконечный цикл:                                   |
        |   | a. ``await self._subscription.get()`` — блокирующее |
        |   |    ожидание события из очереди подписки.            |
        |   | b. Вызов ``self.handle_event(event)``.              |
        |   | c. При ``Exception`` — подавление (логирование      |
        |   |    не должно прерывать цикл).                       |
        +---+-----------------------------------------------------+

        Примечание:
        Цикл завершается при отмене задачи (``CancelledError``),
        которая выполняется в методе ``stop()``.
        """
        assert self._subscription is not None
        while True:
            event = await self._subscription.get()
            try:
                self.handle_event(event)
            except Exception:
                pass

    @staticmethod
    def _resolve_level(level: int | str) -> int:
        """
        Преобразует уровень логирования в числовое значение.

        Поддерживает строки ("DEBUG", "INFO", "WARNING", "ERROR",
        "CRITICAL") и числа. Если строка не распознана, используется
        ``logging.WARNING``.

        Операции:

        +---+-----------------------------------------------------+
        | № | Описание                                            |
        +===+=====================================================+
        | 1 | Если ``level`` является ``int`` — возврат как есть. |
        +---+-----------------------------------------------------+
        | 2 | Если ``level`` является ``str`` — поиск в           |
        |   | ``logging.getLevelNamesMapping()``.                 |
        +---+-----------------------------------------------------+
        | 3 | Если строка не распознана — возврат                 |
        |   | ``logging.WARNING``.                                |
        +---+-----------------------------------------------------+
        | 4 | Если ``level`` не является ни ``int``, ни ``str``   |
        |   | — возврат ``logging.WARNING``.                      |
        +---+-----------------------------------------------------+

        Args:
            level: уровень в виде строки или числа.

        Returns:
            Числовой уровень логирования.
        """
        if isinstance(level, int):
            return level
        if isinstance(level, str):
            level_names = logging.getLevelNamesMapping()
            return level_names.get(level.upper(), logging.WARNING)
        return logging.WARNING


def default_level_mapping() -> dict[str, int]:
    """
    Возвращает стандартное сопоставление типов событий уровням логирования.

    Операции:

    +---+-----------------------------------------------------+
    | № | Описание                                            |
    +===+=====================================================+
    | 1 | Создание пустого словаря ``mapping``.               |
    +---+-----------------------------------------------------+
    | 2 | Добавление событий приложения (``app.*``).          |
    +---+-----------------------------------------------------+
    | 3 | Добавление событий сканирования (``scan.*``).       |
    +---+-----------------------------------------------------+
    | 4 | Добавление событий отмены сканирования              |
    |   | (``scan.cancel_requested``, ``scan.cancelled``).    |
    +---+-----------------------------------------------------+
    | 5 | Добавление событий обработки файлов (``file.*``).   |
    +---+-----------------------------------------------------+
    | 6 | Добавление событий БД (``db.*``).                   |
    +---+-----------------------------------------------------+
    | 7 | Добавление событий таймаутов операций               |
    |   | (``operation.timed_out``).                          |
    +---+-----------------------------------------------------+
    | 8 | Добавление событий поиска (``search.*``).           |
    +---+-----------------------------------------------------+
    | 9 | Добавление событий HTTP (``http.*``).               |
    +---+-----------------------------------------------------+
    | 10| Добавление событий аутентификации (``auth.*``).     |
    +---+-----------------------------------------------------+
    | 11| Добавление событий системы координат                |
    |   | (``coord.*``).                                      |
    +---+-----------------------------------------------------+
    | 12| Добавление событий модулей (``module.*``).          |
    +---+-----------------------------------------------------+
    | 13| Возврат словаря.                                    |
    +---+-----------------------------------------------------+

    Returns:
        Словарь ``event_type -> logging.LEVEL``.
    """
